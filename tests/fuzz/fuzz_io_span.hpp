#pragma once
// Дисковое время случая гейта 9. Отдельным файлом, потому что вопрос здесь ровно один и свой:
// сколько секунд случая ушло НЕ в разбор. Цель с файловым входом в таблице одна —
// `plugin-manifest` кладёт мутанта на диск, потому что `parse_manifest` принимает путь, а не буфер.
#include <chrono>

#include "fuzz_watchdog.hpp"

namespace fuzz {

// Обнуляется прогоном перед каждым случаем и читается им же после возврата читателя.
inline double& io_seconds() {
    static double seconds = 0.0;
    return seconds;
}

// Отмеряет кусок дисковой работы. Порог случая судит СКОРОСТЬ РАЗБОРА, а заминка файловой системы
// на раннере (антивирус на свежесозданном файле, шумный сосед по vCPU) — не свойство формата: без
// вычета она давала бы `FAIL plugin-manifest … 2.1s > 2.0s` на здоровом дереве, да ещё и
// обвиняющий разбор манифеста. Это САМАЯ КРУПНАЯ недетерминированная ось гейта, но не
// единственная: порог мерит настенные часы и потому мигает на загруженном раннере в принципе —
// просто у девяти целей между `started` и возвратом нет ничего, кроме разбора в памяти.
//
// Сторож на время куска СТАВИТСЯ НА ПАУЗУ, а не сдвигается задним числом (см. `fuzz_watchdog.hpp`:
// сдвиг в конце не спасает от срока, истекающего внутри заминки), и на выходе получает сдвиг на
// измеренное. Под вычет попадают только запись и удаление файла; чтение ВНУТРИ `parse_manifest`
// остаётся под порогом нарочно — это и есть предмет цели, и заминка ФС там по-прежнему способна
// дать ложный `FAIL … > 2.0s budget`, а перевалив за `CASE_BUDGET_SEC + WATCHDOG_GRACE_SEC` — ещё
// и текст сторожа `the reader never returned` с его `_Exit(1)`, то есть вердикт пожёстче. Развести
// это можно только швом внутри чужого разбора.
struct IoSpan {
    std::chrono::steady_clock::time_point started = std::chrono::steady_clock::now();
    IoSpan() { watchdog::io_enter(); }
    ~IoSpan() {
        const std::chrono::duration<double> spent = std::chrono::steady_clock::now() - started;
        io_seconds() += spent.count();
        watchdog::io_leave(spent.count());
    }
};

} // namespace fuzz
