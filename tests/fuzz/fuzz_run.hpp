#pragma once
// Прогон ОДНОЙ цели гейта 9: раздача случаев, порог, сторож, счёт принятых. Отдельным файлом от
// `fuzz_readers.cpp`, потому что там живёт разбор командной строки и сборка вердикта по таблице,
// а здесь — единственный вопрос: что происходит с одним читателем на одном потоке мутантов.
#include <chrono>
#include <cstdint>
#include <cstdio>
#include <vector>

#include "fuzz_io_span.hpp"
#include "fuzz_mutate.hpp"
#include "fuzz_target.hpp"
#include "fuzz_watchdog.hpp"

namespace fuzz {

// Порог на ОДИН случай, а не общий таймаут шага: общий говорит «шаг висел» и не называет ни цель,
// ни seed, ни номер, а на машине владельца его нет вовсе. Судит он разбор МЕДЛЕННЫЙ, но
// сходящийся — тот, что вернулся и дал себя измерить. Две секунды — запас на порядок: самая
// тяжёлая цель дерева проходит случай за миллисекунды.
constexpr double CASE_BUDGET_SEC = 2.0;

// Разбор, не вернувшийся вовсе, этому порогу недоступен по построению, и его ловит сторожевой
// поток. Срок у сторожа НАРОЧНО больше: совпади они, два отказа гонялись бы наперегонки, и мутант
// «порог равен нулю» краснел бы то одним текстом, то другим — непредсказуемый гейт вместо
// воспроизводимого. Секунды хватает: порог уже на порядок выше самого медленного случая.
constexpr double WATCHDOG_GRACE_SEC = 1.0;

// Ключ случая — не сумма и не конкатенация: соседние цели и соседние номера обязаны давать НЕ
// похожие буферы, иначе восемь seed'ов смотрят в одно место восемь раз. Перемешивание тройки
// (цель, seed, номер) даёт каждому случаю своё место, и тройка по-прежнему воспроизводит буфер.
inline uint64_t case_key(std::size_t target, uint64_t seed, int index) {
    uint64_t k = seed ^ (static_cast<uint64_t>(target + 1) * 0x9e3779b97f4a7c15ull);
    k ^= static_cast<uint64_t>(index) * 0xbf58476d1ce4e5b9ull;
    fuzz::Rng rng(k);
    return rng.next();
}

struct Stats {
    long long cases = 0;
    long long accepts = 0;
};

// Возвращает false на первом же отказе и печатает его сама: вердикт обязан назвать ВХОД, а не
// факт обрыва. Отказов три — мёртвое семя, превышение порога и цель, не принявшая ни мутанта.
inline bool run_target(const fuzz::Target& t, std::size_t index, const uint64_t* seeds, std::size_t nseeds,
                int cases, Stats* st) {
    const std::vector<uint8_t> seed_bytes = t.seed();
    // Валидность семени утверждается ДО мутаций: это позитивный контроль самого ВХОДА. Мёртвое
    // семя (пустое или отвергнутое своим же читателем) сделало бы всю цель зелёной без предмета.
    // Сторож вооружён и здесь: читатель, зависший на СОБСТВЕННОМ валидном семени цели, не ловился
    // бы ни порогом (он судит вернувшееся), ни сторожем — прогон вставал бы ровно тем способом,
    // который гейт обещал заменить. Номер случая `-1` называет именно семя, а не нулевой случай.
    watchdog::arm(t.name, nseeds == 0 ? 0ull : static_cast<unsigned long long>(seeds[0]), -1,
                  CASE_BUDGET_SEC + WATCHDOG_GRACE_SEC);
    const bool seed_ok = !seed_bytes.empty() && t.read(seed_bytes.data(), seed_bytes.size());
    watchdog::disarm();
    if (!seed_ok) {
        std::fprintf(stderr, "[fuzz] FAIL %s: its own valid seed was refused, the target is dead\n",
                     t.name);
        return false;
    }
    for (std::size_t s = 0; s < nseeds; ++s) {
        for (int i = 0; i < cases; ++i) {
            const uint64_t key = case_key(index, seeds[s], i);
            std::vector<uint8_t> buf = fuzz::mutate(seed_bytes, key);
            // Перепечатка — на КАЖДОМ случае, где формат её требует. Делить случаи пополам
            // казалось защитой хеш-сторожа, но защиты там нет: гейт судит падение, зависание и
            // вакуум, а сторож РАЗМЕРА сам держит счётчики согласованными с длиной, поэтому снятая
            // проверка хеша не краснит прогон ни при какой доле перепечаток. Половина глубины
            // уходила бы на путь, кончающийся одним `return false`. Чинится ТОЛЬКО поле хеша:
            // мутации магии, версии и счётчиков конверт отбивает ровно как раньше.
            if (t.reseal != nullptr) t.reseal(buf);
            // Дисковое время случая копится целью и вычитается ниже: порог судит РАЗБОР.
            fuzz::io_seconds() = 0.0;
            const auto started = std::chrono::steady_clock::now();
            // Пустой буфер тоже подаётся (мутатор умеет усечь до нуля): читатель обязан отбить
            // РАЗМЕР. Указатель при этом ненулевой — буфер всегда копия непустого семени, и
            // `resize(0)` сохраняет выделенную память; нулевой указатель здесь не проверяется.
            fuzz::watchdog::arm(t.name, static_cast<unsigned long long>(seeds[s]), i,
                                CASE_BUDGET_SEC + WATCHDOG_GRACE_SEC);
            const bool ok = t.read(buf.data(), buf.size());
            // Часы останавливаются ПЕРВЫМ делом: порог объявлен скоростью РАЗБОРА, а `disarm`,
            // сравнение буферов и инкременты — бухгалтерия обвязки, и ей в этом числе не место.
            const std::chrono::duration<double> spent = std::chrono::steady_clock::now() - started;
            fuzz::watchdog::disarm();
            // Принятым считается только ИЗМЕНЁННЫЙ буфер. Мутатор умеет вернуть копию семени —
            // «интересное» число ложится поверх байт, где оно уже лежало (нулевая набивка), а
            // перестановка куска при `from == to` копирует его на себя. Такой случай — исходный
            // файл, и конверт принимает его всегда, даже закрытый наглухо. Считай мы и его,
            // проверка на ноль ниже была бы недостижима по построению: цель, отбивающая ВСЕ
            // мутанты, всё равно набрала бы принятых на нулевых правках.
            if (ok && buf != seed_bytes) ++st->accepts;
            ++st->cases;
            // Вычет — про ЕДИНСТВЕННУЮ цель с файловым входом (`fuzz_io_span.hpp`): у остальных
            // счётчик остаётся нулевым, и они судятся ровно как раньше.
            const double parse_sec = spent.count() - fuzz::io_seconds();
            if (parse_sec > CASE_BUDGET_SEC) {
                std::fprintf(stderr, "[fuzz] FAIL %s seed=%llu case=%d: %.1fs > %.1fs budget\n",
                             t.name, static_cast<unsigned long long>(seeds[s]), i, parse_sec,
                             CASE_BUDGET_SEC);
                return false;
            }
        }
    }
    // Ноль принятых — ОТКАЗ, а не наблюдение. Цель, у которой конверт стал отбивать все мутанты на
    // первом байте (ужесточили магию, размер или хеш), зелена и пуста одновременно: прогон её как
    // бы проверил, а читатель ни разу не заглянул внутрь. Без этой строки вакуум ловится только
    // ручным перегоном таблицы мутаций, то есть раз в несколько месяцев.
    if (st->accepts == 0) {
        std::fprintf(stderr,
                     "[fuzz] FAIL %s: of %lld cases not one changed buffer got past the envelope\n",
                     t.name, st->cases);
        return false;
    }
    return true;
}

} // namespace fuzz
