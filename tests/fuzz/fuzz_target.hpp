#pragma once
// Таблица целей гейта 9. Обязательных полей ТРИ, и это не экономия, а требование к доказательству:
// без пекаря семени мутировать нечего, а без обхода содержимого успешный `open()` не проверяет
// ничего — никто не трогает байты, о которых врёт заголовок, и санитайзеру нечего сказать.
// Четвёртое поле необязательное и нужно только форматам, запечатанным контрольной суммой.
// Новый читатель добавляется строкой таблицы, а не вторым шагом CI со своим списком исходников,
// который разойдётся с деревом молча.

#include <cstddef>
#include <cstdint>
#include <cstring>
#include <vector>

namespace fuzz {

struct Target {
    const char* name;
    // Валидное семя. Печётся ТЕМ ЖЕ пекарем, что в бою: семя из файла протухает молча, когда файл
    // перестают печь, а семя из пекаря чинит себя само при смене версии формата.
    std::vector<uint8_t> (*seed)();
    // Читает вход и ОБХОДИТ ВСЁ, что читатель отдал наружу. Возврат — «принял», а не «ок»:
    // мутация вправе дать валидный файл, и приём сам по себе не дефект. Дефект — падение,
    // выход за границы или зависание, а обход как раз и даёт санитайзеру на что посмотреть.
    bool (*read)(const uint8_t* data, size_t size);
    // Перепечатка контрольной суммы, если формат запечатан ею. Нужна не для удобства: у
    // запечатанного формата ЛЮБАЯ мутация ломает хеш, конверт отбивает её первой же проверкой, и
    // разбор содержимого фаззер не видит ни разу — цель зелена и пуста одновременно. Так и было у
    // `ach-state`: ни одного изменённого буфера внутрь за весь прогон. Шов зовётся на КАЖДОМ
    // случае (см. `run_target`) и чинит ТОЛЬКО поле хеша — остальной конверт судит себя сам.
    // У незапечатанных форматов поле остаётся `nullptr` — им чинить нечего.
    void (*reseal)(std::vector<uint8_t>& buf) = nullptr;
};

// Сток для обхода. Без него компилятор вправе выбросить чтение полей целиком — а вместе с ним и
// сам предмет проверки: санитайзер смотрит на выполненное обращение, а не на написанное.
inline void consume(uint64_t v) {
    static volatile uint64_t sink = 0;
    sink += v;
}

// Складывать поля прямо в аргументе нельзя: в мутированном файле знаковое поле содержит что
// угодно, и `a + b` двух int32_t — это переполнение, то есть UB. Санитайзер доложит о нём и
// обвинит ФАЗЗЕР, а не читателя, ради которого гейт писался. Свёртка идёт поштучно через
// uint64_t, где переполнение определено стандартом.
template <typename... T>
inline void consume_all(T... values) {
    (consume(static_cast<uint64_t>(values)), ...);
}

// Строка из битого файла: длина — ЕДИНСТВЕННОЕ, что с ней можно сделать безопасно, а `nullptr`
// читатель отдаёт законно (поля-строки необязательны). Живёт здесь, а не копией в каждой группе
// целей: копий уже было две, и третья повторила бы находку 5 аудита — семью FNV, разъехавшуюся по
// трём файлам.
inline void consume_str(const char* s) {
    if (s == nullptr) return;
    consume(std::strlen(s));
}

// Боевые цели дерева.
const Target* targets(std::size_t* count);

// Группы — по зависимостям линковки: держать все цели в одной единице трансляции значило бы тянуть
// в неё полдерева. Объявления живут ЗДЕСЬ, а не в сборщике таблицы: тогда рассогласование подписи
// ловит компилятор самой группы, а не линкер в конце сборки.
const Target* engine_targets(std::size_t* count);
const Target* ach_targets(std::size_t* count);
const Target* framework_targets(std::size_t* count);
const Target* plugin_targets(std::size_t* count);
#if defined(LN_FUZZ_SCENE)
const Target* scene_targets(std::size_t* count);
#endif

// Позитивный контроль: читатель с ЗАВЕДОМО снятой проверкой длины. Гоняется только под
// `--selftest` и ОБЯЗАН упасть под санитайзером — шаг CI красен, если он НЕ упал. Без него гейт
// зелен и когда мутатор мёртв, и когда цель ничего не читает.
const Target& canary();

} // namespace fuzz
