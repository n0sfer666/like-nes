#pragma once
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <string>
#include <vector>

// Файловая система за платформенным швом: пути, каталоги, копирование. Все строки —
// UTF-8; wide-API живёт только в platform_fs_win32.cpp.
//
// Раньше этот слой лежал в example_ugly_game/assets_path.cpp на ANSI-API
// (GetModuleFileNameA/CreateDirectoryA/fopen) — то есть ломался на типовом профиле
// `C:\Users\Пётр\` и тащил одиннадцать `#if defined(_WIN32)` в код игры.
namespace platform {

// Путь к собственному исполняемому файлу, канонизированный (symlink/.. раскрыты).
// Пусто = не определён. Нужен не только для exe_dir: перезапуск самого себя — единственный
// способ получить дочерний процесс там, где нет fork (см. platform::Child).
std::string exe_path();

// Каталог исполняемого файла. Пусто = не определён.
std::string exe_dir();

// Единственный легальный способ открыть файл по пути в движке. std::fopen на Windows принимает
// ANSI, поэтому путь через профиль `C:\Users\Пётр\` он не открывает вовсе — а выглядит это как
// «файла нет», и тем же обманом ломается каждый бейк, сейв и загрузка манифеста. Сюда сведены
// ВСЕ узкие открытия дерева, чтобы юникод-путь не зависел от манифеста приложения у 30 целей.
std::FILE* open_file(const std::string& utf8_path, const char* mode);

// Файл целиком в строку. Живёт здесь, а не у потребителей, потому что std::ifstream по
// std::string-пути на Windows тоже ANSI: заменять его пришлось бы одинаковым циклом в каждом
// разборщике манифестов. Платформо-независимо (собрано из open_file).
bool read_text(const std::string& path, std::string& out);

// То же для двоичных данных. Отдельная функция, а не «fseek+ftell у себя»: `long` на Win64
// 32-битный (LLP64), поэтому ftell на файле больше 2 ГБ отдаёт отрицательную длину, а бандл
// таких размеров — штатный случай. Читаем потоком и размер не спрашиваем вовсе.
bool read_bytes(const std::string& path, std::vector<uint8_t>& out);

bool file_exists(const std::string& path);
bool is_dir(const std::string& path);

// Непрозрачный токен «версии» файла (время модификации + размер). Меняется — файл изменился.
// Не сравнивать на «больше/меньше» и не хранить между запусками: раскладка платформенная
// (наносекунды у POSIX лежат в разных полях stat, у Windows это FILETIME).
// false = файла нет; вызывающий обязан отличать «нет» от «не менялся».
bool file_stamp(const std::string& path, int64_t& out);

// «Уже существует» — успех только если там каталог: файл с тем же именем иначе молча проходил бы
// дальше, и запись сейва падала бы уже без диагностики.
bool make_dir(const std::string& path);

// Рекурсивное создание. Платформо-независимо (собрано из make_dir/is_dir/root_len/is_sep).
bool ensure_dir(const std::string& path);

bool remove_file(const std::string& path);

// Долговечность записи: буферы файла — на носитель, затем сама запись каталога. Без второго
// шага POSIX может пережить отключение питания с уже переименованным, но ещё не существующим
// для каталога файлом. На Windows каталог отдельной фиксации не требует — там это делает сам
// replace_file, поэтому sync_dir_of ничего не делает (а не «не реализован»).
bool sync_file(std::FILE* f);
void sync_dir_of(const std::string& file_path);

// Атомарная замена существующего файла. Ровно то, на чём стоит сейв-транзакция: обычный
// rename на Windows отказывается перезаписывать цель, и «атомарная» запись превращалась бы
// в удалить-и-надеяться.
//
// ОГРАНИЧЕНИЕ, которого нет на POSIX: `to` не должен быть отображён в память НИКЕМ (в том числе
// самим вызывающим). Живая секция держит файл ссылкой помимо файлового хендла, поэтому подмена
// имени отвергается (ERROR_USER_MAPPED_FILE) — и FILE_SHARE_DELETE этого не меняет, он про
// хендлы, а не про секции. Переносимый рецепт пересборки бандла: снять отображение
// (MappedFile::close / AssetManager::close) → replace_file → открыть заново.
bool replace_file(const std::string& from, const std::string& to);

// Перезаписывает существующий dst. Нужна hot-reload'у: Windows держит загруженный модуль
// залоченным, поэтому грузится копия (решение 4 спеки #12).
bool copy_file(const std::string& src, const std::string& dst);

// Каталог пользовательских данных приложения: %APPDATA%\<app> на Windows,
// ~/Library/Application Support/<app> на macOS, $XDG_DATA_HOME/<app> (иначе
// ~/.local/share/<app>) на Linux. Пусто = переменная окружения не задана или не абсолютна —
// относительный корень отбрасывается намеренно (XDG это предписывает, а путь сейва,
// зависящий от CWD, — ровно та беда, ради которой функция и существует).
std::string user_data_dir(const std::string& app_name);

} // namespace platform
