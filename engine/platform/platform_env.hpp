#pragma once
#include <string>

// Переменные окружения за платформенным швом. Строки — UTF-8, как и везде на границе движка.
//
// std::getenv здесь не годится по двум причинам сразу. Во-первых, на Windows он отдаёт значение
// в ANSI-кодовой странице: `LIKENES_ASSETS=D:\юникод тест-каталог\` возвращается с подменёнными
// символами, каталог «не находится», и выглядит это как отсутствующий ассет. Во-вторых, MSVC
// помечает getenv как небезопасный (C4996) и толкает к `_dupenv_s` — функции Annex K, которой
// нет в glibc, то есть к #ifdef в переносимом коде. Шов снимает оба вопроса разом.
namespace platform {

// false = значения нет ЛИБО оно не читается (битая конвертация, битое имя); out в обоих случаях
// не трогается. Подставлять на false дефолт молча нельзя ровно поэтому — «не прочиталось»
// выглядело бы как «не задано». На «заданную пустой строкой» опираться нельзя ни на одной ОС:
// Windows такое состояние практически не представляет — и `set X=` в cmd.exe, и
// SetEnvironmentVariableW с пустой строкой переменную УДАЛЯЮТ. Пустое значение и отсутствие
// трактовать одинаково.
bool env_var(const char* name, std::string& out);

// Запись в окружение своего процесса; nullptr вместо значения — удалить. Удаление отсутствующей
// переменной — успех (Win32 возвращает на это ошибку, шов её гасит: POSIX-unsetenv молчит).
// Пустая строка вместо значения на Windows равносильна удалению — писать её ради «ручка взведена,
// значения нет» нельзя, ручка окажется опущена; для такого случая значение выбирается любое.
// false = записать не удалось; переменная при этом остаётся какой была, а не стирается.
bool env_put(const char* name, const char* value);

// Проверка «ручка взведена» без значения — самый частый вызов в фикстурах и тестах.
inline bool env_has(const char* name) {
    std::string ignored;
    return env_var(name, ignored);
}

} // namespace platform
