#pragma once

// Запрет инлайна одной строкой на все компиляторы. Живёт за швом не потому, что это про ОС, а
// потому, что гейт «платформенного шва» в CI не различает `_MSC_VER` и `_WIN32` — и различать не
// должен: исключение для «всего лишь компиляторного» условия открывается один раз, а закрывается
// никогда. Синтаксис у MSVC и GCC/Clang разный, значит условная компиляция обязана быть здесь.
//
// Нужен он rt-пробам, замещающим operator new/delete ради счётчика аллокаций в горячем участке.
// Заинлайнив замещающий delete туда, где видна аллокация, GCC 16 видит пару
// «__builtin_operator_new → free» и валит сборку по -Werror=mismatched-new-delete: про то, что
// free тут и есть тело замещающего delete, он уже забыл. Запрет инлайна оставляет указатель
// параметром неизвестного происхождения — сравнивать не с чем. На Mach-O не воспроизводится
// (замещаемые операторы там и без того не инлайнятся), поэтому ловится только на Linux.
#if defined(_MSC_VER)
#define PLATFORM_NOINLINE __declspec(noinline)
#else
#define PLATFORM_NOINLINE __attribute__((noinline))
#endif
