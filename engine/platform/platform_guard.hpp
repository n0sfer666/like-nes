#pragma once

// Шов №4 платформы (спека #12, решение 3): изоляция падений на границе host↔lib.
// Реализации — platform_guard_posix.cpp (sigaction + sigsetjmp) и platform_guard_win32.cpp
// (SEH-фрейм __try/__except), выбор делает CMake.
//
// Спека называет три шва; этот четвёртый появился потому, что решение «SEH-фрейм на границе»
// нельзя выразить существующими тремя: SEH — не ввод-вывод, не процесс и не модуль, а его
// POSIX-двойник (siglongjmp из обработчика сигнала) жил в engine/plugin вместе с `#ifndef
// _WIN32`. Отклонение зафиксировано в ADR, а не спрошено.
namespace platform {

// Аргумент передаётся сырым void*: через SEH-фрейм и siglongjmp не переживает ничего, что
// требует раскрутки стека с вызовом деструкторов. Вызывающий сам оборачивает свои данные.
using GuardedFn = void (*)(void*);

// Однократная установка обработчиков (POSIX). На Windows фрейм ставится в guarded_call, и
// функция ничего не делает — вызывать всё равно можно и нужно, симметрия швов.
void install_crash_isolation();

// false = вызов упал на нарушении доступа/выравнивания/недопустимой инструкции. Что угодно
// иное (в т.ч. C++-исключение) сквозь фрейм проходит наружу: глушить чужие ошибки не задача
// крэш-изоляции. Набор перехватываемых сбоев на обеих ОС одинаков — это инвариант 4 архитектуры.
//
// Вложенный вызов допустим, но точка, где падение станет `false`, платформенная: на Windows
// его ловит ближайший __try, на POSIX — САМЫЙ ВНЕШНИЙ кадр (вложенный своего не ставит, иначе
// прыжок ушёл бы в разрушенный стек). Гарантия, общая для обеих: процесс жив и ровно один кадр
// вернул false. Кому нужна точная атрибуция сбойного вызова — не вкладывать.
bool guarded_call(GuardedFn fn, void* arg);

} // namespace platform
