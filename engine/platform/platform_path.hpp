#pragma once
#include <cstddef>
#include <string>

// Разбор путей: чистая строковая логика, но семантика платформенная. Отдельно от platform_fs
// намеренно — тут нет ни одного системного вызова, а форма пути нужна и тем, кто файлов не
// трогает вовсе (резолв каталога ассетов, склейка каталога сейвов).
namespace platform {

// На POSIX `\` и `:` — легальные символы имени, и трактовать их по-виндовому значило бы съедать
// настоящие каталоги (`//Library/...` при HOME=/).
bool is_sep(char c);
bool is_absolute(const std::string& path);

// Длина корня, который создавать нельзя и не нужно: "C:" — не каталог, а drive-relative путь,
// "\\server\share" — точка монтирования. mkdir по ним вернул бы ошибку и обрубил бы цепочку.
size_t root_len(const std::string& path);

} // namespace platform
