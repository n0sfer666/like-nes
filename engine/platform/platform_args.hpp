#pragma once
#include <string>
#include <vector>

// Аргументы командной строки в UTF-8. Единственный легальный источник argv в дереве.
//
// CRT MSVC отдаёт `main(int, char**)` узкий argv, перекодированный в системную ANSI-кодовую
// страницу: на en-US раннере «синтетика тест.bundle» приезжает как «????????? ????.bundle» —
// путь разрушен ещё ДО входа в шов файловой системы, и никакой wide-API его уже не спасёт.
// Выглядит это не как испорченный аргумент, а как отказ записи: '?' Windows в имени файла не
// принимает вовсе. Настоящая строка запуска доступна только через GetCommandLineW, поэтому
// argv берётся оттуда, а не из параметров main.
//
// Манифест приложения с `activeCodePage=UTF-8` закрыл бы то же самое, но ценой зависимости
// каждой из тридцати целей от верно собранного и приложенного манифеста — молчаливой и
// невоспроизводимой в CI. Шов дешевле и проверяется гейтом 8.
namespace platform {

// [[nodiscard]] на классе: временный `Args(argc, argv);` оставил бы argv висящим на первой же
// строке main — пусть это ловит компилятор, а не комментарий ниже.
class [[nodiscard]] Args {
  public:
    // Переписывает argc/argv вызывающего (отсюда ссылки — как у QCoreApplication, и по той же
    // причине). Объект обязан быть ИМЕНОВАННОЙ локальной переменной main и жить до её конца:
    // строки принадлежат ему, argv показывает внутрь них.
    Args(int& argc, char**& argv);

    Args(const Args&) = delete;
    Args& operator=(const Args&) = delete;

  private:
    // Забрать argv как есть. POSIX так работает всегда, Windows — когда разбор строки запуска
    // отказал; отсюда общий метод, а не два одинаковых цикла.
    void adopt(int argc, char** argv);

    // owned_ → ptrs_ (+ замыкающий nullptr, как требует стандарт от argv). Общая часть обеих
    // реализаций: различается только откуда взялся owned_.
    void index(int& argc, char**& argv);

    std::vector<std::string> owned_;
    std::vector<char*> ptrs_;
};

} // namespace platform
