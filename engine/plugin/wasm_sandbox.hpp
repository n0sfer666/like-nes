#pragma once
#include <wasmtime.h>
#include <cstdint>

// Счётчик топлива — единственный ограничитель времени гостя: без него бесконечный цикл вешает
// прогон навсегда, таймаута у `wasm_run_escape` нет. Поэтому не `bool` с умолчанием, а тип без
// умолчания: каждый вызов пишет намерение, и `WasmFuel::Off` берут только для заведомо конечного
// модуля (аудит #21, ревью A·2).
enum class WasmFuel { On, Off };

// Потолки песочницы. Без них untrusted-гость получает ресурсы хоста целиком: `memory.grow`
// растёт до 4 ГиБ адресного пространства, а цикл без выхода вешает поток движка навсегда —
// песочница защищала память хоста, но не его время и не его RAM (аудит #21, A·2·2).
// Топливо тратится на каждую инструкцию гостя и кончается трапом, поэтому счётчик ставится
// заново перед КАЖДЫМ вызовом: лимит на кадр, а не на всю игру.
//
// Потолок RAM меряет ТОЛЬКО линейную память. Таблица — тоже память хоста, но считается элементами
// и лимитером по умолчанию не ограничена вовсе, а число памятей и таблиц по умолчанию 10 000: без
// этих чисел гость обходит 16 МиБ одним объявлением `(table 1000000 funcref)` либо десятком тысяч
// таблиц — и обходит ДО первой инструкции, то есть не потратив ни капли топлива (аудит #21,
// ревью A·2).
constexpr int64_t WASM_MEMORY_LIMIT = 16 * 1024 * 1024;
constexpr int64_t WASM_TABLE_LIMIT = 65536;
// Бак на вызов. Размер выбран по ЗАПАСУ, а не по амбиции: честный тик гравитации тратит около 9500,
// и гейт ловит «топливо вообще не считается» порогом в процент бака. При баке в миллион этот порог
// был 10 000 при расходе 9 500 — удвоение числа тел или правка `gravity.wat` красили бы гейт, не
// назвав дефекта. Десять миллионов — это по-прежнему единицы миллисекунд, то есть всё ещё лимит на
// кадр, но запас у порога десятикратный (аудит #21, ревью A·2).
constexpr uint64_t WASM_FUEL_PER_CALL = 10000000;

// Оба входа в песочницу строятся ОДНОЙ функцией: потолок, поставленный только на игровом пути,
// оставляет гейт побега мерить другую конфигурацию, чем ту, что уедет игроку (аудит #21, A·2·2).
bool make_sandbox(wasm_engine_t*& engine, wasmtime_store_t*& store,
                  wasmtime_context_t*& ctx, WasmFuel fuel);
