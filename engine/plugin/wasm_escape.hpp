#pragma once
#include "wasm_sandbox.hpp"
#include <string>

// `LinkError` — песочница отбила ИНСТАНЦИРОВАНИЕ (ради этого гейт и живёт). `NoExport` — модуль
// собрался и встал, но названной функции у него нет: это опечатка в фикстуре, а не отбитый побег,
// и одним именем на двоих гейт зеленел бы на кривой фикстуре (аудит #21, ревью A·2).
enum class WasmOutcome { Ok, HostError, CompileError, LinkError, NoExport, TrapOnCall };

// Зонд побега: чужой модуль в той же песочнице, что и игровой путь. `WasmFuel::Off` строит её без
// счётчика — заправка на такой отказывает, и `HostError` становится утверждаемым исходом, а не
// значением перечисления, которого никто не видел.
//
// `why` (если дан) получает текст отказа от wasmtime. Под одним `LinkError` приезжают ПЯТЬ разных
// причин — чужой импорт, потолок элементов таблицы, число таблиц, число памятей и трап `(start)`, —
// и без текста фикстура зеленела бы на причине соседки, а красная строка не назвала бы свою
// (аудит #21, ревью A·2).
WasmOutcome wasm_run_escape(const std::string& wat, const char* export_to_call, WasmFuel fuel,
                            std::string* why = nullptr);
