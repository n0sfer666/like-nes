#pragma once

#include <webgpu/webgpu.h>

#include <cstdint>
#include <vector>

// Карты текстурных слотов гейта 7 считаются в коде по тем же причинам, что и картинки сцены
// материалов: движковому гейту нужен кадр, воспроизводимый на любой машине, а файл привязал бы его
// к бандлу игры-образца. Настоящий загрузчик текстур — предмет ассетной вертикали, а не этой.
//
// КОНТРАКТ ЗНАКА нормали, записанный здесь один раз: карта хранит нормаль в базисе ПРОХОДА
// ОСВЕЩЕНИЯ — +X вправо, +Y ВВЕРХ, +Z на зрителя, — закодированную как `n * 0.5 + 0.5`. Текстурная
// координата растёт вниз, поэтому переворот знака Y делается ровно в одном месте, в генераторе. Не
// записанное соглашение о знаке каждый потребитель пишет по-своему, и расходятся они молча — светом
// с изнанки.
//
// КОНТРАКТ ОККЛЮЗИИ: канал R — доля перекрытого света, 0 не перекрывает ничего, 1 перекрывает
// целиком. Ноль здесь и цвет очистки буфера — одно и то же значение намеренно: пиксель, которого
// не накрыл ни один спрайт, обязан быть неотличим от пикселя материала без слота окклюзии.
namespace slotgold {

// Банк карт по GUID АССЕТА: таблица хранит текстурный слот именно хешем имени, строку знает только
// `library.mat`. Неизвестный guid отдаёт nullptr, а не подстановку: «ассета нет» и «материал не
// просил карту» обязаны различаться, иначе опечатка в `library.mat` читается как замысел.
class Bank {
public:
    bool init(WGPUDevice device, WGPUQueue queue);
    void shutdown();

    WGPUTextureView view(uint64_t guid) const;
    const char* name(uint64_t guid) const;

    // Подстановки для материала БЕЗ слота, по одной на буфер: плоская нормаль (0,0,1) и «ничего не
    // перекрывает» (0). Разные значения у разных буферов — причина, по которой подстановка живёт в
    // описании прохода, а не константой внутри него.
    WGPUTextureView flat() const { return flat_view_; }
    WGPUTextureView open() const { return open_view_; }

private:
    struct Named {
        const char* name;
        uint64_t guid;
        WGPUTexture tex;
        WGPUTextureView view;
    };

    std::vector<Named> maps_;
    WGPUTexture flat_ = nullptr;
    WGPUTexture open_ = nullptr;
    WGPUTextureView flat_view_ = nullptr;
    WGPUTextureView open_view_ = nullptr;
};

} // namespace slotgold
