// КОДИРОВКА текстурных слотов гейта 7 (спека #18), записанная ОДИН раз. До этого файла каждое из
// двух значений было написано трижды — константой в проходе света, пикселем запасной карты банка и
// цветом очистки в `Desc` слотового прохода, — а требование, чтобы все три совпадали, стояло
// комментарием. Расходятся такие копии молча: пиксель, которого не накрыл спрайт, перестаёт быть
// неотличим от пикселя материала без слота, и кадр меняется без единой строки в логе.
//
// Цвет очистки не пишется числами рядом, а ВЫВОДИТСЯ из пикселя: две записи одного значения в
// разных единицах — та же копия, только незаметная.
namespace slotenc {

// Плоская нормаль (0,0,1) в кодировке `n * 0.5 + 0.5`. Контракт знака — `slot_textures.hpp`.
constexpr uint8_t FLAT_NORMAL[4] = {128, 128, 255, 255};
// «Ничего не перекрывает»: канал R — доля перекрытого света, 0 не перекрывает ничего.
constexpr uint8_t OPEN_OCC[4] = {0, 0, 0, 255};

constexpr WGPUColor clear_of(const uint8_t (&px)[4]) {
    return WGPUColor{static_cast<double>(px[0]) / 255.0, static_cast<double>(px[1]) / 255.0,
                     static_cast<double>(px[2]) / 255.0, static_cast<double>(px[3]) / 255.0};
}

} // namespace slotenc
