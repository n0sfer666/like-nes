#pragma once
#include <cstdint>
#include <vector>

// Транскод KTX2/UASTC → BC7 (basis transcoder). Спека #5 «текстуры → KTX2/basis → BC7/ASTC».
// CPU-работа на стороне GPU-consumer'а (вне sim-потока). Детерминирована (фикс. формат).
namespace asset {

// Потолок на уровень — свой, а не позаимствованный у транскодера, и мерится он БЛОКАМИ. Число
// блоков приходит из заголовка KTX2, то есть из файла, а `resize` по нему шёл без единой нашей
// проверки: всё, что стояло между чужим числом и выделением памяти, — внутренняя валидация basisu,
// исходников которой в дереве нет (тянутся FetchContent), то есть проверить её было нечем. Образец
// дисциплины уже есть — `MAX_MAP_TILES` в `map_parse.cpp` (аудит #21, A·2·9).
//
// 1<<22 блока — это ровно 64 МиБ BC7 (по 16 байт на блок) и ровно квадрат 8192×8192. Самый большой
// атлас, который печёт `assetc`, — 512×256, то есть 8192 блока: запас ×512. Потолок поставлен там,
// где кончается здравый смысл, а не там, где начинается наш рабочий размер.
//
// Мерится он блоками, а не площадью, и это правка по ревью, а не вкусовщина. Предел по площади
// называет число байт только на квадратных уровнях: блоки округляются вверх ПО КАЖДОЙ СТОРОНЕ,
// поэтому тонкий уровень 1×(1<<26) держит площадь ровно на пределе и даёт при этом 1×16 777 216
// блоков — 256 МиБ, вчетверо больше обещанного, по тем же восьми подменённым байтам шапки.
// Ограничивать надо то, что тратится, а тратятся блоки: байт на блок ровно шестнадцать, и предел
// по ним прямо называет то число байт, которое мы согласны выделить чужому файлу.
inline constexpr uint64_t MAX_TEXTURE_BLOCKS = 1ull << 22;

// Сколько блоков BC7 занимает уровень w×h, если уровень вообще можно принять, и 0, если нельзя.
//
// Работу делает ПОТОЛОК: соврать шапка KTX2 может ровно одним способом — назвать невозможные
// стороны, потому что числа блоков в файле нет вовсе, basisu считает его сам как
// `ceil(сторона / сторона_блока)` из тех же `pixelWidth`/`pixelHeight`, которые читаем и мы.
//
// Сверка `declared == need` поэтому сторожит не файл, а ШОВ с basisu: сегодня наши округления
// совпадают до числа, и разойтись они могут только при смене версии транскодера или формата
// выпечки (у ASTC-6×6 сторона блока не 4). Разойдясь молча, они дали бы буфер не того размера —
// то есть ровно ту беду, против которой стоит потолок. Исход ОДИН, а не два порознь, потому что
// чинится и то и другое одинаково: пересборкой ассета.
//
// Ноль как отказ, и отдельной ветки под нулевую сторону тут НЕТ намеренно: такая сторона даёт ноль
// блоков, то есть тот же самый ноль, и ветка была бы кодом, который нечем покрасить — ни одна
// мутация не отличила бы её присутствие от отсутствия. По той же причине тут нет и второй,
// «дешёвой» проверки площади: при 16 байтах на блок она доказуемо следует из проверки блоков и
// никогда не сработала бы первой.
//
// `resize` у зовущего идёт по ЭТОМУ числу, а не по `m_total_blocks`. Компилятор такой порядок не
// охраняет — подмена вызова на чужое число собирается молча, — поэтому шов держит враждебная
// фикстура в `transcode_test.cpp`, а не система типов.
constexpr uint64_t level_blocks(uint32_t w, uint32_t h, uint64_t declared) {
    // Округление ВВЕРХ: сторона, не кратная четырём, занимает неполный блок целиком, и пол здесь
    // отдал бы буфер короче того, во что транскодер пишет. Четвёрка — ЗАФИКСИРОВАННОЕ допущение:
    // `assetc` печёт BC7, у него блок 4×4. Формат с блоком 6×6 сделает эту формулу неверной, и
    // сверка ниже начнёт отказывать всегда — заметить это обязан положительный контроль гейта.
    // Переполнения тут нет: обе стороны 32-битные, каждый сомножитель не больше 2^30.
    const uint64_t need =
        ((static_cast<uint64_t>(w) + 3) / 4) * ((static_cast<uint64_t>(h) + 3) / 4);
    if (need > MAX_TEXTURE_BLOCKS) return 0;
    return declared == need ? need : 0;
}

// bc7 — плотный BC7 (16 байт/4x4-блок). Возврат false при невалидном KTX2 — в том числе на уровне,
// который не проходит `level_blocks`.
//
// Контракт отказа: `bc7` не трогается ТОЛЬКО при отказе ДО выделения — это отказ basisu на `init`,
// `start_transcoding` или `get_image_level_info` и наш отказ по потолку либо по сверке. Отказ
// САМОГО транскода приходит уже после `resize`, и тогда вектор перерезан и записан частично.
// `w`/`h` записываются раньше потолка и при отказе по нему содержат ровно те враждебные числа из
// шапки. Поэтому зовущий обязан считать все три выхода неопределёнными, пока возврат не `true`.
//
// `bc7.clear()` на пути отказа НЕ ставится намеренно, и это не мелочь стиля. Пустота буфера —
// ЕДИНСТВЕННАЯ улика гейта `transcode_test.cpp`: отказ как таковой ничего не доказывает (basisu на
// враждебном файле тоже вернёт false, просто уже потратив 256 МБ), а пустой `bc7` доказывает, что
// до `resize` дело не дошло. Добавив сюда `clear()`, правящий сделает мутацию «`resize` идёт по
// `m_total_blocks`» незаметной для гейта — шов A·2·9 станет непроверяемым молча. Вторая причина
// проще: чистка сделала бы частично мёртвой собственную сверку `want` в
// `example_ugly_game/bundle_atlas.cpp` — та сама считает ожидаемый размер и сама чистит буфер.
bool ktx2_to_bc7(const uint8_t* ktx2, uint32_t size, std::vector<uint8_t>& bc7,
                 uint32_t& w, uint32_t& h);

} // namespace asset
