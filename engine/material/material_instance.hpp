#pragma once

#include "param.hpp"

namespace mat {

// Инстанс спрайта: то, что едет в инстансный вертекс-буфер и НЕ трогает пайплайн.
//
// Порядок полей — тот же, что у `game::Instance` игры-образца, и это не совпадение: у библиотеки
// эффектов ОДИН вершинный этап на обоих потребителей (решение 2 спеки #18), а вершинный этап есть
// раскладка этой структуры. Разойдись они — материал рисовался бы верно ровно у одного из них.
//
// Блок параметров лежит ЗДЕСЬ, а не в юниформе, ровно ради инварианта 2 спеки: смена параметра
// обязана оставаться сменой данных инстанса. Юниформ развалил бы батч на по вызову на объект.
struct Instance {
    float x = 0, y = 0;
    float w = 0, h = 0;
    float u0 = 0, v0 = 0;
    float u1 = 1, v1 = 1;
    float r = 1, g = 1, b = 1, a = 1;
    float rot = 0;
    float params[PARAM_BLOCK_FLOATS] = {};
};
static_assert(sizeof(Instance) == 84, "Instance layout pinned (vertex attributes read it by offset)");

} // namespace mat
