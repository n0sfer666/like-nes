#include <cstdint>
#include <string>
#include <vector>

#include "grid.hpp"

// Бейк текстового исходника тайловой карты в zero-parse таблицу (`map_format.hpp`). Живёт в
// движке, а не в `assetc`, по образцу профиля #16, пресетов #14 и достижений #10: тот же разбор
// нужен тестам, и вторая копия в инструменте разошлась бы с первой молча.
//
// Формат (разделитель — `|`, `#` до конца строки — комментарий, пустые строки игнорируются):
//   map       | <имя>
//   tile_size | 16                 # сторона тайла в пикселях
//   origin    | 0 | -32            # мировые координаты угла тайла (0,0); +Y ВНИЗ
//   legend    | . | empty          # глиф -> набор флагов; слов может быть несколько
//   legend    | X | solid
//   row       | X.....X            # строки карты сверху вниз, ширина берётся у первой
//
// Пекарь отбивает НОМЕРОМ СТРОКИ, а не чинит молча:
//   * строка до первой `map` — значение, которому некуда лечь;
//   * незнакомый ключ — опечатка иначе означала бы «поле осталось по умолчанию»;
//   * повтор `tile_size`/`origin` — победил бы последний, то есть смысл решал бы порядок строк;
//   * недостающий ключ (проверяется на закрытии карты) — умолчание здесь ложь: и нулевой размер
//     тайла, и карта без строк читаются без ошибки и означают «уровня нет»;
//   * `tile_size`, который сетка привела бы к другому числу (`grid.cpp` округляет raw до чётного и
//     поднимает до двух), — молчаливый кламп сделал бы исходник враньём: в файле стояло бы одно
//     число, в игре работало бы другое;
//   * НЕВИДИМЫЙ глиф (пробел) — ширина карты зависела бы от хвостовых пробелов, которые редактор
//     подчищает сам. `#` и `|` глифами быть не могут по устройству грамматики: первый срезается
//     комментарием, второй разделяет поля, — и обе записи отбиваются как «глиф не одна видимая
//     буква»;
//   * повтор глифа в легенде — тайл означал бы разное в зависимости от того, какую строку легенды
//     прочитали последней;
//   * `empty` вместе с любым другим словом — противоречие: «пусто» это отсутствие флагов;
//   * глиф строки, которого нет в легенде, — иначе опечатка в карте становится дырой в полу;
//   * строка карты другой длины, чем первая, — прямоугольность карты и есть её раскладка;
//   * повтор ИМЕНИ карты — поиск по имени вернул бы первую, а правили бы вторую.
namespace framework::tilemap {

struct MapBakeError {
    int line = 0;
    std::string message;
};

// Разобранная карта: ровно то, из чего строится `TileGrid`. Флаги лежат тем же порядком
// (`y * width + x`), что и в сетке.
struct ParsedMap {
    std::string name;
    Vec2 origin;
    fix32 tile_size;
    uint32_t width = 0;
    uint32_t height = 0;
    std::vector<TileFlags> flags;
};

// Разбор отдельно от сборки байтов: тест вправе спросить, ЧТО прочиталось, не разбирая при этом
// таблицу обратно.
bool parse_maps(const std::string& text, std::vector<ParsedMap>& out, MapBakeError& err);
bool parse_maps_file(const std::string& path, std::vector<ParsedMap>& out, MapBakeError& err);

bool bake_maps(const std::string& text, std::vector<uint8_t>& out, MapBakeError& err);
bool bake_maps_file(const std::string& path, std::vector<uint8_t>& out, MapBakeError& err);

} // namespace framework::tilemap
