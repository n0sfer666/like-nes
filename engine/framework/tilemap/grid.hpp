#include <cstdint>
#include <vector>

#include "shape.hpp"

// Тайловая сетка коллизии — ОТДЕЛЬНОЕ представление, а не тысячи тел (решение 3 спеки #16).
//
// Тело на тайл стоило бы не памяти, а СМЫСЛА: экран платформера это порядка тысячи тайлов, широкая
// фаза шага сортировала бы их каждый кадр, решатель заводил бы на них манифольды и острова, а
// двигать их некому — сетка статична по построению. Поэтому тайлы живут своей структурой со своими
// запросами, и в `physics::World` их нет ни одного.
//
// Раскладка ПЛОСКАЯ И ПЛОТНАЯ (решение владельца 2026-08-23, шаг A вертикали 2): начало, размер
// тайла, ширина, высота и массив флагов. Инвариант 4 спеки («стоимость не зависит от размера
// уровня») держится не раскладкой, а ОКНОМ запроса — обходятся тайлы в коробке зонда, а не карта, —
// поэтому чанки здесь ничего бы не закрыли и приезжают вместе с форматом, когда появится что
// раскладывать.
namespace framework::tilemap {

// Свойства коллизии — БИТАМИ, а не перечислением: спека требует от тайла «сплошной, односторонний,
// склон, метка триггера», и это набор, а не выбор, — односторонний склон с меткой урона законен.
// Бит заводится вместе с механикой, которая его читает: бит без потребителя — это обещание
// поведения, которого нет.
using TileFlags = uint16_t;
constexpr TileFlags TILE_EMPTY = 0;
constexpr TileFlags TILE_SOLID = 1u << 0;

// Склон — МОДИФИКАТОР ФОРМЫ, а не отдельный вид тайла: он говорит, во что тайл разворачивается
// геометрией (`query.cpp`), и ничего не говорит о том, с каких сторон тайл держит. Поэтому склон
// живёт ВМЕСТЕ с телесным флагом (`solid slope_br`), а не вместо него, и разбор исходника отвергает
// склон без тела — иначе тайл молча выпадал бы из любого запроса, чей фильтр спрашивает `TILE_SOLID`.
//
// Ориентация названа СПЛОШНЫМ УГЛОМ, а не направлением подъёма: «вверх направо» под +Y ВНИЗ читается
// двояко и требует помнить знак оси, а угол виден в раскладке глазами. `slope_br` — прямой угол
// внизу справа, гипотенуза из нижнего левого в верхний правый; остальные три получаются зеркалами.
constexpr TileFlags TILE_SLOPE = 1u << 1;
constexpr TileFlags TILE_SLOPE_FLIP_X = 1u << 2;   // зеркало по X: прямой угол переезжает влево
constexpr TileFlags TILE_SLOPE_FLIP_Y = 1u << 3;   // зеркало по Y: клин становится потолочным
constexpr TileFlags TILE_SLOPE_BITS = TILE_SLOPE | TILE_SLOPE_FLIP_X | TILE_SLOPE_FLIP_Y;

// Односторонний тайл — модификатор того, КАКИЕ ЕГО ГРАНИ держат, и живёт он тоже ВМЕСТЕ с телесным
// флагом (`solid oneway`, решение владельца 2026-08-24). Тайл остаётся сплошным для всякого
// запроса, спрашивающего `TILE_SOLID`, — а вот держать его будет только грань, СМОТРЯЩАЯ ВВЕРХ, и
// только тому, кто пришёл сверху. Решает это ЗАПРОС по хиту (`query.cpp`), а не карта: свип вниз
// обязан видеть платформу, свип вверх — нет, и разница эта про направление движения, которого у
// тайла нет.
//
// Со склоном бит НЕ сочетается, и разбор исходника эту пару отвергает: держащая грань склона —
// гипотенуза, а правило прихода сверху мерится верхом ТАЙЛА, и стоящий на нижней половине склона
// оказался бы ниже него. Бит, который в половине случаев молча не держит, хуже отказа.
constexpr TileFlags TILE_ONEWAY = 1u << 4;

// Диапазон тайлов, попавших в окно запроса. Полуинтервал по обеим осям и УЖЕ отсечён по карте,
// поэтому вызывающий обходит его без единой проверки границ.
struct TileWindow {
    int32_t x0 = 0;
    int32_t y0 = 0;
    int32_t x1 = 0;
    int32_t y1 = 0;

    bool empty() const { return x1 <= x0 || y1 <= y0; }
};

// Работа ЗАПРОСА к сетке. Отдельной структурой по тому же основанию, что `QueryCounters` у физики:
// цена запроса принадлежит запросу, и число, обнуляемое чужим шагом, непонятно кому принадлежит.
struct TileCounters {
    // Тайлы, дошедшие до геометрии, — то, что запрос рассмотрел сверх окна. Это мера ОКНА, и
    // отвечает она ровно на инвариант 4: обходим ли мы зонд или карту. Число попаданий на этот
    // вопрос не отвечает — попаданий может не быть потому, что уровень пустой.
    uint64_t scanned = 0;
};

class TileGrid;

namespace detail {

// Шов «запрос → счётчик», ровно тот же и по той же причине, что `physics::detail::QuerySeam`:
// запросы живут в другом TU и в безымянном пространстве, где `friend` их не назовёт, а публичная
// запись счётчика дала бы игре возможность соврать про цену. Замка тут не сделать, не затащив
// запросы внутрь класса; дверь названа.
struct TileQuerySeam {
    static void note(const TileGrid& g, uint64_t scanned);
};

} // namespace detail

class TileGrid {
public:
    // `tile_size` приводится к чётному числу raw и минимуму в два — обоснование обеих половин в
    // `grid.cpp`: нулевой размер схлопывает карту в ячейку, нечётный оставляет щель между тайлами.
    TileGrid(Vec2 origin, fix32 tile_size, uint32_t width, uint32_t height);

    void set(uint32_t x, uint32_t y, TileFlags flags);
    void fill(uint32_t x0, uint32_t y0, uint32_t x1, uint32_t y1, TileFlags flags);

    // Координаты ЗНАКОВЫЕ и за картой законны: вопрос «что за соседом» задаётся и на краю карты, и
    // ответ там обязан быть «пусто», а не выход за массив. Край карты — настоящая грань, и тайл
    // на нём обязан её отдавать.
    TileFlags at(int32_t x, int32_t y) const;
    bool solid_at(int32_t x, int32_t y) const { return (at(x, y) & TILE_SOLID) != 0; }

    uint32_t width() const { return width_; }
    uint32_t height() const { return height_; }
    Vec2 origin() const { return origin_; }
    fix32 tile_size() const { return tile_size_; }

    // Коробка тайла в мировых осях. Считается умножением на индекс, а не накоплением: накопление
    // копило бы и ошибку округления, и коробка дальнего тайла разъехалась бы с коробкой соседа.
    physics::Aabb tile_bounds(int32_t x, int32_t y) const;

    // Окно запроса: коробка в мировых осях → диапазон тайлов, отсечённый по карте. Деление берётся
    // ЦЕЛОЧИСЛЕННОЕ по сырому Q16.16 с округлением ВНИЗ, а не `fix32::operator/`: тот усекает к
    // нулю, и левее начала координат окно уезжало бы на тайл — ровно там, где карта с
    // отрицательным началом обычна.
    TileWindow window(const physics::Aabb& probe) const;

    const TileCounters& counters() const { return counters_; }

private:
    friend struct detail::TileQuerySeam;
    void note_scanned(uint64_t scanned) const { counters_.scanned = scanned; }

    Vec2 origin_;
    fix32 tile_size_;
    uint32_t width_ = 0;
    uint32_t height_ = 0;
    std::vector<TileFlags> flags_;
    mutable TileCounters counters_;
};

namespace detail {

inline void TileQuerySeam::note(const TileGrid& g, uint64_t scanned) {
    g.note_scanned(scanned);
}

} // namespace detail
} // namespace framework::tilemap
