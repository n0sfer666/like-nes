#include "shape.hpp"

// Свип формы вдоль отрезка — КОНСЕРВАТИВНОЕ ПРОДВИЖЕНИЕ (решение владельца, интервью 2026-08-09).
//
// Идея одна: пока формы разделены на `s`, а сближаются вдоль направления разделения со скоростью
// `c` на весь путь, за долю пути `s/c` они гарантированно не столкнутся — эта доля проходится
// целиком, и всё повторяется с нового места. Продвижение НИКОГДА не перепрыгивает касание, поэтому
// тонкая геометрия не теряется по построению, а не «при достаточно мелком шаге».
//
// Отвергнутая альтернатива — выборка вдоль пути в N точек — пропускает препятствие тоньше шага
// выборки, то есть ровно тот дефект, ради которого свип и заводят: пуля сквозь стену. Вторая
// альтернатива, луч по сумме Минковского, точна и не итеративна, но это отдельный геометрический код
// с нуля, который больше нигде не переиспользуется, — здесь же вся работа делается расстоянием между
// ядрами, у которого потребитель уже есть (`distance.hpp`).
//
// Луч — ЧАСТНЫЙ СЛУЧАЙ этого же свипа: форма из одной точки с нулевым радиусом. Отдельной
// трассировки поэтому нет вовсе, и это не экономия строк: две реализации разошлись бы на округлении,
// и «луч видит стену, а свип персонажа — нет» стало бы наблюдаемо через полгода, на конкретном угле.
namespace framework::physics {

// Свип не ВРАЩАЕТ форму: она переносится, а не поворачивается по пути. Ограничение названо здесь,
// потому что молчание о нём читалось бы как «поворот учтён». Игре, которой нужен поворот, дешевле
// разбить движение на несколько свипов, чем движку — тянуть его через всё продвижение.
struct CastHit {
    // Доля пути [0, 1] до касания. Ноль означает касание в НАЧАЛЕ пути — формы уже пересекались.
    fix32 fraction;
    Vec2 point;
    // Единичная, НАРУЖУ ИЗ ПРЕПЯТСТВИЯ — то есть навстречу движению. Это соглашение отличается от
    // нормали манифольда (та идёт из `a` в `b`), и отличается намеренно: нормаль свипа игра
    // применяет к отражению и скольжению вдоль стены, а там нужна нормаль ПОВЕРХНОСТИ, в которую
    // упёрлись, а не направление, в котором двигались.
    Vec2 normal;
};

// Потолок итераций продвижения. Сходимость линейная и быстрая почти всегда; медленный случай — путь
// ПОЧТИ КАСАТЕЛЬНЫЙ к препятствию, где сближение на шаг мало, а расстояние убывает медленно.
constexpr uint32_t MAX_CAST_ITERATIONS = 24;

// `moving` уже развёрнута и стоит в НАЧАЛЕ пути; `travel` — перенос целиком, от начала к концу.
// Возвращает false, только если путь свободен: исчерпанный потолок итераций считается касанием, см.
// обоснование в `cast.cpp`.
bool cast_shape(const WorldShape& moving, Vec2 center, Vec2 travel, const WorldShape& target,
                Vec2 target_center, CastHit& out);

} // namespace framework::physics
