#pragma once
#include "shape.hpp"

// Массовые характеристики формы: где у неё центр масс и насколько трудно её раскрутить.
//
// Отдельным файлом от `shape.cpp`, потому что это другая ответственность: там геометрия формы
// (что она такое), здесь — её инерция (как она отвечает на импульс). Смешать их значило бы
// получить файл, который правят и когда меняется набор форм, и когда меняется решатель.
namespace framework::physics {

// Центр масс однородной формы в её локальных координатах. Нужен `make_body`: тело вращается вокруг
// центра масс, а не вокруг начала координат, которое автор выбрал как ему удобно. Форма, заданная
// со смещением, поэтому не «смещается», а переносит на себя позицию тела.
Vec2 centroid(const Shape& s);

// Момент инерции, делённый на массу (юнит^2), относительно ЦЕНТРОИДА формы. Возвращается raw
// Q16.16 в int64, а не fix32, и это не перестраховка: у коробки 512x16 значение около 87000, то
// есть втрое за потолок Q16.16. Насыщение здесь означало бы не потерю точности, а тело, которое
// крутится в триста раз охотнее, чем должно; обратная величина, которую хранит тело, из int64
// получается честно и просто уходит в ноль на действительно огромных формах — то есть вращение
// запирается, что для такой формы и есть правда.
int64_t unit_inertia_raw(const Shape& s);

} // namespace framework::physics
