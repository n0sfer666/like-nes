// Разделяющая ось и отсечение грани — путь узкой фазы для форм, у которых есть рёбра (решение
// владельца: SAT + отсечение). Круг сюда не попадает: у него нет ни одной оси, которую можно
// перебрать, и его случай решается ближайшей точкой (см. `narrowphase.cpp`).
//
// Отсечение по Сазерленду—Ходжману нужно именно ради ДВУХ точек контакта. Одной точки хватает,
// чтобы тело не проваливалось, и не хватает, чтобы ящик стоял: одна точка не создаёт момента,
// удерживающего грань прижатой, и ящик на полу медленно заваливается на угол. Гейт 3 спеки #15
// (устойчивость стопки) — это ровно про разницу между одной точкой и двумя.
namespace framework::physics {

// Центры масс передаются отдельно от форм: плечи в манифольде отсчитываются от них, а `WorldShape`
// — это уже развёрнутая геометрия, в которой центр не отличим от любой другой точки.
//
// `margin` — спекулятивное поле: зазор, до которого пара всё ещё считается контактом (обоснование —
// `units.hpp`). Ноль означает точный контракт «только на перекрытии», и именно его берут запросы.
bool collide_sat(const WorldShape& a, Vec2 center_a, const WorldShape& b, Vec2 center_b, fix32 margin,
                 Manifold& out);

} // namespace framework::physics
