#pragma once
#include "fixed.hpp"
#include "fixmath.hpp"

// Контракт единиц и потолков физики. Отдельным файлом и первым — потому что незаписанное
// соглашение о единицах каждая подсистема напишет по-своему, и разойдутся они не на компиляции,
// а на golden-хеше через полгода. Тот же урок, что со знаком осей ввода (`engine/input/codes.hpp`).
//
// **1 юнит = 1 пиксель** (решение владельца, 2026-08-08). Так уже считает игра-образец
// (`SHIP_SPEED = from_int(340)`), поэтому между симуляцией и рендером нет ни одной конверсии,
// которую пришлось бы держать согласованной.
//
// **+X вправо, +Y ВНИЗ** — та же экранная система, что у ввода. Гравитация, соответственно,
// ПОЛОЖИТЕЛЬНА по Y; знак, взятый из школьной физики, дал бы мир, где всё падает вверх.
namespace framework::physics {

// Q16.16 насыщает на ±32768, и насыщение — не авария, а тихая ложь: тело, вылетевшее за диапазон,
// прилипает к границе вместо того, чтобы улететь. Потолки взяты с четырёхкратным запасом от
// насыщения, чтобы промежуточные величины (сумма позиции и шага, скорость после импульса)
// оставались в диапазоне и на вырожденном кадре.
constexpr fix32 WORLD_HALF = fix32::from_int(8192);        // мир: [-8192, +8192] по обеим осям
constexpr fix32 MAX_SPEED = fix32::from_int(2048);         // потолок модуля скорости, юнит/с
// Угол и угловая скорость меряются в ОБОРОТАХ и оборотах в секунду, а не в радианах: приведение к
// периоду в оборотах точно до бита (период равен единице), а в радианах — нет, и тело, крутящееся
// десять секунд, приезжало бы в угол, зависящий от того, сколько раз его успели свернуть.
// Обоснование целиком — `fixtrig.hpp`; здесь важно, что единица названа, а не подразумевается.
// Шестнадцать оборотов в секунду — почти оборот за кадр при 60 Гц: выше вращение всё равно
// перестаёт читаться глазом, а форма за шаг успевает провернуться мимо контакта.
constexpr fix32 MAX_ANG_SPEED = fix32::from_int(16);       // потолок угловой скорости, оборот/с

// Оборот в радианах — множитель между угловой скоростью в оборотах и линейной скоростью точки
// формы (v = TAU * w * r). Записан СЫРЫМ значением, а не выражением: 2*pi иррационально, и любая
// его запись есть выбор округления. Выбор сделан один раз и здесь; вторая запись того же числа в
// другом файле разошлась бы с этой на младшем разряде — и разницу нашёл бы golden-хеш, а не
// компилятор. Обратная величина рядом, потому что делить на TAU в решателе — это деление во
// внутреннем цикле ради константы.
constexpr fix32 TAU = fix32::from_raw(411775);             // 6.283185
constexpr fix32 INV_TAU = fix32::from_raw(10430);          // 0.159149

// Потолок полуразмера формы. Тоже не косметика: AABB считается как позиция ± полуразмер, и при
// сумме за 32768 границы НАСЫЩАЮТСЯ — а насыщенный AABB не «слишком большой», он неверный, и
// широкая фаза начинает разом и терять пары, и выдумывать их.
constexpr fix32 MAX_SHAPE_HALF = fix32::from_int(4096);

// Нижняя граница объёма формы. Ядро без площади — точка или отрезок — пересекается с чем-либо с
// нулевой вероятностью, поэтому такому ядру радиус назначается принудительно: тело с нулевым
// радиусом не «очень маленькое», оно НЕ СТАЛКИВАЕТСЯ, и узнать об этом можно только по тому, что
// оно уехало сквозь пол. Шестнадцатая юнита совпадает с допуском проникновения не случайно: ниже
// него контакт всё равно считается разрешённым.
constexpr fix32 MIN_SHAPE_EXTENT = fix32::from_float(0.0625);

// Потолки материала. Упругость выше единицы — это контакт, отдающий больше энергии, чем получил:
// мяч разгоняется от каждого удара до MAX_SPEED. Отрицательное трение ещё хуже: предел конуса
// Кулона считается как clamp(v, -limit, limit), и при отрицательном limit границы меняются
// местами — выражение вырождается в константу, то есть в постоянный касательный импульс из ниоткуда.
constexpr fix32 MAX_RESTITUTION = fix32::from_int(1);
constexpr fix32 MAX_FRICTION = fix32::from_int(4);

// Земное ускорение в пикселях — не 9.8: при 16 px на метр это ~157, но платформеры почти всегда
// берут больше, иначе прыжок ощущается «лунным». Значение — умолчание конфигурации мира, а не
// константа физики: игра вправе задать своё.
constexpr fix32 DEFAULT_GRAVITY_Y = fix32::from_int(1200);

// Допуск проникновения. Разрешать контакт до нуля нельзя: тела в стопке вечно колеблются вокруг
// точного касания, и колебание попадает в sim-хеш. Щель в 1/16 пикселя глазу невидима.
constexpr fix32 CONTACT_SLOP = fix32::from_float(0.0625);

// Поле СПЕКУЛЯТИВНОГО контакта: зазор, при котором пара уже отдаётся решателю, хотя формы ещё не
// перекрылись. Ширина взята не с потолка — это тот же CONTACT_SLOP, и равенство здесь несущее.
// Допуск уже объявляет полосу |глубина| <= 1/16 разрешённым контактом, поэтому полоса зазора той же
// ширины не расширяет понятие касания, а достраивает его симметрично: контакт живёт в [-1/16, +1/16]
// вокруг точного касания, и «почти коснулись» перестаёт означать «ничего не происходит».
//
// Без этого поля контакт рождался ТОЛЬКО на перекрытии, и башня, выставленная впритык, проваливалась
// сама в себя: пары нет — значит нет и опоры, ящик кадр падает свободно, и так по этажу за кадр
// сверху вниз. Замер на шести ящиках: просадка 7.3 юнита (почти полящика) за первые восемь кадров,
// ровно 21 кадр свободного падения по 0.333 юнита. Поле убирает это целиком: зазор 0 — уже контакт.
//
// Шире брать нельзя даром: спекулятивная точка входит в события и в счётчик касаний наравне с
// настоящей, а решателю она стоит гашения сближения РАНЬШЕ поверхности. Цена второго — ошибка
// отскока не больше SPECULATIVE_MARGIN / dt, то есть 3.75 юнит/с при 60 Гц; на поле в юнит она была
// бы уже 60 юнит/с, то есть шестая часть отскока с упругостью 0.6 при ударе на 600 юнит/с.
constexpr fix32 SPECULATIVE_MARGIN = CONTACT_SLOP;

// Ниже этой скорости сближения упругость не применяется. Без порога любой контакт под действием
// гравитации получает крошечный отскок каждый кадр, и стопка «кипит» вместо того, чтобы стоять.
constexpr fix32 RESTITUTION_CUTOFF = fix32::from_int(64);

// Доля проникновения, снимаемая за шаг позиционной коррекцией. Единица дала бы выталкивание
// рывком и передачу энергии в скорость через следующий кадр; общепринятая доля — 0.2.
constexpr fix32 POSITION_CORRECTION = fix32::from_float(0.2);

// Направление сохраняется, модуль заменяется: покомпонентный кламп превратил бы круг ограничения
// в квадрат и сделал бы диагональ быстрее прямой. Вся арифметика — в `clamp_length`, потому что
// «поделить на length()» потолка не даёт: длина насыщается, и множитель выходит завышенным.
inline Vec2 clamp_speed(Vec2 v, fix32 limit) { return clamp_length(v, limit); }

// Скорость, выше которой дискретный шаг перестаёт разрешать контакт правильно. **MAX_SPEED такого
// не обещает и обещать не может**, и это надо называть вслух: 2048 юнит/с — потолок АРИФМЕТИКИ, за
// которым насыщается Q16.16, а не гарантия против проскока.
//
// Контакт ищется по пересечению форм в сэмплированной позиции, а не по траектории между сэмплами.
// За шаг тело проходит speed * dt. Окно, внутри которого хотя бы один сэмпл обязан оказаться, —
// сумма ПОЛУРАЗМЕРОВ двух форм по оси движения, а не сумма толщин: сторону разрешения выбирает ось
// наименьшего перекрытия, по центрам, и тело, за один шаг проскочившее серединную плоскость
// препятствия, получает нормаль в спину и выталкивается наружу с той стороны, с которой пришло.
// Наблюдаемо это ровно то же, что и проскок насквозь.
//
// Замер: коробка 32x32 на пол толщиной 16 — окно 24 юнита, то есть потолок 1440 юнит/с при
// dt = 1/60. На 2048 (34 юнита за шаг) то же тело уходит сквозь пол. Непрерывное обнаружение (CCD)
// спека #15 выносит за скоуп явно, поэтому граница НАЗВАНА здесь, а не оставлена на догадку.
constexpr fix32 max_safe_speed(fix32 dt, fix32 half_sum) { return half_sum / dt; }

// Потолок угловой скорости КОНКРЕТНОГО тела: точка на его поверхности не вправе двигаться быстрее
// MAX_SPEED. Общего потолка в оборотах для этого мало, и разница не теоретическая — форма радиусом
// 4096 на 16 оборотах в секунду имеет поверхностную скорость 411 тысяч юнит/с, то есть выражение
// TAU * w * r насыщает Q16.16 в двенадцать раз. Насыщенная скорость точки контакта — это не
// «неточно быстро», это произвольное число, из которого решатель считает импульс.
//
// `reach` — расстояние от центра масс до самой дальней точки ПОВЕРХНОСТИ формы. Ноль означает, что
// формы фактически нет, и тогда ограничивать нечего.
constexpr fix32 max_angular_speed(fix32 reach) {
    if (!(reach.raw > 0)) return MAX_ANG_SPEED;
    // Знаменатель считается в int64 и БЕЗ насыщения. Произведение TAU * reach вылетает за Q16.16 уже
    // на 5215 юнитах, а насыщенный знаменатель — это потолок, ПЕРЕСТАЮЩИЙ зависеть от размера: у
    // всего, что больше, выходило одно и то же 0.0625 оборота в секунду, то есть поверхностная
    // скорость тем выше потолка, чем крупнее форма, — ровно наоборот тому, ради чего потолок введён.
    const int64_t denom = (static_cast<int64_t>(TAU.raw) * reach.raw) >> fix32::SHIFT;
    if (denom <= 0) return MAX_ANG_SPEED;
    const int64_t limit = (static_cast<int64_t>(MAX_SPEED.raw) * fix32::ONE) / denom;
    return min_fix(MAX_ANG_SPEED, fix32::from_raw(fix32::sat(limit)));
}

// Потолок НАКОПЛЕННОГО решателем (шкала относительной скорости, raw Q16.16 — см. комментарий к
// `ManifoldPoint::normal_impulse`). Относительная скорость двух тел не может превысить удвоенный
// потолок скорости, потому что клампятся оба, — значит и желаемое её изменение сверх этого
// физического смысла не имеет. Кламп нужен не для аккуратности: накопленное умножается на `k` при
// переносе шкалы тёплого старта и на `cone` в конусе Кулона, и оба произведения считаются в int64
// БЕЗ насыщения — то есть переполнение там было бы не «неточностью», а UB.
constexpr int64_t MAX_ACCUM = 2 * static_cast<int64_t>(MAX_SPEED.raw);

} // namespace framework::physics
