#pragma once
#include "shape.hpp"

// Расстояние между ЯДРАМИ двух форм и свидетель, на котором оно достигнуто.
//
// Отдельным файлом, а не приватной функцией зазора, по той же причине, по которой отдельно живёт
// `nearest.cpp`: на этот вопрос отвечают ДВА потребителя — контакт скруглений (`gap.cpp`) и свип
// формы (`cast.cpp`), — и написанные порознь они разъехались бы на округлении. Расхождение при этом
// было бы не «чуть разные числа»: свип, считающий расстояние иначе, чем узкая фаза, останавливает
// тело там, где узкая фаза контакта не видит, и наоборот — то есть персонаж либо застревает в
// воздухе, либо въезжает в стену на глазах у игрока.
namespace framework::physics {

// Итог перебора вершин. Идентификатор точки контакта здесь НЕ собирается: пространства
// идентификаторов принадлежат путям узкой фазы (`contact.hpp`), а свип к ним отношения не имеет.
// Возвращается сырой свидетель, а собирает идентификатор тот, кому он нужен.
struct CoreDistance {
    Vec2 on_a;         // точка ядра `a`, ближайшая к ядру `b`
    Vec2 dir;          // единичное, из `a` в `b` — та же ориентация, что у нормали манифольда
    fix32 dist;        // между ЯДРАМИ, со знаком; радиусы вычитает вызывающий, их два
    uint8_t vertex = 0;      // номер вершины-свидетеля
    bool witness_in_a = false;  // свидетель — вершина `a` (иначе вершина `b`)
};

// ПРЕДУСЛОВИЕ: ядра НЕ пересекаются — то же самое, что у `collide_core_gap`, и по той же причине.
// Минимум расстояния между непересекающимися выпуклыми множествами достигается хотя бы в одной
// вершине, поэтому перебора вершин достаточно. У ПЕРЕСЕКАЮЩИХСЯ ближайшая пара лежит на скрещении
// рёбер, все вершины дают положительное расстояние, и ответ вышел бы «формы разошлись» на настоящем
// перекрытии. Отрицательный `dist` здесь законен и означает другое: вершина одной формы залезла
// внутрь ядра другой, и на такой паре перебор точен.
CoreDistance core_distance(const WorldShape& a, const WorldShape& b);

} // namespace framework::physics
