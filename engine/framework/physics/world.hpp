// Мир физики: хранилище тел и один шаг симуляции. Шаг ФИКСИРОВАННЫЙ — `dt` приходит снаружи, из
// стадии `Stage::Sim` расписания слоя (#14), и мир не имеет права его придумывать: переменный шаг
// делает результат функцией частоты кадров, то есть железа.
namespace framework::physics {

// Дескриптор тела — индекс, а не указатель: указатель протух бы при росте вектора, а индекс
// переживает любое добавление. Тела не удаляются (вертикаль 1), поэтому индекс стабилен.
struct BodyId {
    static constexpr uint32_t INVALID = 0xffffffffu;
    uint32_t index = 0;
    bool valid() const { return index != INVALID; }
};

// Бюджет пар на тело — размер РЕЗЕРВА, а не предел. Сцена, которая его перебрала, получит
// аллокацию посреди шага, и гейт 6 про неё скажет; сцена, которой контакт молча не выдали, ничего
// не скажет — тело просто провалится сквозь пол на глазах у игрока. Пропущенная аллокация дешевле
// пропущенного контакта, поэтому предела здесь нет намеренно.
constexpr uint32_t PAIR_BUDGET_PER_BODY = 16;

class World {
public:
    // `capacity` — размер РЕЗЕРВА тел, по той же логике, что и бюджет пар: это граница, внутри
    // которой обещан ноль аллокаций в шаге, а не предел числа тел. Сцена, перебравшая её, получит
    // реаллокацию — и гейт 6 про неё скажет. Отказывать в добавлении было бы хуже: не добавленное
    // тело не скажет ничего, оно просто не существует.
    //
    // Обещание нуля аллокаций держится на ДВУХ границах сразу, и вторая жёстче первой: число тел не
    // выше `capacity` И число пересечений AABB, ГДЕ ХОТЯ БЫ ОДНО ТЕЛО ПОДВИЖНО, не выше
    // `capacity * PAIR_BUDGET_PER_BODY`. Оговорка про подвижность не формальность: пару из двух
    // неподвижных тел широкая фаза отбрасывает до записи в список (`broadphase.cpp`), поэтому пол из
    // тысячи статических плиток бюджет не тратит вовсе, — а без оговорки контракт требовал бы от
    // игры больше, чем код.
    //
    // Худший случай второй границы — квадратичный, n(n-1)/2, и он перерастает линейный резерв уже с
    // 34 тел, так что плотная куча внутри заявленной ёмкости своё расширение всё-таки получит.
    // Резерв здесь рассчитан на разреженную сцену, а не на худший случай: честный квадрат на 500
    // телах это ~125 тысяч манифольдов, десятки мегабайт под редчайшую раскладку.
    //
    // Расширение при этом АМОРТИЗИРУЕТСЯ, а не случается один раз: ёмкость вектора остаётся у мира
    // между шагами, но растёт она по максимуму за прогон, и каждый кадр, где пар больше, чем во всех
    // предыдущих, снова стоит аллокации. Оседающая куча уплотняется не за один шаг, поэтому гейт 6
    // держит формулировку по правде: после ПРОГРЕВА шаги идут без единой аллокации, а не после
    // первого.
    explicit World(uint32_t capacity);

    // Смена тяготения БУДИТ всё замершее, и это не любезность, а условие корректности: замерший
    // остров тяготения не читает вовсе, поэтому перевёрнутая гравитация не подняла бы его никогда —
    // ни в этом кадре, ни в тысячном. Отказ выглядел бы не как ошибка, а как «физика сломалась».
    //
    // Сравнение перед пробуждением обязательно: игра вправе выставлять тяготение каждый кадр из
    // конфигурации, и безусловное пробуждение отменяло бы правило покоя целиком — тем же тихим
    // способом, каким это делало чтение через неконстантный `body()`.
    void set_gravity(Vec2 g) {
        if (g.x.raw == gravity_.x.raw && g.y.raw == gravity_.y.raw) return;
        gravity_ = g;
        rest_.wake_all();
    }
    Vec2 gravity() const { return gravity_; }

    // Возвращает невалидный дескриптор, если ключ уже занят. Проверка стоит здесь, а не в
    // документации: на уникальности ключа стоит ВЕСЬ детерминизм модуля, и дубль ломает его не
    // громко, а тихо — оба компаратора видят равные ключи как равные элементы, порядок равных
    // introsort не определяет, и результат начинает зависеть от реализации стандартной библиотеки,
    // то есть от ОС. Цена — квадрат от числа тел НА ЗАГРУЗКЕ уровня; шага она не касается.
    BodyId add(const BodyDesc& d);

    // Неконстантная ручка тела — путь, которым игра его правит: толкает, переставляет, меняет маску
    // или роль. Ручка при этом НИЧЕГО не делает с правилом покоя, и это осознанно.
    //
    // Отвечать на выдачу ручки нечем: перегрузку выбирает КОНСТАНТНОСТЬ МИРА, а не намерение
    // вызывающего, поэтому сюда попадает и цикл отрисовки, каждый кадр читающий трансформации. Буди
    // эта строка остров — правило покоя выключилось бы молча (окно не досчитало бы до `REST_FRAMES`
    // ни разу); размораживай «на кадр» — чтение мира двигало бы мир, и хеш состояния расходился бы
    // между прогоном с отрисовкой и без неё. Поэтому правка замечается СВЕРКОЙ в начале следующего
    // шага (`rest.hpp`, вторая дверь): замершее тело обязано быть равно копии, снятой при заморозке.
    //
    // Наблюдаемое следствие, которое стоит знать вызывающему: сразу после правки `at_rest()` ещё
    // говорит «замерло» — правка вступает в силу шагом, а не присваиванием. Нужно немедленно и
    // наверняка (правка не тела, а чего-то, что мир о теле помнит) — `wake()` ниже.
    Body& body(BodyId id) { return bodies_[id.index]; }
    const Body& body(BodyId id) const { return bodies_[id.index]; }
    const std::vector<Body>& bodies() const { return bodies_; }

    // Замирание острова — правило покоя из `rest.hpp`. Часть ШАГА, а не оптимизация: оно действует
    // всегда, выключателя у него нет, и хеш состояния его учитывает.
    bool at_rest(BodyId id) const { return rest_.frozen(id.index); }
    void wake(BodyId id) { rest_.wake(id.index, islands_); }

    // Сон — гейт 5 спеки #15 — это ровно одно: для замершей пары не считать узкую фазу, а взять
    // манифольд прошлого кадра из кеша. Больше он не делает НИЧЕГО, поэтому выключатель не трогает
    // ни состояние, ни счётчики покоя: гейт сверяет два прогона одной сцены и обязан получить
    // одинаковые хеши бит в бит, а выключатель, что-то по дороге сбрасывающий, давал бы им разные
    // входы. Игре он тоже доступен — сцена, где важнее предсказуемая цена шага, чем её величина,
    // вправе экономию запретить.
    void set_sleep_enabled(bool on) { sleep_enabled_ = on; }
    bool sleep_enabled() const { return sleep_enabled_; }
    // Сколько пар последнего шага геометрию не считали, а взяли из кеша. Счётчик наружу выведен
    // ради гейта 5, и это не «тест лезет во внутренности»: гейт сверяет два прогона одной сцены и
    // без такого счётчика зелен вакуумно — мир, у которого ветка сна ни разу не сработала, сверяет
    // один и тот же код сам с собой и не отличим от мира, у которого она работает. Утверждение
    // «спало N кадров» этой дыры не закрывает: оно про то, что тела ЗАМЕРЗЛИ, а сон — про то, что
    // на замерших сэкономили. Заглуши `recall` в `return false` — замирание останется прежним.
    uint32_t recalled_pairs() const { return static_cast<uint32_t>(counters_.recalled); }
    // Тело спит, когда оно замерло И экономия разрешена. Разделение видно наружу намеренно: игре
    // важно «стоит ли ящик» (`at_rest`), профилю — «сэкономили ли мы на нём узкую фазу».
    bool sleeping(BodyId id) const { return sleep_enabled_ && rest_.frozen(id.index); }

    // Число ПАР с контактом, а не точек: пара «грань об грань» даёт две точки, и считать их значило
    // бы получить счётчик, который меняется от того, под каким углом лежит ящик. Замершие пары
    // входят сюда наравне с решаемыми: касание, которое перестало решаться, касаться не перестало, и
    // счётчик, падающий от замирания, сообщал бы игре о расцеплении, которого не было.
    uint32_t contact_count() const {
        return static_cast<uint32_t>(manifolds_.size() + resting_.size());
    }
    // Пересечения с телами-триггерами считаются отдельно и в `contact_count` не входят: контакт —
    // это то, что разрешает решатель, а перекрытие зоны он не разрешает по определению.
    uint32_t trigger_count() const { return static_cast<uint32_t>(triggers_.size()); }

    void step(fix32 dt);

    // Работа, которую стоил ПОСЛЕДНИЙ шаг, — гейт 8 спеки #15, обоснование величин в `counters.hpp`.
    // Наружу выведено по той же причине, что и `recalled_pairs()`: гейт, меряющий цену шага по
    // стенным часам, на раннере CI флейкует, а по этим величинам утверждается точно и одинаково на
    // трёх ОС.
    const WorkCounters& counters() const { return counters_; }

    // События последнего шага, по возрастанию ключа пары. Буфер живёт до СЛЕДУЮЩЕГО шага и им же
    // затирается: копию, пережившую шаг, никто не обязан поддерживать в осмысленном виде — ключи в
    // ней остались бы валидными, а глубина и точка описывали бы позапрошлый кадр.
    const std::vector<ContactEvent>& events() const { return events_; }

    // Накопительный голден потока событий, обоснование — `event_hash.hpp`. Отдельно от `hash()`,
    // потому что отвечает на другой вопрос и краснеет по другим причинам.
    uint64_t event_hash() const { return event_hash_; }

    // Хеш состояния по возрастанию ключа — гейты 1 и 2 спеки #15. Не const-функция по буферу, но
    // логически const, поэтому буфер `mutable`: заставлять вызывающего таскать скретч через весь
    // тест значило бы вынести деталь реализации в его код. Цена сказана прямо: `mutable` делает
    // метод НЕРЕЕНТЕРАБЕЛЬНЫМ — два потока, зовущих `hash()` на одном мире (запись реплея и
    // сетевой прогноз — ровно те, кто его зовёт), перетопчут общий скретч.
    uint64_t hash() const;

private:
    std::vector<Body> bodies_;
    std::vector<Pair> pairs_;
    std::vector<Manifold> manifolds_;
    // Отдельный список, а не флаг на манифольде. Флаг заставил бы решатель спрашивать «а это не
    // триггер?» в трёх местах — подготовка, скорости, позиции, — то есть знать про роль тела в игре;
    // раздельные списки оставляют решателю ровно то, что он решает. Тем же разделением триггеры не
    // попадают в кеш тёплого старта: накапливать импульс для контакта, который никогда не решается,
    // значило бы тратить его бюджет на пустое.
    std::vector<Manifold> triggers_;
    // Контакты замерших островов. Третий список по той же причине, по которой второй, — у него
    // другой потребитель. Решателю он не нужен (остров неподвижен по правилу покоя), событиям,
    // связности и кешу нужен целиком. Именно ЗДЕСЬ проходит граница сна: со сном эти манифольды
    // отданы кешем без пересчёта, без сна — посчитаны узкой фазой заново. Содержимое обязано
    // совпасть бит в бит, и гейт 5 спрашивает ровно это.
    std::vector<Manifold> resting_;
    Broadphase broad_;
    Islands islands_;
    RestTracker rest_;
    bool sleep_enabled_ = true;
    ManifoldCache cache_;
    ContactTracker tracker_;
    std::vector<ContactEvent> events_;
    uint64_t event_hash_ = 0;
    mutable std::vector<uint32_t> scratch_;
    WorkCounters counters_;
    Vec2 gravity_ = {fix32{}, DEFAULT_GRAVITY_Y};
};

} // namespace framework::physics
