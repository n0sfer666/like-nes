#pragma once
#include <vector>

#include "body.hpp"
#include "broadphase.hpp"
#include "contact.hpp"

// Мир физики: хранилище тел и один шаг симуляции. Шаг ФИКСИРОВАННЫЙ — `dt` приходит снаружи, из
// стадии `Stage::Sim` расписания слоя (#14), и мир не имеет права его придумывать: переменный шаг
// делает результат функцией частоты кадров, то есть железа.
namespace framework::physics {

// Дескриптор тела — индекс, а не указатель: указатель протух бы при росте вектора, а индекс
// переживает любое добавление. Тела не удаляются (вертикаль 1), поэтому индекс стабилен.
struct BodyId {
    static constexpr uint32_t INVALID = 0xffffffffu;
    uint32_t index = 0;
    bool valid() const { return index != INVALID; }
};

// Бюджет пар на тело — размер РЕЗЕРВА, а не предел. Сцена, которая его перебрала, получит
// аллокацию посреди шага, и гейт 6 про неё скажет; сцена, которой контакт молча не выдали, ничего
// не скажет — тело просто провалится сквозь пол на глазах у игрока. Пропущенная аллокация дешевле
// пропущенного контакта, поэтому предела здесь нет намеренно.
constexpr uint32_t PAIR_BUDGET_PER_BODY = 16;

class World {
public:
    // `capacity` — размер РЕЗЕРВА тел, по той же логике, что и бюджет пар: это граница, внутри
    // которой обещан ноль аллокаций в шаге, а не предел числа тел. Сцена, перебравшая её, получит
    // реаллокацию — и гейт 6 про неё скажет. Отказывать в добавлении было бы хуже: не добавленное
    // тело не скажет ничего, оно просто не существует.
    explicit World(uint32_t capacity);

    void set_gravity(Vec2 g) { gravity_ = g; }
    Vec2 gravity() const { return gravity_; }

    // Возвращает невалидный дескриптор, если ключ уже занят. Проверка стоит здесь, а не в
    // документации: на уникальности ключа стоит ВЕСЬ детерминизм модуля, и дубль ломает его не
    // громко, а тихо — оба компаратора видят равные ключи как равные элементы, порядок равных
    // introsort не определяет, и результат начинает зависеть от реализации стандартной библиотеки,
    // то есть от ОС. Цена — квадрат от числа тел НА ЗАГРУЗКЕ уровня; шага она не касается.
    BodyId add(const BodyDesc& d);
    Body& body(BodyId id) { return bodies_[id.index]; }
    const Body& body(BodyId id) const { return bodies_[id.index]; }
    const std::vector<Body>& bodies() const { return bodies_; }
    uint32_t contact_count() const { return static_cast<uint32_t>(contacts_.size()); }

    void step(fix32 dt);

    // Хеш состояния по возрастанию ключа — гейты 1 и 2 спеки #15. Не const-функция по буферу, но
    // логически const, поэтому буфер `mutable`: заставлять вызывающего таскать скретч через весь
    // тест значило бы вынести деталь реализации в его код. Цена сказана прямо: `mutable` делает
    // метод НЕРЕЕНТЕРАБЕЛЬНЫМ — два потока, зовущих `hash()` на одном мире (запись реплея и
    // сетевой прогноз — ровно те, кто его зовёт), перетопчут общий скретч.
    uint64_t hash() const;

private:
    std::vector<Body> bodies_;
    std::vector<Pair> pairs_;
    std::vector<Contact> contacts_;
    Broadphase broad_;
    mutable std::vector<uint32_t> scratch_;
    Vec2 gravity_ = {fix32{}, DEFAULT_GRAVITY_Y};
};

} // namespace framework::physics
