// Голден потока событий — ОТДЕЛЬНЫЙ от голдена состояния (решение владельца, интервью 2026-08-09).
//
// Отдельный, потому что вопросы разные. Хеш состояния отвечает «сошлись ли позиции и скорости», и
// свернуть в него ещё и события значило бы получить один голден, который краснеет на любой из двух
// причин и не называет, на какой. Хуже: события — производная от контактов, а не от состояния, и
// пара, которая касается на кадр раньше, состояние на этом кадре ещё не меняет. Общий хеш проглотил
// бы такую перестановку молча ровно до тех пор, пока она не сдвинет тело.
//
// Свёртка — НАКОПИТЕЛЬНАЯ по кадрам: голден снимается с прогона целиком, а не с последнего кадра.
// Событие живёт один кадр и в состоянии следов не оставляет, поэтому «хеш событий последнего кадра»
// был бы хешем пустоты в тот же миг, как сцена улеглась.
