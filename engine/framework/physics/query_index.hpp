#include <vector>

#include "body.hpp"
#include "counters.hpp"

// Ускоряющая структура ЗАПРОСОВ — sweep-and-prune по X, живущий между шагами (перф-раунд перед
// вертикалью 2 спеки #16).
//
// Широкая фаза шага (`broadphase.cpp`) отвечает на другой вопрос и здесь не годится: она строит
// ПАРЫ из списка тел, а запрос — это одна форма против всех. Общего у них ровно сортировка, и
// делить её значило бы делить состояние между шагом и запросом, то есть завести у ЧИТАЮЩЕЙ операции
// зависимость от того, был ли шаг. Общий КОД порядка при этом вынесен — `sweep_order.hpp`.
//
// Почему SAP, а не сетка, — по тому же основанию, что в `broadphase.cpp`: сетке нужен размер
// ячейки, подобранный под типичный размер тела, а SAP не настраивается ничем.
//
// Полоса ищется ДВУМЯ двоичными поисками, и второй неочевиден. Порядок отсортирован по ЛЕВОМУ краю,
// поэтому тела правее запроса отсекаются верхней границей сразу. А вот тело, начинающееся левее
// запроса, может доставать до него правым краем — и отсечь такие одним сравнением нечем. Поэтому
// рядом с порядком лежит ПРЕФИКСНЫЙ МАКСИМУМ правых краёв: он не убывает по построению, значит
// множество позиций, где он ещё меньше левого края запроса, — это префикс, и его граница ищется
// двоично. Без него нижняя граница была бы всегда нулём, то есть скан шёл бы от начала списка и
// выигрыш оставался бы только на телах справа.
//
// Шов протухания — `World::mutate()`, и метится индекс по факту ВЫДАЧИ ручки, а не по факту
// записи: узнать о записи мир не может, ссылку он уже отдал. Отсюда ГРАНИЦА контракта, названная
// там же: ручка действительна до ближайшего запроса или шага. Ссылка, пережившая запрос между своей
// выдачей и записью, оставляет индекс чистым и протухшим одновременно — запрос успел перестроить
// его до того, как в тело написали. Замка на это нет, а надежда на «никто так не пишет» дефектом
// уже бывала, поэтому граница стоит утверждением в комментарии, а не в голове.
//
// Консервативность пометки дешева и несимметрична по цене ошибки: лишняя перестройка стоит одного
// лога сортировки, а индекс, отставший от тел, отвечает не медленно, а НЕВЕРНО — тело, которого
// запрос не видит там, куда его только что переставили. Перестройка при этом ленивая, а не по месту
// правки: игра, переставляющая сто тел подряд, иначе платила бы сто сортировок за один запрос.
namespace framework::physics {

// Полоса кандидатов — полуинтервал позиций В ПОРЯДКЕ, а не в списке тел.
struct Band {
    uint32_t begin = 0;
    uint32_t end = 0;
};

class QueryIndex;

namespace detail {

// Шов «полоса → счётчик»: цена запроса принадлежит запросу, и писать её вправе только он. Именован
// он потому, что публичным быть не должен, а закрытым для `scan_band` стать не может — тот живёт в
// другом TU и другом (безымянном) пространстве, где `friend` его не назовёт. Замка тут не сделать,
// не затащив функции запроса внутрь класса; дверь названа, и из игры она пишется только руками.
struct QuerySeam {
    static void note(const QueryIndex& index, uint64_t scanned);
};

} // namespace detail

class QueryIndex {
public:
    void reserve(uint32_t capacity);

    // Пометить протухшим. Зовётся из мира на КАЖДОЙ двери, за которой тело меняется: добавление,
    // именованная правка (`World::mutate`) и шаг. Читающих дверей здесь нет — чтение тела мир не
    // меняет; про границу именованной правки сказано выше.
    void invalidate() { dirty_ = true; }

    // Полоса кандидатов по X. Тела вне неё не пересекаются с запросом по X ни при каком Y, поэтому
    // узкую фазу для них звать не за чем; тела ВНУТРИ кандидатами и остаются — полоса надмножество,
    // как и положено широкой фазе, и полный тест AABB вызывающий делает сам.
    //
    // Приведение индекса в соответствие — ЧАСТЬ ответа, а не шаг перед ним: тип, чей главный риск —
    // ответить не медленно, а НЕВЕРНО, не вправе позволять спросить себя до перестройки. Ёмкость
    // векторов её переживает, поэтому после прогрева она не ходит в кучу — то же обещание и та же
    // его граница, что у бюджета пар в `world.hpp`. Метод константный, а внутренности `mutable`, и
    // цена та же, что у `World::hash()`: ленивая перестройка делает его НЕРЕЕНТЕРАБЕЛЬНЫМ.
    Band band(const std::vector<Body>& bodies, const Aabb& probe) const;

    uint32_t body_at(uint32_t slot) const { return order_[slot]; }
    const Aabb& bounds_at(uint32_t slot) const { return bounds_[order_[slot]]; }
    const QueryCounters& counters() const { return counters_; }

private:
    friend struct detail::QuerySeam;
    void note_scanned(uint64_t scanned) const { counters_.scanned = scanned; }
    void refresh(const std::vector<Body>& bodies) const;
    uint32_t band_begin(fix32 min_x) const;
    uint32_t band_end(fix32 max_x) const;

    mutable std::vector<uint32_t> order_;
    mutable std::vector<Aabb> bounds_;
    mutable std::vector<fix32> prefix_max_x_;
    mutable QueryCounters counters_;
    mutable bool dirty_ = true;
};

namespace detail {

inline void QuerySeam::note(const QueryIndex& index, uint64_t scanned) {
    index.note_scanned(scanned);
}

} // namespace detail
} // namespace framework::physics
