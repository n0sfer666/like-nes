// Контакт, у которого пересеклись ТОЛЬКО скругления: ядра разошлись, а формы — нет.
//
// Теорема о разделяющей оси перебирает нормали ГРАНЕЙ, и этого достаточно ровно до тех пор, пока
// пересечение выражается гранями. Скругление их не имеет: ближайшая точка круглой поверхности лежит
// на оси, которой нет ни в одном списке нормалей. У пары «отрезок об отрезок» это не экзотика, а
// обычное дело — у ядра-отрезка обе нормали перпендикулярны ему самому, оси ВДОЛЬ отрезка нет вовсе,
// и две коллинеарные капсулы, разнесённые на полюнита при сумме радиусов в восемь, проходили SAT как
// пересекающиеся, а отсечение боковыми плоскостями выбрасывало у них все точки до одной. Наблюдаемо
// это было «капсула пролетает сквозь статическую капсулу насквозь»: узкая фаза отвечала «контакта
// нет» на настоящем перекрытии.
//
// Отдельным файлом, а не веткой внутри `sat.cpp`: вопрос здесь другой — не «по какой грани
// разъезжаться», а «насколько разошлись ядра», — и отвечает на него расстояние, а не проекции.
namespace framework::physics {

// Идентификаторы точек этого пути живут в СВОЁМ пространстве (`CORE_GAP_ID_BIT`, правило целиком —
// `contact.hpp`).
//
// ПРЕДУСЛОВИЕ: ядра НЕ пересекаются. Перебор вершин находит минимум расстояния только у
// непересекающихся выпуклых множеств; у пересечения ближайшая пара лежит на скрещении рёбер, все
// вершины дают положительное расстояние, и путь ответил бы «контакта нет» на настоящем перекрытии —
// ровно тот отказ, ради которого файл написан. Держать предусловие обязан вызывающий, и он это
// умеет: пересечение ядер он доказывает перебором граней и отвечает на него сам, опорной осью
// (`sat.cpp`, `axis_contact`). Единственная пара, где такого доказательства нет, — два ОТРЕЗКА (все
// четыре нормали перпендикулярны общей прямой), но ей оно и не нужно: пара отрезков либо расходится,
// и перебор вершин на ней точен, либо скрещивается, и тогда отсечение выдаёт точку само.
bool collide_core_gap(const WorldShape& a, Vec2 center_a, const WorldShape& b, Vec2 center_b,
                      Manifold& out);

} // namespace framework::physics
