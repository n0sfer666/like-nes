// Решатель последовательных импульсов. Контакты обрабатываются по одному, по очереди, и проход
// повторяется фиксированное число раз.
//
// **Число итераций — часть контракта детерминизма, а не настройка производительности** (решение
// владельца, спека #15). Решатель, останавливающийся «когда сойдётся», сходится за разное число
// проходов на разных входах и в общем случае за разное — на разных ОС, если критерий сходимости
// хоть где-то смотрит на округление. Фиксированное число даёт одинаковый результат ценой того,
// что очень высокая стопка слегка проседает; это видимый и предсказуемый недостаток, а
// расходящийся golden-хеш — невидимый.
namespace framework::physics {

constexpr uint32_t VELOCITY_ITERATIONS = 8;

// Позиционная коррекция — один проход, и это не «пока хватит». Глубина проникновения внутри
// прохода НЕ пересчитывается (постоянного манифольда у вертикали 1 ещё нет), поэтому второй
// проход не сходился бы к нулю, а просто применил ту же долю от той же глубины повторно — то
// есть тихо умножил бы `POSITION_CORRECTION` на число итераций. Пересчёт придёт вместе с
// манифольдом в вертикали 2, и тогда у константы появится смысл быть больше единицы.
constexpr uint32_t POSITION_ITERATIONS = 1;

void solve_velocity(std::vector<Body>& bodies, std::vector<Contact>& contacts);
void solve_position(std::vector<Body>& bodies, const std::vector<Contact>& contacts);

} // namespace framework::physics
