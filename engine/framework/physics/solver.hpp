// Решатель последовательных импульсов. Точки контакта обрабатываются по одной, по очереди, и проход
// повторяется фиксированное число раз.
//
// **Число итераций — часть контракта детерминизма, а не настройка производительности** (решение
// владельца, спека #15). Решатель, останавливающийся «когда сойдётся», сходится за разное число
// проходов на разных входах и в общем случае за разное — на разных ОС, если критерий сходимости
// хоть где-то смотрит на округление. Фиксированное число даёт одинаковый результат ценой того,
// что очень высокая стопка слегка проседает; это видимый и предсказуемый недостаток, а
// расходящийся golden-хеш — невидимый.
namespace framework::physics {

// Число ЧЁТНОЕ, и это условие, а не совпадение: точки манифольда обходятся попеременно вперёд и
// назад (`solver.cpp`), и только при чётном числе итераций каждая из них одинаково часто оказывается
// первой. Нечётное вернуло бы систематический момент, ради снятия которого обход и заведён.
//
// Величина задаёт ГЛУБИНУ СТЕКА, который движок держит, и держит её линейно: импульс идёт по цепи
// контактов по одному за итерацию. Замерено (`framework_physics_depth_test`) прогоном башни по
// одному ящику до первой упавшей:
//
//     итераций | mu >= 0.05 | mu = 0
//            8 |  8 ящиков  | 2 ящика
//           16 | 10 ящиков  | 3 ящика
//
// Трение стоит в таблице отдельной колонкой, потому что оно не условие корректности, а второй
// источник сходимости: недобранное итерациями оно рассеивает. Ящик на нулевом трении — законный
// материал, ему просто нечем гасить остаток, и граница у него своя.
//
// За границей башня НЕ проседает — она заваливается: недорешённый импульс оставляет
// систематический момент, тот копит наклон, наклонённая нормаль сходит с вертикали и даёт
// горизонталь. Это дефект сходимости, а не геометрии: `unit_inertia = 0` на каждом ящике делает
// стабильными и 24 ящика при нулевом трении, и 16 при штатном.
constexpr uint32_t VELOCITY_ITERATIONS = 16;

// Позиционная коррекция — по-прежнему один проход. Постоянный манифольд появился, но глубина
// проникновения внутри прохода всё ещё НЕ пересчитывается: для этого пришлось бы гонять узкую фазу
// по разу на итерацию. Второй проход поэтому не сходился бы к нулю, а применил ту же долю от той же
// глубины повторно — то есть тихо умножил бы `POSITION_CORRECTION` на число итераций.
constexpr uint32_t POSITION_ITERATIONS = 1;

// `dt` — тот же шаг, которым мир интегрирует, и передаётся он ради спекулятивной цели: зазор
// контакта переводится в разрешённую скорость сближения только делением на шаг (`prepare.cpp`).
//
// Обе функции возвращают число ПРИМЕНЁННЫХ проекций — гейт 8 спеки #15. Именно применённых:
// точку с нулевой эффективной обратной массой скоростной решатель пропускает, а позиционный
// пропускает точку без избытка проникновения над допуском, — то есть произведение «манифольды на
// точки на итерации» назвало бы работу, которой никто не делал, и на замершей сцене показало бы
// полную загрузку там, где решатель не тронул ни одной точки.
uint64_t solve_velocity(std::vector<Body>& bodies, std::vector<Manifold>& manifolds, fix32 dt);
uint64_t solve_position(std::vector<Body>& bodies, const std::vector<Manifold>& manifolds);

} // namespace framework::physics
