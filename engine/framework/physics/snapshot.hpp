// Снимок состояния мира физики и его возврат — основание отката (шаг A вертикали 1 спеки #22).
//
// Снимок ЗНАЕТ мир изнутри, а не наоборот: `World` не растёт двумя методами сериализации, а
// снимок объявлен его другом. Граница проведена так, потому что вопрос «что именно составляет
// состояние» принадлежит откату, а не шагу симуляции: мир обязан считать тик, а не помнить, кто и
// зачем его копирует.
//
// Обещание снимка — не «те же позиции», а НЕОТЛИЧИМОСТЬ: мир после возврата обязан отвечать на
// каждый публичный вопрос ровно то же, что отвечал в точке снятия. Отсюда два рода полей.
//
// Первый — то, что ЧИТАЕТ ШАГ до того, как перезаписать: тела, связность островов (её берёт
// `wake_touched` в начале шага, а пересобирает он же в конце), правило покоя, кеш тёплого старта,
// диффер контактов и накопительный хеш событий. Потеряй любое — переигранный тик разойдётся.
//
// Второй — то, что шаг перезаписывает целиком, но что мир отдаёт наружу МЕЖДУ шагами: списки
// контактов, триггеров и замерших пар, буфер событий и счётчики работы. Симуляции они не нужны, а
// вот игре, которая после отката спросит `contact_count()` или `events()` до следующего шага,
// нужны — иначе она получит ответ из будущего, которого больше не случится.
//
// Что НЕ входит и почему — утверждение, а не умолчание:
//   * `pairs_` и `broad_` — обе половины широкой фазы. Она clear-ит и заполняет свои буферы заново
//     в первой строке шага, и наружу их не отдаёт никто: это скретч, а не состояние;
//   * `scratch_` — скретч обхода хеша, живёт внутри одного вызова;
//   * `queries_` — индекс запросов. Копировать его было бы ХУЖЕ, чем не копировать: индекс несёт
//     флаг «чист», и снимок, вернувший чистый индекс к телам прошлого тика, отдавал бы запросам
//     позиции, которых уже нет. Возврат его метит протухшим.
//
// Ёмкость векторов остаётся у снимка между снятиями, поэтому второе и следующие снятия одной
// сцены идут без единой аллокации — на этом стоит гейт 4 спеки #22.
namespace framework::physics {

class World;

struct WorldSnapshot {
    // Снять состояние мира. Первое снятие сцены платит аллокациями за ёмкость, дальнейшие — нет.
    void capture(const World& w);
    // Вернуть мир в снятое состояние. Списки возвращаются ЦЕЛИКОМ, а не поэлементно: тело,
    // добавленное после снятия, из мира исчезает — это и есть верная семантика отката, потому что
    // в переигранных тиках его добавления ещё не случилось. Держатель его `BodyId` обязан знать,
    // что индекс живёт не дольше кадра, в котором выдан.
    void apply(World& w) const;

    bool taken() const { return taken_; }
    // Тиков в снимке нет: номер тика — свойство ОТКАТА, а не состояния мира. Мир не знает, какой
    // сейчас тик, и знать не должен — иначе снимок стал бы вторым источником правды о времени.

private:
    std::vector<Body> bodies_;
    std::vector<Manifold> manifolds_;
    std::vector<Manifold> triggers_;
    std::vector<Manifold> resting_;
    Islands islands_;
    RestTracker rest_;
    ManifoldCache cache_;
    ContactTracker tracker_;
    std::vector<ContactEvent> events_;
    WorkCounters counters_;
    uint64_t event_hash_ = 0;
    Vec2 gravity_{};
    bool sleep_enabled_ = true;
    bool taken_ = false;
};

} // namespace framework::physics
