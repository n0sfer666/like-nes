#pragma once
#include <cstdint>

#include "fixtrig.hpp"
#include "units.hpp"

// Форма столкновения — ОДНА структура на все четыре типа из решения владельца (спека #15, п. 5):
// выпуклое ЯДРО из точек плюс РАДИУС скругления вокруг него.
//
//   круг       — одна точка и радиус
//   капсула    — две точки (отрезок) и радиус
//   многоугольник — от трёх точек, радиус ноль
//   AABB       — частный случай многоугольника из четырёх точек
//
// Одна структура, а не четыре наследника и не тег с объединением, потому что альтернатива стоит
// дорого ровно там, где больно: узкая фаза с четырьмя типами — это шестнадцать сочетаний, из
// которых десять пишутся «почти как соседнее», расходятся на округлении и разъезжаются не в тесте
// формы, а в golden-хеше через полгода. С ядром и радиусом сочетаний три, и каждое отвечает за
// собственную геометрическую ситуацию, а не за пару имён типов.
//
// Точки хранятся ИНЛАЙН (решение владельца: потолок 16 вершин), а не в общей арене. Цена названа
// прямо: форма занимает 264 байта, тело — около 320, и 500 тел гейта 8 это 160 КБ, которые
// широкая фаза протаскивает через кеш каждый кадр. Замер — вертикаль 3; арена остаётся вариантом
// отступления, и переход к ней не меняет ни одной сигнатуры ниже.
namespace framework::physics {

constexpr uint8_t MAX_VERTICES = 16;

struct Shape {
    fix32 radius;
    uint8_t count = 0;
    // Ядро в ЛОКАЛЬНЫХ координатах тела, центр масс — в начале координат. Смещение формы
    // относительно тела задаётся точками, а не отдельным полем: тело вращается вокруг центра масс,
    // и «сдвинутая форма при неподвижном центре вращения» — это не смещение, а другая физика.
    // `make_body` поэтому не игнорирует смещение, а переносит на него позицию тела.
    Vec2 points[MAX_VERTICES]{};
    // Внешние нормали рёбер, нормаль i принадлежит ребру (i, i+1). Кешируются на построении, а не
    // считаются в узкой фазе: SAT сравнивает расстояния вдоль нормалей, то есть нормали обязаны
    // быть единичными, то есть каждая стоит корня. Шестнадцать корней на форму на пару на кадр —
    // это дороже всей остальной узкой фазы вместе взятой.
    Vec2 normals[MAX_VERTICES]{};

    // Сравнение по УМОЛЧАНИЮ, вместе с хвостом за `count`. Хвост сравнивается не по недосмотру: он
    // инициализирован нулями, а сравнивается форма всегда со СВОЕЙ ЖЕ копией (`rest.hpp`), поэтому
    // разойтись хвосты могут ровно в одном случае — форму переписали. Зачем сравнение тела вообще —
    // `body.hpp`, `operator==`.
    bool operator==(const Shape&) const = default;
};

// Конструкторы задают НАМЕРЕНИЕ; законность формы наводит `sanitize` (его зовёт `make_body`).
// Разделение нарочное: тест вправе собрать заведомо вырожденную форму и проверить, что мир её
// починил, а не считать, что чинить нечего.
Shape circle(fix32 r);
Shape capsule(Vec2 a, Vec2 b, fix32 r);
Shape box(fix32 hx, fix32 hy);
Shape polygon(const Vec2* pts, uint32_t n);

// Кламп координат и радиуса, выпуклая оболочка ядра (она же задаёт обход против часовой в
// математических осях), пересчёт нормалей. Невыпуклый или перечисленный не по кругу многоугольник
// — не ошибка вызывающего, которую можно «задокументировать»: SAT на нём даёт не грубый контакт, а
// НЕВЕРНЫЙ, с нормалью внутрь, и тело затягивает в препятствие. Оболочка снимает вопрос целиком.
Shape sanitize(const Shape& s);

// Та же форма в МИРОВЫХ осях. Узкая фаза работает только с ней: SAT сравнивает проекции двух
// форм на общие оси, а «общие» они лишь после того, как обе повёрнуты в одну систему. Разворот
// делается один раз на форму в паре, а не на каждую проверяемую ось, — иначе шестнадцать осей
// стоили бы шестнадцати разворотов всей формы.
struct WorldShape {
    fix32 radius;
    uint8_t count = 0;
    Vec2 points[MAX_VERTICES]{};
    Vec2 normals[MAX_VERTICES]{};
};

void to_world(const Shape& s, Vec2 position, Rot rot, WorldShape& out);

struct Aabb {
    Vec2 min;
    Vec2 max;
};

// AABB формы, повёрнутой на `rot` и стоящей в `position`. Считается по вершинам ядра, а не по
// AABB неповёрнутой формы: последний при повороте на 45 градусов не покрывает форму, и широкая
// фаза начинает терять пары ровно тогда, когда тело крутится.
Aabb bounds(const Shape& s, Vec2 position, Rot rot);
bool overlaps(const Aabb& a, const Aabb& b);

// Расстояние от начала координат формы до самой дальней точки её поверхности. Инвариантно к
// повороту, поэтому считается один раз на построении: по нему берётся потолок угловой скорости
// тела (`max_angular_speed`).
fix32 reach(const Shape& s);

} // namespace framework::physics
