#pragma once
#include <cstdint>

#include "filter.hpp"
#include "mass.hpp"
#include "shape.hpp"

// Тело и его форма — данными, а не классом с виртуальным `integrate()`. Наследование в API слоя
// запрещено правилами (`framework/README.md`), и здесь это не догма: виртуальный вызов на форму
// внутри узкой фазы означал бы порядок обхода, зависящий от таблицы виртуальных функций, то есть
// от компоновки, то есть от ОС. Набор форм расширяется данными (`Shape` — ядро плюс радиус), а не
// новым потомком.
namespace framework::physics {

// Статическое тело неподвижно и бесконечно тяжело; кинематическое движется заданной скоростью и не
// реагирует на удары; динамическое подчиняется решателю. Различие держится ОДНИМ полем, а не тремя
// массивами: тип меняется по ходу игры (платформа-лифт становится обломком).
enum class BodyType : uint8_t { Static = 0, Kinematic = 1, Dynamic = 2 };

// Умолчание трения — именованной constexpr-константой, а не выражением прямо в инициализаторе
// поля: `from_float` спека разрешает только в constexpr-константах на границе, и «в инициализаторе
// оно всё равно свернётся» — рассуждение, которое пришлось бы восстанавливать при каждом чтении.
constexpr fix32 DEFAULT_FRICTION = fix32::from_float(0.4);

struct Material {
    fix32 restitution;                    // 0 — глина, 1 — идеальный отскок; выше — кламп
    fix32 friction = DEFAULT_FRICTION;    // коэффициент Кулона, комбинируется корнем
    bool operator==(const Material&) const = default;
};

struct BodyDesc {
    // Ключ задаёт ИГРА и обязан быть уникальным и стабильным между запусками. На нём стоит весь
    // детерминизм: и порядок контактов, и порядок обхода в хеше состояния берутся отсюда, а не из
    // индекса в массиве и не из адреса. Индекс зависит от порядка создания, адрес — от аллокатора.
    uint32_t key = 0;
    BodyType type = BodyType::Dynamic;
    Shape shape;
    Vec2 position;
    Vec2 velocity;
    fix32 angle;                          // оборотов, см. `units.hpp`
    fix32 angular_velocity;               // оборотов в секунду
    fix32 mass = fix32::from_int(1);
    // Демпфирование — доля скорости, снимаемая за секунду. Не трение о поверхность: оно действует
    // и в пустоте, и нужно ровно затем, чтобы вращающийся обломок когда-нибудь остановился.
    fix32 linear_damping;
    fix32 angular_damping;
    Material material;
    LayerMask layer = LAYER_DEFAULT;
    LayerMask mask = MASK_ALL;
    // Триггер участвует в поиске контактов наравне со всеми и НЕ участвует в их разрешении: зона
    // урона обязана знать точку и нормаль касания (искры рисуются там, где задело), но не смеет
    // толкать игрока. Флагом на теле, а не отдельным списком: тело меняет роль по ходу игры —
    // закрытая дверь становится проходом, — и переезд между списками означал бы, что индекс тела
    // перестал быть стабильным, а на его стабильности стоит `BodyId`.
    bool trigger = false;
};

struct Body {
    uint32_t key = 0;
    BodyType type = BodyType::Dynamic;
    Shape shape;
    Vec2 position;
    Vec2 velocity;
    // Угол приведён к [0, 1) обороту на построении и после каждой интеграции. Приведение здесь
    // не косметика: угол входит в хеш состояния, и тело, провернувшееся на десять оборотов, обязано
    // хешироваться так же, как то же тело в том же положении, — иначе гейт 2 отличал бы истории,
    // а не результаты.
    fix32 angle;
    fix32 angular_velocity;
    // Поворот, посчитанный по углу один раз за шаг. Кеш, а не удобство: узкая фаза трогает все
    // вершины формы, и синус на каждую вершину — это таблица и интерполяция там, где для всей
    // формы значение одно.
    Rot rot;
    // Хранится ОБРАТНАЯ масса: решатель делит на сумму масс в каждой итерации, а бесконечная масса
    // статики выражается нулём вместо ветки на каждый контакт.
    fix32 inv_mass;
    // А вот момент инерции хранится ПРЯМОЙ и на единицу массы (I/m, raw Q16.16 в int64), хотя
    // решателю нужен обратный. Причина не в удобстве: обратный момент в Q16.16 не живёт. У коробки
    // 32x32 величина I/m равна 170.67, то есть обратная — 1/170.67, всего raw 383 при массе 1. Она
    // делится на массу, и на 384 единицах округляется в РОВНО НОЛЬ — вращение выключается насмерть
    // внутри диапазона, который кламп массы объявляет законным (до 4096), и молча. Решатель поэтому
    // умножает на плечо ДО деления на момент (`inertia_term_q32` в `axis_terms.cpp`): отношение
    // arm^2/(I/m) — величина порядка единицы, и в ней разрядов хватает всем.
    //
    // Ноль означает «вращение заперто» — форма без площади. Статике и кинематике отдельного нуля не
    // нужно: у них нулевая обратная масса, и угловой вклад обнуляется вместе с линейным.
    int64_t unit_inertia = 0;
    // Собственный потолок угловой скорости — функция размера формы (`max_angular_speed`). Хранится,
    // а не пересчитывается в интеграторе: он требует модуля каждой вершины, то есть корня, а
    // меняться ему не с чего — форма после построения неизменна.
    fix32 max_angular = MAX_ANG_SPEED;
    fix32 linear_damping;
    fix32 angular_damping;
    Material material;
    // Фильтр и роль копируются с дескриптора без правки: у слоя нет незаконных значений. Маска,
    // равная нулю, означает «ни с кем» — это законное намерение (выключенный коллайдер), а не
    // ошибка, которую надо чинить приведением. Тело с нулевой маской просто не даёт пар.
    LayerMask layer = LAYER_DEFAULT;
    LayerMask mask = MASK_ALL;
    bool trigger = false;

    // Сравнение тела ЦЕЛИКОМ — и `= default` здесь несущее, а не сокращение записи. На нём стоит
    // правило покоя: замерший остров шаг не двигает, поэтому единственный способ заметить правку,
    // сделанную игрой через неконстантную ручку `World::body()`, — сверить тело с копией, которую
    // оставил `settle` (`rest.hpp`). Спросить ручку о намерении нельзя: перегрузку выбирает
    // константность мира, а не намерение вызывающего.
    //
    // Перечислять поля руками здесь было бы не «многословнее», а НЕВЕРНО через раунд: поле,
    // добавленное в тело и забытое в сравнении, закрывает дверь пробуждения молча — ящик, которому
    // сменили маску, останется висеть на полу, которого он больше не касается. Умолчание сравнивает
    // и новое поле тоже, ничего для этого не требуя. Цена названа: сравнение трогает всю форму, то
    // есть 264 байта из ~320, — но `bounds()` широкой фазы читает те же вершины КАЖДЫЙ кадр и для
    // каждого тела, замершего в том числе, так что сверка дешевле уже оплаченного.
    bool operator==(const Body&) const = default;
};

// Диапазон масс. Обратная масса живёт в Q16.16, где 1/4096 — это raw 16: ещё не ноль, но уже
// шестипроцентная ступенька. Молча принять массу 100000 значило бы дать телу обратную массу ноль,
// то есть сделать его статикой, о чём игра не узнала бы никогда. Кламп честнее: ошибка в массе
// становится видимой на глаз (тело тяжелее, чем просили), а не невидимой (тело не движется).
constexpr fix32 MIN_MASS = fix32::from_float(0.015625);   // 1/64
constexpr fix32 MAX_MASS = fix32::from_int(4096);

// Потолок демпфирования. Доля, снимаемая за шаг, считается как `damping * dt` и вычитается из
// единицы; выше 1/dt множитель ушёл бы в минус, то есть демпфирование РАЗВОРАЧИВАЛО бы скорость
// вместо того, чтобы её гасить. Кламп на 60 держит множитель неотрицательным при шаге 1/60.
constexpr fix32 MAX_DAMPING = fix32::from_int(60);

Body make_body(const BodyDesc& d);

// Единственный способ менять угол. Приведение к периоду и пересчёт `rot` — ОДИН инвариант, и держать
// его должно одно место: угол, записанный мимо этой функции, оставляет форму повёрнутой по-старому,
// то есть тело, которое рисуется под одним углом, а сталкивается под другим.
void set_angle(Body& b, fix32 turns);

// AABB тела в мировых координатах — общий язык широкой фазы: любая форма сводится к нему, поэтому
// широкая фаза не знает про формы вовсе.
Aabb bounds(const Body& b);

} // namespace framework::physics
