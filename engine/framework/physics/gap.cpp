#include "gap.hpp"

#include <cstdint>

#include "nearest.hpp"

namespace framework::physics {
namespace {

struct Candidate {
    Vec2 on_a;       // точка ядра `a`, ближайшая к ядру `b`
    Vec2 dir;        // единичное, из `a` в `b` — та же ориентация, что у нормали манифольда
    fix32 dist;      // расстояние между ядрами, со знаком
    uint32_t id = 0;
};

// Строгое «меньше», и порядок обхода фиксирован: у двух коллинеарных капсул кратчайшее расстояние
// достигается сразу на двух парах вершина-ребро, и правило «побеждает первый» — не «всё равно
// какой», а условие того, что три ОС выберут одну и ту же точку контакта.
void consider(Candidate& best, const Candidate& c) {
    if (c.dist < best.dist) best = c;
}

} // namespace

bool collide_core_gap(const WorldShape& a, Vec2 center_a, const WorldShape& b, Vec2 center_b,
                      Manifold& out) {
    Candidate best{{}, {}, fix32::from_raw(INT32_MAX), 0};
    // Минимум расстояния между двумя НЕПЕРЕСЕКАЮЩИМИСЯ выпуклыми множествами достигается хотя бы в
    // одной ВЕРШИНЕ, поэтому перебора вершин каждой формы против ядра другой достаточно: вторую
    // точку пары находит `nearest_on_core`, и она же отвечает за случай «вершина против ребра».
    // Оговорка про непересекающиеся — несущая, и её держит вызывающий: пересечение ядер он
    // разбирает сам и сюда не доводит (`sat.cpp`, `axis_contact`).
    for (uint8_t i = 0; i < b.count; ++i) {
        const Nearest n = nearest_on_core(b.points[i], a);
        consider(best, {n.point, n.dir, n.dist, CORE_GAP_ID_BIT | static_cast<uint32_t>(i)});
    }
    for (uint8_t i = 0; i < a.count; ++i) {
        const Nearest n = nearest_on_core(a.points[i], b);
        // `dir` смотрит из ядра `b` в вершину `a`, а нормаль манифольда нужна из `a` в `b`. Знак
        // разворачивается, а вырожденное умолчание — нет: у совпавшей с ядром вершины направления
        // нет вовсе, и `nearest_on_core` подставляет туда мировую ось (`FALLBACK_DIR`). Пройди она
        // через минус, и разъезжающаяся пара уходила бы в РАЗНЫЕ стороны в зависимости от того,
        // какая половина перебора победила, — то есть от нумерации вершин. Спрашивается при этом
        // именно флаг, а не нулевое расстояние: вершина, легшая ровно на грань, тоже даёт ноль, но
        // с живой нормалью, и подмена её умолчанием была бы выброшенным правильным ответом.
        // Идентификаторы двух половин перебора разведены байтом: одна и та же вершина, найденная с
        // разных сторон, — это разные геометрические причины.
        const Vec2 dir = n.degenerate ? FALLBACK_DIR : -n.dir;
        consider(best, {a.points[i], dir, n.dist,
                        CORE_GAP_ID_BIT | 0x100u | static_cast<uint32_t>(i)});
    }

    // Расстояние берётся со знаком, и минимум — тоже: на отрицательной ветке это САМАЯ ГЛУБОКАЯ из
    // найденных точек, а не кратчайший выход. Выбор намеренный и именно в эту сторону: занизить
    // проникновение значит оставить пару перекрытой ещё на кадр, завысить — потратить лишнюю
    // итерацию решателя. Отрицательное расстояние означает, что вершина одной формы залезла внутрь
    // ядра другой: у такой пары перебор точен, и ответ здесь законный.
    const fix32 separation = best.dist - a.radius - b.radius;
    if (separation.raw > 0) return false;

    // Точка контакта — СЕРЕДИНА между поверхностями, тем же правилом, что у SAT и у точечного ядра:
    // взять поверхность одной из форм значило бы сместить плечо на половину проникновения в её
    // сторону, и момент зависел бы от того, какая форма оказалась первой в паре.
    const Vec2 point = best.on_a + best.dir * (a.radius + fix32::from_raw(separation.raw / 2));

    out.normal = best.dir;
    out.count = 1;
    ManifoldPoint& p = out.points[0];
    p = ManifoldPoint{};
    p.anchor_a = point - center_a;
    p.anchor_b = point - center_b;
    p.penetration = -separation;
    p.id = best.id;
    return true;
}

} // namespace framework::physics
