#pragma once
#include <vector>

#include "contact.hpp"

// Память контактов между кадрами — то, без чего манифольд остаётся «постоянным» только на словах.
//
// Решатель за восемь итераций доводит контакт почти до нуля скорости сближения, но начинает каждый
// кадр с нуля НАКОПЛЕННОГО. Стопка из пяти ящиков за восемь итераций не успевает передать вес
// сверху вниз, поэтому нижний ящик каждый кадр слегка проседает, а на следующем его выталкивает
// обратно: стопка дрожит и медленно разъезжается. Тёплый старт вводит в первую итерацию то, чем
// кончил прошлый кадр, и та же стопка стоит.
//
// Хранится ПОЛНЫЙ манифольд прошлого кадра ради двух его полей — накопленного импульса и `k`. `k`
// нужен потому, что накопленное живёт в шкале относительной скорости и при смене геометрии
// переводится в новую шкалу отношением (см. `rescale` в `prepare.cpp`).
namespace framework::physics {

class ManifoldCache {
public:
    // Резерв — на конструкторе мира: `store` в шаге обязан укладываться в уже выделенное (гейт 6).
    void reserve(size_t pairs);

    // Переносит накопленное прошлого кадра в точки `m`, сопоставляя их ПО ИДЕНТИФИКАТОРУ ПРИЧИНЫ, а
    // не по месту в манифольде. Место меняется, когда тело чуть проворачивается и отсечение выдаёт
    // те же две точки в другом порядке, — и импульс перетекал бы с одного угла ящика на другой.
    void carry(Manifold& m) const;

    // Достаёт манифольд прошлого кадра ЦЕЛИКОМ. Нужен спящему острову: его контакты в этом кадре не
    // считаются заново, а игре и трекеру событий геометрия по-прежнему нужна. Отдавать прошлую
    // законно ровно потому, что остров ЗАМЕР по правилу покоя (`rest.hpp`): его тела не сдвинулись
    // ни на разряд, значит пересчёт вернул бы те же числа из тех же входов.
    //
    // Довод верен НЕ ДЛЯ ВСЯКОЙ записи, и оговорка стоит денег. Манифольд считается в начале шага, а
    // запоминается в конце — между ними интеграция и позиционная коррекция, которые тела ещё живого
    // острова двигают. Поэтому запись, сделанная РЕШЁННОЙ парой, описывает позиции ДО последней
    // правки, полученной этой парой, и на первом же замершем кадре законсервировала бы их навсегда:
    // прогон со сном разошёлся бы с прогоном без сна на 1 raw глубины и не сошёлся больше никогда
    // (гейт 5 спеки #15 ловил ровно это). Отдаётся поэтому только запись, сделанная УЖЕ замершей
    // парой, — у неё вход узкой фазы и правда тот же, что вчера. Цена — один пересчёт узкой фазы на
    // паре в тот единственный кадр, когда она замерла.
    bool recall(uint32_t key_a, uint32_t key_b, Manifold& out) const;

    // Пары приходят упорядоченными по ключам, поэтому список остаётся отсортированным и `carry`
    // ищет двоичным поиском. Нарушение порядка не сделает ответ НЕВЕРНЫМ (совпадение ключей
    // проверяется явно) — оно лишь потеряет тёплый старт, то есть даст дрожащую стопку вместо
    // неправильной физики.
    //
    // Списков два, и оба упорядочены сами по себе — решённые контакты и спящие. Запоминаются они
    // ВМЕСТЕ: забудь спящие, и остров, проснувшийся через сотню кадров, начал бы тёплый старт с
    // нуля, то есть повёл бы себя иначе, чем тот же остров в прогоне без сна. Слияние здесь, а не у
    // вызывающего, потому что порядок — условие двоичного поиска, то есть свойство этого класса.
    void store(const std::vector<Manifold>& contacts, const std::vector<Manifold>& resting);

private:
    // Индекс записи, `previous_.size()` — не нашли. Индекс, а не указатель, потому что признак
    // «запись сделана замершей парой» лежит в параллельном массиве: держать его полем манифольда
    // значило бы протащить знание о сне в структуру, которую читает решатель.
    size_t find(uint32_t key_a, uint32_t key_b) const;

    std::vector<Manifold> previous_;
    std::vector<uint8_t> resting_;
};

} // namespace framework::physics
