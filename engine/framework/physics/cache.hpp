#include "contact.hpp"

// Память контактов между кадрами — то, без чего манифольд остаётся «постоянным» только на словах.
//
// Решатель за восемь итераций доводит контакт почти до нуля скорости сближения, но начинает каждый
// кадр с нуля НАКОПЛЕННОГО. Стопка из пяти ящиков за восемь итераций не успевает передать вес
// сверху вниз, поэтому нижний ящик каждый кадр слегка проседает, а на следующем его выталкивает
// обратно: стопка дрожит и медленно разъезжается. Тёплый старт вводит в первую итерацию то, чем
// кончил прошлый кадр, и та же стопка стоит.
//
// Хранится ПОЛНЫЙ манифольд прошлого кадра ради двух его полей — накопленного импульса и `k`. `k`
// нужен потому, что накопленное живёт в шкале относительной скорости и при смене геометрии
// переводится в новую шкалу отношением (см. `rescale` в `prepare.cpp`).
namespace framework::physics {

class ManifoldCache {
public:
    // Резерв — на конструкторе мира: `store` в шаге обязан укладываться в уже выделенное (гейт 6).
    void reserve(size_t pairs);

    // Переносит накопленное прошлого кадра в точки `m`, сопоставляя их ПО ИДЕНТИФИКАТОРУ ПРИЧИНЫ, а
    // не по месту в манифольде. Место меняется, когда тело чуть проворачивается и отсечение выдаёт
    // те же две точки в другом порядке, — и импульс перетекал бы с одного угла ящика на другой.
    void carry(Manifold& m) const;

    // Пары приходят упорядоченными по ключам, поэтому список остаётся отсортированным и `carry`
    // ищет двоичным поиском. Нарушение порядка не сделает ответ НЕВЕРНЫМ (совпадение ключей
    // проверяется явно) — оно лишь потеряет тёплый старт, то есть даст дрожащую стопку вместо
    // неправильной физики.
    void store(const std::vector<Manifold>& manifolds);

private:
    std::vector<Manifold> previous_;
};

} // namespace framework::physics
