#pragma once
#include <cstdint>

#include "fixmath.hpp"

// Контакт — результат узкой фазы и вход решателя, поэтому живёт отдельно от обоих: иначе один из
// них включал бы другой ради структуры, и стрелка зависимости внутри модуля пошла бы вбок.
namespace framework::physics {

struct Contact {
    uint32_t a = 0;             // индекс тела в мире
    uint32_t b = 0;
    Vec2 normal;                // единичная, направлена из `a` в `b`
    fix32 penetration;          // глубина проникновения по нормали, > 0

    // Накопленные импульсы держатся В контакте, а не в локальной переменной итерации: решатель
    // последовательных импульсов обязан клампить СУММУ за шаг (нормальная — неотрицательна,
    // касательная — конусом Кулона), а не каждую добавку по отдельности. Кламп по добавке даёт
    // стопку, которая проваливается сама в себя: отрицательные поправки нижних итераций съедают
    // работу верхних.
    //
    // Величина здесь — не импульс, а ЖЕЛАЕМОЕ ИЗМЕНЕНИЕ ОТНОСИТЕЛЬНОЙ СКОРОСТИ в raw Q16.16, и
    // это не переименование. Импульс равен ему, делённому на сумму обратных масс, а сумма доходит
    // до 1/4096 — частное вылетает за Q16.16 задолго до того, как контакт разрешён. Насыщение там
    // означало бы не потерю точности, а полную потерю контакта: накопленная сумма перестаёт расти,
    // добавка обнуляется, и оставшиеся семь итераций не делают ничего. Замер на прежней схеме:
    // тело массой 243 и тяжелее ПРОВАЛИВАЛОСЬ сквозь статику, при том что кламп массы сам же
    // объявлял легальным весь диапазон до 4096. Деление на сумму заменено умножением на долю
    // (`share_a`/`share_b`), которая по построению лежит в [0, 1] и насытиться не может.
    // Накопленное ограничено сверху восемью итерациями по разности скоростей, то есть 2^35.
    int64_t normal_impulse = 0;
    int64_t tangent_impulse = 0;

    // Целевая скорость отскока, посчитанная ОДИН раз по скорости сближения на входе в шаг.
    // Считать упругость от текущей скорости внутри каждой итерации нельзя: итерации гасят
    // сближение, цель уезжает вслед за ним, и мяч отскакивает тем ниже, чем больше итераций, —
    // то есть число итераций начинает менять физику, а не только точность.
    fix32 bias;

    // Доли обратных масс (inv_mass / сумма) и коэффициент трения — тоже один раз за шаг: между
    // итерациями они не меняются, а среднее геометрическое трения — это целочисленный корень,
    // двоичный поиск на 33 шага с делением в каждом. Во внутреннем цикле он стоил бы дороже всего
    // остального решателя вместе взятого.
    fix32 share_a;
    fix32 share_b;
    fix32 friction;
};

// Пара-кандидат из широкой фазы. Ключи тел копируются рядом с индексами, потому что порядок
// решения обязан быть функцией КЛЮЧЕЙ (стабильных между запусками), а не индексов (зависящих от
// порядка создания) — а сортировать по ключу, каждый раз ходя в массив тел, значило бы тянуть
// широкой фазе знание о теле.
struct Pair {
    uint32_t a = 0;
    uint32_t b = 0;
    uint32_t key_a = 0;
    uint32_t key_b = 0;
};

} // namespace framework::physics
