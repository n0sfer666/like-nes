#pragma once
#include <cstdint>

#include "fixmath.hpp"

// Контакт — результат узкой фазы и вход решателя, поэтому живёт отдельно от обоих: иначе один из
// них включал бы другой ради структуры, и стрелка зависимости внутри модуля пошла бы вбок.
namespace framework::physics {

// Две точки — это ВСЁ, что может дать пересечение двух выпуклых форм на плоскости: их границы
// пересекаются либо по одной точке (угол в грань), либо по отрезку (грань в грань), и отрезок
// задаётся концами. Третья точка была бы либо дублем, либо признаком невыпуклой формы.
constexpr uint8_t MAX_MANIFOLD_POINTS = 2;

// Пути узкой фазы нумеруют точки КАЖДЫЙ ПО-СВОЕМУ, и пара тел вправе переключаться между ними от
// кадра к кадру: капсула, наехавшая на угол, уходит с пути отсечения на путь зазора и обратно.
// Тёплый старт ищет точку прошлого кадра по идентификатору и переносит на неё накопленный импульс —
// совпади нумерации, и в контакт приехало бы накопленное с ЧУЖОЙ геометрии. Поэтому старший бит
// идентификатора называет путь, и правило записано здесь одно на всех: `feature_id` отсечения
// (`sat.cpp`) занимает младшие 25 бит и старших не трогает, точечное ядро и зазор ядер берут свои.
//
// Несовпадение идентификаторов — не потеря: тёплый старт просто не находит точку и начинает с нуля,
// то есть тратит итерации. Ложное СОВПАДЕНИЕ — вброс энергии, и оно тихое.
constexpr uint32_t POINT_CORE_ID_BIT = 0x40000000u;
constexpr uint32_t CORE_GAP_ID_BIT = 0x80000000u;
// Запасной ответ отсечения — точка на одной опорной оси (`sat.cpp`, `axis_contact`). Свой бит, хотя
// причина точки называется тем же `feature_id`: та же пара граней, разобранная отсечением, — это
// ДРУГАЯ точка, посчитанная другим правилом, и накопленное с неё переносить не на что.
constexpr uint32_t REF_AXIS_ID_BIT = 0x20000000u;

// Коэффициенты разрешения вдоль ОДНОЙ оси — нормали или касательной. Считаются один раз за шаг:
// между итерациями они не меняются, а внутри итерации каждый из них стоил бы деления.
struct AxisTerms {
    // Эффективная обратная масса вдоль оси: inv_m_a + inv_m_b + inv_I_a*(r_a x ось)^2 + то же для b.
    // Хранится, потому что тёплый старт следующего кадра пересчитывает накопленное через ОТНОШЕНИЕ
    // старой и новой (см. `rescale` в `prepare.cpp`).
    fix32 k;
    // Доли: сколько от накопленного изменения относительной скорости достаётся каждому телу.
    // Линейная доля — inv_m/k, то есть [0, 1] по построению; угловая — inv_I*(r x ось)/k, домноженная
    // на INV_TAU. Множитель здесь, а не в решателе, потому что угловая скорость меряется в ОБОРОТАХ:
    // момент меняет её в радианах, и перевод — постоянный множитель, которому незачем жить во
    // внутреннем цикле. В `k` он не входит: там TAU из скорости точки и INV_TAU из момента
    // сокращаются, и `k` остаётся ровно тем же выражением, что в учебнике.
    // Умножение на долю вместо деления на k — не оптимизация: частное 1/k доходит до тысяч и
    // насыщается в Q16.16 задолго до того, как контакт разрешён, а доля насытиться не может.
    fix32 lin_a, lin_b;
    fix32 ang_a, ang_b;
};

struct ManifoldPoint {
    // Плечи от центров масс до точки контакта, в МИРОВЫХ осях. Мировых, а не локальных: решатель
    // складывает их со скоростями, и лишний поворот на каждую итерацию — это таблица синуса во
    // внутреннем цикле.
    Vec2 anchor_a;
    Vec2 anchor_b;
    // Глубина ПЕРЕКРЫТИЯ со знаком: положительная — формы влезли друг в друга, отрицательная — между
    // ними ещё зазор такой величины (спекулятивный контакт, `units.hpp`). Знак не декоративный, его
    // читают оба потребителя: решатель переводит зазор в разрешённую скорость сближения, позиционная
    // коррекция такую точку не трогает вовсе — выталкивать не из чего.
    fix32 penetration;

    // Идентификатор геометрической ПРИЧИНЫ точки: какое ребро об какое. По нему точка узнаётся в
    // следующем кадре и получает накопленный импульс предыдущего (тёплый старт). Сопоставление по
    // порядку в манифольде не годится: точки меняются местами, когда тело чуть проворачивается, и
    // импульс перетекал бы с одного угла ящика на другой. Пространства путей узкой фазы разведены
    // старшими битами — см. `POINT_CORE_ID_BIT` и `CORE_GAP_ID_BIT` выше.
    uint32_t id = 0;

    // Накопленные величины — не импульсы, а ЖЕЛАЕМОЕ ИЗМЕНЕНИЕ ОТНОСИТЕЛЬНОЙ СКОРОСТИ в raw
    // Q16.16, и это не переименование. Импульс равен ему, делённому на `k`, а `k` доходит до
    // 1/4096 — частное вылетает за Q16.16 задолго до того, как контакт разрешён. Насыщение там
    // означало бы не потерю точности, а полную потерю контакта: накопленная сумма перестаёт расти,
    // добавка обнуляется, и оставшиеся итерации не делают ничего. Замер на прежней схеме: тело
    // массой 243 и тяжелее ПРОВАЛИВАЛОСЬ сквозь статику, при том что кламп массы сам же объявлял
    // легальным весь диапазон до 4096.
    int64_t normal_impulse = 0;
    int64_t tangent_impulse = 0;

    // Цель решателя: скорость сближения, к которой он гонит контакт (сходится к `vn = -bias`).
    // Складывается из двух слагаемых с противоположными знаками — отскока и разрешённого сближения
    // по зазору, — и считается ОДИН раз за шаг. Считать упругость от текущей скорости внутри каждой
    // итерации нельзя: итерации гасят сближение, цель уезжает вслед за ним, и мяч отскакивает тем
    // ниже, чем больше итераций, — то есть число итераций начинает менять физику, а не точность.
    // Разбор обоих слагаемых — `prepare.cpp`.
    fix32 bias;

    AxisTerms normal;
    AxisTerms tangent;

    // Предел конуса Кулона В ЕДИНИЦАХ НАКОПЛЕННОГО: |lambda_t| <= cone * lambda_n. Множитель — не
    // просто трение, а trenie * k_t / k_n, и отношение здесь обязательно. Конус ограничивает
    // ИМПУЛЬСЫ (P_t <= mu * P_n), а накопленные величины живут в шкале скорости: P = lambda / k, и
    // у нормали с касательной эти k разные, потому что плечо входит в них по-разному. В вертикали 1
    // отношение было тождественной единицей (вращения не было), и его отсутствие не было видно.
    fix32 cone;
};

// Манифольд — все точки контакта одной пары тел с ОДНОЙ общей нормалью. Общей, потому что для двух
// выпуклых форм направление разделения одно: две точки касания грани об грань разрешаются вдоль
// того же направления, и разные нормали в них означали бы, что формы невыпуклые.
struct Manifold {
    uint32_t a = 0;             // индекс тела в мире
    uint32_t b = 0;
    uint32_t key_a = 0;         // ключи копируются рядом: тёплый старт ищет пару между кадрами,
    uint32_t key_b = 0;         // а индекс между кадрами не обязан значить то же тело
    Vec2 normal;                // единичная, направлена из `a` в `b`
    uint8_t count = 0;
    ManifoldPoint points[MAX_MANIFOLD_POINTS];
};

// Пара-кандидат из широкой фазы. Ключи тел копируются рядом с индексами, потому что порядок
// решения обязан быть функцией КЛЮЧЕЙ (стабильных между запусками), а не индексов (зависящих от
// порядка создания) — а сортировать по ключу, каждый раз ходя в массив тел, значило бы тянуть
// широкой фазе знание о теле.
struct Pair {
    uint32_t a = 0;
    uint32_t b = 0;
    uint32_t key_a = 0;
    uint32_t key_b = 0;
};

} // namespace framework::physics
