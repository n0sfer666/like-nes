#pragma once
#include <cstdint>

// Счётчики работы шага — гейт 8 спеки #15.
//
// Гейт спрашивает «укладывается ли целевое число тел в бюджет кадра», и прямой ответ на него —
// стенное время. Гейтом в CI оно быть не может: раннер GitHub делит железо с соседом, разброс там
// кратный, и красный шаг «кадр занял 3.1 мс вместо 2» через месяц отключат как флейкующий. Поэтому
// в CI утверждаются ЭТИ величины — детерминированные, одинаковые на трёх ОС до единицы, — а время
// меряется рядом и печатается в лог, не роняя прогон. Разделение не компромисс: время отвечает на
// вопрос «быстро ли», счётчики — на вопрос «не начали ли мы делать в разы больше работы», и второй
// как раз тот, на который CI способен ответить надёжно.
//
// Все величины считаются ЗА ОДИН ШАГ и обнуляются в его начале: накопительные счётчики за прогон
// пришлось бы делить на число кадров, а деление скрывает выброс — сцена, в которой один кадр стоил
// в сто раз дороже среднего, дала бы приличное среднее.
namespace framework::physics {

struct WorkCounters {
    // Сколько кандидатов рассмотрела широкая фаза: число проходов внутреннего цикла sweep-and-prune,
    // переживших проверку на выход из полосы, но взятых ДО фильтров слоя, бесполезной пары и
    // перекрытия AABB (`broadphase.cpp`). Считать до проверки полосы значило бы прибавлять по одному
    // лишнему проходу на каждое тело — то самое сравнение, которым цикл и обрывается; считать после
    // фильтров — получить число выданных пар, которое рядом и так есть. Это мера качества широкой
    // фазы, и она единственная здесь растёт квадратично, если сортировка перестанет разделять тела.
    // Число выданных пар (`pairs`) на этот вопрос не отвечает: пар может быть мало ровно потому, что
    // сцена разреженная, при том что перебрали мы каждого с каждым.
    uint64_t broad_candidates = 0;
    // Пары, дошедшие до узкой фазы, — то, что широкая фаза выдала наружу.
    uint64_t pairs = 0;
    // Вызовы `collide`. Меньше числа пар: пара двух неподвижных тел, чью геометрию отдал кеш
    // покоя, узкую фазу не зовёт вовсе — на замершей сцене это главная экономия, и без отдельного
    // счётчика она неотличима от «пар стало меньше».
    uint64_t narrow_checks = 0;
    // Манифольды, чью геометрию вернул кеш покоя вместо пересчёта.
    uint64_t recalled = 0;
    // Проекции решателя: сколько раз пара «нормаль + трение» реально применена. Именно применена, а
    // не предложена, — точки с нулевой эффективной обратной массой решатель пропускает (`solver.cpp`),
    // поэтому произведение «точек на итерации» дало бы число, которого никто не считал.
    uint64_t velocity_projections = 0;
    // То же для позиционной коррекции: точки, у которых избыток проникновения над допуском оказался
    // положительным. На замершей сцене обязан падать в ноль.
    uint64_t position_projections = 0;
    // Тела, к которым шаг применил тяготение и затухание: ДИНАМИЧЕСКИЕ и не замершие (`world.cpp`).
    // Не «сколько тел шаг подвинул»: интеграция и кламп границ пропускают только статику и
    // замерших, то есть кинематическое тело они двигают, а этот счётчик его не видит — сцена
    // колонны честно печатает ноль при пятистах телах, которые шаг обходит каждым циклом. Мера
    // здесь именно нагрузки на решатель: замершее тело перестаёт стоить проекций, и падение этого
    // числа — прямое свидетельство, что правило покоя работает.
    uint64_t active_bodies = 0;

    void reset() { *this = WorkCounters{}; }
};

// Работа ЗАПРОСА — отдельная структура, а не поле в `WorkCounters`, и разделены они не по вкусу.
// Счётчики шага обнуляются началом шага; запрос зовут из игровой логики в произвольный момент кадра,
// в том числе вовсе без шага между двумя запросами. Одно поле на две таких жизни давало бы число,
// которое непонятно кому принадлежит: шаг стирал бы работу запроса, а запрос — работу шага.
struct QueryCounters {
    // Тела, дошедшие до теста AABB, — то, что запрос рассмотрел сверх двоичного поиска полосы. Это
    // мера индекса, и она единственная здесь отвечает на вопрос «а не обходим ли мы весь мир»:
    // число найденных попаданий на него не отвечает, попаданий может не быть ровно потому, что
    // сцена разреженная, при том что перебрали мы каждого.
    uint64_t scanned = 0;
};

} // namespace framework::physics
