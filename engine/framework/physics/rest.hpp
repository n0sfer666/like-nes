// Правило покоя: остров, простоявший на месте, ЗАМИРАЕТ — скорости обнуляются, и шаг перестаёт его
// двигать. Живёт в самом шаге и действует одинаково при сне включённом и выключенном; сон — это
// отдельный и более поздний вопрос «можно ли не считать узкую фазу для того, что уже замерло».
//
// Почему правило, а не доказанная неподвижная точка. Прошлая редакция усыпляла остров по повтору
// отпечатка состояния: если конец шага N бит в бит равен концу шага N-1, то шаг N+1 вернёт то же, и
// пропуск законен. Довод верен, но его посылка на этой арифметике НЕ ВЫПОЛНЯЕТСЯ — измерено:
// за 12000 кадров отпечаток не повторился ни у башни из шести ящиков, ни у трёх, ни у одного
// одинокого ящика на полу. Остаток ниже кванта неустраним: решатель оставляет ±2 raw скорости, а
// позиционная коррекция при одной итерации ещё и переталкивает стопку саму об себя на 13–20 raw за
// кадр. Критерий, который никогда не срабатывает, — это не строгий критерий, а мёртвый код, и гейт
// на нём зелен вакуумно.
//
// Поэтому неподвижная точка не отыскивается, а СОЗДАЁТСЯ. Замирание — единственное место, где шаг
// вносит в состояние то, чего в уравнениях нет, и цена названа честно: остановить оно вправе только
// движение медленнее `REST_SLOP / REST_FRAMES` за кадр. Всё, что быстрее, покидает окно раньше, чем
// оно закроется, и продолжает считаться.
//
// Оговорка, без которой правило неверно: замершее держится, пока остров никто не трогает снаружи.
// «Снаружи» тут ТРИ разных двери, и каждая закрыта своим средством, потому что вопрос за ними
// разный:
//
//   подвижный сосед  — `wake_touched`, по пересечению AABB, то есть заведомо раньше контакта;
//   правка тела      — там же, СВЕРКОЙ замершего тела с копией, оставленной `settle`;
//   смена обстановки — `wake_all` из `World::set_gravity` и из сдвинутой статики.
//
// Вторая дверь заслуживает отдельного слова, потому что очевидный её вариант неверен. Правку игра
// делает через неконстантную ручку `World::body()`, и спросить ручку о намерении НЕЛЬЗЯ: перегрузку
// выбирает константность мира, а не намерение вызывающего, поэтому в неё попадает и цикл отрисовки,
// каждый кадр читающий трансформации. Будить остров по факту выдачи ручки — значит выключить правило
// покоя молча (окно не досчитает до `REST_FRAMES` никогда). Размораживать «всего на кадр» — значит
// сделать ЧТЕНИЕ мира меняющим его траекторию: остров, размороженный на кадр, этот кадр проживает
// целиком, с тяготением, решателем и позиционной коррекцией, и замерзает обратно уже в другой точке.
// Наружу это не видно вовсе — `at_rest()` всё время `true`, число замороженных кадров то же, — а
// хеш состояния расходится, то есть ломается единственный несущий инвариант модуля. Измерено:
// расхождение с 44-го кадра, к 600-му ящики разъезжаются на 5–35 raw.
//
// Поэтому не спрашиваем, а СРАВНИВАЕМ. Тело, которое шаг заморозил, обязано остаться ровно таким,
// каким `settle` его оставил; разошлось — значит правка была, и остров живёт потому, что его
// тронули, а не потому, что на него посмотрели. Чтение при этом стоит РОВНО НОЛЬ.
//
// Третья дверь — та, о которой легче всего забыть, и молчит она громче всех: замерший остров не
// читает ни тяготения, ни геометрии вокруг, поэтому перевёрнутая гравитация и телепортированный пол
// не сделают с ним НИЧЕГО. Не «сработают позже» — никогда, потому что будить его в этой раскладке
// больше некому.
namespace framework::physics {

// Окно покоя: тело обязано УДЕРЖАТЬСЯ в круге такого радиуса от точки, где окно открылось, столько
// кадров подряд. Мерится смещение от ЯКОРЯ, а не от прошлого кадра, и это существенно: покадровая
// разница у ползущего тела ниже любого разумного порога, а расстояние от якоря растёт монотонно и
// окно закрывает. Двух чисел ровно поэтому два — одно задаёт, что считать дрожанием, второе не даёт
// дрожанию притвориться медленным ходом.
//
// 64 raw — это 1/1024 юнита, втрое выше измеренного дрожания стопки (13–20 raw за кадр) и вчетверо
// ниже разрешения, на котором дрожание вообще выразимо в пикселе. 8 кадров — восьмая доля секунды,
// на порядок длиннее наблюдавшегося цикла решателя (период 2).
//
// Вместе они и есть контракт: замереть вправе только то, что идёт медленнее 8 raw за кадр, то есть
// проходит пиксель за две с лишним минуты. Такое движение игра не покажет и за весь уровень.
constexpr fix32 REST_SLOP = fix32::from_raw(64);
constexpr uint32_t REST_FRAMES = 8;

// Угол сравнивается ТОЧНЫМ равенством, без порога, и это не строгость ради строгости. Оборот живёт
// в тех же Q16.16, то есть один младший разряд угла — это 2*pi/65536 радиана; на плече в 11 юнитов
// (угол ящика 16x16) он даёт 69 raw смещения, больше всего линейного окна. Любой ненулевой порог по
// углу был бы шире линейного, то есть отменял бы его.
class RestTracker {
public:
    // Резерв — на конструкторе мира: гейт 6 требует нуля аллокаций в шаге, а правило работает КАЖДЫЙ
    // шаг и для всех тел.
    void reserve(uint32_t capacity);

    bool frozen(uint32_t body) const { return body < frozen_.size() && frozen_[body] != 0; }

    // Оживить остров тела. Именно остров: оживший в одиночку ящик поехал бы сквозь замерших соседей —
    // их контакты в этом кадре не решаются. Окно покоя при этом сбрасывается ВСЕМУ острову: это явный
    // приказ игры «пусть едет», и отсчитывать его заново — ровно то, чего она просит.
    void wake(uint32_t body, const Islands& islands);

    // Оживить ВСЁ. Для случаев, когда изменилось не тело, а обстановка вокруг него: тяготение или
    // положение статики. Кого именно это касается, спросить не у кого — замерший остров ни того ни
    // другого не читает, а старой раскладки, по которой можно было бы найти задетых, шаг уже не
    // помнит. Грубость намеренная и ограничена редкостью события: подвижная опора — это `Kinematic`,
    // она держит остров живым сама и сюда не попадает.
    void wake_all();

    // Начало шага: оживить всё, чего в этом кадре может коснуться движущееся, и всё, что игра
    // правила сама. Спрашивается пересечение AABB, а не контакт, и это НАМЕРЕННО грубее нужного —
    // лишнее пробуждение стоит кадра работы, пропущенное стоит тела, провалившегося сквозь пол.
    void wake_touched(const std::vector<Body>& bodies, const std::vector<Pair>& pairs,
                      const Islands& islands);

    // Конец шага: продлить или закрыть окно каждому телу, заморозить острова, у которых окно
    // закрылось у всех, и снять КОПИЮ с каждого замершего тела — по ней следующий шаг и узнает, что
    // игра его правила. Тела принимаются НЕКОНСТАНТНЫМИ, потому что замирание их и меняет: скорость
    // и угловая скорость замершего динамического тела становятся РОВНО нулём. Без этого замирание
    // было бы только пропуском работы, а остаточные ±2 raw ждали бы первого же пробуждения, чтобы
    // тронуть тело с места, которое игра считает лежащим.
    void settle(std::vector<Body>& bodies, const Islands& islands);

private:
    void resize(size_t n);
    // Тело «шевелится» в этом кадре: не статика и либо живо, либо уже назначено к пробуждению.
    bool stirs(const std::vector<Body>& bodies, const Islands& islands, uint32_t i) const;
    // Статика сдвинулась с прошлого шага. Тело, о котором записи ещё нет, считается сдвинувшимся:
    // добавленная на ходу плита — это та же смена обстановки, что и уехавшая.
    bool static_moved(const Body& b, uint32_t i) const;
    // Замершее тело правили снаружи: оно больше не равно копии, снятой при заморозке. Спрашивается
    // РАВЕНСТВО ЦЕЛИКОМ, а не «сдвинулось ли»: игра вправе не только толкнуть тело, но и сменить ему
    // маску, форму, роль или тип, — и каждое из этих изменений отнимает у замершего опору ровно так
    // же, как уехавший из-под него пол.
    bool edited(const Body& b, uint32_t i) const { return !(b == settled_[i]); }
    // Кинематике скорость обнулять НЕЛЬЗЯ — её задаёт игра, и обнулить значило бы отменить приказ.
    // Поэтому замереть кинематическое тело вправе только с точным нулём скорости; остановившаяся
    // платформа не мешает грузу на ней, а едущая держит весь остров живым.
    bool may_freeze(const Body& b) const;

    std::vector<uint8_t> frozen_;
    std::vector<uint8_t> wake_;
    std::vector<uint8_t> ready_;
    std::vector<uint32_t> held_;
    std::vector<Vec2> anchor_;
    std::vector<fix32> anchor_angle_;
    // Якорь у статики держит не окно покоя (замирать ей нечего), а прошлое положение: сравнение с ним
    // и есть весь ответ на «сдвинули ли пол». Флаг рядом отличает «не двигалась» от «ещё не видели»:
    // без него плита, добавленная в начале координат, читалась бы как стоящая тут всегда.
    std::vector<uint8_t> tracked_;
    // Копия каждого замершего тела на момент заморозки — вторая дверь целиком. Копия, а не отпечаток
    // из выбранных полей: отпечаток пришлось бы дописывать вслед за каждым новым полем тела, а
    // забытое поле не падает, оно молча перестаёт будить. Пишется только на ПЕРЕХОДЕ в замершее —
    // пока остров стоит, копировать нечего, и кадр замершего острова остаётся стоимости сравнения.
    // Цена — второй экземпляр тел (~320 байт на тело); она и есть плата за дверь без дыр.
    std::vector<Body> settled_;
};

} // namespace framework::physics
