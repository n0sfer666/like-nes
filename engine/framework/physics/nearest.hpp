#pragma once
#include "shape.hpp"

// Ближайшая точка ядра формы — вторая половина узкой фазы, та, которую SAT закрыть не может.
// Разделяющая ось перебирает НОРМАЛИ, а у круга их нет: его «грань» — вся окружность. Поэтому пара,
// где хотя бы одна форма выродилась в точку, считается расстоянием, а не проекциями.
//
// Отдельным файлом, а не приватной частью узкой фазы, потому что тем же запросом отвечают
// перекрытие и трассировка луча (гейт 4, вертикаль 2 PR B): «ближайшая точка ядра» — самостоятельный
// геометрический вопрос, и вторая его реализация разошлась бы с первой на округлении.
namespace framework::physics {

// Направление для вырожденного случая — точка совпала с ядром. Оно обязано быть ОПРЕДЕЛЁННЫМ, а не
// каким придётся: иначе два тела, положенные ровно друг на друга (спавн в одной точке — обычное
// дело), разъедутся в стороны, зависящие от мусора в регистрах. Взята мировая вертикаль, вверх
// (+Y вниз), — но обещание здесь только одно: ось ФИКСИРОВАНА. Какое из двух тел пары уедет вверх,
// решает вызывающий, и он же обязан отвечать на это одинаково независимо от того, с какой стороны
// пришёл запрос (`gap.cpp`, второй цикл перебора).
//
// В заголовке, а не приватной константой: вызывающий, разворачивающий направление знаком, обязан
// уметь отличить вырожденный ответ от обычного — развёрнутое умолчание перестаёт быть умолчанием.
constexpr Vec2 FALLBACK_DIR = {fix32{}, fix32::from_int(-1)};

struct Nearest {
    // Направление ИЗ формы в запрошенную точку, единичное. При совпадении точки с ядром направления
    // нет, и тогда сюда кладётся определённое умолчание, а не мусор: два тела, заспавненные в одной
    // позиции, обязаны разъезжаться одинаково на всех платформах.
    Vec2 dir;
    // Расстояние ДО ЯДРА, со знаком: отрицательное означает, что точка внутри многоугольника.
    // Радиус скругления здесь не учитывается — его вычитает вызывающий, потому что радиусов два.
    fix32 dist;
    Vec2 point;           // сама ближайшая точка ядра
    uint8_t feature = 0;  // ребро (или вершина), которому она принадлежит

    // Направления НЕ БЫЛО: точка совпала с ядром, и в `dir` лежит `FALLBACK_DIR`. Отдельным полем, а
    // не признаком `dist == 0`, потому что нулевое расстояние бывает и совершенно законным: вершина,
    // легшая ровно на грань многоугольника, — на целочисленных координатах обычное дело, — уходит по
    // ветке «точка внутри» с нулевой глубиной и вполне определённой нормалью грани. Вызывающий,
    // разворачивающий `dir` знаком, обязан отличать одно от другого: развёрнутое умолчание
    // перестаёт быть умолчанием, а развёрнутая нормаль грани — это правильный ответ, выброшенный
    // ради умолчания.
    bool degenerate = false;
};

// Ближайшая точка отрезка. Параметр вдоль ребра считается в int64 и с нормировкой: квадрат длины
// ребра в Q16.16 насыщается уже на 182 юнитах, а формы бывают до 4096 — на насыщенном знаменателе
// параметр выходит нулевым, и «ближайшей» всегда оказывается первая вершина.
Vec2 closest_on_segment(Vec2 a, Vec2 b, Vec2 p);

Nearest nearest_on_core(Vec2 p, const WorldShape& s);

} // namespace framework::physics
