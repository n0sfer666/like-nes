#pragma once
#include <cstdint>
#include <vector>

#include "body.hpp"

// Хеш состояния физики — то, что сверяет гейт 1 спеки #15 между macOS, Linux и Windows и гейт 2
// между обычным и перетасованным порядком создания тел.
//
// Обход идёт по ВОЗРАСТАНИЮ КЛЮЧА, а не по порядку в массиве, и в этом весь смысл функции: массив
// хранит тела в порядке создания, а порядок создания — как раз то, что гейт 2 обязан не заметить.
// Хеш по индексам был бы гейтом на порядок вставки, а не на результат симуляции.
namespace framework::physics {

// `scratch` — рабочий буфер под порядок обхода, владеет им вызывающий: так функция не ходит в кучу
// и её можно звать хоть каждый кадр (гейт 6). Содержимое буфера значения не имеет, размер — тоже:
// он приводится к числу тел на месте.
uint64_t state_hash(const std::vector<Body>& bodies, std::vector<uint32_t>& scratch);

} // namespace framework::physics
