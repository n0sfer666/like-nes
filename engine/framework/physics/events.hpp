#pragma once
#include <vector>

#include "body.hpp"
#include "contact.hpp"

// События контакта: начало, продолжение, конец — и доставка ПОСЛЕ шага, а не из середины решателя.
//
// Требование спеки #15 буквальное («доставка игровым системам после шага физики, не из середины
// solver'а»), и причина у него не стилистическая: решатель проходит по контактам
// `VELOCITY_ITERATIONS` раз за шаг, внутри итераций состояние тел промежуточное, а игровая реакция
// на событие (убить, открыть дверь, сменить тип тела) поменяла бы мир под ногами у оставшихся
// итераций. Событие поэтому — запись в буфер, который игра читает, когда шаг уже кончился.
namespace framework::physics {

enum class ContactPhase : uint8_t { Begin = 0, Stay = 1, End = 2 };

struct ContactEvent {
    // Ключи, а не индексы: событие переживает шаг и уезжает в игровую логику, а индекс осмыслен
    // только внутри мира и только пока никто не добавлял тел.
    uint32_t key_a = 0;
    uint32_t key_b = 0;
    ContactPhase phase = ContactPhase::Begin;
    bool trigger = false;
    // Геометрия касания. У фазы `End` она ПУСТАЯ, и это честный ответ, а не потеря: в момент, когда
    // событие возникает, касания уже нет, а точка с прошлого кадра описывала бы состояние, которого
    // больше не существует. Игре, которой нужна точка расставания, нужна точка последнего касания —
    // она приходила в `Stay` кадром раньше.
    Vec2 normal;
    Vec2 point;
    fix32 penetration;
};

// Память о том, кто с кем касался в прошлом кадре. Ровно она превращает множество текущих контактов
// в поток событий: «начало» — это то, чего не было, «конец» — то, чего не стало.
class ContactTracker {
public:
    // Резерв — на конструкторе мира: буферы обязаны укладываться в уже выделенное (гейт 6 спеки #15).
    void reserve(size_t pairs);

    // Все три списка приходят упорядоченными по (key_a, key_b), потому что все три получены
    // фильтрацией одного списка пар и порядок в нём задан ключами. Раздельными их держит мир:
    // решателю триггеры отдавать нельзя, и знание об этом не должно жить в решателе.
    //
    // Спящие контакты (`resting`) приходят отдельным списком, но событиями НЕ отличаются от
    // решаемых: ящик, заснувший на полу, с пола никуда не делся, и `end` о нём был бы враньём —
    // обработчик расставания сработал бы на камне, который просто лежит. Поэтому они попадают в тот
    // же поток и дают `stay` из геометрии, запомненной кешем.
    //
    // Тела нужны ровно за одним — перевести плечо точки контакта в мировую точку: манифольд хранит
    // плечо от центра масс, потому что этим живёт решатель, а игре нужна точка на карте.
    void update(const std::vector<Body>& bodies, const std::vector<Manifold>& contacts,
                const std::vector<Manifold>& resting, const std::vector<Manifold>& triggers,
                std::vector<ContactEvent>& out);

private:
    struct Touched {
        uint64_t id = 0;   // (key_a << 32) | key_b — пара одним сравнимым числом
        bool trigger = false;
    };

    std::vector<ContactEvent> current_;
    std::vector<Touched> previous_;
};

} // namespace framework::physics
