#pragma once
#include <cstdint>

// Слои и маски: «кто с кем сталкивается», выраженное данными ТЕЛА, а не таблицей мира.
//
// Решение владельца (интервью 2026-08-09, вертикаль 2 PR B): у тела свой слой и маска тех, с кем
// оно готово столкнуться; пара живёт, только если СОГЛАСНЫ ОБА. Спека формулировала это матрицей
// 32x32 в мире, и отказ от неё стоит объяснения: матрица — ГЛОБАЛЬНОЕ состояние, у которого нет
// владельца. Её пришлось бы отдельно пекти, отдельно версионировать и отдельно чинить, когда тело
// приехало из одного бандла, а правило для его слоя — из другого. Пара полей на теле такого вопроса
// не задаёт: правило едет вместе с телом, которое им пользуется.
//
// Хеш состояния (`state_hash.cpp`) слой, маску и флаг триггера НЕ включает — и это осознанная
// граница, а не забывчивость: он сворачивает ЭВОЛЮЦИОНИРУЮЩЕЕ состояние (позицию, скорость, угол),
// то есть то, что шаг вычисляет, а не то, чем сцену настроили. Настройка пинится своими гейтами —
// `framework_physics_filter_test` для слоёв и триггеров, голден потока событий для их последствий.
// Сдвинуть эту границу можно, но тогда в хеш обязаны войти и тип тела, и материал, и форма: иначе
// получится произвольная половина, которая на вид обещает больше, чем проверяет.
//
// Согласие ОБОИХ, а не одного. Одностороннее правило делает отношение несимметричным, и тело
// оказывается втянуто в контакт, от которого явно отказалось. Здесь это не абстрактная придирка:
// порядок внутри пары нормализован по ключу (`broadphase.cpp`), то есть «кто из двоих спрашивает»
// решает сортировка ключей, а не игра, — и односторонний фильтр давал бы результат, зависящий от
// того, чей ключ меньше.
namespace framework::physics {

// Слой — БИТ, а не индекс. Тело живёт ровно в одном слое, но маска перечисляет много, и держать
// две кодировки одного понятия значило бы переводить их друг в друга на каждой правке.
using LayerMask = uint32_t;

constexpr LayerMask LAYER_DEFAULT = 1u;
constexpr LayerMask MASK_ALL = 0xffffffffu;

// Правило пары. Инлайн в заголовке, а не в отдельном TU: это две операции «и», а зовётся оно из
// внутреннего цикла широкой фазы, где вызов через границу трансляции стоил бы дороже самого правила.
constexpr bool layers_agree(LayerMask layer_a, LayerMask mask_a, LayerMask layer_b,
                            LayerMask mask_b) {
    return (layer_a & mask_b) != 0u && (layer_b & mask_a) != 0u;
}

// Правило ЗАПРОСА, и оно одностороннее — намеренно. У луча нет своего слоя: он не тело, ни с кем не
// сталкивается и ни от чего не отталкивается, поэтому «согласие обоих» здесь не выражается вовсе —
// второй стороне нечем соглашаться. Тело, не желающее попадать под запрос, выражает это ЧЕРЕЗ СЛОЙ:
// запрос перечисляет слои, которые ему интересны. Разница с правилом пары названа здесь прямо,
// потому что одинаковые на вид маски работают в двух местах по разным правилам.
constexpr bool query_accepts(LayerMask query_mask, LayerMask body_layer) {
    return (query_mask & body_layer) != 0u;
}

} // namespace framework::physics
