#pragma once
#include <vector>

#include "cast.hpp"
#include "world.hpp"

// Запросы к миру: перекрытие области, трассировка луча, свип формы (гейт 4 спеки #15).
//
// Все три — ЧИТАЮЩИЕ: мир передаётся по константной ссылке, и ни один запрос не двигает тела и не
// трогает кеш манифольдов. Это не аккуратность, а условие вменяемости: запрос зовут из игровой
// логики в произвольный момент кадра, и запрос, меняющий состояние, сделал бы результат симуляции
// функцией того, сколько раз игра что-то спросила.
namespace framework::physics {

struct QueryFilter {
    // Маска СЛОЁВ, которые запросу интересны. Правило одностороннее, обоснование — `filter.hpp`.
    LayerMask mask = MASK_ALL;
    // Триггеры по умолчанию НЕ попадают в ответ. Умолчание выбрано по самому частому запросу: луч
    // видимости не должен упираться в зону урона, а свип персонажа — тормозить о неё. Игре, которой
    // нужно обратное («что за зоны накрывают точку»), флаг стоит одного слова, и она про этот вопрос
    // как раз думает; той, что просто трассирует луч, умолчание «включая триггеры» подсунуло бы
    // невидимую стену, о которой она не думает вовсе.
    bool include_triggers = false;
};

struct Overlap {
    BodyId body;
    uint32_t key = 0;
};

struct RayHit {
    BodyId body;
    uint32_t key = 0;
    fix32 fraction;    // доля пути от начала к концу
    Vec2 point;
    Vec2 normal;       // наружу из препятствия, соглашение — `cast.hpp`
};

// Форма запроса вращается вокруг СВОЕЙ `position`, а не вокруг центра масс, как форма тела. Разница
// намеренная: центр масс тела — следствие того, что тело вращает решатель, а у запроса ни массы, ни
// решателя нет, и «поставить форму сюда» означает именно сюда.
//
// `out` очищается и заполняется по возрастанию КЛЮЧА тела. Порядок по ключу, а не по индексу: индекс
// есть порядок создания, и гейт 2 спеки #15 перетасовывает его специально — запрос, отвечающий в
// порядке индексов, разошёлся бы сам с собой на той же сцене.
void overlap_shape(const World& w, const Shape& s, Vec2 position, fix32 angle, const QueryFilter& f,
                   std::vector<Overlap>& out);

// Все касания формы, по одному вызову на тело. Обходом, а не вектором ответов, потому что
// спрашивают его из тика персонажа, а тик персонажа не ходит в кучу: гейт
// `framework_character_alloc_test` называет `overlap_shape` поимённо как то, чем это заявление
// ломается молча. Форма обратного вызова — та же, что у систем сцены (`core/stage.hpp`): указатель
// на функцию плюс `void*`, без `std::function`, у которой своё владение и своя куча.
//
// Касание считается ТЕМ ЖЕ узким запросом, что и свип (`cast_shape` нулевым путём), а не
// `collide_shapes`: персонаж ходит в мир свипами, и второй критерий касания означал бы, что «во что
// я уже влез» и «во что я упрусь» вправе разойтись на допуске — а на этом допуске стоит весь зазор
// `SKIN`. Нормаль поэтому приходит та же, по которой персонажа разбирает `move_and_slide`.
//
// Порядок обхода — порядок ПОЛОСЫ, то есть раскладки, и разводить ничьи обязан потребитель (ключом,
// как это делают `overlap_shape` и `closer`). Отдавать упорядоченное здесь нечем: порядок требует
// накопления, накопление — памяти, а её у обхода нет по построению.
using ContactFn = void (*)(void* user, const RayHit& hit);
void each_contact(const World& w, const Shape& s, Vec2 position, fix32 angle, const QueryFilter& f,
                  ContactFn fn, void* user);

// Ближайшее касание луча. `delta` — путь целиком, а не направление: длина запроса и его направление
// это одна величина, и раздельные «направление плюс дальность» пришлось бы согласовывать в каждом
// вызове (нормировано ли направление? учтена ли дальность в доле?).
bool raycast(const World& w, Vec2 origin, Vec2 delta, const QueryFilter& f, RayHit& out);

// Ближайшее касание формы, перенесённой на `travel`. Поворота по пути нет (см. `cast.hpp`).
bool shapecast(const World& w, const Shape& s, Vec2 position, fix32 angle, Vec2 travel,
               const QueryFilter& f, RayHit& out);

} // namespace framework::physics
