#pragma once
#include <cstddef>
#include <cstdint>

// Примитив свёртки, общий у хеша состояния и хеша событий.
//
// Вынесен, как только потребителей стало два, и не ради экономии девяти строк: два голдена, сложенные
// РАЗНЫМИ смешиваниями, невозможно сравнивать между собой, а расхождение констант никак себя не
// проявляет — оба хеша просто считаются, оба перепиниваются, и разница вылезает через полгода, когда
// кто-нибудь сверит одно с другим.
namespace framework::physics {

constexpr uint64_t FNV_OFFSET = 0xcbf29ce484222325ULL;
constexpr uint64_t FNV_PRIME = 0x100000001b3ULL;

inline void mix(uint64_t& h, uint32_t v) {
    // Байтами, а не целым словом: смешивание четырёх байт по одному не зависит от порядка байт в
    // машине, а `h ^= v` — зависело бы. Хеш сверяется между x86 и ARM, и на ARM он обязан совпасть
    // не потому, что обе платформы little-endian сегодня, а потому, что вопрос здесь не задаётся.
    for (int i = 0; i < 4; ++i) {
        h ^= static_cast<uint64_t>((v >> (i * 8)) & 0xffu);
        h *= FNV_PRIME;
    }
}

// Формы ниже сведены аудитом #21 (находка 5): те же три цикла лежали по слою десятью рукописными
// копиями с ТЕМИ ЖЕ константами. Их именно ТРИ, а не одна, и это не удобство — каждая даёт СВОЁ
// число на одном и том же входе, поэтому свести их между собой значило бы перештамповать голдены,
// которые они считают. Разница ровно в том, чем кормится xor: по одному байту, по восьми байтам
// целого в фиксированном little-endian порядке, или целым словом разом.
//
// `mix_word` порядка байт НЕ фиксирует и потому endian-независимой не является; она оставлена
// только там, где голден уже на ней стоит, и новому хешу брать её незачем — берётся `mix_u64`.
inline void mix_bytes(uint64_t& h, const uint8_t* p, size_t n) {
    for (size_t i = 0; i < n; ++i) {
        h ^= static_cast<uint64_t>(p[i]);
        h *= FNV_PRIME;
    }
}

inline void mix_u64(uint64_t& h, uint64_t v) {
    for (int i = 0; i < 8; ++i) {
        h ^= (v >> (i * 8)) & 0xffu;
        h *= FNV_PRIME;
    }
}

inline void mix_word(uint64_t& h, uint64_t v) { h = (h ^ v) * FNV_PRIME; }

} // namespace framework::physics
