// Связность тел по контактам: кто с кем связан цепочкой касаний.
//
// Нужна ровно затем, чтобы сон был решением ГРУППЫ, а не тела. Ящик, лежащий на ящике, который
// вот-вот поедет, обязан проснуться вместе с ним, и узнать об этом заранее можно только через того,
// кто их связывает: сам по себе нижний ящик неподвижен ровно до того кадра, в котором его толкнули.
//
// Статика в связности НЕ участвует, и это не оптимизация. Пол — общий сосед всей сцены, и через него
// весь уровень стал бы ОДНИМ островом: башня в одном углу карты не давала бы заснуть камню в другом,
// а любое движение будило бы всё разом. Тот же довод про кинематику НЕ работает — она движется, и
// лежащий на ней груз обязан числиться с ней в одной группе, иначе он заснёт на уезжающей платформе.
namespace framework::physics {

class Islands {
public:
    void reserve(uint32_t capacity);

    // Оба списка манифольдов — рёбра одного графа. Спящие пары живут отдельным списком (решателю их
    // отдавать нечего), но связывать тела не перестают: выпади они из графа, остров разваливался бы
    // ровно в тот кадр, когда заснул, и на следующем каждый его ящик решал бы за себя.
    void build(const std::vector<Body>& bodies, const std::vector<Manifold>& contacts,
               const std::vector<Manifold>& resting);

    // Представитель компоненты — МИНИМАЛЬНЫЙ индекс в ней. Минимальный, а не «тот, что оказался
    // корнем после объединения по рангу»: представитель служит ярлыком острова между вызовами, и
    // ярлык, зависящий от порядка объединения, менялся бы от кадра к кадру на неизменной сцене.
    //
    // Тело, добавленное ПОСЛЕ последней сборки, представляет само себя: ответ «сам себе остров» для
    // него верен — ни одного контакта у него ещё не было.
    uint32_t root(uint32_t body) const { return body < root_.size() ? root_[body] : body; }

private:
    uint32_t find(uint32_t i);

    std::vector<uint32_t> parent_;
    std::vector<uint32_t> root_;
};

} // namespace framework::physics
