// Отношение q = arm^2 / (I/m), безразмерное и порядка единицы: и плечо, и корень из момента на
// единицу массы — это габарит формы, и он в частном сокращается. Кламп потолком fix32 стоит ДО
// умножения на обратную массу: у формы с выродившимся ядром и большим радиусом момент считается по
// ядру (это названо в `mass.cpp`), то есть знаменатель уходит к нулю, а произведение — за int64.
// Знак терять негде: числитель — квадрат.
int64_t over_inertia(int64_t arm_sq, int64_t unit_inertia) {
    if (unit_inertia <= 0) return 0;
    const int64_t q = (arm_sq * fix32::ONE) / unit_inertia;
    return q > INT32_MAX ? INT32_MAX : q;
}

// Потолок вклада, выраженный в Q16.32. Вклад входит в `k` величиной Q16.16 и там ограничен потолком
// fix32; здесь та же граница держится на шестнадцать разрядов ниже, потому что в ЭТОЙ же шкале из
// него считается доля: числитель `term * INV_TAU` обязан быть на тридцать два разряда крупнее
// знаменателя `arm * k`, иначе частное не попадёт в Q16.16 без второго округления. Насыщение стоит
// на этом потолке, а не после сдвига, ровно затем, чтобы обе величины упирались в предел
// ОДНОВРЕМЕННО — см. `angular_share`.
constexpr int64_t MAX_TERM_Q32 = static_cast<int64_t>(INT32_MAX) << fix32::SHIFT;

// Вклад вращения в эффективную обратную массу: inv_I * arm^2, посчитанный БЕЗ промежуточного inv_I
// и в шкале Q16.32. Порядок здесь несущий, а не стилистический. Обратный момент в Q16.16 не
// помещается снизу: у коробки 32x32 он равен raw 383 при массе 1 и РОВНО НУЛЮ при массе 384 —
// вращение выключалось внутри объявленного диапазона масс, тихо и на всех платформах одинаково.
// Умножение на квадрат плеча ДО деления убирает ступеньку: делится величина порядка габарита, а не
// её обратная.
int64_t inertia_term_q32(fix32 inv_mass, int64_t unit_inertia, fix32 arm) {
    if (arm.raw == 0) return 0;
    const int64_t arm_sq = (static_cast<int64_t>(arm.raw) * arm.raw) >> fix32::SHIFT;
    const int64_t term = static_cast<int64_t>(inv_mass.raw) * over_inertia(arm_sq, unit_inertia);
    const int64_t capped = term > MAX_TERM_Q32 ? MAX_TERM_Q32 : term;
    // Хвост ниже разрешения `k` отбрасывается ПРЯМО ЗДЕСЬ, а не при сложении. `k` — величина Q16.16,
    // и вклад входит в неё сдвигом вниз; доля же считается из полного Q16.32, и полный хвост стал бы
    // вкладом, которого в `k` нет вовсе. Цена расхождения измерима: у коробки 32x32 массой 4096 на
    // плече 3.2 вклад равен 62912, то есть ЦЕЛИКОМ хвост — в `k` не попадает ни разряда, а доля от
    // него живая, и решатель применял бы 1.06 * lambda вместо lambda на верхнем краю диапазона масс.
    // Именно отбрасывание, а не округление: `k` собирается тем же сдвигом вниз, и любое другое
    // правило разъехалось бы с ним в другую сторону.
    return (capped >> fix32::SHIFT) << fix32::SHIFT;
}

// Угловая доля: inv_I * arm * INV_TAU / k. Считается ИЗ ТОГО ЖЕ значения, что легло в `k`, и это
// главное свойство функции, а не экономия. Независимый второй расчёт клампился бы на ДРУГОМ пороге:
// вклад в `k` насыщается по arm^2, доля — по arm, и в окне между порогами решатель применял бы не
// то, что заложил. Такое расхождение уже стоило вертикали 2 одного тихого дефекта — доля выходила
// нулём при живом вкладе в `k`, и тяжёлое тело недополучало больше половины отпора, проваливаясь
// сквозь статику. Здесь оно невыразимо в ОБЕ стороны, и обе закрыты у источника: `inertia_term_q32`
// возвращает вклад уже насыщенным и уже приведённым к разрешению `k`, поэтому ни потолок, ни
// отброшенный хвост не могут попасть в одну величину и не попасть в другую.
//
// Масштаб держится вдвое длиннее (Q16.32) до самого деления: величина inv_I * arm при массе 4096
// равна 2.3e-5, то есть полтора младших разряда Q16.16, и после перевода в обороты от неё не
// осталось бы ничего. Знак приходит только из знаменателя, а целочисленное деление усекает к нулю —
// поэтому доля СИММЕТРИЧНА по знаку плеча: зеркальная сцена остаётся зеркалом.
fix32 angular_share(int64_t term_q32, fix32 arm, fix32 k) {
    if (term_q32 == 0 || arm.raw == 0 || !(k.raw > 0)) return fix32{};
    // Оба произведения помещаются в int64 с запасом вдвое: числитель не выше 1.5e18 (потолок вклада
    // на INV_TAU), знаменатель — 4.6e18 (два потолка fix32). `__int128` недоступен на MSVC, и это
    // единственная причина, по которой границы приходится держать в уме, а не в типе.
    const int64_t num = term_q32 * INV_TAU.raw;
    const int64_t den = static_cast<int64_t>(arm.raw) * k.raw;
    return fix32::from_raw(fix32::sat(num / den));
}

