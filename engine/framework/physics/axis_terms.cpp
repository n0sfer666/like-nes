AxisTerms axis_terms(const Body& a, const Body& b, Vec2 ra, Vec2 rb, Vec2 axis) {
    AxisTerms t;
    // Плечо входит в `k` КВАДРАТОМ, и это не формальность: контакт у края длинной формы разрешается
    // почти без изменения линейной скорости — импульс уходит в поворот, — а контакт против центра
    // масс поворота не даёт вовсе.
    const fix32 arm_a = cross(ra, axis);
    const fix32 arm_b = cross(rb, axis);
    const int64_t term_a = inertia_term_q32(a.inv_mass, a.unit_inertia, arm_a);
    const int64_t term_b = inertia_term_q32(b.inv_mass, b.unit_inertia, arm_b);
    t.k = a.inv_mass + b.inv_mass + fix32::from_raw(fix32::sat(term_a >> fix32::SHIFT)) +
          fix32::from_raw(fix32::sat(term_b >> fix32::SHIFT));
    if (!(t.k.raw > 0)) return t;
    t.lin_a = a.inv_mass / t.k;
    t.lin_b = b.inv_mass / t.k;
    t.ang_a = angular_share(term_a, arm_a, t.k);
    t.ang_b = angular_share(term_b, arm_b, t.k);
    return t;
}

