// Эффективная обратная масса контакта вдоль оси и доли тел в ней. Отдельным файлом от подготовки
// контактов, потому что это отдельная величина с собственным контрактом единиц и собственным
// классом дефектов: оба провала вертикали 2 (вращение, выключенное округлением; доля, обнулившаяся
// при живом вкладе в `k`) жили здесь, а наблюдались за двести сорок шагов сцены — где «доля равна
// нулю» и «доля вдвое меньше нужной» дают один и тот же исход «тело утонуло».
//
// Определяющее свойство величины, которое и делает её проверяемой напрямую: приложенное решателем
// изменение относительной скорости вдоль оси равно `lambda` — ни больше, ни меньше. Это тождество
// связывает `k` и доли между собой, и любое их расхождение видно на одном контакте без единого шага
// мира (гейт `framework_physics_terms_test`).
namespace framework::physics {

// `ra`/`rb` — плечи от центров масс до точки контакта, `axis` — единичная ось (нормаль или
// касательная). Ось обязана быть единичной: тождество выше держится на `dot(axis, axis) == 1`.
AxisTerms axis_terms(const Body& a, const Body& b, Vec2 ra, Vec2 rb, Vec2 axis);

} // namespace framework::physics
