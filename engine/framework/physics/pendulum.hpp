#pragma once
#include <cstdint>

#include "fixmath.hpp"

namespace framework::physics {

// Маятник — дуга `arc` от отвеса и линейная скорость `speed` по ней, px и px/тик, а не угол и угловая
// скорость: угол в оборотах на длинном подвесе квантуется грубее пикселя, и энергия у такого маятника
// росла до 8 % от одного округления. Дуга вправо положительна, `+Y` вниз, как у контроллера #16.
struct Pendulum {
    fix32 arc;
    fix32 speed;
};

// Длина — от 1 до 5000 px: `length · 2π` в Q16.16 насыщается выше ~5215 px, а нулевая длина делит
// дугу на ноль, и оба отказа молчат — шаг идёт дальше на неверном угле. Уровень держит 16..256
// (`scene_read`), другой источник длины обязан держать свой диапазон сам.
fix32 pendulum_turns(fix32 arc, fix32 length);
// Размах — до горизонтали в обе стороны, четверть окружности дугой.
fix32 pendulum_cap(fix32 length);
Vec2 pendulum_end(Vec2 pivot, fix32 length, fix32 arc);
// Единичная касательная в сторону роста дуги.
Vec2 pendulum_tangent(fix32 arc, fix32 length);

// Полунеявный Эйлер: скорость от тяжести `g` (px/тик²) и раскачки `push`, затем дуга новой
// скоростью, затем затухание — доля `1 / damping` скорости за тик: с ним энергия без раскачки не
// растёт и на округлении. На пределе размаха маятник встаёт: дуга зажимается, скорость обнуляется.
// `damping` строго больше нуля: ноль — целочисленное деление на ноль, отрицательный раскачивает
// маятник вместо затухания. Проверки на горячем пути нет — делитель задаёт игра константой.
void swing_pendulum(Pendulum& p, fix32 length, fix32 g, fix32 push, int32_t damping);

} // namespace framework::physics
