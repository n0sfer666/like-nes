// Примитивы порядка sweep-and-prune, общие у широкой фазы шага (`broadphase.cpp`) и индекса
// запросов (`query_index.cpp`). Общий здесь именно КОД, а не состояние: делить состояние между
// шагом и запросом нельзя по причине, названной в `query_index.hpp`, — но утверждение о
// детерминизме у обеих сортировок ОДНО, и разъехаться им нечем. Разъедутся они молча: правка одной
// копии оставит вторую как была, и увидено это будет разным набором кандидатов на одной из трёх ОС.
namespace framework::physics {

// Границы РАСШИРЯЮТСЯ на спекулятивное поле, и без этого поле не работает вовсе: `overlaps` считает
// касание границ отсутствием перекрытия (строгое `<`), поэтому две формы, стоящие ровно впритык, до
// узкой фазы не доходят. Именно так башня и проваливалась сама в себя: опоры нет, пока ящик в неё
// не влез. Расширение на ПОЛНОЕ поле с каждой стороны, а не на половину: отсечение обязано быть
// НАДМНОЖЕСТВОМ — пропущенная им пара невосстановима, а лишняя стоит одного отказа узкой фазы.
inline Aabb padded(const Aabb& a, fix32 margin) {
    const Vec2 pad = {margin, margin};
    return {a.min - pad, a.max + pad};
}

// Порядок по ЛЕВОМУ краю, ничьи разводятся ключом, и добивка обязательна: при равных левых краях
// (сетка тайлов, стопка ящиков — норма, а не редкость) порядок равных элементов у `std::sort`
// стандартом не определён, значит зависел бы от реализации библиотеки, то есть от ОС. Ключ тела
// уникален не по договорённости, а принудительно — `World::add` отбивает дубликат, — поэтому
// добивка им делает порядок единственным.
inline bool sweep_before(const Aabb& l, uint32_t l_key, const Aabb& r, uint32_t r_key) {
    if (!(l.min.x == r.min.x)) return l.min.x < r.min.x;
    return l_key < r_key;
}

} // namespace framework::physics
