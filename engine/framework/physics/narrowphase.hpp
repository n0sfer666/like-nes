// Узкая фаза: пара-кандидат из широкой фазы превращается в манифольд — или отбрасывается.
//
// Сочетаний ТРИ, а не шестнадцать, и это прямое следствие единой формы (ядро плюс радиус):
//
//   ядро-точка против любого   — ближайшая точка ядра, одна точка контакта
//   два отрезка                — то же, плюс отсечение по разделяющей оси для параллельного случая
//   всё остальное              — разделяющая ось и отсечение грани
//
// Разбиение по ГЕОМЕТРИИ, а не по именам типов: «круг об коробку» и «круг об многоугольник» — это
// один и тот же вопрос о расстоянии до ядра, и написанные порознь они разъезжаются на округлении.
namespace framework::physics {

// Заполняет `out` (кроме индексов и ключей тел — их ставит вызывающий) и возвращает true, если тела
// касаются. Нормаль единичная и направлена ИЗ `a` В `b`: это соглашение, а не деталь, — решатель
// считает по нему знак скорости сближения, и перепутанное направление даёт не «неточность», а
// притягивание вместо отталкивания.
//
// Поле передаётся ЯВНО, хотя вызывающий у этой перегрузки один. У шага два разных вопроса к одной и
// той же паре тел: разрешаемому контакту он смотрит на кадр вперёд (`SPECULATIVE_MARGIN` — иначе
// тело кадр падает свободно сквозь опору, которой ещё «нет»), а тела-ЗОНЕ вперёд смотреть незачем —
// она ничего не разрешает, и её событие отвечает на тот же вопрос, что `overlap`: «кто здесь
// сейчас». Была бы константа спрятана внутрь, зона срабатывала бы за 1/16 юнита ДО входа, и два
// ответа на один вопрос разошлись бы — молча, потому что оба выглядят правдоподобно.
//
// У спекулятивной точки `penetration` ОТРИЦАТЕЛЬНА и равна минус зазору. Знак несёт смысл и читается
// ниже по течению: решатель ограничивает по нему сближение, позиционная коррекция такую точку не
// трогает вовсе.
bool collide(const Body& a, const Body& b, fix32 margin, Manifold& out);

// Тот же выбор пути, но по уже развёрнутым формам и с ЯВНЫМ полем. Нужен свипу (`cast.cpp`) и
// запросу перекрытия (`query.cpp`): свип обязан спросить «пересекаются ли формы в НАЧАЛЕ пути» тем же
// кодом, которым отвечает шаг, — иначе он остановит тело там, где решатель контакта не видит, или
// наоборот пропустит начало внутри стены. Тело сюда не подходит: форма свипа не принадлежит никакому
// телу, она приехала из запроса игры.
//
// Поле — параметр, а не константа внутри, ровно потому, что у запроса и у шага он РАЗНЫЙ. Шаг
// смотрит вперёд на кадр и вправе считать контактом почти-касание; запрос отвечает на вопрос игры
// «кто здесь сейчас» и обязан отвечать по факту — иначе `overlap` вернул бы тело, стоящее рядом, а
// свип остановил бы стрелу на 1/16 юнита раньше стены. Нулевое поле = точный контракт.
bool collide_shapes(const WorldShape& a, Vec2 center_a, const WorldShape& b, Vec2 center_b,
                    fix32 margin, Manifold& out);

} // namespace framework::physics
