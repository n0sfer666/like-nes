#pragma once
#include "body.hpp"
#include "contact.hpp"

// Узкая фаза: пара-кандидат из широкой фазы превращается в контакт с нормалью и глубиной — или
// отбрасывается. Вертикаль 1 знает три сочетания: круг-круг, круг-коробка, коробка-коробка.
namespace framework::physics {

// Заполняет `out` (кроме индексов тел — их ставит вызывающий) и возвращает true, если тела
// действительно пересекаются. Нормаль единичная и направлена ИЗ `a` В `b`: это соглашение, а не
// деталь, — решатель считает по нему знак скорости сближения, и перепутанное направление даёт не
// «неточность», а притягивание вместо отталкивания.
bool collide(const Body& a, const Body& b, Contact& out);

} // namespace framework::physics
