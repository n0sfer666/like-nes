// Узкая фаза: пара-кандидат из широкой фазы превращается в манифольд — или отбрасывается.
//
// Сочетаний ТРИ, а не шестнадцать, и это прямое следствие единой формы (ядро плюс радиус):
//
//   ядро-точка против любого   — ближайшая точка ядра, одна точка контакта
//   два отрезка                — то же, плюс отсечение по разделяющей оси для параллельного случая
//   всё остальное              — разделяющая ось и отсечение грани
//
// Разбиение по ГЕОМЕТРИИ, а не по именам типов: «круг об коробку» и «круг об многоугольник» — это
// один и тот же вопрос о расстоянии до ядра, и написанные порознь они разъезжаются на округлении.
namespace framework::physics {

// Заполняет `out` (кроме индексов и ключей тел — их ставит вызывающий) и возвращает true, если тела
// действительно пересекаются. Нормаль единичная и направлена ИЗ `a` В `b`: это соглашение, а не
// деталь, — решатель считает по нему знак скорости сближения, и перепутанное направление даёт не
// «неточность», а притягивание вместо отталкивания.
bool collide(const Body& a, const Body& b, Manifold& out);

} // namespace framework::physics
