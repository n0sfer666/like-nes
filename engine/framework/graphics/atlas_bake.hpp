// Бейк текстового исходника нарезки атласа в zero-parse таблицу (`atlas_format.hpp`). Живёт в
// движке, а не в `assetc`, по образцу карты #16, профиля #16, пресетов #14 и достижений #10: тот же
// разбор нужен тестам, и вторая копия в инструменте разошлась бы с первой молча.
//
// Формат (разделитель — `|`, `#` до конца строки — комментарий, пустые строки игнорируются):
//   atlas  | 128 | 128                       # размер страницы в пикселях, ОДИН раз на файл
//   region | hero_idle_0 | 0 | 0 | 16 | 24 | 8 | 24    # имя | x | y | w | h | привязка x | y
//
// Страница одна на файл, потому что она одна в заголовке формата: атлас, не влезший в страницу, —
// это второй файл и вторая секция, а не второе значение ключа. Точка привязки ОБЯЗАТЕЛЬНА: любое
// умолчание здесь — невидимое соглашение о том, за какой угол подвешен каждый спрайт в игре, и
// узнаётся оно тогда, когда персонаж уезжает вбок.
//
// Пекарь отбивает НОМЕРОМ СТРОКИ, а не чинит молча:
//   * строка до `atlas` — без размера страницы регион нечем проверить на выход за её край;
//   * незнакомый ключ — опечатка иначе означала бы «поле осталось по умолчанию»;
//   * повтор `atlas` — победил бы последний, то есть смысл файла решал бы порядок строк;
//   * нулевая сторона страницы или региона — пустой регион рисуется как ничто и читается без
//     ошибки, то есть отдаёт отладку в рантайм;
//   * регион, свисающий за край страницы, — он сэмплит соседний спрайт, и это тоже читается без
//     единой ошибки;
//   * пустое имя — смещение 0 в блобе означает «имени нет», и поиск по пустой строке нашёл бы
//     такой регион первым;
//   * повтор ИМЕНИ — поиск по имени вернул бы первый, а правили бы второй (тот же довод, что у
//     карт #16);
//   * координата с точкой или знаком — половина пикселя в прямоугольнике означала бы, что нарезка
//     зависит от округления сэмплера, а «-4» молча заворачивалось бы в 65532;
//   * больше 65535 регионов — `RegionId` (`clip.hpp`) шестнадцатибитный, и до 65536-го кадр не
//     доедет номером вовсе;
//   * исходник без единого региона — таблица без регионов читается без ошибки и означает «атласа
//     нет».
//
// Перекрытие регионов НЕ отбивается: 9-slice и два имени на одну картинку — законные записи, и
// запрет отнял бы их ради дефекта, которого у нарезки нет.
namespace framework::graphics {

struct AtlasBakeError {
    int line = 0;
    std::string message;
};

// `RegionId` региона — его НОМЕР ПО ПОРЯДКУ объявления: пекарь не сортирует и не переупорядочивает
// строки. Сортировка (хоть по имени, хоть по площади) была бы вторым правилом о том, какой номер у
// региона, и разошлась бы с исходником при первом же взгляде глазами.
struct ParsedRegion {
    std::string name;
    uint16_t x = 0;
    uint16_t y = 0;
    uint16_t w = 0;
    uint16_t h = 0;
    Vec2 pivot{};
};

struct ParsedAtlas {
    uint16_t page_width = 0;
    uint16_t page_height = 0;
    std::vector<ParsedRegion> regions;
};

// Разбор отдельно от сборки байтов: тест вправе спросить, ЧТО прочиталось, не разбирая при этом
// таблицу обратно.
bool parse_atlas(const std::string& text, ParsedAtlas& out, AtlasBakeError& err);
bool parse_atlas_file(const std::string& path, ParsedAtlas& out, AtlasBakeError& err);

bool bake_atlas(const std::string& text, std::vector<uint8_t>& out, AtlasBakeError& err);
bool bake_atlas_file(const std::string& path, std::vector<uint8_t>& out, AtlasBakeError& err);

} // namespace framework::graphics
