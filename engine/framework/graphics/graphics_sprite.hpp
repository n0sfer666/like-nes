#pragma once
#include <cstdint>

#include "atlas_read.hpp"
#include "fixmath.hpp"

// Спрайты, порядок отрисовки и батчи (спека #17, вертикаль 2, шаг A). Здесь ТОЛЬКО раскладка:
// список спрайтов превращается в порядок отрисовки и в набор батчей, и ни одна строка файла не
// знает про RHI, буфер вершин и текстуру. Гейты 6 (число draw-call'ов) и 8 (zero-alloc) поэтому
// закрываются СЧЁТЧИКАМИ на трёх ОС, а не картинкой на машине владельца.
//
// Игра-образец решает вырожденный случай: один атлас, один материал, порядок отрисовки равен
// порядку подачи (`SpriteBatch` в `example_ugly_game/batch.cpp` — единственный буфер инстансов и
// единственный draw-call). Шаг A обобщает его до слоёв и нескольких материалов, оставляя тот случай
// внутри как частный: список с одним материалом обязан дать РОВНО один батч.
namespace framework::graphics {

using framework::Vec2;

// Геометрия та же, что у отладочного квада шага E, и это не совпадение: поворот единичным
// направлением, а не углом, потому что тригонометрии в целочисленной математике нет, а потребителю
// нужна матрица. Материал — идентичность того, чем рисуют (пайплайн + текстура), и слой не входит в
// него намеренно: два слоя на одном атласе обязаны склеиваться в один draw-call.
struct Sprite {
    Vec2 center{};
    Vec2 half{};
    Vec2 dir{fix32::from_int(1), fix32{}};
    uint32_t rgba = 0xffffffffu;
    RegionId region = 0;
    uint16_t material = 0;
    int16_t layer = 0;
};

// Батч — ОТРЕЗОК отсортированного порядка, а не копия спрайтов: копирование ради группировки
// стоило бы второго буфера, а порядок и так лежит числами.
struct Batch {
    uint32_t first = 0;
    uint32_t count = 0;
    uint16_t material = 0;
};

// Ключ сортировки: слой (старшие 16), материал (средние 16), НОМЕР ПОДАЧИ (младшие 32). Третье поле
// делает порядок ПОЛНЫМ — двух равных ключей не бывает, — и это несущее решение, а не украшение:
// `std::stable_sort` ходит в кучу (гейт 8 запрещает), а `std::sort` при равных ключах даёт порядок,
// зависящий от реализации, то есть РАЗНУЮ картинку на трёх ОС. Стабильность здесь свойство ключа, а
// не алгоритма.
//
// Слой знаковый, поэтому смещается в беззнаковый диапазон: побитовый сдвиг отрицательного числа
// сравнивался бы не в том порядке, и фон уехал бы поверх персонажа ровно на отрицательных слоях.
uint64_t sprite_key(const Sprite& s, uint32_t submitted);

// Буферы ПРИНАДЛЕЖАТ ВЫЗЫВАЮЩЕМУ (гейт 8): и спрайты, и ключи, и батчи. Переполнение любого из трёх
// СЧИТАЕТСЯ, а не молчит, по той же причине, что у оверлея шага E: недорисованный кадр снаружи
// выглядит ровно как кадр, который так и задумывали.
class SpriteList {
public:
    SpriteList(Sprite* sprites, uint64_t* keys, uint32_t capacity);

    void clear();
    void push(const Sprite& s);

    // Сортирует ключи на месте и режет их на батчи по смене материала. Возвращает число батчей,
    // то есть число будущих draw-call'ов, — им и меряется гейт 6.
    uint32_t build(Batch* out, uint32_t max_batches);

    uint32_t count() const { return count_; }
    uint32_t dropped() const { return dropped_; }
    const Sprite* data() const { return sprites_; }

    // Спрайт по месту в ОТСОРТИРОВАННОМ порядке: `build` переставляет ключи, а не спрайты, поэтому
    // читать их подряд из `data()` — значит читать порядок подачи.
    const Sprite& drawn(uint32_t i) const;

private:
    Sprite* sprites_ = nullptr;
    uint64_t* keys_ = nullptr;
    uint32_t capacity_ = 0;
    uint32_t count_ = 0;
    uint32_t dropped_ = 0;
};

} // namespace framework::graphics
