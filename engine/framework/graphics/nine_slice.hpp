#pragma once

#include "sprite.hpp"

// 9-slice (спека #17, вертикаль 2, шаг A): панель растягивается серединами, а углы сохраняют
// натуральный размер. Здесь тоже только раскладка — на выходе обычные спрайты в общем списке.
//
// Куски заданы ДЕВЯТЬЮ РЕГИОНАМИ, а не одним с отступами, и это следует из шага D: спека прямо
// называет перекрытие регионов законной записью «9-slice и псевдонимы», то есть панель нарезается в
// `atlas.txt` именами. Альтернатива — подрезать UV одного региона внутри слоя — потребовала бы,
// чтобы слой считал UV, а он их не считает нигде.
namespace framework::graphics {

struct NineSliceRegions {
    RegionId tl = 0, t = 0, tr = 0;
    RegionId l = 0, c = 0, r = 0;
    RegionId bl = 0, b = 0, br = 0;
};

// `corner` — ПОЛНЫЙ размер угла в мировых единицах, а не в пикселях: сколько экранных пикселей
// приходится на мировую единицу — это зум, и он вопрос к рендеру, а не к раскладке (спека переносит
// его в отдельный шаг вертикали 2). Угол больше половины панели УРЕЗАЕТСЯ до неё: два угла, не
// помещающиеся рядом, иначе перекрылись бы, и панель нарисовалась бы шире, чем просили.
void nine_slice(SpriteList& out, const NineSliceRegions& regions, Vec2 center, Vec2 half,
                Vec2 corner, uint32_t rgba, uint16_t material, int16_t layer);

} // namespace framework::graphics
