#pragma once
#include "clip.hpp"

// Проигрыватель клипа: состояние — ОДНО число тиков, всё остальное считается из него функциями
// `clip.hpp`. Ни кадра, ни номера шага в состоянии не лежит намеренно: два источника правды о
// текущем кадре разошлись бы на первой же перемотке, и прогон, начатый с середины, перестал бы
// совпадать с прогоном, доигравшим до неё.
//
// Скорость воспроизведения — ЦЕЛОЧИСЛЕННАЯ ДРОБЬ, а не множитель: время шкалы получается как
// `elapsed * num / den` в 64 битах, то есть точно и без накопления. Множитель на fix32 пришлось бы
// прибавлять к накопителю каждый тик, и три машины разошлись бы на длинном прогоне — той же
// ошибкой округления, ради которой в этом движке нет float в тике вовсе.
//
// Цена решения названа вслух: смена скорости на ходу ПЕРЕСЧИТЫВАЕТ шкалу от начала клипа, а не
// продолжает её с текущего кадра. Это следствие того, что состояние — тики, а не время шкалы, и
// менять скорость посреди клипа поэтому стоит вместе с `anim_play`.
namespace framework::graphics {

struct AnimPlayer {
    Clip clip{};
    uint32_t elapsed = 0;
    uint16_t rate_num = 1;
    uint16_t rate_den = 1;
};

uint64_t anim_time(const AnimPlayer& p);
uint16_t anim_frame(const AnimPlayer& p);
bool anim_finished(const AnimPlayer& p);

// Возвращают ЧИСЛО СЛУЧИВШИХСЯ событий, а записывают не больше `max`. Разведены они потому, что
// потерянное событие анимации — это не пропущенный кадр, а не нанесённый удар: усечение обязано
// быть ВИДНО вызывающему, а не проявиться разницей sim-хеша через сотню тиков. Вернувшееся число
// больше `max` и есть эта улика.
uint32_t anim_play(AnimPlayer& p, const Clip& c, AnimEvent* out, uint32_t max);
uint32_t anim_step(AnimPlayer& p, AnimEvent* out, uint32_t max);

} // namespace framework::graphics
