#pragma once

#include "fixmath.hpp"

// Зум (вертикаль 2, шаг D спеки #17). Зум — это СОГЛАШЕНИЕ о том, сколько экранных пикселей
// приходится на мировую единицу, и живёт оно здесь, а не в `CameraConfig`, по одной причине:
// `camera_follow` пишет `Camera::center`, то есть камера стоит НА ПУТИ СОСТОЯНИЯ. Поле зума в ней
// затащило бы разрешение экрана и настройку игрока в тик, и «поменял окно — разошёлся sim-хеш»
// стало бы законным поведением. Вид знает про камеру, камера про вид — нет.
//
// Масштаб один на оба преобразования: `pixels_per_unit * zoom`. Второй множитель где-нибудь ещё
// был бы вторым КОНТРАКТОМ, расходящимся с первым на округлении, — то же основание, по которому
// окно тайловой карты заимствуется у сетки, а не считается заново.
namespace framework::graphics {

using framework::Vec2;

// Отказы вида. Зум — число игрока (ползунок настроек, скрипт катсцены), поэтому «ноль», «минус» и
// «слишком мелко, чтобы отличаться от нуля» обязаны быть НАЗВАНЫ, а не поделены молча: деление на
// ноль в fix32 насыщает, то есть вырожденный вид отрисовал бы мир одним пикселем и выглядел бы как
// чёрный экран, а не как ошибка настройки.
enum ViewportFault : uint8_t {
    VIEWPORT_OK = 0,
    VIEWPORT_ZOOM_NOT_POSITIVE,
    VIEWPORT_PPU_NOT_POSITIVE,
    VIEWPORT_SCREEN_EMPTY,
};

// Отдельного отказа «масштаб схлопнулся в ноль» здесь нет, и это утверждение, а не недосмотр:
// `pixels_per_unit` целый и уже признан не меньше единицы, поэтому произведение не меньше самого
// зума, а тот уже признан положительным. Проверка, которую нечем провалить, — украшение, и
// отбить её было бы нечем ни одной сломанной реализации.

struct Viewport {
    Vec2 screen_half{};
    fix32 zoom = fix32::from_int(1);
    int32_t pixels_per_unit = 1;
};

ViewportFault viewport_check(const Viewport& v);

// Экранных пикселей на мировую единицу. Ноль означает отказ вида — считать по нему нечего.
fix32 viewport_scale(const Viewport& v);

// Половина ВИДИМОЙ ОБЛАСТИ в мировых единицах. Именно её потребляют `CameraConfig::half_view`
// (границы уровня режут центр с оглядкой на неё) и окно отрисовки тайлов: зум, не доехавший до
// них, менял бы картинку, но не culling — камера у края уровня показывала бы пустоту за краем.
Vec2 viewport_half_world(const Viewport& v);

// Мир → экран. `center` — центр ОТРИСОВКИ слоя (`camera_layer_center`), а не `Camera::center`:
// параллакс и тряска живут там, и вид обязан брать уже посчитанное, а не считать во второй раз.
Vec2 world_to_screen(const Viewport& v, Vec2 center, Vec2 world);
Vec2 screen_to_world(const Viewport& v, Vec2 center, Vec2 screen);

// Экранная точка, ПРИВЯЗАННАЯ К ПИКСЕЛЮ. Округление вниз считается по экранной сетке, а не по
// мировой, потому что при нецелом масштабе мировая сеткой быть перестаёт: доля от привязанного
// мирового значения на целый пиксель уже не попадает. Спека называла этот выбор вопросом к
// бэкенду — бэкенд получает пиксели, поэтому целым остаётся ЭКРАННЫЙ шаг.
Vec2 world_to_screen_snapped(const Viewport& v, Vec2 center, Vec2 world);

// Совпадает ли мировая сетка с экранной, то есть цел ли масштаб. Ответ нужен потребителю
// pixel-perfect: при дробном масштабе привязка мирового центра (`CAMERA_PIXEL_PERFECT`) и привязка
// экранной точки дают РАЗНЫЕ сетки, и молчаливого способа выбрать одну из них нет.
bool viewport_is_pixel_exact(const Viewport& v);

} // namespace framework::graphics
