#pragma once
#include <cstdint>

#include "grid.hpp"
#include "sprite.hpp"

// Отрисовка тайловой карты с culling'ом (спека #17, вертикаль 2, шаг B). Гейт 7 спрашивает не
// «видно ли тайлы», а «зависит ли цена кадра от размера уровня», поэтому здесь ЧИСЛА: сколько
// тайлов обошли и сколько из них получили спрайт. Ни GPU, ни окна в этом вопросе нет.
//
// Окно берётся у самой сетки (`TileGrid::window`), а не считается заново. Вторая реализация
// перевода коробки в диапазон тайлов была бы вторым КОНТРАКТОМ, расходящимся на округлении, — и
// расхождение это выглядело бы как полоса непрорисованных тайлов по краю экрана ровно на карте с
// отрицательным началом, то есть там, где деление усекается к нулю, а не вниз.
//
// Этот файл — ШОВ между тайлами и графикой, и живёт он поэтому отдельной целью
// (`framework_graphics_tiles`): затащить сетку в саму `framework_graphics` значило бы, что клипы и
// камера линкуют тайлы и физику под ними, не спросив ни одного тайла.
namespace framework::graphics {

// Тайл рисуется тем, что таблица назвала для ЕГО БИТОВ. Собственного визуального индекса у тайла
// сегодня нет: сетка несёт флаги коллизии и ничего больше, а завести индекс — это правка формата
// испечённой секции, у которой пока нет ни одного потребителя (то же основание, по которому шаг D
// не заводил многостраничность атласа).
//
// Регион `0` значит «не рисовать»: пустой тайл им и остаётся, а карта, для чьих битов таблицу не
// заполнили, обязана давать дыру, а не чужую картинку.
constexpr uint32_t TILE_KINDS = 64;

struct TileSet {
    RegionId region[TILE_KINDS] = {};
    uint32_t rgba = 0xffffffffu;
    uint16_t material = 0;
    int16_t layer = 0;
};

// Цена кадра числами. `visited` — мера ОКНА, то есть ровно то, что читает гейт 7: вырасти уровень
// в тридцать раз, а число не изменись — culling есть. `emitted` от него отделён намеренно: пустая
// карта даёт ноль спрайтов при любом окне, и одним лишь числом спрайтов culling не доказывается.
struct TileDrawStats {
    uint32_t visited = 0;
    // Тайлы, ПОДАННЫЕ в список. Не «нарисованные»: поместились ли они, знает список, и потери
    // считает его собственный `dropped()`. Два счётчика потерь под разными именами разошлись бы
    // на первом же переполнении, и спорить пришлось бы с обоими.
    uint32_t emitted = 0;
    // Тайл, чьи биты вышли за таблицу (появился новый флаг, таблицу не расширили). Не рисуется и
    // СЧИТАЕТСЯ: дыра в карте и «так и задумано» снаружи неразличимы.
    uint32_t unknown = 0;
};

TileDrawStats draw_tiles(SpriteList& out, const tilemap::TileGrid& grid, const physics::Aabb& view,
                         const TileSet& set);

} // namespace framework::graphics
