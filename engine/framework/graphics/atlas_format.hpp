#pragma once
#include <cstdint>

// Zero-parse раскладка таблицы регионов атласа: `assetc` печёт её из текстового исходника, рантайм
// читает прямо из mmap-региона бандла — тем же швом, что карты (#16), профили движения (#16),
// пресеты ввода (#14) и достижения (#10). Причина здесь своя: НАРЕЗКА атласа правится каждым
// перерисованным спрайтом, и пересборка движка на каждый сдвинутый на пиксель кадр убивает цикл
// рисования ровно так же, как пересборка на передвинутый тайл убивала цикл подбора уровня.
//
// Ключ — ИМЯ, и это главное решение шага: `RegionId` из `clip.hpp` есть НОМЕР СТРОКИ в этой
// таблице, то есть величина, которую переупаковка атласа меняет вся целиком. Имя переживает
// переупаковку, номер — нет, поэтому клип, анимация и игровой код называют регион словом, а номер
// получают один раз на загрузке. Хранить в клипе имя вместо номера значило бы платить `strcmp` на
// кадр в тике.
//
// Прямоугольник лежит в ПИКСЕЛЯХ страницы целыми числами, а не в UV: UV зависят от размера
// страницы, а он меняется при той же переупаковке — таблица тогда перепекалась бы дважды по одной
// причине. Точка привязки, наоборот, лежит СЫРЫМ Q16.16 (`fix32::raw`): центр региона нечётной
// ширины приходится на половину пикселя, а числа с плавающей точкой сделали бы бейк зависимым от
// FPU машины, которая его пекла.
namespace framework::graphics {

constexpr uint8_t ATLAS_MAGIC[4] = {'L', 'N', 'A', 'R'};   // like-nes atlas regions
constexpr uint32_t ATLAS_VERSION = 1;

// Размер страницы лежит в ЗАГОЛОВКЕ, а не выводится из текстуры: без него читателю нечем отбить
// регион, свисающий за край, — а свисающий регион читается без ошибки и рисует соседа.
struct AtlasHeader {
    uint8_t magic[4];
    uint32_t version;
    uint32_t region_count;
    uint32_t regions_offset;
    uint32_t strings_offset;
    uint32_t total_size;
    uint16_t page_width;
    uint16_t page_height;
};
static_assert(sizeof(AtlasHeader) == 28, "AtlasHeader layout pinned (zero-parse ABI)");

// Точка привязки хранится У РЕГИОНА, а не у спрайта, потому что у кадров одного клипа она РАЗНАЯ:
// замах меняет ширину картинки, и общая на клип привязка увела бы персонажа вбок на кадре замаха.
// Отсчитывается от левого верхнего угла региона, в пикселях, +Y вниз — тем же направлением, что
// мир (#15).
struct AtlasRow {
    uint32_t name_offset;
    uint16_t x;
    uint16_t y;
    uint16_t w;
    uint16_t h;
    int32_t pivot_x_raw;
    int32_t pivot_y_raw;
};
static_assert(sizeof(AtlasRow) == 20, "AtlasRow layout pinned (zero-parse ABI)");

} // namespace framework::graphics
