// Покрытие слоёв на бейке (спека #24, В7). Политика вьюпорта показывает мир за игровой зоной до
// предела `VIEW_LIMIT`, и дыру за краем слоя увидит только владелец широкого экрана — поэтому она
// ловится здесь, а не глазами. Камера ходит по зоне внутри `bounds` (иначе по карте), и каждый
// слой обязан закрыть всё, что предел покажет из любого её положения, с поправкой на параллакс и
// смещение и тряску до `CAMERA_SHAKE_MAX`. Слой с повтором по оси закрывает её всегда. Дальний
// слой (`p < 1` по x) обязан повторяться по x — это политика сопровождения, а не покрытие: слой,
// подогнанный под нынешние bounds, молча откроет дыру, как только уровень вырастет.
//
// Проверка включается вызовом, а не импортом Tiled: сэмплы и фикстуры импортёра — не уровни под
// эту политику.
