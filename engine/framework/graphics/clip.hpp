#pragma once
#include <cstdint>

// Анимационный клип как ДАННЫЕ и его временная шкала (решение 2 спеки #17). Ни текстуры, ни
// устройства, ни окна здесь нет вовсе: клип — это последовательность регионов атласа с
// длительностями в ТИКАХ, и всё, что умеет этот файл, — отвечать, какой кадр стоит на шкале в
// момент t.
//
// Величины ЦЕЛЫЕ, а не fix32, и это не экономия. Решение 3 спеки требует, чтобы кадр был функцией
// от НОМЕРА ТИКА: событие анимации («удар попал на четвёртом кадре») влияет на геймплей, то есть
// входит в sim-хеш, а длительность, накопленная сложением дробей, разошлась бы между машинами
// ровно так же, как разошлась бы физика на float. Тик — целое число, длительность кадра — целое
// число тиков, и вопрос «какой кадр в тике t» решается делением с остатком, у которого нет
// округления.
//
// Функция от тика, а не накопитель, ещё и потому, что перемотка тогда стоит ноль: состояние
// проигрывателя — одно число `elapsed`, и прогон, начатый с середины, обязан совпасть с прогоном,
// доигравшим до неё (это утверждает гейт шага A).
namespace framework::graphics {

using RegionId = uint16_t;
using AnimEvent = uint16_t;

// Ноль — «метки нет», поэтому событие с номером 0 не существует. Отдельного булева поля рядом не
// заводим: два источника правды о том, есть ли метка, первым же расхождением дали бы кадр, у
// которого метка «есть», но не значит ничего.
constexpr AnimEvent ANIM_EVENT_NONE = 0;

enum ClipFlags : uint16_t {
    CLIP_ONCE = 0,
    CLIP_LOOP = 1u << 0,
    CLIP_PINGPONG = 1u << 1,
};

// Длительность в тиках, и НОЛЬ здесь запрещён: кадр нулевой длины делает «кадр = функция от тика»
// неопределённым — на шкале он занимает пустое место, в которое не попадает ни один тик, но
// событие на нём при этом обязано когда-то сработать. Отбивается разбором (шаг бейка), а рантайм
// остаётся тотальным и на данных, пришедших мимо разбора: такой кадр не показывается ни одному
// тику И не стреляет меткой. Правило одно на показ и на метку намеренно — разойдись они, клип
// наносил бы удар, которого игрок не видел.
struct ClipFrame {
    RegionId region = 0;
    uint16_t duration = 1;
    AnimEvent event = ANIM_EVENT_NONE;
};

// Кадры лежат ЧУЖОЙ памятью: клип не владеет ничем, потому что жить ему предстоит указателем
// внутрь mmap-региона бандла — тем же швом, что таблица профилей #16 и карт #16.
struct Clip {
    const ClipFrame* frames = nullptr;
    uint16_t frame_count = 0;
    uint16_t flags = CLIP_ONCE;
};

inline bool clip_loops(const Clip& c) { return (c.flags & CLIP_LOOP) != 0; }
inline bool clip_pingpongs(const Clip& c) { return (c.flags & CLIP_PINGPONG) != 0; }

// ШАГ шкалы — не то же самое, что кадр. Пинг-понг проходит кадры вперёд, а потом обратно, и
// средние кадры стоят на шкале ДВАЖДЫ: шагов у клипа из n кадров получается 2n-2, а кадров
// по-прежнему n. Всё, что считает время и события, считает шагами; наружу отдаётся кадр.
uint32_t clip_steps(const Clip& c);
uint16_t step_frame(const Clip& c, uint32_t step);

// Период — длительность полного круга шкалы: для цикла это то, по чему берётся остаток, для
// одноразового клипа — момент, после которого он замер на последнем кадре.
uint32_t clip_period(const Clip& c);

// Порядковый номер шага в БЕСКОНЕЧНО развёрнутой шкале: у циклического клипа он растёт вместе с
// кругами, у одноразового упирается в последний шаг. Именно из него берутся события — «шаг
// сменился» и «событие сработало» это одно и то же утверждение, и считать их порознь значило бы
// завести вторую копию правила о том, когда клип переходит на следующий кадр.
uint64_t clip_step_ordinal(const Clip& c, uint64_t t);

uint16_t clip_frame_at(const Clip& c, uint64_t t);
bool clip_finished(const Clip& c, uint64_t t);

} // namespace framework::graphics
