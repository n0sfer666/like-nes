#pragma once

#include "fixmath.hpp"

// Камера (спека #17, решение 5): набор ПОЛИТИК, а не единственный «умный» режим. Каждая политика —
// разряд в конфигурации плюс свои числа; выключенная не стоит ничего и ничего не меняет.
//
// Порядок применения — часть контракта, а не деталь: мёртвая зона задаёт КУДА камера хочет,
// границы уровня режут это «куда», потолок скорости — насколько она успевает за тик, и границы
// режут результат ещё раз, а тряска и привязка к пикселю живут ПОСЛЕ и в состояние не пишут.
//
// Границы стоят ДО потолка скорости именно потому, что потолок режет ДЛИНУ шага: цель за краем
// уровня даёт шаг, большая часть которого уходит в ось, упёршуюся в стену, — потолок считает эту
// часть потраченной, а границы её потом срезают. Камера у края уровня отставала бы от цели вдоль
// СВОБОДНОЙ оси тем сильнее, чем дальше цель за краем. Второй срез, после шага, снимает это с
// вычислений совсем: он держит утверждение «центр внутри границ» безусловным, не полагаясь на то,
// что предыдущий центр уже был внутри.
namespace framework::graphics {

using framework::Vec2;

enum CameraPolicy : uint16_t {
    CAMERA_PLAIN = 0,
    CAMERA_DEADZONE = 1u << 0,
    CAMERA_SPEED_LIMIT = 1u << 1,
    CAMERA_LOOK_AHEAD = 1u << 2,
    CAMERA_BOUNDS = 1u << 3,
    CAMERA_PIXEL_PERFECT = 1u << 4,
};

struct CameraBounds {
    fix32 min_x{}, min_y{}, max_x{}, max_y{};
};

struct CameraConfig {
    uint16_t policies = CAMERA_PLAIN;
    Vec2 half_view{};
    Vec2 dead_half{};
    fix32 max_speed{};
    fix32 look_ahead{};
    fix32 look_rate{};
    CameraBounds bounds{};
    int32_t pixels_per_unit = 1;
};

struct Camera {
    Vec2 center{};
    fix32 look{};
    uint32_t shake_ticks = 0;
    uint32_t shake_total = 0;
    fix32 shake_amp{};
    uint32_t shake_seed = 0;
};

// Тик следования: `facing` — знак взгляда цели (-1, 0, +1), а не её скорость. Скорость сюда не
// годится: она обнуляется на пике прыжка и в кадре разворота, и look-ahead дёргался бы туда-обратно
// на каждой остановке.
void camera_follow(Camera& c, const CameraConfig& cfg, Vec2 target, int32_t facing);

// Тряска ПАРАМЕТРИЗУЕТСЯ ТИКОМ, а не `rand()`: смещение — чистая функция от (тик, seed), поэтому
// перемотка записи даёт ту же тряску, а не другую. В `Camera` от неё лежит только заказ (сколько
// тиков и какой амплитуды), но не накопленное смещение — иначе тряска сдвигала бы центр насовсем.
void camera_shake(Camera& c, uint32_t ticks, fix32 amp, uint32_t seed);
Vec2 camera_shake_offset(const Camera& c, uint64_t tick);

// Центр для ОТРИСОВКИ одного слоя. `parallax` — доля, с которой слой едет за камерой: единица это
// игровой слой, половина — дальний фон, ноль — небо, приколоченное к экрану. Тряска умножается на
// ту же долю: дальний слой обязан трястись слабее, иначе параллакс на удар распадается.
//
// Привязка к сетке считается ПОСЛЕ умножения, а не до: доля от привязанного значения на сетку уже
// не попадает, и фон дрожал бы относительно переднего плана ровно там, где режим обязан это убрать.
Vec2 camera_layer_center(const Camera& c, const CameraConfig& cfg, uint64_t tick, fix32 parallax);

// Центр для ОТРИСОВКИ игрового слоя — тот же слой с долей единица. Отдельно от `Camera::center`,
// потому что в симуляцию не пишет ничего из этого.
Vec2 camera_view_center(const Camera& c, const CameraConfig& cfg, uint64_t tick);

} // namespace framework::graphics
