#pragma once
#include <cstdint>

// План переигрывания (вертикаль 1 спеки #22): куда откатываться и сколько тиков повторить.
//
// Отдельно от симуляции и отдельно от шаблона сессии, потому что решение здесь ЦЕЛОЧИСЛЕННОЕ и
// проверяется без единого шага мира. Все три правила отката — «побеждает самый ранний
// испорченный тик», «глубже выписанной глубины не откатываемся», «переиграть ровно head-from» —
// это арифметика на двух счётчиках, и именно в ней живёт ошибка на единицу. В шаблоне,
// инстанцируемом симуляцией, она была бы видна только через расхождение хеша.
//
// Часы сессии живут ЗДЕСЬ же, а не полем рядом: номер текущего тика и точка возврата — одна пара,
// и вторая копия номера тика в сессии разъехалась бы с этой на первом же откате.
namespace framework::rollback {

using Tick = uint32_t;

class ReplayPlan {
public:
    // `depth` — сколько тиков назад ещё разрешено вернуться. Ноль означает «откатов нет вовсе»:
    // это не вырожденный случай, а рабочая конфигурация для позитивного контроля — на ней гейт
    // отката обязан краснеть.
    void reset(uint32_t depth);

    Tick head() const { return head_; }
    void advanced() { ++head_; }

    // Ввод на тик `t` разошёлся с тем, чем этот тик уже посчитан. `false` — вернуться туда уже
    // нельзя: снимок вытеснен из кольца, и расхождение с другим пиром отсюда неизбежно. Исход
    // назван и посчитан (`too_deep`), а не проглочен: молчащий отказ отката выглядит ровно как
    // его успех — до первого сравнения хешей.
    bool note_dirty(Tick t);

    bool pending() const { return pending_; }
    Tick from() const { return from_; }
    uint32_t replay_count() const { return pending_ ? head_ - from_ : 0; }

    // Часы переводятся назад, план гасится. Зовётся ПОСЛЕ восстановления снимка: тик, на который
    // указывает `head` после возврата, ещё не сыгран.
    void rewind();

    uint32_t depth() const { return depth_; }
    uint32_t too_deep() const { return too_deep_; }

private:
    Tick head_ = 0;
    Tick from_ = 0;
    bool pending_ = false;
    uint32_t depth_ = 0;
    uint32_t too_deep_ = 0;
};

} // namespace framework::rollback
