#pragma once
#include <cstdint>

#include "fixed.hpp"

// Форма отклика стика: мёртвая зона, порог насыщения, кривая. Всё на fix32 и целых, потому что
// результат уходит в InputFrame и попадает в sim-хеш: тот же наклон стика обязан дать те же
// байты на трёх ОС.
//
// Мёртвая зона здесь ДВУХ видов, и это не роскошь: по осям (`axial`) её ставят на клавиатурную
// пару и на одиночную ось, а на стик — радиальную (`radial`), потому что осевая на стике режет
// квадратом и даёт «залипание» по диагонали ровно там, где игрок ведёт по кругу.
namespace framework::input {

struct Vec2 {
    fix32 x, y;
};

struct StickShape {
    fix32 deadzone = fix32::from_float(0.18);   // радиус нечувствительности, [0, 1)
    fix32 outer = fix32::from_int(1);           // модуль, начиная с которого отклонение полное
    uint32_t curve_exp = 1;                     // 1 линейная, 2 квадратичная, 3 кубическая
};

// Детерминированный целочисленный корень: результат — floor от точного значения в Q16.16.
// Своя реализация, а не std::sqrt, по той же причине, по какой в симе нет float: библиотечный
// корень на double точен, но округление к fix32 зависит от компилятора и флагов FMA.
fix32 sqrt_fix(fix32 v);

// Кривая отклика на нормализованном [0,1]: t^exp. Показатель целый, потому что дробную степень
// пришлось бы считать логарифмом, а он на fix32 даёт ступеньки крупнее самой кривой.
fix32 apply_curve(fix32 t, uint32_t exp);

// Одна ось: мёртвая зона по модулю, нормализация остатка на (outer - deadzone), кривая, знак.
fix32 axial(fix32 v, const StickShape& s);

// Пара осей как вектор: круговая мёртвая зона и клампинг в единичный круг. Диагональ
// клавиатуры (1,1) имеет модуль √2 и без этого давала бы ход быстрее, чем по прямой.
Vec2 radial(Vec2 v, const StickShape& s);

// Триггер: односторонняя ось [0,1] с порогом срабатывания; ниже порога — ноль, выше —
// растянутый на весь диапазон остаток. Дребезг у самого порога гасит гистерезис на стороне
// потребителя, здесь его нет намеренно: он требует памяти, а функция чистая.
fix32 trigger(fix32 v, fix32 threshold);

} // namespace framework::input
