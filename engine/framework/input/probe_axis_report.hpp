#pragma once
#include "device_state.hpp"
#include "input_types.hpp"

// Свидетель осей: единственная часть пробы, чей вывод обязан пережить копипаст в чужой терминал.
// Строка состояния перерисовывается по `\r`, поэтому в присланном логе от неё остаётся один
// последний кадр — а шаг гейта 8 спеки #14 просит НАЗВАТЬ знаки по каждой оси. Дважды подряд
// прогон приезжал с `move=(+0.00,+0.00)` во всех сохранившихся кадрах, и по нему нельзя было
// отличить «стик не трогали» от «бэкенд оси не отдаёт вовсе» — ровно та неразличимость, ради
// которой в пробу добавлялся отчёт о первом опросе.
namespace framework::input {

class AxisWitness {
public:
    void observe(const ::input::DeviceState& dev, const ::input::InputFrame& frame);
    void report() const;

private:
    enum Dir { Right = 0, Left, Up, Down, DIRS };

    // Экстремумы копятся отдельно по сырой оси и по разрешённой: расхождение между ними и есть
    // ответ на вопрос «кто съел стик» — бэкенд, не приславший событие, или раскладка с мёртвой
    // зоной. По одному числу это неразличимо.
    double raw_lo_[2] = {0, 0}, raw_hi_[2] = {0, 0};
    double res_lo_[2] = {0, 0}, res_hi_[2] = {0, 0};
    bool seen_[DIRS] = {};
};

} // namespace framework::input
