#pragma once
#include <string>

#include "action_map.hpp"

// Имена источников ввода в текстовом манифесте пресетов: `key:W`, `pad:south`, `padaxis:-ly`,
// `mouse:left`, `trigger:rt`. Разбор нужен `assetc` при бейке, обратное преобразование — UI
// перебиндов, поэтому таблица одна на оба направления: два независимых списка разошлись бы, и
// первым признаком стала бы кнопка, которую нельзя переназначить обратно в то же имя.
//
// Имена кнопок пада — НОРМАЛИЗОВАННЫЕ (`south`/`east`/`west`/`north`), а не буквы: `pad:a` на
// Switch Pro физически лежит там, где на Xbox `b`, и пресет, написанный буквами, менял бы
// значение от устройства. Физические подписи появляются на слое профилей.
namespace framework::input {

// Разобрать имя источника. Возвращает false на неизвестном имени — молчаливый `SourceKind::None`
// превратил бы опечатку в пресете в «действие просто не срабатывает».
bool parse_source(const std::string& text, ::input::Source& out);

// Обратно: стабильное имя источника (то же, что принимает parse_source). Неизвестный источник
// даёт пустую строку.
std::string source_name(const ::input::Source& src);

} // namespace framework::input
