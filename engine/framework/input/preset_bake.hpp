#include <vector>

// Бейк текстового манифеста пресетов в zero-parse таблицу (`preset_format.hpp`). Живёт в движке,
// а не в `assetc`, по образцу достижений #10: тот же разбор нужен тестам, и вторая копия в
// инструменте разошлась бы с первой молча.
//
// Формат (разделитель — `|`, `#` до конца строки — комментарий):
//   preset | <имя>
//   action | <имя> | <источник> [| <источник> …]
//   axis   | <имя> | <источник +> | <источник -|->
//   shape  | <имя> | <мёртвая зона> | <насыщение> | <степень кривой> | <парная ось|->
// Строки `action`/`axis`/`shape` относятся к последнему объявленному `preset`.
//
// Одну ось разрешено объявлять несколькими строками `axis` (клавиши, стрелки, стик) — это
// альтернативные источники, а не разные оси. Отсюда то, что пекарь отбивает НОМЕРОМ СТРОКИ, а не
// принимает молча: имя в `shape`, которого ни одна строка `axis` этого пресета не объявляет
// (форма потерялась бы, а ось осталась бы с нулевой мёртвой зоной); вторую `shape` на то же имя
// (она затирала бы первую целиком); один источник, тянущий ось в обе стороны (побеждает последняя
// строка, то есть знак решал бы порядок); и пресет сверх пределов движка — `MAX_ACTIONS` действий
// или `MAX_AXES` ЛОГИЧЕСКИХ осей, потому что `PresetTable::bind` отвергает такой пресет целиком и
// молча, уже без номера строки.
namespace framework::input {

struct PresetBakeError {
    int line = 0;
    std::string message;
};

bool bake_presets(const std::string& text, std::vector<uint8_t>& out, PresetBakeError& err);
bool bake_presets_file(const std::string& path, std::vector<uint8_t>& out, PresetBakeError& err);

} // namespace framework::input
