#pragma once
#include "fixmath.hpp"

// Синус, косинус и поворот вектора — целочисленные, без единого обращения к libm.
//
// Причина та же, по которой в физике нет `float`: `std::sin` не обязан давать один и тот же бит на
// glibc, на MSVC CRT и на Apple libm, а поворот тела входит в sim-хеш. Таблица с линейной
// интерполяцией даёт результат, зависящий только от арифметики int32/int64, то есть одинаковый
// везде по построению, а не по удаче.
//
// **Угол измеряется в ОБОРОТАХ, а не в радианах**, и это не стилистика. Приведение угла к периоду —
// операция, которая делается на КАЖДОМ вызове, и в оборотах она точна до бита: период равен
// единице, значит «взять угол по модулю периода» — это взять младшие 16 бит Q16.16, без деления и
// без округления. В радианах период равен 2*pi, числу, которого в Q16.16 нет; каждое приведение
// вносило бы ошибку, растущую с числом оборотов, и тело, крутящееся десять секунд, приезжало бы в
// угол, зависящий от того, сколько раз его успели свернуть. Радиан в API не остаётся вовсе:
// «почти правильная» конверсия на границе — тот же самый источник ошибки, только спрятанный.
namespace framework {

// Синус угла, заданного в оборотах. Значение вне [0, 1) сворачивается само, знак — тоже:
// sin_turns(-a) == -sin_turns(a) БИТ В БИТ, а не «с точностью до округления».
fix32 sin_turns(fix32 turns);
fix32 cos_turns(fix32 turns);

// Поворот, посчитанный один раз и переиспользуемый. Тело хранит угол, но узкая фаза трогает все
// вершины формы: считать синус на каждую вершину значило бы платить таблицей и интерполяцией за
// то, что для всей формы одинаково.
struct Rot {
    fix32 s;
    fix32 c = fix32::from_int(1);
};

// Сравнение — ТОЧНОЕ, по сырым разрядам обеих компонент. Порог здесь был бы неверен: `Rot` не
// измеряется, а вычисляется по углу, и два поворота, посчитанные из одного угла, совпадают бит в
// бит. Нужно оно затем, что `Rot` входит в тело, а тело сравнивается целиком (`body.hpp`).
constexpr bool operator==(Rot a, Rot b) { return a.s == b.s && a.c == b.c; }

Rot rotation(fix32 turns);

// Поворот вектора и обратный ему. Обе координаты берутся через `dot`, то есть с ОДНИМ округлением
// на компоненту: `c * v.x - s * v.y` округляет дважды, и на почти-осевых углах вторая потеря
// съедает младший бит — форма, повёрнутая на 0 и на 1 оборот, переставала бы совпадать сама с собой.
Vec2 rotate(Rot r, Vec2 v);
Vec2 unrotate(Rot r, Vec2 v);

// Угол из градусов — для авторинга, где «45» читается, а «0.125 оборота» нет. `from_float`
// спека разрешает только в constexpr-константах на границе, поэтому деление здесь целое: 360
// делится нацело на все углы, которыми пользуются в редакторе, а остаток честно теряется.
constexpr fix32 turns_from_degrees(int32_t deg) {
    return fix32::from_raw(fix32::sat((static_cast<int64_t>(deg) << fix32::SHIFT) / 360));
}

} // namespace framework
