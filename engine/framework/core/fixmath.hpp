#pragma once
#include <cstdint>

#include "fixed.hpp"

// Детерминированная векторная математика слоя: одна реализация на всех, кто попадает в sim-хеш.
//
// Здесь она оказалась не ради красоты. Корень и модуль вектора сначала жили приватно в форме
// стика (#14), и физике (#15) понадобились ровно они же. Вторая реализация целочисленного корня —
// это не дублирование кода, а второй КОНТРАКТ: две функции, одинаковые сегодня, расходятся на
// округлении в первый же раз, когда одну из них «чуть-чуть уточнили», и расхождение всплывает
// golden-хешем, который назовёт виноватым не тот модуль.
namespace framework {

struct Vec2 {
    fix32 x, y;
};

constexpr Vec2 operator+(Vec2 a, Vec2 b) { return {a.x + b.x, a.y + b.y}; }
constexpr Vec2 operator-(Vec2 a, Vec2 b) { return {a.x - b.x, a.y - b.y}; }
constexpr Vec2 operator-(Vec2 a) { return {-a.x, -a.y}; }
constexpr Vec2 operator*(Vec2 a, fix32 s) { return {a.x * s, a.y * s}; }
constexpr bool operator==(Vec2 a, Vec2 b) { return a.x == b.x && a.y == b.y; }

// floor(sqrt(v)) на целых, без обращения к libm. Двоичный поиск, потому что он одинаков на любой
// платформе и не зависит от доступности 128-битного умножения. Сравнение через деление, а не
// mid*mid: квадрат кандидата переполняет int64 на верхней границе диапазона.
int64_t isqrt64(int64_t v);

// Корень в Q16.16: floor от точного значения. Отрицательный вход даёт ноль, а не завёрнутый
// результат, — вызывающему незачем проверять знак перед каждым вызовом.
fix32 sqrt_fix(fix32 v);

// Скалярное и псевдоскалярное произведения с ОДНИМ округлением. `a.x * b.x + a.y * b.y` на fix32
// округляет дважды, и на разности почти равных величин (нормаль контакта против скорости) вторая
// потеря съедает знак результата — тело начинает «залипать» в поверхности вместо отскока.
fix32 dot(Vec2 a, Vec2 b);
fix32 cross(Vec2 a, Vec2 b);

// Модуль вектора без промежуточного fix32-умножения: квадраты накапливаются в int64, корень
// берётся из Q32.32 и даёт Q16.16 прямо (sqrt(v * 2^32) == sqrt(v) * 2^16).
fix32 length(Vec2 v);

// Квадрат длины в Q16.16 с насыщением. Сравнивать квадраты дешевле, чем брать два корня, и на
// расстояниях порядка размера мира (8192) квадрат уже не помещается в fix32 — насыщение здесь
// осознанное: сравнение «дальше порога» остаётся верным, точное значение за порогом не нужно.
fix32 length_sq(Vec2 v);

// Единичный вектор И его длина за один корень. Отдельной функцией, потому что «поделить на
// length()» единичного вектора НЕ даёт: длина округляется вниз до 1/65536, и на коротких векторах
// деление на заниженный делитель раздувает модуль — при разности (1, 1) в raw нормаль выходит
// длиной 1.41 вместо 1. В физике ошибка входит в импульс дважды (в проекцию скорости и в
// направление приложения), то есть даёт двукратный перебор, а в конусе Кулона выпускает трение за
// конус, то есть качает энергию. Поэтому корень берётся с восемью дополнительными битами.
// Нулевой вектор даёт нулевую длину и нулевое направление — знак «направления нет».
fix32 normalize(Vec2 v, Vec2& out);

// Вектор, укороченный до заданного модуля с сохранением направления. Тоже не сводится к делению на
// length(): длина не только округляется, но и НАСЫЩАЕТСЯ на 32768, и множитель limit/len выходит
// завышенным — «ограниченный» вектор остаётся выше потолка (при (32767, 32767) и потолке 2048
// получалось 2896). Здесь масштаб берётся одним делением в int64, а усечение деления только
// уменьшает модуль, поэтому потолок гарантирован, а не «обычно соблюдается».
Vec2 clamp_length(Vec2 v, fix32 limit);

constexpr fix32 abs_fix(fix32 v) { return v.raw < 0 ? -v : v; }
constexpr fix32 min_fix(fix32 a, fix32 b) { return a < b ? a : b; }
constexpr fix32 max_fix(fix32 a, fix32 b) { return a < b ? b : a; }
constexpr fix32 clamp_fix(fix32 v, fix32 lo, fix32 hi) { return min_fix(max_fix(v, lo), hi); }

} // namespace framework
