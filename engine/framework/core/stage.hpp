#pragma once
#include <cstdint>

#include "fixed.hpp"

// Стадии тика: крупная сетка порядка, внутри которой системы упорядочены явными зависимостями.
// Сетка фиксирована и НЕ расширяется играми: стадия — это контракт между модулями фреймворка
// (#15–#18 складываются в те же пять), а произвольная стадия от игры превратила бы порядок в
// договорённость между чужими друг другу модулями.
namespace framework {

enum class Stage : uint32_t {
    Input = 0,    // сырое состояние устройств → действия игрока
    PreSim = 1,   // намерения из действий: желаемая скорость, запросы прыжка/выстрела
    Sim = 2,      // физика и правила мира — то, что попадает в sim-хеш
    PostSim = 3,  // производное от нового состояния: камера, анимации, звуковые события
    Present = 4,  // подготовка к отрисовке; в sim-хеш не входит
};

constexpr uint32_t STAGE_COUNT = 5;

// Всё, что система получает от расписания. Намеренно узко: доступ к миру и ассетам система
// держит в собственном контексте (`user`), иначе расписание стало бы god-объектом, через который
// модули видят друг друга.
struct Tick {
    uint32_t index = 0;  // номер тика симуляции
    fix32 dt;            // шаг тика; fix32, потому что результат попадает в sim-хеш
};

using SystemFn = void (*)(void* user, const Tick&);

} // namespace framework
