#pragma once

// Позитивный контроль счётчика из `framework_alloc_probe.hpp`: без него «ноль аллокаций» неотличим
// от неработающего перехвата, а неработающий перехват выглядит как самый зелёный гейт на свете.
//
// Здесь ОБЪЯВЛЕНИЯ, тела — в `framework_alloc_probe_control.cpp`, и разделение это вынуждено
// компилятором, а не вкусом. Выделение, чей результат никуда не наблюдаем, стандарт разрешает
// выбросить целиком вместе с парным освобождением, и оба живых компилятора этим правом пользуются
// по-разному:
//
//   clang -O3  выбрасывал пару new/delete, подставляя адрес из статической памяти, — в объектнике
//              не оставалось даже ССЫЛКИ на `operator new`. Лечилось запретом инлайна на выделяющей
//              функции (раунд #15).
//   gcc -O3    выбрасывает её ДАЖЕ ЗА `PLATFORM_NOINLINE`: прогон владельца на Nobara вернул
//              `control: the counter sees a real allocation` красным при живом счётчике —
//              в том же прогоне рост мира он насчитал честно (growth=24). Воспроизведено локально
//              на g++-16: -O2 гасит выравненный контроль, -O3 оба.
//
// Отдельный TU закрывает ВЫЗЫВАЮЩЕГО: тела ему не видны, LTO в дереве не включён. Этого мало, и
// это измерено, а не предположено: внутри собственного TU компилятор видит тело целиком и
// выбрасывает выделение там — наивный вынос ронял выравненный контроль на ОБОИХ компиляторах,
// включая тот, на котором он до сих пор проходил. Вторая половина барьера живёт в теле
// (побег указателя через `volatile` туда и обратно), таблица замеров — в
// `framework_alloc_probe_control.cpp`. Флага, отключающего именно эту оптимизацию, у gcc нет.
//
// Файл НЕ включает `framework_alloc_probe.hpp` и включать не должен: тот ОПРЕДЕЛЯЕТ глобальные
// operator new/delete и живёт ровно в одном TU на программу. Счётчик здешние выделения видят через
// замещение, работающее на уровне линковки, — то есть ровно тем путём, каким его видит проверяемый
// код.
namespace framework::probe::control {

// Обычное выделение с записью в выданный блок. `true` — блок выдан и запись в него доехала;
// возвращаемое значение существует для того, чтобы у вызова был наблюдаемый результат.
bool plain_allocation();

// Над-выравненное выделение. `true` — выданный адрес выровнен по запрошенной границе.
//
// Форма перегрузки выбирается КОМПИЛЯТОРОМ по `alignof` типа, а не автором кода, поэтому контроль
// на неё отдельный: пока над-выравненных типов на горячем пути нет, выравненная ветка перехвата не
// исполняется ни разу, и её поломка ждала бы первого `alignas` в чужом коде, где выглядела бы как
// «гейт всегда проходил, значит дело не в нём».
//
// Проверяется и возврат: адрес, выданный ручной разметкой, обязан пережить `delete` — под ASan
// неверный `free` роняет прогон, и это ровно тот сигнал, который нужен.
bool aligned_allocation();

} // namespace framework::probe::control
