#pragma once
#include <cstdint>
#include <string>
#include <vector>

#include "fixed.hpp"

// Текстовый слой пекарей слоя: границы полей и число из текста. Одна копия на дерево — до
// 2026-08-31 их было ЧЕТЫРЕ (`framework/input/preset_text.cpp`, `character/profile_text.cpp`,
// `graphics/atlas_text.cpp`, `tilemap/map_text.cpp`), и каждая следующая записывала в своей шапке
// одно и то же основание: общий слой пришлось бы класть в `framework/core`, то есть править
// работающие модули, а линковка с любым из них вытянула бы за тремя функциями чужую подсистему
// целиком. Второе верно и сейчас, первое было неверно с самого начала: `framework/core` — низ
// слоя, на него УЖЕ линкуются все четверо (input прямо, graphics прямо, tilemap и character через
// framework_physics), и ничего, кроме `fix32`, отсюда не приезжает.
//
// Цена копий была не в строках, а в том, что расхождение между ними ничем не отбивалось: правка
// «32767.999999 даёт число противоположного знака» доехала до трёх файлов из четырёх руками, и
// узнать об этом можно было только прочитав все четыре подряд.
//
// `strtod`/`strtoul` тут не годятся: они зависят от локали, и в ru_RU «0.18» прочиталось бы нулём
// на одной машине и восемнадцатью сотыми на другой — то есть бейк перестал бы быть
// байт-детерминированным по составу окружения.
namespace framework::core {

std::string trim(const std::string& s);
// Поля разделяются `|` и обрезаются по краям: редактор, подчистивший хвостовые пробелы, не должен
// менять смысл строки.
std::vector<std::string> split_fields(const std::string& line);
bool parse_fix(const std::string& s, fix32& out);
// Целые — только неотрицательные, знак отбивается как «не число». Заворачивание «-4» в 65532 дало
// бы значение, проходящее проверку диапазона и лежащее совсем не там, где написано в исходнике.
bool parse_u32(const std::string& s, uint32_t& out);
bool parse_u16(const std::string& s, uint16_t& out);

} // namespace framework::core
