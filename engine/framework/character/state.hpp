#pragma once
#include <cstdint>

#include "../physics/world.hpp"
#include "fixmath.hpp"

// Состояние кинематического персонажа и его вход за тик (спека #16, вертикаль 1).
//
// Персонаж НЕ тело решателя: он двигается «сколько разрешено» шейпкастом и сам решает, как
// реагировать (решение владельца 1 спеки #16). Поэтому его состояние живёт здесь, а не в
// `physics::Body`: у тела есть масса, импульсы и сон, и ни одно из трёх к управляемому персонажу
// не применимо — тело, которое толкают импульсом, невозможно остановить ровно на краю платформы.
//
// Оси те же, что у физики и у ввода: **+X вправо, +Y ВНИЗ**, единица — пиксель
// (`physics/units.hpp`). Прыжок поэтому даёт ОТРИЦАТЕЛЬНУЮ `velocity.y`, и знак этот записан
// здесь, потому что незаписанное соглашение о знаке каждый потребитель напишет по-своему.
namespace framework::character {

// Наблюдаемое состояние движения. Перечисление, а не набор флагов: анимации (#17) вешаются на
// состояние, и «земля и воздух одновременно» — это не редкий случай, а сломанный контракт.
// Вертикаль 1 знала две, вертикаль 3 добавила лестницу. Скольжения и оглушения здесь НЕТ, и это не
// забывчивость: состояние заводится вместе с механикой, которая его выставляет, а состояние без
// такой механики — обещание поведения, которого нет (то же правило, что у битов тайла).
enum class MoveState : uint32_t {
    Ground = 0,
    Air = 1,
    // Персонаж висит на лестнице: тик считает не контроллер, а `ladder.cpp`, и ни тяготения, ни
    // разгона по горизонтали в этом тике нет.
    Ladder = 2,
};

// Вход за тик. Фронт нажатия НЕ приходит снаружи: контроллер выводит его сам из `jump_held` и
// собственной памяти. Иначе у контракта появилась бы вторая точка, где вызывающий обязан не
// ошибиться, — а «нажатие» и «удержание», разъехавшиеся на один тик, дают прыжок, который
// срабатывает через раз и выглядит как дефект окна прощения, а не как дефект вызова.
struct MoveInput {
    fix32 move_x;      // [-1, 1]: доля максимальной скорости, знак — направление
    bool jump_held = false;
    // Намерение «вниз» — отдельным полем, а не отрицательным `move_x` или второй осью: у персонажа
    // нет движения по вертикали от ввода, и вниз он просит РАЗРЕШЕНИЯ пройти сквозь одностороннюю
    // платформу, а не скорости. Само по себе поле не делает ничего: спуск случается только на
    // ФРОНТЕ прыжка (`controller.cpp`), поэтому зажатое «вниз» не роняет стоящего.
    bool down_held = false;
    // Намерение «вверх» — только для лестницы, и появилось оно вместе с ней. Отдельным полем, а не
    // второй осью `move_x`: горизонталь это ДОЛЯ максимальной скорости, а лазание идёт постоянной
    // скоростью профиля, и общая ось означала бы, что наполовину отклонённый стик лезет вдвое
    // медленнее — то есть аналоговое управление там, где механика дискретна.
    bool up_held = false;

    // Сравнение ПОЛЯМИ, а не байтами: у структуры есть байт выравнивания, в который никто не пишет,
    // и байтовое сравнение объявляло бы два одинаковых нажатия разными. Наружу это нужно откату
    // (спека #22): кольцо ввода спрашивает «подтверждение отличается от предсказанного?», и ложное
    // «да» там означает откат на каждом тике.
    bool operator==(const MoveInput& o) const {
        return move_x.raw == o.move_x.raw && jump_held == o.jump_held && down_held == o.down_held &&
               up_held == o.up_held;
    }
};

struct Character {
    Vec2 position;
    Vec2 velocity;
    MoveState state = MoveState::Air;

    // Окна прощения — В ТИКАХ (решение владельца 4 спеки #16). Секунды сюда не годятся: окно в
    // секундах при делении на шаг тика даёт дробное число тиков, а округление дроби — это уже
    // поведение, зависящее от шага, то есть от машины.
    uint32_t coyote_left = 0;   // тиков, пока прыжок после схода с опоры ещё разрешён
    uint32_t buffer_left = 0;   // тиков, пока запомненное нажатие ещё живо
    // Тиков, пока лестница не хватается обратно после прыжка с неё. Живёт рядом с окнами прощения
    // и истекает так же — по тику за тик, — но смысл у него обратный: те РАЗРЕШАЮТ действие после
    // того, как повод исчез, а это ЗАПРЕЩАЕТ, пока повод ещё рядом.
    uint32_t ladder_regrab_left = 0;

    bool on_ground = false;
    bool jump_active = false;   // подъём по удержанию ещё длится (отпускание его обрывает)
    bool jump_was_held = false; // прошлый тик: отсюда берётся фронт нажатия и отпускания

    // Наблюдаемые итоги последнего шага. Не отладка: анимация удара о потолок и звук трения о
    // стену (#17) обязаны читать ФАКТ касания, а не выводить его из того, что скорость обнулилась,
    // — она обнуляется и при нулевом вводе.
    bool hit_ceiling = false;
    bool hit_wall = false;

    // ЗАПОМНЕННАЯ ОПОРА — тело, на котором персонаж стоял по итогам прошлого тика (решение
    // владельца: «контроллер помнит свою опору»). Помнить её приходится именно контроллеру: свип
    // персонажа статичен, поэтому платформа, наехавшая на стоящего, его собственным запросом не
    // видна вовсе — движение опоры обязан переносить тот, кто знает, чья она.
    //
    // Держится и в окне coyote: окно и означает «опора считается ещё моей», и прыжок из него с
    // едущей платформы обязан наследовать её горизонталь так же, как обычный. Забывается, когда не
    // осталось ни опоры, ни окна.
    physics::BodyId support{physics::BodyId::INVALID};

    // Персонажа ВЖАЛО: платформа сдвинула его туда, где он пересёкся с чем-то, кроме собственной
    // опоры. Факт, а не последствие, — ровно как `hit_wall`: убивать, выталкивать или не делать
    // ничего решает игра, а движок не имеет права выбрать за неё одно из трёх.
    bool crushed = false;
};

} // namespace framework::character
