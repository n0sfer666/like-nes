#include "collision.hpp"

// ДВИЖЕНИЕ МИРА ПОД ПЕРСОНАЖЕМ — шаг 0 тика целиком: персонажа сначала везёт его опора, потом
// убирает с дороги всякий, кто в него въехал (находка владельческого прогона §6, 2026-09-01).
//
// Своим файлом рядом с переносом опорой, а не строкой в контроллере: вопросы разные. Перенос
// отвечает «куда уехало то, на чём я СТОЮ», и спрашивает его только стоящий; снос отвечает «во что
// я уже влез», и спрашивает его всякий — в прыжке, в падении, на лестнице. Общего у них ровно
// скорость чужого тела (`support_velocity`), и она живёт в `support.hpp` одна на обоих.
//
// Чем это было. До сноса тик персонажа не смотрел на движущиеся тела вовсе, если не стоял на них,
// и кинематическая платформа проезжала СКВОЗЬ висящего персонажа: за полсекунды она заглатывала
// его на пятьдесят юнитов, а разбор касания в `move_and_slide` отходил на `SKIN` вдоль оси, по
// которой персонаж погрузился МЕНЬШЕ, — то есть поперёк хода платформы. Наблюдалось это владельцем
// как «выжимает наверх, будто пасту из тюбика»: выдавливание и есть тот отход, накопленный по
// восьмой доле юнита за тик, а причина — не он, а то, что персонажа никто не убирал с дороги.
namespace framework::character {

// Подвинуть персонажа тем, что движется под ним и в него. `true` — обошлось (в том числе когда
// двигать было нечем); `false` — персонажа ВЖАЛО хотя бы одной из половин. Отказ ничего с
// персонажем не делает и ничего за игру не решает: давить, выталкивать или терпеть — её выбор.
//
// Половины одним вызовом, потому что связаны они одним исключением: из толкателей выпадает ровно
// то тело, которое персонажа только что ВЕЗЛО, иначе его ход зачёлся бы дважды за тик. Оставленное
// снаружи, это решение повторялось бы в каждом тике, который зовёт шаг 0 (обычном и лестничном), и
// разъехалось бы в первом же новом.
//
// `standing` — стоял ли персонаж на своей опоре в НАЧАЛЕ тика. Сошедшего возить нельзя: опора
// помнится и в окне coyote ради наследования горизонтали, но по воздуху она никого не везёт — и
// исключать её из толкателей тогда тоже нельзя, потому что въезжает она в него на общих правах.
//
// Сносится ТОЛЬКО составляющая хода тела вдоль нормали касания — то есть ровно то, чем оно в
// персонажа въезжает. Касательная не сносит намеренно: перенос опорой возит пассажира и вбок,
// потому что тот на опоре СТОИТ, а бок платформы не трение, и таскать за ним прижатого к нему
// персонажа значило бы выдумать сцепление, которого в мире нет. По той же причине уезжающее тело
// не тянет персонажа за собой: составляющая ОТ него отрицательна, и сноса не происходит вовсе.
bool moved_by_world(const CollisionScene& s, const CharacterHull& hull, physics::BodyId support,
                    bool standing, fix32 dt, Vec2& position);

} // namespace framework::character
