#pragma once
#include <cstdint>

#include "fixmath.hpp"

// Профиль движения — ДАННЫЕ, а не наследование (решение владельца 2 спеки #16). Игра настраивает
// персонажа значениями, а не переопределением виртуальных методов: подкласс пришлось бы пересобирать
// ради правки высоты прыжка, а профиль правится в ассете и применяется без пересборки.
//
// Единицы — пиксель и секунда (`physics/units.hpp`), оси — +X вправо, +Y ВНИЗ. Окна прощения — в
// ТИКАХ (решение 4): окно в секундах при делении на шаг даёт дробное число тиков, а округление
// дроби есть поведение, зависящее от шага, то есть от машины.
namespace framework::character {

// Потолки профиля. Нужны по той же причине, что клампы физики: fix32 насыщает на ±32768, и
// насыщение — не авария, а тихая ложь. Персонаж с ускорением за потолком не «очень резвый», он
// приезжает в скорость, посчитанную из насыщенного произведения, то есть в НЕВЕРНУЮ.
constexpr fix32 MAX_MOVE_SPEED = fix32::from_int(2048);   // тот же потолок, что MAX_SPEED физики
constexpr fix32 MAX_MOVE_ACCEL = fix32::from_int(16384);  // юнит/с²: вдвое ниже насыщения
constexpr fix32 MAX_JUMP_HEIGHT = fix32::from_int(1024);  // юнит
constexpr uint32_t MAX_WINDOW_TICKS = 64;                 // окно прощения, тиков

struct MoveProfile {
    fix32 max_speed;      // потолок горизонтальной скорости, юнит/с
    fix32 ground_accel;   // разгон к цели по земле, юнит/с²
    fix32 ground_decel;   // торможение к цели по земле, юнит/с²
    fix32 air_accel;      // то же в воздухе: раздельное управление — требование спеки, а не
    fix32 air_decel;      // экономия полей, и «в воздухе как на земле» задаётся равенством

    // Тяготение РАЗНОЕ на подъёме и падении: равное даёт математически честную параболу, которая
    // ощущается вялой — персонаж долго висит в верхней точке. Это ровно то место, где #16 расходится
    // с #15: solver считает мир, контроллер считает ощущение.
    fix32 gravity_rise;   // юнит/с², пока поднимаемся
    fix32 gravity_fall;   // юнит/с², пока падаем
    fix32 max_fall_speed; // кламп скорости падения, юнит/с

    // Прыжок задаётся ВЫСОТОЙ, а не «силой» (требование спеки). Высота наблюдаема и переносима:
    // «сила 420» ничего не говорит о том, дотянется ли персонаж до платформы, и при правке
    // тяготения молча меняет смысл.
    fix32 jump_height;      // целевая высота при удержании кнопки, юнит
    // Высота при отпускании кнопки, юнит — но НЕ ровно она: первый тик прыжка успевает
    // проинтегрировать полную скорость подъёма ещё до того, как отпускание вообще становится
    // наблюдаемым (фронт требует, чтобы кнопка была нажата в предыдущем тике). Фактическая вершина
    // короткого прыжка равна `min_jump_height + jump_speed*dt`, то есть при штатных 16 юнитах и
    // 60 Гц — 22.37 вместо 16. Записано формулой, а не «примерно»: гейт прыжка сверяет вершину
    // касания ПОЛОСОЙ вокруг неё, и односторонний порог прятал бы здесь любую правку.
    fix32 min_jump_height;

    uint32_t coyote_ticks = 0;  // прыжок разрешён ещё столько тиков после схода с опоры
    uint32_t buffer_ticks = 0;  // нажатие живёт столько тиков и срабатывает при приземлении
};

// Скорости, выведенные из высот. Считаются ОДИН РАЗ на профиль и шаг, а не в тике: вывод стоит
// целочисленного корня, а тик обязан оставаться zero-alloc и дешёвым. Второе важнее первого —
// корень в тике сам по себе не страшен, но `derive` зависит от `dt`, и вывод внутри шага сделал
// бы траекторию функцией того, кто и когда подставил другой шаг.
struct MoveDerived {
    fix32 jump_speed;      // начальная скорость подъёма, модуль (velocity.y = -jump_speed)
    fix32 min_jump_speed;  // потолок скорости подъёма после отпускания кнопки
};

// Привести профиль в законный диапазон. Отдельно от `derive`, по образцу `sanitize`/`make_body`
// физики: тест вправе собрать заведомо вырожденный профиль и проверить, что его починили, а не
// считать, что чинить нечего.
MoveProfile sanitize(const MoveProfile& p);

// Вывести скорости под ЗАДАННЫЙ шаг тика. `dt` здесь не украшение: дискретное интегрирование
// промахивается мимо непрерывной параболы на величину, пропорциональную шагу, и поправка на
// полтика — единственное, что делает обещание «высота равна `jump_height`» правдой, а не
// приближением. Вывод целиком — в `profile.cpp`.
MoveDerived derive(const MoveProfile& p, fix32 dt);

// Профиль по умолчанию: персонаж бегает и прыгает сразу (решение 5 спеки #16). Значения — не
// «примерные»: 340 юнит/с совпадает со скоростью корабля игры-образца (`SHIP_SPEED`), тяготение —
// с `DEFAULT_GRAVITY_Y` физики, высота прыжка в 64 юнита это четыре тайла по 16.
MoveProfile default_profile();

} // namespace framework::character
