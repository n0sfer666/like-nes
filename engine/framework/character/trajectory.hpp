#pragma once
#include <cstdint>

#include "state.hpp"

// Хеш траектории персонажа — то, что сверяет гейт 1 спеки #16 между macOS, Linux и Windows.
//
// Свёртка взята ТА ЖЕ, что у хеша состояния физики (`physics::mix`), а не написана заново. Две
// одинаковые сегодня свёртки расходятся на первой же «уточнённой» константе, и расхождение ничем
// себя не проявляет: оба голдена считаются, оба перепиниваются, а сравнить один с другим больше
// нельзя — это ровно тот довод, которым `hash_mix.hpp` и был вынесен из физики.
namespace framework::character {

// Накопитель, а не функция от массива: траектория это ПОСЛЕДОВАТЕЛЬНОСТЬ тиков, и держать её
// целиком в памяти ради хеша незачем — тест кормит состояние по тику и не хранит ничего.
struct TrajectoryHash {
    uint64_t value;

    TrajectoryHash();

    // Порядок полей — часть голдена: перестановка двух подряд идущих полей даёт другой хеш при том
    // же состоянии. Менять его можно, но только вместе с перепечаткой голдена, и это не побочный
    // эффект правки, а отдельное решение.
    void feed(const Character& c);
};

} // namespace framework::character
