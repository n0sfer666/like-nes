#pragma once
#include "collision.hpp"
#include "slide.hpp"

// Два приёма прощения ГЕОМЕТРИЕЙ — в отличие от окон coyote и буфера, которые прощают ВРЕМЕНЕМ.
// Оба нужны по одной причине: кинематический персонаж честно упирается в то, во что упёрся, а
// играющий видит не касание коробок, а «зацепился ни за что» и «слетел со ступеньки на ровном
// месте». Оба выключаются нулём в профиле и тогда не стоят ни одного свипа.
//
// Отдельным модулем от `slide.cpp`, а не случаем внутри `move_and_slide`: скольжение отвечает на
// вопрос «куда доехало движение», а эти двое — на вопрос «а не подвинуть ли персонажа ПОМИМО его
// движения». Смешать их значило бы сделать доводку невидимой для того, кто читает траекторию.
namespace framework::character {

// Шаг перебора бокового сдвига. Юнит равен пикселю (`units.hpp`), и дробный шаг здесь был бы
// ложной точностью: угол, который не обходится целым пикселем, не обходится и половиной.
constexpr fix32 CORNER_STEP = fix32::from_int(1);

// Прощение УГЛА ПОТОЛКА. Персонаж, поднимающийся и задевающий головой край потолочного тайла,
// сдвигается вбок не больше чем на `max_shift`, если этим сдвигом путь вверх освобождается целиком.
//
// ТОЛЬКО ГОЛОВА (решение владельца 2026-08-24): ступенька под ногами — это шаг B вертикали 3, где
// приезжают склоны, и там же порог «до какого угла это пол» становится полем профиля. Сюда её
// дописывать нельзя: подъём на ступеньку меняет ОПОРУ, то есть спорит с пробой земли, а сдвиг под
// потолком не спорит ни с чем.
//
// Условия срабатывания:
//   * `travel.y < 0` — только на подъёме. Это РАННИЙ ВЫХОД, а не независимая проверка: наблюдаемое
//     «на падении и на ровном бегу не прощаем» держит условие нормали ниже, и прогон гейта со
//     снятым знаком (2026-08-24) не поймал НИ ОДИН случай. Оставлено ради свипа, которого при ходе
//     вбок и вниз не нужно делать вовсе, — не ради поведения;
//   * свип вверх обязан вернуть нормаль ПОТОЛКА, а не стены — иначе приём растаскивал бы персонажа
//     вдоль стены, вдоль которой он и так скользит. Именно это условие и отбивает ноги;
//   * сам боковой сдвиг обязан быть свободен — иначе персонаж проходит сквозь тот угол, ради
//     обхода которого сдвигается;
//   * после сдвига свип вверх обязан не встретить НИЧЕГО: «стало ближе» это не «освободилось».
//
// Сторона перебирается от направления движения по горизонтали, при нуле — вправо. Правило
// произвольное и потому записано здесь: без него выбор стороны на строго вертикальном прыжке
// зависел бы от порядка веток.
//
// Окно приводится ВНУТРИ (потолок `MAX_CORNER_CORRECTION`), поэтому вызов с любым значением
// кончается: перебор шага — целый счётчик, а не сложение, которое насыщается на потолке типа.
//
// Возвращает, случился ли сдвиг. Позиция меняется ТОЛЬКО при успехе.
bool corner_correct(const CollisionScene& s, const CharacterHull& hull, Vec2 travel,
                    fix32 max_shift, fix32 max_slope, Vec2& position);

// Прилипание к земле на спусках. Персонаж, у которого опора БЫЛА и который не поднимается,
// притягивается вниз не больше чем на `max_distance`, если там пол.
//
// Условие «не поднимается» живёт у вызывающего (`controller.cpp`, шаг 8), потому что там же лежит
// снимок «опора была». Знак берётся ДО движения: касание потолка гасит `velocity.y` тем же тиком, и
// прочитанный после него ноль выдавал бы прыжок за спуск. Так и было до 2026-08-24 — прыжок под
// потолком с просветом меньше одного тика подъёма притягивался обратно на пол и исчезал целиком.
//
// Окно приводится ВНУТРИ (потолок `MAX_GROUND_SNAP`) — тем же правилом, что и у сдвига выше.
//
// Возвращает, случилось ли притяжение. Позиция меняется ТОЛЬКО при успехе, и персонаж встаёт на
// зазор `SKIN` над полом — ровно туда же, куда его ставит разбор касания в `move_and_slide`.
bool snap_to_ground(const CollisionScene& s, const CharacterHull& hull, fix32 max_distance,
                    fix32 max_slope, Vec2& position);

} // namespace framework::character
