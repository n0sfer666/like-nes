// Шов «где персонаж встречает мир»: ОДИН запрос на два представления геометрии.
//
// Геометрия уровня живёт в двух видах и по разным основаниям: тела решателя (#15) — потому что их
// двигают и будят, тайловая сетка (#16, вертикаль 2) — потому что экран платформера это тысяча
// тайлов, которых никто не двигает, и телами они стоили бы смысла, а не памяти. Контроллеру же
// нужен один ответ: что ближе на пути. Спрашивать два источника ПООЧЕРЁДНО прямо в `move_and_slide`
// значило бы записать порядок слияния в трёх местах (движение, проба опоры, будущие приёмы
// вертикали 3) и получить три разных правила на равной доле пути — расхождение, наблюдаемое раз в
// сто прогонов на одной раскладке.
//
// Оба указателя ОПЦИОНАЛЬНЫ. Сцена без сетки — гейты вертикали 1 и любая сцена на телах; сцена без
// тел — уровень, целиком собранный из тайлов; пустая сцена законна и отвечает «пути ничто не
// мешает», а не падает: персонаж в пустоте это не ошибка вызывающего.
//
// Заголовок физики включён ОТНОСИТЕЛЬНЫМ путём, и это не стиль: у `physics/query.hpp` и
// `tilemap/query.hpp` одно базовое имя, оба каталога лежат на пути включений цели, и голое
// `#include "query.hpp"` разрешалось бы ПОРЯДКОМ ЛИНКОВКИ. Порядок линковки — не то, чем стоит
// выбирать заголовок.
namespace framework::tilemap {
class TileGrid;
}

namespace framework::character {

// Хитбокс и слои, по которым персонаж считает мир твёрдым. Отдельно от `Character`: состояние
// хешируется голденом, а форма и маска — описание запроса, и складывать их в одну структуру значит
// либо тащить 264 байта формы в хеш, либо объяснять в каждом хеше, какие поля он пропускает.
//
// Маска — про ТЕЛА: у сетки слоёв нет, тайл отбирается флагами (`TileFilter`). Разойтись этим двум
// отборам нечем ровно до тех пор, пока у персонажа один вопрос «что тут твёрдое»; односторонние
// тайлы вертикали 3 зададут второй, и тогда отбор станет полем сцены, а не хитбокса.
struct CharacterHull {
    physics::Shape shape;
    physics::LayerMask mask = physics::MASK_ALL;
};

// Мир глазами персонажа. Оба источника ЧИТАЮТСЯ: сцена не двигает ни тела, ни тайлы.
struct CollisionScene {
    const physics::World* world = nullptr;
    const tilemap::TileGrid* grid = nullptr;
};

// Ответ слияния. Тела и тайлы отвечают разными структурами (`physics::RayHit` знает про `BodyId` и
// ключ, `tilemap::TileHit` — про координаты тайла), и общими у них ровно эти два поля — то есть
// ровно то, чем пользуется движение. Тащить наверх и ключ тела, и адрес тайла значило бы заставить
// каждого читателя разбираться, какая половина заполнена.
struct SceneHit {
    fix32 fraction;
    Vec2 normal;
};

// Ближайшее касание формы, перенесённой на `travel`, по обоим источникам сразу.
//
// ПОРЯДОК СЛИЯНИЯ — часть контракта, потому что от него зависит траектория, а траектория пинится
// голденом на трёх ОС:
//   1. меньшая доля пути;
//   2. на РАВНОЙ доле — более встречная поверхность (меньший `dot(normal, travel)`): персонаж
//      упирается в то, во что едет, а не в то, вдоль чего скользит, и выбор не зависит от того,
//      тайлами или телом автор уровня выложил пол;
//   3. на равной доле и равной встречности — ТЕЛА. Правило произвольное и потому записано числом
//      здесь, а не подразумевается порядком вызовов внутри.
bool cast_nearest(const CollisionScene& s, const CharacterHull& hull, Vec2 position, Vec2 travel,
                  SceneHit& out);

} // namespace framework::character
