// РЕЖИМ ДВИЖЕНИЯ «лестница» (вертикаль 3, шаг D) — альтернативный тик, а не приём внутри обычного.
//
// Своим файлом и своим тиком, потому что на лестнице не работает ни один шаг обычного: тяготения
// нет, разгона по горизонтали нет, прыжок значит «отпустить», а движение идёт с постоянной
// скоростью вверх или вниз. Вписать это в восемь шагов контроллера можно было бы только условиями
// внутри каждого — то есть заведя вторую машину состояний, размазанную по чужому порядку, где
// «висит на лестнице» читалось бы из комбинации `on_ground`, скорости и тяготения.
//
// Тайл лестницы ничего не держит (`TILE_LADDER` живёт без `TILE_SOLID`, `tilemap/grid.hpp`), и это
// главное свойство режима: геометрия шахты не меняется вовсе, а меняется то, КТО считает тик.
namespace framework::character {

// Посчитать тик лестницы. `true` — тик СЪЕДЕН целиком: скорость, движение, состояние и память
// кнопки уже записаны, и обычному шагу делать в этом тике нечего. `false` — персонаж лестницы не
// касается (или только что её отпустил), и тик считает контроллер.
//
// Окно перехвата истекает ЗДЕСЬ и на каждом тике, а не только на лестнице: считать его в
// контроллере значило бы разложить одну величину по двум владельцам, и тик, съеденный лестницей,
// её бы не двигал.
bool ladder_step(const CollisionScene& s, const CharacterHull& hull, const MoveProfile& p,
                 const MoveDerived& d, const MoveInput& in, fix32 dt, Character& c);

} // namespace framework::character
