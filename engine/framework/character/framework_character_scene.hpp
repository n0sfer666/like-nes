// Общая сцена гейтов персонажа: пол, стена, потолок и площадка с краем.
//
// СМЕШАННАЯ (решение владельца 2026-08-24, вертикаль 3): пол и стена выложены ТАЙЛАМИ, потолок
// остался ТЕЛОМ. Иначе слияние двух источников (`collision.hpp`) под голденом не наблюдается вовсе:
// сцена из одних тайлов пинит тайловую половину шва, сцена из одних тел — телесную, а порядок,
// которым они спорят между собой, не пинит ни та, ни другая. Здесь спорят: прыжок у стены под
// потолком разбирает за один тик касание тела и касание сетки.
//
// Геометрия при переезде на тайлы сохранена ДО ЮНИТА — те же грани, что были у трёх коробок. Так
// расхождение голдена означает «слияние поменяло движение», а не «сцена переехала»: разъехавшись
// заодно и обстановкой, перепечатанное число не сообщало бы ничего.
//
// Мир здесь НЕ ШАГАЕТСЯ ни разу. Персонаж не тело решателя, а статике решатель не нужен — `World`
// играет роль контейнера геометрии, который умеют опрашивать запросы #15; сетка не двигается по
// построению. Движущиеся платформы, ради которых мир придётся шагать, приходят шагом B вертикали 3.
//
// Сцена общая у трёх целей нарочно: гейты обязаны расходиться вопросом, а не обстановкой. Голден,
// окна прощения и высота прыжка, посчитанные на трёх разных раскладках, невозможно сравнивать между
// собой — «прыжок стал ниже» и «пол переехал» выглядят одинаково. Четвёртый гейт, туннелирование,
// сюда не входит осознанно: ему нужна ЗАВЕДОМО тонкая стена, а тонкая стена в общей сцене меняла бы
// траекторию голдена ради вопроса, который голден не задаёт.
namespace framework::character {

// Верх пола ровно на y = 0: считать высоту прыжка от круглого числа проще, чем от полутора
// полуразмеров, и все ожидания тестов ниже написаны от него.
constexpr fix32 FLOOR_TOP = fix32{};
constexpr fix32 HULL_HALF_W = fix32::from_int(8);
constexpr fix32 HULL_HALF_H = fix32::from_int(16);

// Край площадки, с которого персонаж сходит в гейте окна coyote.
constexpr fix32 LEDGE_RIGHT = fix32::from_int(200);

// Тайл в 10 юнитов: все грани прежней сцены кратны ему, поэтому раскладка ложится на сетку без
// единого доборного юнита. Начало отнесено левее и выше всего, что в сцене есть, — сетка отвечает
// пусто за своими краями, но грань на краю карты настоящая, и класть её туда, где стоит персонаж,
// значило бы завести стену из ничего.
constexpr fix32 TILE = fix32::from_int(10);
constexpr Vec2 GRID_ORIGIN{fix32::from_int(-420), fix32::from_int(-210)};

inline void add_static(physics::World& w, uint32_t key, Vec2 center, fix32 half_w, fix32 half_h) {
    physics::BodyDesc d;
    d.key = key;
    d.type = physics::BodyType::Static;
    d.shape = physics::box(half_w, half_h);
    d.position = center;
    w.add(d);
}

// Сцена целиком. Указатели на её половины отдаёт `view()`, а не хранит поле: сцена возвращается по
// значению, и указатель, взятый до перемещения, смотрел бы в прежнее место.
struct Scene {
    physics::World world;
    tilemap::TileGrid grid;

    CollisionScene view() const { return {&world, &grid}; }
};

// Пол кончается на LEDGE_RIGHT, дальше — пропасть. Стена слева, потолок над левой половиной.
inline Scene make_scene() {
    physics::World w(4);
    w.set_gravity({fix32{}, fix32{}});
    // Потолок висит НИЖЕ целевой высоты прыжка: подвешенный выше он не участвовал бы в результате
    // вовсе, и гейт удара головой проверял бы, что персонаж до него не долетел.
    add_static(w, 3, {fix32::from_int(-300), FLOOR_TOP - fix32::from_int(58)}, fix32::from_int(100),
               fix32::from_int(10));

    // 62 x 41 тайла: от (-420, -210) до (200, 200) — ровно габарит прежних коробок.
    tilemap::TileGrid g(GRID_ORIGIN, TILE, 62, 41);
    g.fill(0, 1, 2, 21, tilemap::TILE_SOLID);    // стена: x [-420, -400], y [-200, 0]
    g.fill(2, 21, 62, 41, tilemap::TILE_SOLID);  // пол:   x [-400,  200], y [   0, 200]
    return {std::move(w), std::move(g)};
}

inline CharacterHull make_hull() {
    CharacterHull h;
    h.shape = physics::sanitize(physics::box(HULL_HALF_W, HULL_HALF_H));
    return h;
}

// Персонаж, стоящий на полу в `x`: центр на полувысоту выше пола, плюс зазор, в котором он и
// держится после первой же пробы опоры.
inline Character standing_at(fix32 x) {
    Character c;
    c.position = {x, FLOOR_TOP - HULL_HALF_H - SKIN};
    c.state = MoveState::Ground;
    c.on_ground = true;
    return c;
}

} // namespace framework::character
