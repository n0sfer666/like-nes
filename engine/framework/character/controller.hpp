// Тик кинематического персонажа (спека #16, вертикаль 1).
//
// ПОРЯДОК ВНУТРИ ТИКА — часть контракта, а не деталь реализации: от него зависят и высота прыжка
// (вывод поправки на полтика в `profile.cpp` опирается ровно на этот порядок), и то, на каком тике
// истекает окно прощения. Порядок такой:
//
//   1. нажатие запоминается буфером;
//   2. горизонтальная скорость подтягивается к цели с ускорением или торможением;
//   3. тяготение меняет вертикальную скорость и клампится скоростью падения;
//   4. прыжок ПЕРЕЗАПИСЫВАЕТ вертикальную скорость, если он разрешён и запрошен;
//   5. отпускание кнопки обрывает подъём, ограничивая скорость минимальной высотой;
//   6. движение со скольжением по шейпкасту;
//   7. окна прощения истекают на один тик;
//   8. проба опоры задаёт состояние и назначает окно coyote.
//
// Окна назначаются ПОСЛЕ истечения (7 перед 8) — иначе окно, выданное в тике схода с опоры, тут же
// теряло бы один тик из своей длины, и «шесть тиков прощения» означало бы пять.
//
// Zero-alloc: ни один шаг не ходит в кучу. Запросы #15 держат `WorldShape` на стеке и заполняют
// `RayHit` по ссылке, вектора здесь нет ни одного. Устройством это или дисциплиной — вопрос не к
// комментарию: рядом лежит `overlap_shape`, который держит `std::vector`, и один вызов не тем
// запросом снял бы инвариант 5 спеки #16 молча. Поэтому он пинится счётчиком обращений к куче в
// `framework_character_alloc_test` — с позитивным контролем, общим с гейтом 6 спеки #15.
namespace framework::character {

// `d` обязан быть выведен из `p` ТЕМ ЖЕ `dt` (`derive`). Пара передаётся раздельно, потому что
// вывод стоит целочисленного корня, и делать его каждый тик значило бы платить за то, что не
// меняется.
//
// Профиль приводится в диапазон ВНУТРИ (`sanitize`), как и в `derive`: у подсистемы два входа, и
// требовать приведения только от одного из них значит завести ловушку, срабатывающую от порядка
// вызовов. Позиция по итогам тика клампится границей мира — за ней Q16.16 насыщается, а насыщенная
// координата делает мусором любой шейпкаст.
void step(const CollisionScene& s, const CharacterHull& hull, const MoveProfile& p,
          const MoveDerived& d, const MoveInput& in, fix32 dt, Character& c);

} // namespace framework::character
