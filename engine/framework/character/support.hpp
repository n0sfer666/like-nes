#pragma once
#include "collision.hpp"

// ПЕРЕНОС ОПОРОЙ (вертикаль 3, шаг B3): персонаж, стоящий на движущейся платформе, едет вместе с
// ней. Своим файлом, а не строчкой в контроллере, потому что вопрос отдельный: контроллер считает
// тик персонажа, а здесь считается движение ЧУЖОГО тела и то, помещается ли персонаж туда, куда оно
// его двигает.
//
// Платформа — только ТЕЛО. У `tilemap::TileGrid` начало координат лишь читается, сдвинуть слой
// тайлов нечем, и движущийся тайловый пол в этом движке невыразим; следствие оттуда же — платформа
// не может быть односторонней, потому что `TILE_ONEWAY` живёт на тайле.
namespace framework::character {

// Скорость запомненной опоры. Ноль отдаётся и на невалидной опоре, и на замершей: «опоры нет» и
// «опора стоит» дают один и тот же перенос, и разводить их вторым ответом незачем.
//
// Неподвижность спрашивается ТЕМ ЖЕ предикатом, которым её читает интеграция мира (`world.cpp`):
// статика неподвижна по типу, замершее тело — по правилу покоя, и в обоих случаях записанная в тело
// скорость движением не становится. Перенос по ней уводил бы персонажа с НЕПОДВИЖНОЙ платформы —
// то есть в сторону от опоры, которая никуда не ехала.
Vec2 support_velocity(const CollisionScene& s, physics::BodyId support);

// Перенести персонажа движением опоры за тик. `true` — перенос состоялся (в том числе когда
// переносить было нечего); `false` — персонажа ВЖАЛО.
//
// Перенос идёт ПЕРВЫМ шагом тика и БЕЗ свипа, и оба свойства несущие. Первым — потому что порядок
// кадра «физика, потом персонаж» (решение владельца) означает, что платформа уже сдвинулась, а
// персонаж ещё нет: между ними ровно `velocity * dt` — вверх это перекрытие, вниз просвет. Перенос
// его и снимает, восстанавливая тот самый зазор, который был в конце прошлого тика; он не создаёт
// новой геометрии, а возвращает старую. Без свипа — потому что свип, стартующий внутри опоры,
// отвечает долей ноль с нормалью ПОЛА (`cast.cpp`), то есть про саму опору, и отличить им стену от
// собственной платформы нечем.
//
// Перенос АТОМАРЕН ПО ОСИ: случается целиком либо не случается вовсе, и мерится это по каждой оси
// отдельно. Перенос «сколько влезло» пришлось бы мерить ровно тем свипом, который здесь неприменим,
// а на едущей вверх платформе он вдавливал бы персонажа в потолок понемногу каждый тик — то есть за
// десяток тиков сквозь него. Отказ ничего не делает с персонажем и ничего за игру не решает:
// убивать, выталкивать или терпеть — её выбор.
//
// А вот по осям вопросы РАЗНЫЕ, и мерить их одним ответом неверно. Вверх платформа персонажа
// ПРИЖИМАЕТ к потолку: места между ними не остаётся, и отказ — единственная честная развязка. Вбок
// она лишь ЕДЕТ у него под ногами: сверху пусто, стена рядом не давит, и упёршийся пассажир значит
// ровно то, что крыша проехала под подошвами, — ящик на ленте, доехавший до стены, остаётся стоять.
// Поэтому непроходимая горизонталь роняется в СКОЛЬЖЕНИЕ и `true`, а отказом остаётся только
// непроходимая вертикаль. Найдено третьей находкой владельческого прогона §6 (2026-09-01): плита
// везла персонажа, прижатого к козырьку, отказ поднимал `crushed`, и образец возвращал его в точку
// появления — «сбрасывает в спавн» на ровном месте.
bool carry_by_support(const CollisionScene& s, const CharacterHull& hull, physics::BodyId support,
                      fix32 dt, Vec2& position);

} // namespace framework::character
