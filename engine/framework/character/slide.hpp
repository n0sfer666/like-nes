#pragma once
#include "query.hpp"
#include "state.hpp"

// Движение со скольжением и проба опоры — весь контакт персонажа с миром.
//
// Персонаж двигается ШЕЙПКАСТОМ, а не «сдвинуть и вытолкнуть»: свип #15 не перепрыгивает касание по
// построению (`cast.hpp`), поэтому тонкая стена не теряется на большой скорости — это инвариант 2
// спеки #16, и он достаётся даром, а не «при достаточно мелком шаге».
namespace framework::character {

// Хитбокс и слои, по которым персонаж считает мир твёрдым. Отдельно от `Character`: состояние
// хешируется голденом, а форма и маска — описание запроса, и складывать их в одну структуру значит
// либо тащить 264 байта формы в хеш, либо объяснять в каждом хеше, какие поля он пропускает.
struct CharacterHull {
    physics::Shape shape;
    physics::LayerMask mask = physics::MASK_ALL;
};

// Зазор до поверхности. СТРОГО больше допуска проникновения физики, и строгость несущая: свип
// останавливается уже НА `CONTACT_SLOP` (`cast.cpp`), то есть форма, стоящая ровно в допуске,
// возвращает долю пути ноль в ЛЮБОМ направлении — включая направление ОТ поверхности. Персонаж,
// отдыхающий ровно в допуске, гасил бы прыжок о собственный пол: свип вверх немедленно отдавал бы
// касание с нормалью (0, -1), а скольжение вдоль неё обнуляло бы вертикальную скорость. Именно так
// и было — прыжок поднимался на 0.0625 юнита вместо 64, и держалось это лишь на том, что
// `nearest_on_core` возвращал расстояние с запасом от кванта вдоль грани; точный ответ обнажил
// ошибку.
//
// Величина выписана СВОИМ числом, а не выражением от `CONTACT_SLOP`: утверждение ниже обязано
// сравнивать две независимо выбранные константы. Записанное через сам допуск (`slop * 2`) оно было
// тавтологией — не срабатывало ни при каком значении допуска, кроме нуля, — то есть выглядело
// гейтом, ничего не проверяя. Теперь сдвиг любой из двух величин навстречу другой ловится сборкой.
constexpr fix32 SKIN = fix32::from_float(0.125);
static_assert(physics::CONTACT_SLOP.raw < SKIN.raw,
              "the character skin must stay strictly wider than the sweep contact slop");

// Проба опоры бьёт вчетверо дальше зазора: персонаж отдыхает на зазоре плюс остаток допуска, и
// проба длиной в сам зазор упиралась бы в границу «касание или нет» — то есть отвечала бы на вопрос
// об опоре округлением.
constexpr fix32 GROUND_PROBE = fix32::from_raw(SKIN.raw * 4);

// Порог «это опора, а не стена»: косинус 45 градусов. Вертикаль 1 живёт на прямоугольной статике,
// где нормаль пола ровно (0, -1), и порог тут работает только на углах; собственным полем профиля
// он станет в вертикали 3, когда появятся склоны и вопрос «до какого угла это пол» станет
// настройкой игры, а не константой движка.
constexpr fix32 SURFACE_NORMAL_Y = fix32::from_float(0.70710678);

// Потолок проходов скольжения за тик. Исчерпан — остаток пути ОТБРАСЫВАЕТСЯ, и это осознанно:
// персонаж, зажатый в угол, обязан остановиться, а не проехать сквозь одну из стен.
constexpr uint32_t SLIDE_PASSES = 4;

struct SlideResult {
    bool hit_ceiling = false;
    bool hit_wall = false;
};

// Сдвинуть на `travel` со скольжением вдоль встреченных поверхностей. Гасит составляющую скорости
// вдоль нормали касания — ту же, что и составляющую остатка пути: иначе персонаж, упёршийся в пол,
// накапливал бы скорость падения и при первом же шаге в сторону улетал бы вниз рывком.
SlideResult move_and_slide(const physics::World& w, const CharacterHull& hull, Vec2 travel,
                           Vec2& position, Vec2& velocity);

// Есть ли под персонажем опора. Читающая: мир не двигает, состояние не трогает.
bool probe_ground(const physics::World& w, const CharacterHull& hull, Vec2 position);

} // namespace framework::character
