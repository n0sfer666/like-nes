#pragma once
#include <cstdint>

#include "framework_character_scene.hpp"

// Уровень ЦЕЛЕВОГО РАЗМЕРА для гейта 7 спеки #16 — и его же уменьшенная копия.
//
// Раскладка ПОРОЖДАЕТСЯ, а не читается из `example_ugly_game/assets`: гейт движка, стоящий на
// ассетах игры-образца, краснеет от правки уровня, к движку отношения не имеющей, — и это ровно тот
// разрез не по смыслу, от которого предостерегает направление зависимостей (инвариант 1 спеки #14).
// Здесь геометрия — часть утверждения, поэтому и живёт рядом с ним.
//
// Карт ДВЕ, и в этом весь замысел гейта. Инвариант 4 спеки («стоимость запроса не зависит от
// размера уровня») наблюдаем только сравнением, а не абсолютным числом: одна карта дала бы цифру,
// про которую нельзя сказать, окно она описывает или карту. Поэтому маленькая и целевая отличаются
// ТОЛЬКО габаритом — 8 192 тайла против 262 144, в тридцать два раза по площади, — а вдоль всего
// маршрута геометрия у них побитово одна и та же: узор периодичен, старт стоит в одной и той же
// колонке, и маршрут не подходит к краю ни одной из них. Разъедься хоть в юните — расхождение
// счётчиков читалось бы как «окно поехало», хотя поехала бы обстановка.
namespace framework::character::perf {

// Тайл в 16 юнитов и начало в нуле — те же, что у уровня игры-образца: корпус персонажа (16 x 32)
// ложится на такую сетку целым числом тайлов, и высота прыжка профиля (64) меряется в тайлах без
// остатка. Так «пролез под потолком» и «не достал до площадки» считаются глазами по раскладке.
constexpr fix32 TILE_SIZE = fix32::from_int(16);
constexpr uint32_t PATTERN_W = 32;
constexpr uint32_t PATTERN_H = 13;
constexpr uint32_t FLOOR_ROW = 12;

// Обе карты ШИРЕ и ВЫШЕ узора, и узор кладётся с шагом `PATTERN_W` по X; строки ниже пола пусты —
// персонаж туда не попадает, а окно запроса на пол не заглядывает глубже одного тайла.
constexpr uint32_t SMALL_W = 256;
constexpr uint32_t SMALL_H = 32;
constexpr uint32_t TARGET_W = 1024;
constexpr uint32_t TARGET_H = 256;

// Старт — ОДНА И ТА ЖЕ колонка на обеих картах, а не середина каждой: середины стоят в разной фазе
// узора и в разных мировых координатах, и голден траектории разошёлся бы сам собой, ничего не
// сказав про стоимость запроса.
constexpr uint32_t START_COL = 128;

// Запас до края карты, который маршрут обязан оставить. Он не про вкус: у самого края окно запроса
// ОТСЕКАЕТСЯ картой, `scanned` падает — и маленькая карта показала бы работы МЕНЬШЕ целевой, то
// есть инвариант 4 «подтвердился» бы отсечением, которого на целевой карте нет.
constexpr uint32_t SAFE_MARGIN_TILES = 8;

constexpr uint32_t WARMUP_TICKS = 60;
constexpr uint32_t MEASURED_TICKS = 1800;
// Смена направления. Период выбран так, чтобы за него персонаж проходил около семидесяти тайлов —
// две с лишним копии узора в каждую сторону, и при этом не подходил к краю маленькой карты.
constexpr uint32_t FLIP_TICKS = 200;

// Узор шириной ровно `PATTERN_W`. Легенда та же, что у `example_ugly_game/assets/tilemap.txt`:
// `.` пусто, `X` сплошной, `=` односторонний, `/` и `\` — склоны, поднимающиеся вправо и влево.
//
// Что здесь есть и зачем: пол на всю ширину (иначе персонаж проваливается и меряет падение),
// холм в две ступени со склонами на входе и выходе (ходьба по наклонной грани), односторонняя
// площадка на 48 юнитов над полом — прыжок в 64 до неё достаёт, — и потолочный выступ с просветом
// ровно в высоту корпуса: под ним персонаж проходит, а прыгнув под ним, бьётся головой.
inline const char* const PATTERN[PATTERN_H] = {
    "................................",
    "................................",
    "................................",
    "................................",
    "................................",
    "................................",
    "................................",
    "................................",
    ".........................XXXXXX.",
    "......====......................",
    "................/XXXX\\..........",
    ".............../XXXXXX\\.........",
    "XXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXX",
};

inline tilemap::TileFlags flags_of(char c) {
    switch (c) {
        case 'X': return tilemap::TILE_SOLID;
        case '=': return tilemap::TILE_SOLID | tilemap::TILE_ONEWAY;
        case '/': return tilemap::TILE_SOLID | tilemap::TILE_SLOPE;
        case '\\':
            return tilemap::TILE_SOLID | tilemap::TILE_SLOPE | tilemap::TILE_SLOPE_FLIP_X;
        default: return tilemap::TILE_EMPTY;
    }
}

// Позитивный контроль самого узора: строка, потерявшая символ, сдвинула бы всё правее себя на тайл
// и осталась бы правдоподобной на вид. Утверждается гейтом, а не `static_assert`, потому что длину
// строкового литерала в constexpr пришлось бы считать вручную — той же рукой, что и ошиблась бы.
inline bool pattern_is_rectangular() {
    for (uint32_t row = 0; row < PATTERN_H; ++row) {
        uint32_t n = 0;
        while (PATTERN[row][n] != '\0') ++n;
        if (n != PATTERN_W) return false;
    }
    return true;
}

// Мир нужен сцене контейнером геометрии тел, и тел в нём НЕТ ни одного: гейт мерит цену ТАЙЛОВОГО
// запроса, и подмешивать в счётчик работу широкой фазы значило бы получить число, про которое
// нельзя сказать, чьё оно.
inline Scene make_level(uint32_t width, uint32_t height) {
    physics::World w(1);
    w.set_gravity({fix32{}, fix32{}});
    tilemap::TileGrid g({fix32{}, fix32{}}, TILE_SIZE, width, height);
    for (uint32_t y = 0; y < PATTERN_H && y < height; ++y)
        for (uint32_t x = 0; x < width; ++x)
            g.set(x, y, flags_of(PATTERN[y][x % PATTERN_W]));
    return {std::move(w), std::move(g)};
}

inline fix32 tick_dt() { return fix32::from_int(1) / fix32::from_int(60); }

inline fix32 floor_top() { return TILE_SIZE * fix32::from_int(static_cast<int32_t>(FLOOR_ROW)); }

inline Character start_character() {
    Character c;
    c.position = {TILE_SIZE * fix32::from_int(static_cast<int32_t>(START_COL)) + TILE_SIZE / fix32::from_int(2),
                  floor_top() - HULL_HALF_H - SKIN};
    c.state = MoveState::Ground;
    c.on_ground = true;
    return c;
}

// Маршрут — ФУНКЦИЯ ОТ НОМЕРА ТИКА, а не записанная лента: он обязан быть одним и тем же на обеих
// картах до бита, а лента этого не обещает, она это лишь повторяет.
inline MoveInput input_at(uint32_t t) {
    MoveInput in;
    in.move_x = ((t / FLIP_TICKS) % 2) == 0 ? fix32::from_int(1) : fix32::from_int(-1);
    in.jump_held = (t % 37) < 6;
    in.down_held = (t % 211) < 4;
    return in;
}

} // namespace framework::character::perf
