namespace framework::brawl {

// Тик одного троса; возвращает седока, которого трос отпустил в этом тике. Седок отпускает его
// прыжком по фронту — вылетает с касательной скоростью; трос роняет седока, ушедшего из пула или
// секции, мёртвого, в реакции или в чужом захвате — тот летит со своей скоростью, отбрасывание
// удара остаётся. Роняет и седока не в точке подвеса — его сдвинул поводок камеры, — и седока, в
// которого трос несёт на тело физмира: лифт ходит сам, и встать о него, как о стену, трос не может.
// После отпускания трос не берётся `ROPE_COOLDOWN` тиков. Тайл на пути седока останавливает трос:
// дуга остаётся прошлой, скорость обнуляется; односторонний держит седока, как бойца: сверху трос
// встаёт на него, снизу и сбоку седок проходит. Седок в стопе удара — своего, ударив с троса, — не
// падает: трос стоит вместе с ним. Пока седок бьёт, ввода у него нет, как у контроллера в ударе: ни
// раскачки, ни разворота, ни прыжка.
EntId ride_rope(RopeState& r, const scene::Rope& rope, BodyPool& pool, std::span<const Command> commands,
                StageSections& sections, const BrawlWorld& w);

// Захват: живое тело в platform, в воздухе, не в реакции, не в стопе удара и не в чужом захвате, с
// зажатым захватом; руки — верх корпуса — не дальше `ROPE_REACH` от конца троса, путь корпуса к
// концу свободен. Трос с седоком или в остывании не берётся; скорость троса — проекция скорости тела.
// Прыжок, зажатый в тике захвата, фронтом не считается: отпустит только новое нажатие.
void grab_rope(StageRopes& ropes, const scene::LevelObjects& level, Body& b, const BrawlInput& in,
               StageSections& sections, const PlatformWorld& p);

} // namespace framework::brawl
