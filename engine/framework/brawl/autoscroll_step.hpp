// Автоскролл (решение владельца 2026-10-11): прямоугольники `autoscroll` проходятся по порядку уровня,
// каждый один раз, с постоянной скоростью. Старт — центр за шаг дошёл до начала дорожки по оси или
// пересёк его (`before` — центр прошлого шага, как `seen` у замка арены). Судится центр уже после
// возврата: пока по оси идёт `settle`, соседняя дорожка стартует позже на его отставание. Дальше
// `center.axis = scroll`, `scroll` идёт к дальнему краю на `|speed|` за тик, знак `speed` —
// направление. Дорожка — центры вида, у которых зона камеры внутри прямоугольника. Дошёл — `ride`
// переходит к следующему, пройденный не перезапускается. После проезда центр по его оси идёт от
// прошлого шага к следованию, зажатому `clamp_level`, шагом `max(|speed|, разрыв / 8)` (`settle`, по
// каждой оси своё): поводок держал игроков у заднего края, и мгновенный возврат к их середине прыгал
// бы видом на половину ширины за кадр, а шаг ровно `|speed|` привязал бы к скорости проезда игроков,
// идущих вперёд. Цена доли: отставание держится около восьми скоростей игроков, и пара, разнесённая
// почти на ширину вида, прижимается передним краем, пока не сожмётся. Возврат не зависит от `ride`:
// следующая дорожка, пропущенная или по другой оси, его не трогает.
// `speed = 0` пропускается на старте: такая дорожка держала бы камеру навсегда. По `y` центр
// следует только в platform, и в belt старт по `y` возможен лишь ровно на центре вида. `on` — край
// в этом тике двигал камеру и толкает игроков.
Ride ride_scroll(StageCamera& camera, Vec2 before, const scene::LevelObjects& level);

