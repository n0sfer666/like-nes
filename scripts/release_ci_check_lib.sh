# shellcheck shell=bash
# Утверждения о пакете, ПРИЕХАВШЕМ из CI (спека #20, вертикаль 3) — отдельно от того, что их
# запускает: их зовёт и сам оркестратор (release_ci.sh: скачал — проверь), и гейт правил
# (check_release_ci.sh), и самопроверка на сломанных фикстурах. Утверждение, существующее только
# внутри своего прогона, невозможно уронить нарочно, а значит — неизвестно, умеет ли оно падать.

# Утверждения о CRT живут своим файлом (предмет — таблица импортов, а не состав), но зовутся
# отсюда: пакет Windows приезжает именно этим путём, и требовать от каждого гейта помнить про
# второй `source` значит однажды его забыть.
# shellcheck source=scripts/release_crt_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/release_crt_lib.sh"

# Целостность передачи. Сверка идёт с SHA256SUMS, приехавшим В ТОМ ЖЕ артефакте, и это утверждение
# ровно про доставку — «архив доехал целым», — а не про подлинность: подписи у артефакта нет, и
# заявлять большее значило бы называть проверку суммы защитой, которой она не является. Подлинность
# держит следующее утверждение, у которого источник независимый.
assert_download_intact() {
  local pkg="$2" sums="$1/SHA256SUMS" got
  [ -s "$pkg" ] || { bad "скачанный пакет пуст или отсутствует: $pkg"; return 1; }
  [ -s "$sums" ] || { bad "в артефакте нет SHA256SUMS — сверять сумму не с чем"; return 1; }
  got=$(sha256_of "$pkg")
  if ! grep -Fqx -- "$got  $(basename "$pkg")" "$sums"; then
    bad "сумма скачанного пакета не найдена в его SHA256SUMS: $got"
    return 1
  fi
  ok "архив доехал целым (сумма совпала с SHA256SUMS артефакта)"
}

# ЦЕПОЧКА — главное утверждение вертикали. Оркестратор просил собрать конкретный коммит; GitHub
# отдал артефакт конкретного прогона; штамп внутри пакета называет коммит независимо от обоих.
# Сходятся все три — значит доехал ТОТ пакет. Не сходятся — значит доехал какой-то, и разница
# между этими случаями и есть всё, что даёт путь через чужую машину.
#
# Штамп несёт КОРОТКИЙ хеш (cmake/version_stamp.cmake: rev-parse --short), поэтому сравнение —
# префиксом, а не равенством: требовать сорок символов там, где их семь, значило бы отбивать
# честный пакет.
assert_ci_chain() {
  local pkg="$1" want_version="$2" want_sha="$3" stamp l1 l2 short
  stamp=$(ci_stamp_of "$pkg") || true
  [ -n "$stamp" ] || { bad "в пакете нет like-nes/version.txt — штамп не прочитать"; return 1; }
  l1=$(printf '%s\n' "$stamp" | sed -n 1p)
  l2=$(printf '%s\n' "$stamp" | sed -n 2p)
  if [ "$l1" != "like-nes engine $want_version" ]; then
    bad "штамп приехавшего пакета называет не ту версию: '$l1' вместо '$want_version'"; return 1
  fi
  short=${l2#commit }
  if [ "$short" = "$l2" ] || [ -z "$short" ]; then
    bad "штамп не называет коммит: '$l2'"; return 1
  fi
  case "$want_sha" in
    "$short"*) ;;
    *) bad "штамп называет коммит $short, а прогон собирал $want_sha"; return 1 ;;
  esac
  ok "цепочка сошлась: прогон на $short, тот же коммит в штампе, версия $want_version"
}

# Про приехавший пакет утверждается то же, что про собранный здесь: СОСТАВ поимённо, лицензии и
# штамп с тройкой. Вертикали 1 и 2 распаковывают пакет и зовут эти три утверждения
# (check_release.sh, check_release_container.sh), а вертикаль 3 сверяла только две строки штампа —
# и пакет без `editor_shell.exe`, без `wgpu_native.dll` или с лицензией в нуль байт доезжал как
# успех, сойдись версия и коммит. Прогон CI тоже ничего о пакете не утверждает: там только
# release.sh и upload, а `--verify`-этапа нет.
#
# Тройка берётся ИЗ ИМЕНИ ПАКЕТА — тем же приёмом, что в вертикалях 1-2 (release.sh называет её
# `-DLIKE_NES_TARGET_TRIPLE` и он же ставит в имя), поэтому «пакет собран не на Windows» перестаёт
# проходить по совпадению версии и коммита. `assert_runtime_named` здесь не зовётся и звать его
# нечем: его независимый источник — кеш CMake, а тот остался на раннере.
# Тройка -> ОС в форме `uname -s`, которую понимает expected_files. Отдельной функцией, потому что
# по ней же строит фикстуры самопроверка: сравнивай гейт с копией этого маппинга — и общая ошибка
# обеих половин осталась бы зелёной, ровно как у имени рантайма в assert_runtime_named.
ci_os_of_triple() {
  case "$1" in
    windows-*) printf 'MINGW\n' ;;
    linux-*) printf 'Linux\n' ;;
    macos-*) printf 'Darwin\n' ;;
    *) return 1 ;;
  esac
}

assert_ci_package() {
  local root="$1" pkg="$2" version="$3" base triple os tmp rc=0
  base=$(basename "$pkg" .tar.gz)
  triple=${base#"like-nes-engine-$version-"}
  if [ "$triple" = "$base" ] || [ -z "$triple" ]; then
    bad "имя пакета не называет тройку: $(basename "$pkg")"; return 1
  fi
  os=$(ci_os_of_triple "$triple") || {
    bad "тройка $triple не называет известную ОС — состав пакета неизвестен"; return 1
  }
  tmp=$(mktemp -d)
  if ! tar -xzf "$pkg" -C "$tmp"; then
    bad "архив не распаковывается: $(basename "$pkg")"; rm -rf "$tmp"; return 1
  fi
  assert_composition "$root" "$tmp" "$os" || rc=1
  assert_licenses "$root" "$tmp" || rc=1
  assert_stamp "$tmp" "$version" "$triple" || rc=1
  # Про зависимость от VC++ Redistributable утверждается ТОЛЬКО на пакете Windows: на прочих
  # платформах PE-файлов в нём нет вовсе, и утверждение отбило бы честный пакет за то, что
  # осматривать нечего (счётчик осмотренных бинарей у него нулевой).
  if [ "$os" = MINGW ]; then
    assert_crt_self_contained "$root" "$tmp" || rc=1
    assert_static_crt "$root" "$tmp" || rc=1
  else
    # Пропуск ВСЛУХ, как у всех прочих в дереве: молчаливый в общем прогоне читается как пройденный
    # гейт, а «утверждений о CRT не было» и «они прошли» — разные исходы.
    ok "ПРОПУСК: пакет $os, PE-файлов в нём нет — о VC++ Redistributable утверждать нечего"
  fi
  rm -rf "$tmp"
  return "$rc"
}
