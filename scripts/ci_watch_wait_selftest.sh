#!/usr/bin/env bash
# Самопроверка ОЖИДАНИЯ наблюдателя CI: сколько опросов он успел сделать и смотрит ли он ещё раз
# перед тем, как сказать «узнать не удалось».
#
# Отдельный файл от `ci_watch_selftest.sh` по границе предмета, а не по счётчику строк: там
# проверяется ВЕРДИКТ — чистая функция от набора прогонов, — а здесь поведение ЦИКЛА во времени,
# ради которого приходится подменять `gh` заглушкой и гонять самого наблюдателя целиком. Зовётся он
# оттуда же внешней командой: в логе тогда названо сломанное, а не «что-то из двух разошлось».
set -uo pipefail

DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
. "$DIR/ci_watch_lib.sh"

fails=0
ok() {
    if [ "$2" = "$1" ]; then
        printf 'ok   %s\n' "$3"
    else
        printf 'FAIL %s: ожидалось «%s», получено «%s»\n' "$3" "$1" "$2"
        fails=$((fails + 1))
    fi
}

# --- сколько опросов наблюдатель успел сделать --------------------------------------------------
# Бюджет наблюдателя мерится стенными часами, а узнаёт он что-либо только опросом, и до 2026-08-24
# эти две величины считались одной. Число опросов — та улика, которая отличает «CI не досчитал» от
# «наблюдатель не смотрел», и потому оно суждение, а не печать по месту.
ok 80 "$(polls_due 2400 30)" "40 минут по 30 секунд — восемьдесят опросов"
ok 0 "$(polls_due 10 30)" "бюджет короче интервала — честный ноль"
if polls_due 2400 0 >/dev/null 2>&1; then
    printf 'FAIL нулевой интервал разобран числом — деление на ноль выдано за ответ\n'
    fails=$((fails + 1))
else
    ok 1 1 "нулевой интервал отказывается кодом, а не отдаёт число"
fi
ok observed "$(watch_health 77 80)" "77 опросов из 80 — здоровый прогон, запросы тоже стоят времени"
ok observed "$(watch_health 40 80)" "ровно половина — ещё наблюдение: граница названа и включена"
ok asleep "$(watch_health 39 80)" "меньше половины — утверждение о наблюдателе, а не о CI"
ok asleep "$(watch_health 4 80)" "четыре опроса за сорок минут — процесс не исполнялся"
ok observed "$(watch_health 0 0)" "нулевой бюджет сном не является"

# Сломанные реализации здоровья. Первая — поведение ДО починки: наблюдатель молчал о том, сколько
# раз смотрел, то есть всегда выглядел добросовестным. Вторая валит в сон любой честный таймаут и
# делает предупреждение шумом, которое перестают читать.
health_ok() {
    [ "$("$1" 77 80)" = observed ] && [ "$("$1" 4 80)" = asleep ]
}
always_observed() {
    : "$1" "$2"
    printf 'observed'
}
always_asleep() {
    : "$1" "$2"
    printf 'asleep'
}
health_ok watch_health || {
    printf 'FAIL честное суждение о числе опросов не проходит собственные фикстуры\n'
    fails=$((fails + 1))
}
for broken in always_observed always_asleep; do
    if health_ok "$broken"; then
        printf 'FAIL фикстуры пропустили сломанное суждение %s\n' "$broken"
        fails=$((fails + 1))
    else
        printf 'ok   сломанное суждение %s отбито\n' "$broken"
    fi
done

# --- последний взгляд перед «не знаю» -----------------------------------------------------------
# Свойство ЦИКЛА, а не суждения, поэтому проверяется прогоном самого наблюдателя с заглушкой вместо
# `gh`. Фикстура воспроизводит ровно случившееся 2026-08-24: последнее наблюдение говорит
# `in_progress`, а прогон к этому моменту давно зелёный.
STUB=$(mktemp -d)
trap 'rm -rf "$STUB"' EXIT
cat >"$STUB/gh" <<'STUBEOF'
#!/usr/bin/env bash
# Первый `run list` отвечает незавершённым прогоном, все следующие — зелёным. Счётчик в файле:
# каждый вызов заглушки — отдельный процесс, переменной ему не хватило бы.
n=$(cat "$STUB_N" 2>/dev/null || printf 0)
case "$1 ${2:-}" in
    "run list")
        n=$((n + 1))
        printf '%s' "$n" >"$STUB_N"
        if [ "$n" -le 1 ]; then printf 'in_progress null push 111 ci\n'
        else printf 'completed success push 111 ci\n'; fi
        ;;
    "run view") printf '  success build\n' ;;
esac
STUBEOF
chmod +x "$STUB/gh"

run_watcher() {
    STUB_N="$STUB/n" CI_WATCH_GH="$STUB/gh" CI_WATCH_TIMEOUT_S=1 CI_WATCH_INTERVAL_S=1 \
        bash "$1" >/dev/null 2>&1
}
rm -f "$STUB/n"
run_watcher "$DIR/ci_watch.sh"
ok 0 "$?" "дедлайн при зелёном прогоне — вердикт success, а не «узнать не удалось»"

# Позитивный контроль: реализация БЕЗ последнего взгляда обязана быть отбита. Без него фикстура
# выше зелена и на том наблюдателе, который врал.
sed '/^final_look$/d' "$DIR/ci_watch.sh" >"$STUB/no_final_look.sh"
rm -f "$STUB/n"
run_watcher "$STUB/no_final_look.sh"
if [ "$?" -eq 0 ]; then
    printf 'FAIL наблюдатель без последнего взгляда прошёл фикстуру — она ничего не сторожит\n'
    fails=$((fails + 1))
else
    ok 1 1 "наблюдатель без последнего взгляда отбит"
fi

if [ "$fails" -ne 0 ]; then
    printf '\nci-watch-wait-selftest: FAIL — проверок с находками %d\n' "$fails"
    exit 1
fi
printf 'ci-watch-wait-selftest: PASS\n'
