# shellcheck shell=bash
# ПОДМЕНЫ прогона гейта 5 (спека #19), названные вслух. Отдельно от раннера потому, что заглушка,
# живущая внутри своего прогона, проверяема только этим прогоном: живой прогон 2026-09-06 показал
# ровно этот дефект — заглушка клона звала саму себя, разворачивала пустой каталог, и сборка падала
# «нет CMakeLists.txt» на исправном документе. Вынесенная, она проверяется ВЫЗОВОМ
# (assert_start_stub_runs), а не грепом по раннеру.
#
# Обе подмены оставляют текст команды документа дословным: подправь мы его — гейт проверял бы не ту
# инструкцию, которую читает человек.

# Путь в тело заглушки едет ЗНАЧЕНИЕМ, а не текстом: каталог прогона на машине владельца лежит в
# /var/folders/…, и апостроф в чужом пути разорвал бы кавычку молча.
start_shq() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

start_write_stubs() {
  local stub="$1" src="$2" want="$3"
  mkdir -p "$stub"
  # sudo: в контейнере мы root, а sudo там нет вовсе. Выкинуть слово из строки значило бы исполнять
  # не написанное; ставить настоящий sudo — ставить пакет, о котором документ не просил.
  cat > "$stub/sudo" <<'EOS'
#!/bin/sh
exec "$@"
EOS
  # git clone: прогон судит ДЕРЕВО, которое коммитят, а не то, что уже лежит на GitHub. Настоящий
  # клон отвечал бы про прошлый push — то есть гейт молчал бы ровно о правке, которую сейчас вносят.
  # Что адрес в документе ведёт именно в этот репозиторий, держит assert_start_clone_url: подмена
  # снимает сеть, а не проверку адреса.
  #
  # Подменяется РОВНО адрес из документа, а не всякий клон: FetchContent тянет зависимости тем же
  # `git clone`, и живой прогон 2026-09-06 показал, во что это обходится — вместо glfw в
  # `_deps/glfw-src` разворачивалась копия НАШЕГО дерева, а конфигурация умирала «Failed to checkout
  # tag». Чистая машина зависимости и должна тянуть по-настоящему: сеть снимается с той единственной
  # команды, ответ на которую иначе пришёл бы из прошлого push.
  {
    echo '#!/bin/sh'
    printf 'STUB_DIR=%s\n' "$(start_shq "$stub")"
    printf 'SRC=%s\n' "$(start_shq "$src")"
    printf 'WANT=%s\n' "$(start_shq "$want")"
    cat <<'EOS'
# Каталог заглушек вычищается из PATH ПЕРЕБОРОМ — та же мера и по той же причине, что у набора про
# вызов appimagetool: без неё `git ls-files` ниже находит эту же заглушку, а не git, уходит в ветку
# `exec` с чужими аргументами и оставляет пустой каталог. Разрешается git в момент ВЫЗОВА, а не
# записи заглушки: ставит его фаза установки, то есть при записи его в системе ещё нет.
clean=
saved_ifs=$IFS
IFS=:
for d in $PATH; do
  if [ "$d" != "$STUB_DIR" ]; then clean=${clean:+$clean:}$d; fi
done
IFS=$saved_ifs
PATH=$clean
export PATH
real=$(command -v git 2>/dev/null) || real=
if [ -z "$real" ]; then
  echo "docs-start: настоящего git в PATH нет — подменять нечего" >&2
  exit 127
fi
# Самонахождение отбивается ОТКАЗОМ, а не молчаливым исполнением: чистка PATH выше — единственное,
# что стоит между заглушкой и бесконечной рекурсией, и потерянная строка не роняет гейт, а ВЕШАЕТ
# его — на каждом коммите, потому что гейт стоит в checks.json. Висящий гейт хуже падающего:
# падение читается как находка, а тишина — как «ещё считает».
if [ "$real" = "$STUB_DIR/git" ] || [ "$real" -ef "$STUB_DIR/git" ] 2>/dev/null; then
  echo "docs-start: PATH ведёт в саму заглушку — настоящего git не осталось" >&2
  exit 127
fi
# Аргументы НЕ сдвигаются: `shift` укорачивал бы и ту команду, которую ветка ниже отдаёт настоящему
# git, и тот получал бы адрес вместо подкоманды. Адрес — ПЕРВЫЙ операнд после `clone`, а не
# последний: последним стоит каталог назначения, если читатель его назвал.
url=
dst=
if [ "${1-}" = clone ]; then
  first=1
  for a in "$@"; do
    if [ -n "$first" ]; then first=; continue; fi
    case "$a" in
      -*) ;;
      *) if [ -z "$url" ]; then url=$a; elif [ -z "$dst" ]; then dst=$a; fi ;;
    esac
  done
fi
# Адрес сверяется ПОБАЙТНО со строкой документа: и она, и подменяемая команда пришли из одного
# файла, поэтому нормализовать тут нечего, а копия правил нормализации разъехалась бы с оригиналом.
if [ -n "$url" ] && [ "$url" = "$WANT" ]; then
  [ -n "$dst" ] || dst=$(basename "$url" .git)
  echo "docs-start: клон подменён копией примонтированного дерева -> $dst"
  mkdir -p "$dst"
  # Копируются файлы, ВИДИМЫЕ git (индекс плюс ненаписанное, без игнорируемого) — тот же охват, что
  # у бюджета длины и гейта кодировок: каталоги сборки хозяйской машины на чистую машину не едут.
  ( cd "$SRC" && "$real" -c safe.directory='*' ls-files -z --cached --others --exclude-standard \
      | tar -cf - --null -T - ) | ( cd "$dst" && tar -xf - )
  exit 0
fi
exec "$real" "$@"
EOS
  } > "$stub/git"
  chmod +x "$stub/sudo" "$stub/git"
}
