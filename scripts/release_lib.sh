# shellcheck shell=bash
# Общие кирпичи релиза (спека #20): контрольная сумма, манифест содержимого и детерминированный
# архив. Отдельный файл, потому что этих трёх функций три потребителя — сам `release.sh`, гейт
# `check_release.sh` и его самопроверка; повтори их у каждого, и «два прогона дали одну сумму»
# перестало бы что-либо утверждать: сравнивались бы две разные реализации сравнения.

# `shasum` есть на macOS и в git-bash, `sha256sum` — на Linux. Ни одна из двух не универсальна,
# и молчаливый выбор «какая нашлась» здесь допустим ровно потому, что обе печатают один хеш.
sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

# Манифест — это утверждение о СОДЕРЖИМОМ, живущее отдельно от архива. Архив у разных tar'ов
# разный байт в байт (ustar против pax), а манифест зависит только от файлов, поэтому
# воспроизводимость проверяется им, а сумма архива — уже следствием на одной и той же машине.
manifest_of() {
  local root="$1"
  ( cd "$root" && find . -type f | LC_ALL=C sort | while read -r f; do
      printf '%s  %s\n' "$(sha256_of "$f")" "${f#./}"
    done )
}

# Время последнего коммита — единственный штамп времени, который у релиза есть и который не
# меняется между прогонами. Взять `now` значило бы получать новую сумму каждую секунду и объявить
# это «невоспроизводимо по природе», хотя невоспроизводимым его сделали бы мы сами.
release_stamp() {
  TZ=UTC0 git -C "$1" log -1 --date=format-local:%Y%m%d%H%M.%S --format=%cd
}

# Стейдж обязан состоять из ОБЫЧНЫХ файлов. Симлинк и пустой каталог `find -type f` не видит, и не
# видит их одинаково у обоих: и упаковщик, и манифест прошли бы мимо, а слепота ОБЩАЯ не ловится
# сверкой архива с манифестом вовсе. Отказ громче тихой пропажи: версионированные `.so.N` — штатная
# форма поставки на Linux, и разобраться с ними обязана вертикаль, которая их привезёт.
stage_is_plain() {
  local root="$1" odd
  odd=$( cd "$root" && find . ! -type f ! -type d -o -type d -empty )
  if [ -n "$odd" ]; then
    printf 'release: в стейдже не только обычные файлы, паковать нечем:\n%s\n' "$odd" >&2
    return 1
  fi
}

# Архив собирается из ОТСОРТИРОВАННОГО списка файлов с занулённым владельцем и общим mtime: порядок
# обхода каталога, uid машины и время установки — три источника, каждого из которых достаточно,
# чтобы два прогона одного кода дали разные байты. `gzip -n` убирает четвёртый (имя и время в
# заголовке). Диалект tar разный на macOS и Linux, поэтому флаги выбираются по факту, а не по вере.
# Диалект отдаётся наружу глобалью, а не выбирается внутри упаковщика: подменные упаковщики
# самопроверки обязаны отличаться от настоящего РОВНО снятой мерой. Прошитый в них `--uid 0` падал
# на git-bash с `unrecognized option` (там tar — GNU), архив не появлялся вовсе, и «подмена отбита»
# выходило из отсутствия предмета, а не из дефекта — ровно тот класс, что ловит `vacuous-gate`.
tar_pack_flags() {
  if tar --version 2>/dev/null | grep -q GNU; then
    TAR_PACK=(--owner=0 --group=0 --numeric-owner --format=ustar)
  else
    TAR_PACK=(--uid 0 --gid 0 --numeric-owner --format=ustar)
  fi
}

pack_dir() {
  local root="$1" out="$2" stamp="$3" list rc=0
  stage_is_plain "$root" || return 1
  list="$(mktemp)"
  tar_pack_flags
  ( cd "$root" && find . -type f | LC_ALL=C sort > "$list" \
    && TZ=UTC0 xargs -I{} touch -h -t "$stamp" {} < "$list" \
    && tar "${TAR_PACK[@]}" -cf - -T "$list" ) | gzip -n -9 > "$out" || rc=$?
  # Код прогона перехвачен, поэтому уборка идёт и на падении: `rm` последней строкой под `set -e` у
  # вызывающего пропускался бы ровно в тех прогонах, после которых мусор и остаётся.
  rm -f "$list"
  return "$rc"
}

# Версия разрешается ОДНОЙ функцией на оба входа — хостовый release.sh и контейнерный
# release_container.sh. Копия правила во втором значила бы, что отсутствие тега ловится уже ВНУТРИ
# контейнера, то есть после сборки образа: пятнадцать минут ожидания ради сообщения, которое
# известно на первой секунде.
resolve_version() {
  local root="$1" version="$2"
  if [ -z "$version" ]; then
    version=$(git -C "$root" describe --tags --exact-match HEAD 2>/dev/null || true)
  fi
  # Версии нет — отказ. Подстановка "0.0.0" дала бы пакет, чей штамп не отличает релиз от
  # случайного состояния дерева, а узнаётся это только у того, кто его уже скачал.
  if [ -z "$version" ]; then
    echo "release: на HEAD нет тега и версия не названа — укажи --version vX.Y.Z" >&2
    return 1
  fi
  if ! printf '%s' "$version" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+([-.][A-Za-z0-9.]+)?$'; then
    echo "release: версия '$version' не похожа на тег vX.Y.Z" >&2
    return 1
  fi
  printf '%s\n' "$version"
}

# Файл сумм пересчитывается по ФАКТИЧЕСКОМУ содержимому каталога версии, а не дописывается строкой
# текущего прогона: пакеты трёх ОС кладутся в один каталог разными запусками (`--only`), и файл,
# перезаписанный одной строкой, оставлял бы релиз с суммой последней собранной трети. Потребителей
# два — хостовой упаковщик и оркестратор CI, который приносит пакет Windows в тот же каталог; вторая
# копия правила ровно этот дефект и вернула (артефакт прогона несёт СВОЙ SHA256SUMS с одной
# строкой, и скачивание прямо в каталог версии затирало им суммы двух других третей).
# Родные установщики попадают сюда наравне с архивом: файл сумм — про ДОСТАВКУ («скачанное доехало
# целым»), и пакет, которого в нём нет, проверить нечем вовсе. Про воспроизводимость он при этом не
# говорит ни у одного из них: сумма .dmg от прогона к прогону разная (hdiutil пишет своё время и
# UUID), у .AppImage она повторяется — но утверждают это гейты (check_release_dmg.sh по манифесту
# тома, check_release_appimage.sh по самим байтам образа), а не наличие строки в этом файле.
write_sums() {
  ( cd "$1" && find . -maxdepth 1 \( -name '*.tar.gz' -o -name '*.dmg' -o -name '*.AppImage' -o -name '*.msi' \) | sed 's|^\./||' | LC_ALL=C sort \
    | while read -r f; do printf '%s  %s\n' "$(sha256_of "$f")" "$f"; done > SHA256SUMS )
}
