# shellcheck shell=bash
# Утверждения о готовом установщике Windows (спека #20, вертикаль 4, шаг C). Читаются они msitools
# (`msiinfo`, `msiextract`), которых на Windows нет вовсе, — поэтому осмотр живёт на машине
# владельца и на линукс-раннере, а сборка поставляемого пакета на раннере Windows. Граница между
# «чем собрано» и «чем осмотрено» здесь проходит по машинам, и молчать о ней нельзя.
#
# Пакет — не архив: содержимое лежит в CAB внутри OLE-хранилища, и «поимённый состав» достаётся
# только распаковкой. Поэтому большинство утверждений работает по РАЗВЁРНУТОМУ дереву и делит их с
# архивом (assert_composition, assert_licenses, assert_stamp). Здесь пакет читается и сверяется как
# СОДЕРЖИМОЕ; то, чего в дереве нет вовсе — пользовательская установка, полнота удаления, линия
# обновления и ярлык, — судится по тем же таблицам в release_msi_behavior_lib.sh.

# Три служебные строки заголовка (имена колонок, типы, имя таблицы с ключами) — не данные. Возврат
# каретки снимается здесь: msiinfo печатает таблицы окончаниями CRLF, и он приезжает в ПОСЛЕДНЕЕ
# поле строки — то есть сравнение двух одинаковых значений расходилось на невидимом байте. Первым
# прогоном гейта так упали три утверждения из десяти.
# Код возврата msiinfo слушается, а не отбрасывается: у отсутствующей таблицы экспорт отвечает
# единицей, и молчаливое пустое от неё неотличимо от таблицы без строк — то есть сверка «пустое
# против пустого» равняла бы два пакета, ни одного из которых не читала (класс `vacuous-gate`).
msi_table() {
  local out
  out=$(msiinfo export "$1" "$2" 2>/dev/null) || return 1
  printf '%s\n' "$out" | tail -n +4 | tr -d '\r'
}

msi_prop() { msi_table "$1" Property | awk -F'\t' -v k="$2" '$1 == k { print $2 }'; }

msi_extract_to() {
  local msi="$1" dir="$2"
  mkdir -p "$dir" || return 1
  ( cd "$dir" && msiextract "$msi" ) >/dev/null 2>&1
}

# Сводный поток пакета несёт случайный package code (свойство 9) и время сборки (12 и 13) — ровно
# те три строки, из-за которых байт-равенства у MSI не бывает. Всё остальное обязано совпадать, и
# отбрасываются они ПОИМЁННО, а не таблицей целиком: в том же потоке живут платформа с языком,
# заголовок и версия схемы, и молча простить их значило бы не проверять сводку вовсе.
msi_norm_table() {
  local out
  out=$(msi_table "$1" "$2") || return 1
  if [ "$2" = _SummaryInformation ]; then
    printf '%s\n' "$out" | awk -F'\t' '$1 != 9 && $1 != 12 && $1 != 13'
  else
    printf '%s\n' "$out"
  fi
}

# Воспроизводится СОДЕРЖИМОЕ, а байты — нет, и утверждается здесь именно содержимое: все таблицы
# двух пакетов равны. Список таблиц берётся у обоих и сверяется первым — пакет, потерявший таблицу
# целиком, иначе прошёл бы обход, которому нечего обходить (тот же класс, что `vacuous-gate`).
assert_msi_content_reproducible() {
  local a="$1" b="$2" ta tb t n=0 nd=0 d ra rb
  ta=$(msiinfo tables "$a" 2>/dev/null | tr -d '\r' | LC_ALL=C sort)
  tb=$(msiinfo tables "$b" 2>/dev/null | tr -d '\r' | LC_ALL=C sort)
  if [ -z "$ta" ]; then bad "в пакете $a не видно ни одной таблицы"; return 1; fi
  if [ "$ta" != "$tb" ]; then
    bad "наборы таблиц двух прогонов разошлись"
    diff <(printf '%s\n' "$ta") <(printf '%s\n' "$tb") | sed 's/^/       /' >&2 || true
    return 1
  fi
  while IFS= read -r t; do
    [ -n "$t" ] || continue
    ra=$(msi_norm_table "$a" "$t") || { bad "таблица $t первого пакета не экспортируется"; return 1; }
    rb=$(msi_norm_table "$b" "$t") || { bad "таблица $t второго пакета не экспортируется"; return 1; }
    if [ "$ra" != "$rb" ]; then
      bad "таблица $t разошлась между прогонами"
      d=$(diff <(printf '%s\n' "$ra") <(printf '%s\n' "$rb")) || true
      printf '%s\n' "$d" | sed 's/^/       /' >&2
      return 1
    fi
    n=$((n + 1))
    [ -z "$ra" ] || nd=$((nd + 1))
  done <<EOF
$ta
EOF
  if [ "$n" -eq 0 ]; then bad "не осмотрено ни одной таблицы"; return 1; fi
  # Таблиц СО СТРОКАМИ считается отдельно: пустых у пакета половина по построению (19 из 35 на
  # первом же живом прогоне), и общее число не различает «сверил содержимое» и «сравнил пустое с
  # пустым». Ноль здесь — отказ, а не тишина.
  if [ "$nd" -eq 0 ]; then bad "ни одна таблица не содержит строк — сравнивалось пустое с пустым"; return 1; fi
  ok "содержимое пакета воспроизводится ($n таблиц, из них $nd со строками; сводный поток без package code и времени)"
}

# Два прогона обязаны быть ДВУМЯ прогонами. Сравнение содержимого пакета с его же копией зелено
# вакуумно (тот же класс, что правило `vacuous-gate`), и единственная улика, отличающая копию от
# второй сборки, — package code: он случаен, и совпасть у двух вызовов компилятора не может. Стал
# бы формат когда-нибудь детерминированным — это находка, а не тишина: гейт скажет об этом здесь.
assert_msi_runs_distinct() {
  local a="$1" b="$2" pa pb
  pa=$(msi_table "$a" _SummaryInformation | awk -F'\t' '$1 == 9 { print $2 }')
  pb=$(msi_table "$b" _SummaryInformation | awk -F'\t' '$1 == 9 { print $2 }')
  if [ -z "$pa" ] || [ -z "$pb" ]; then bad "в сводном потоке нет package code — пакет собран не тем"; return 1; fi
  if [ "$pa" = "$pb" ]; then
    bad "у двух прогонов один package code ($pa) — сравнивается копия, а не вторая сборка"
    return 1
  fi
  ok "прогонов действительно два (package code разный: $pa и $pb)"
}

# Развёрнутый пакет обязан быть ЗЕРКАЛОМ стейджа: `msiextract` кладёт файлы ровно в то дерево, из
# которого пакет собран, и своего файла установщик не добавляет. Сверяется мультимножество сумм
# вместе с именами, то есть утверждение ничего не знает о раскладке msi_dir_id — подмена раскладки
# обязана его валить, а состав по expected_files она пройдёт.
assert_msi_mirrors_stage() {
  local ex="$1" stage="$2" a b
  a=$(manifest_of "$stage" | LC_ALL=C sort)
  b=$(manifest_of "$ex" | LC_ALL=C sort)
  if [ -z "$a" ]; then bad "стейдж $stage пуст — зеркалить нечего"; return 1; fi
  if [ "$a" != "$b" ]; then
    bad "развёрнутый пакет разошёлся со стейджем"
    diff <(printf '%s\n' "$a") <(printf '%s\n' "$b") | sed 's/^/       /' >&2 || true
    return 1
  fi
  ok "развёрнутый пакет — зеркало стейджа ($(printf '%s\n' "$a" | wc -l | tr -d ' ') файлов)"
}
