# shellcheck shell=bash
# ПРОВОДКА гейтов (спека #20): каждое имя assert_*, которое гейт зовёт, обязано быть определено ТЕМ,
# что гейт сорсит сам. Предмет отдельный от гигиены прогона (release_check_hygiene.sh): там про
# «в какой форме сложено и что осталось снаружи», здесь — про то, соберётся ли гейт вообще.
#
# Ветка --live вертикали 3 уже падала на `assert_pack_normalized: command not found` у утверждения,
# которого этап правил не касался вовсе. Первая версия этой проверки резолвила имена `declare -F` В
# ПРОЦЕССЕ ВЫЗЫВАЮЩЕГО, то есть по набору функций, который засорсил САМ НАБОР самопроверки, — и
# гейт, забывший `source`, проходил её, пока библиотеку сорсил кто-то другой. То есть проверка была
# вакуумна ровно к тому сценарию, ради которого написана (находка ревью шага B вертикали 4).
# Поэтому имена резолвятся в ЧИСТОМ bash, куда сорсится только то, что сорсит сам гейт.
gate_sourced_libs() {
  sed 's/#.*//' "$1" | sed -n 's|^[[:space:]]*\.[[:space:]]*"\$ROOT/scripts/\([A-Za-z0-9_.-]*\)".*|\1|p'
}

# Комментарии вырезаются ДО поиска имён: устаревшее имя в шапке стало бы ложной находкой — тот же
# класс, что уже чинили в assert_ci_no_second_packer. Алфавит имени с цифрами и заглавными: шаблон
# `[a-z_]` усёк бы будущий assert_sha256_of до assert_sha и уронил гейт на пустом месте.
gate_assert_names() {
  sed 's/#.*//' "$1" | grep -oE '\bassert_[A-Za-z0-9_]+' | LC_ALL=C sort -u
}

assert_gate_asserts_defined() {
  local gate="$1" root names missing
  root=$(cd "$(dirname "$gate")/.." && pwd)
  names=$(gate_assert_names "$gate")
  # Пустой список — находка, а не «нарушений нет»: гейт, в котором греп не нашёл ни одного
  # утверждения, проверяется этой функцией вакуумно.
  [ -n "$names" ] || { bad "в $(basename "$gate") нет ни одного assert_* — проверка вакуумна"; return 1; }
  missing=$(ROOT="$root" bash -c '
    for lib in $2; do . "$ROOT/scripts/$lib" >/dev/null 2>&1 || true; done
    for n in $1; do declare -F "$n" >/dev/null || printf "%s\n" "$n"; done
  ' _ "$names" "$(gate_sourced_libs "$gate")")
  if [ -n "$missing" ]; then
    bad "$(basename "$gate") зовёт утверждения, которых нет среди засорсенного им:"
    printf '%s\n' "$missing" | sed 's/^/       /' >&2
    return 1
  fi
  ok "утверждения гейта $(basename "$gate") определены ($(printf '%s\n' "$names" | wc -l | tr -d ' '))"
}
