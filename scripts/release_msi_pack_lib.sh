# shellcheck shell=bash
# Вызов компилятора MSI и суждение о его ИСХОДЕ (спека #20, вертикаль 4, шаг C). Отдельный файл от
# раскладки по той же границе, что `…_pack_selftest.sh` отделён от набора про содержимое: предмет
# здесь — «чем собрано и появился ли файл», а не «что куда легло».
#
# Компилятора ДВА, и это не запасной путь, а два хоста. Поставляемый пакет собирает WiX v3 на
# раннере Windows — родной инструмент, который единственный там есть. Фикстуры гейта собирает
# `wixl` из msitools на машине владельца — WiX на macOS не существует. Оба читают ОДИН исходник в
# одном диалекте, и ровно поэтому фикстура проверяет тот же генератор, что и продакшн, а не свою
# копию правил. Граница названа вслух: совпадение ПОВЕДЕНИЯ двух компиляторов ничем здесь не
# доказано, доказано совпадение ВХОДА — а выход настоящего WiX осматривает check_release_ci.sh на
# пакете, приехавшем из прогона.

msi_tool_name() {
  if command -v candle >/dev/null 2>&1 && command -v light >/dev/null 2>&1; then
    printf 'wix\n'
    return 0
  fi
  if command -v wixl >/dev/null 2>&1; then
    printf 'wixl\n'
    return 0
  fi
  return 1
}

# Код 2 — «инструмента нет», и он отличается от отказа сборки: msitools не стоит на раннере Windows,
# WiX не стоит на macOS, и ни то, ни другое не есть поломка. Путать их нельзя — пропуск обязан быть
# назван вслух, а отказ обязан ронять прогон.
#
# Об успехе судим по ФАЙЛУ, а не по коду возврата: `light` при отказе оставляет обрубок, и `-f`
# принимает его наравне с готовым пакетом. Ненулевой код при этом слушается ПЕРВЫМ и печатается
# целиком — он достовернее и называет причину.
msi_pack() {
  local base="$1" wxs="$2" out="$3" tool rc log obj
  tool="$(msi_tool_name)" || return 2
  log="$(mktemp)" || return 1
  rm -f "$out"
  case "$tool" in
    wix)
      obj="$out.wixobj"
      ( cd "$base" && candle -nologo -arch x64 -out "$obj" "$wxs" \
        && light -nologo -spdb -out "$out" "$obj" ) >"$log" 2>&1
      rc=$?
      rm -f "$obj"
      ;;
    *)
      ( cd "$base" && wixl --arch x64 -o "$out" "$wxs" ) >"$log" 2>&1
      rc=$?
      ;;
  esac
  if [ "$rc" -ne 0 ]; then
    printf 'release: компилятор MSI (%s) отказал, код %s:\n' "$tool" "$rc" >&2
    cat "$log" >&2
    rm -f "$log" "$out"
    return 1
  fi
  # Лог печатается и на УСПЕХЕ: у WiX предупреждения проверки (ICE) не поднимают код возврата, а
  # именно там живёт ICE61 про диапазоны таблицы Upgrade — то есть единственная диагностика,
  # способная сказать о линии обновления что-то сверх наших утверждений, уходила в никуда.
  if [ -s "$log" ]; then
    printf 'release: компилятор MSI (%s) сказал:\n' "$tool" >&2
    cat "$log" >&2
  fi
  rm -f "$log"
  if [ ! -s "$out" ]; then
    printf 'release: компилятор MSI (%s) завершился нулём, но пакета %s нет\n' "$tool" "$out" >&2
    rm -f "$out"
    return 1
  fi
}
