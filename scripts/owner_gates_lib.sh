# shellcheck shell=bash
# Разбор docs/owner-verification.md: какие ручные гейты в нём есть, какие открыты и что владельцу с
# каждым делать. Один разбор на гейт (check_owner_gates.sh) и на печать ручной половины
# (owner_check.sh) — вторая копия списка разъехалась бы с документом молча, ровно list-drift из
# ci_lint.py. Так уже и было: owner_check.sh звал гейт 9 спеки #17 открытым четыре дня после
# закрытия и не называл шести открытых вовсе.
#
# Эталон — САМ документ: заголовок раздела `## N. Gate(s) K[ and M] of #S — …` и метка статуса
# `<!-- gate: open | <что делать> -->` / `<!-- gate: closed <дата> -->` под ним. Метка
# HTML-комментарием, а не frontmatter'ом, по тому же решению 2 спеки #19, что у штампа перевода:
# документ обязан читаться прямо на хостинге репозитория, и служебная строка читателю не
# показывается. ДЕЙСТВИЕ живёт в метке, потому что владельцу перечень нужен инструкцией, а не
# адресом: заголовок раздела говорит, куда идти, и молчит о том, что там делать.

# Путь назван ОДНИМ местом: его читают гейт, owner_check.sh и набор самопроверки, а написанный
# в трёх копиях он есть ровно тот list-drift, ради которого гейт и заведён.
# shellcheck disable=SC2034
OWNER_DOC=docs/owner-verification.md

# Разделитель полей — US (0x1f), а НЕ таб. Таб входит в «IFS whitespace» шелла, поэтому подряд
# идущие табы `read` схлопывает в один, и пустое поле (нет действия у закрытого, нет баннера у
# открытого) исчезает, сдвигая ВСЕ следующие: у закрытого раздела дата баннера приезжала в поле
# действия, и оба новых утверждения — «открыт без шага» и «баннер не совпал» — валили исправный
# документ. Непробельный разделитель пустые поля сохраняет.
# shellcheck disable=SC2034
OWNER_FS=$'\037'

owner_ok() { printf 'owner-gates: OK   %s\n' "$1"; }
owner_bad() { printf 'owner-gates: FAIL %s\n' "$1" >&2; }

# Разделы-гейты: номер раздела, спека, номера гейтов через запятую, статус, дата, заголовок целиком,
# действие владельца, дата из БАННЕРА закрытия. Незнакомая форма заголовка печатается со спекой `?`,
# отсутствующая метка — статусом `-`, метка не той формы — `!`: «не разобрал» и «нарушений нет»
# обязаны различаться, иначе опечатка в разметке молча выкидывает раздел из гейта. Разбор по ПОЛЯМ,
# а не регуляркой с длинным тире: em dash многобайтовый, и образец с ним судил бы локаль.
#
# Тело ```-блоков пропускается: документ на две с половиной тысячи строк состоит из команд и САМ
# показывает читателю форму метки, а `## 3. …` внутри блока читался бы структурой документа. Ту же
# границу проводит check_docs.sh, где комментарий шелла, принятый за заголовок, делал живым якорь,
# которого у документа нет.
owner_gates_sections() {
  awk -v OFS="$OWNER_FS" '
    function flush() { if (have) print sec, spec, nums, status, date, title, act, banner; have = 0 }
    /^```/ { inb = !inb; next }
    inb { next }
    /^## / {
      flush()
      if ($0 !~ /^## [0-9]+\./) next
      sec = $2; sub(/\.$/, "", sec)
      if (sec == "0") next
      have = 1; spec = "?"; nums = "?"; status = "?"; date = ""; title = $0; act = ""; banner = ""
      if ($3 == "Gate" && $4 ~ /^[0-9]+$/ && $5 == "of" && $6 ~ /^#[0-9]+$/) {
        nums = $4; spec = substr($6, 2)
      } else if ($3 == "Gates" && $4 ~ /^[0-9]+$/ && $5 == "and" && $6 ~ /^[0-9]+$/ && $7 == "of" && $8 ~ /^#[0-9]+$/) {
        nums = $4 "," $6; spec = substr($8, 2)
      }
      next
    }
    have && status == "?" && /^<!-- gate:/ {
      if ($0 ~ /^<!-- gate: open -->$/) { status = "open" }
      else if ($0 ~ /^<!-- gate: open \| .+ -->$/) {
        status = "open"; act = $0
        sub(/^<!-- gate: open \| /, "", act); sub(/ -->$/, "", act)
      }
      else if ($0 ~ "^<!-- gate: closed( [0-9/-]+)? -->$") {
        status = "closed"; if ($4 ~ /^[0-9]/) date = $4
      }
      else { status = "!" }
      next
    }
    # Баннер закрытия — ЧЕЛОВЕЧЕСКАЯ копия того же факта, и без сверки с меткой они разъезжаются:
    # метка open над разделом с «Closed …» убирает гейт из перечня владельца, а читатель документа
    # видит обратное. Берётся ПЕРВЫЙ баннер раздела: у §6 за ним идёт ещё и Re-closed.
    have && banner == "" && /^> \*\*(Closed|Re-closed) / { banner = $3; sub(/\*\*$/, "", banner) }
    have && status == "?" && NF > 0 { status = "-" }
    END { flush() }
  ' "$1"
}

# По одному ГЕЙТУ в строке: спека, номер, статус, дата, раздел. Раздел 15 несёт два гейта одной
# процедурой, поэтому разделов 17, а гейтов 18 — считать их одним значило бы потерять один из них.
owner_gates_flat() {
  owner_gates_sections "$1" | awk -F"$OWNER_FS" -v OFS="$OWNER_FS" '
    {
      n = split($3, g, ",")
      for (i = 1; i <= n; i++) print $2, g[i], $4, $5, $1
    }
  '
}

# Строки таблицы шапки: спека, номер, дата закрытия («—» у открытых). Дата берётся ПЕРВЫМ
# СОВПАДЕНИЕМ, а не с начала ячейки: та бывает прозой («closed on 2026-08-30 after …»), и требовать
# от неё начинаться датой значило бы запретить документу объяснять, что произошло.
#
# Образец СТРОКОЙ, а не литералом `/…/`: у §2 дата двойная (`2026-08-05/06`), а слэш внутри
# скобочного выражения литерал ОБРЫВАЕТ — awk сообщает «nonterminated character class». Экранировать
# его нельзя тоже: в скобочном выражении ERE обратный слэш по POSIX ЛИТЕРАЛЕН (gawk трактует как
# escape, mawk и BSD — нет), и `[0-9\/-]` стал бы платформозависимым — тот же класс, что `[ \t]` в
# BSD sed, давший `prerequisi-es` в гейте документации. Строка обе беды снимает разом.
# Интервалов `{4}` тут нет по третьей причине: mawk на голой Ubuntu их не понимает.
owner_gates_table() {
  awk -F' *\\| *' -v OFS="$OWNER_FS" '
    /^\| .*\]\(\.\.\/\.context\/specs\// {
      spec = $3; num = $3
      sub(/^.*\[#/, "", spec); sub(/\].*$/, "", spec)
      sub(/^.*\) */, "", num)
      d = $5
      if (match(d, "[0-9][0-9][0-9][0-9]-[0-9][0-9][0-9/-]*")) d = substr(d, RSTART, RLENGTH)
      print spec, num, d
    }
  ' "$1"
}

# Открытые гейты человеку: «#S гейт K ОТКРЫТ — что делать (§N руководства)». Печатается ДЕЙСТВИЕ из
# метки, а не заголовок раздела: правило 18 держит процедуру владельца частью задачи, и перечень,
# ужавшийся до адреса, отправляет его читать две с половиной тысячи строк.
owner_gates_open_lines() {
  owner_gates_sections "$1" | awk -F"$OWNER_FS" '
    $4 == "open" {
      n = $3; gsub(/,/, " и ", n)
      many = (n ~ / и /)
      printf "  #%s гейт%s %s %s — %s (\302\247%s руководства)\n", \
        $2, (many ? "ы" : ""), n, (many ? "ОТКРЫТЫ" : "ОТКРЫТ"), $7, $1
    }
  '
}

# Закрытые одной строкой: их поверхность перепрогона владельцу тоже нужна, а перечислять их
# по одному значило бы утопить в них открытые.
owner_gates_closed_lines() {
  owner_gates_sections "$1" | awk -F"$OWNER_FS" '
    $4 == "closed" {
      n = $3; gsub(/,/, " и ", n)
      many = (n ~ / и /)
      list = list (list == "" ? "" : ", ") "#" $2 " гейт" (many ? "ы " : " ") n
    }
    END {
      if (list != "") printf "  закрытые (%s) — перепрогон, когда коммит тронул их поверхность\n", list
    }
  '
}
