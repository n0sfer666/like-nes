#!/usr/bin/env bash
# Гейты, судящие ПРОДУКТЫ сборки: три голдена (физика в Debug, восемь голденов ядра, бандл игры) и
# фаззинг читателей секций. Своя группа у них по тому же устройству, что у правил дерева и правил
# релиза: семейство доросло до четырёх этапов, а preflight.sh держит порядок и условия этапов, а не
# их тела. Следующий гейт по продукту сборки дописывает строку СЮДА.
#
# Признак группы ОБРАТЕН признаку двух других («сборки и сети не нужно»): здесь предмет — именно
# собранное. Условие записано один раз и здесь, а не у каждого этапа: группа обязана идти ПОСЛЕ
# этапов сборки в preflight.sh, потому что отсутствие бинаря она не проверяет — отсутствие
# неотличимо от «этап сборки не звали», а это забота вызывающего.
#
# «После сборки» не значит «без единой своей сборки»: голден Debug конфигурирует и собирает СВОЙ
# каталог `build-debug` (тело — `check_debug_golden.sh`), потому что предмет у него — расхождение
# уровней оптимизации, и собранного `build-ci` для этого мало. Три остальных этапа своих сборок не
# делают и требуют готовых `build-ci`/`build-full`.
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1
# shellcheck source=scripts/preflight_stage_lib.sh
. "$ROOT/scripts/preflight_stage_lib.sh"

# Вердикт фаззера печатается ЦЕЛИКОМ, а не только на отказе: строка PASS называет число целей,
# seed'ов и случаев, и просевший набор виден глазами только в логе успешного прогона.
fuzz_readers_gate() {
    local out
    out=$(./build-full/fuzz_readers 2>&1) || { echo "$out"; return 1; }
    echo "$out"
    grep -q "\[fuzz\] PASS targets=10 " <<< "$out"
}

# По одному этапу на голден, чтобы имя упавшего стояло в логе (обоснование и сами литералы — в
# `check_goldens.sh`). Порядок: Debug требует своей сборки и стоит дороже всех, бандл сверяется
# продуктом build-ci и потому идёт после него.
stage "Голден физики совпадает в Debug (инвариант 1 спеки #15)" \
    bash scripts/check_goldens.sh debug
stage "8 голденов ядра целы (гейт 2 спеки #11, все восемь локально)" \
    bash scripts/check_goldens.sh core
stage "Бандл игры сверен с исходниками (tool-free секции)" \
    bash scripts/check_goldens.sh bundle
# Гейт 9 аудита #21. Каталог ПОЛНЫЙ, а не build-ci: сцена IDE уходит под `#if` вместе с IDE_POC, и
# на урезанной конфигурации прогон проверял бы девять форматов из десяти, не сказав об этом ни
# строкой. Отсюда же греп по ЧИСЛУ целей, а не по одному слову PASS.
stage "Читатели секций держат битый файл (гейт 9 аудита #21)" fuzz_readers_gate
stages_verdict "продукты сборки"
