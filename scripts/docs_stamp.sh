#!/usr/bin/env bash
# Проштамповать перевод суммой его en-исходника (спека #19, вертикаль 1).
#
#   bash scripts/docs_stamp.sh docs/ru/getting-started/build.md
#
# Штамп подтверждает «я перевёл ИМЕННО эту версию источника», и механически отличить перевод от
# штампа нельзя — ровно как подпись DCO нельзя отличить от строки в сообщении коммита. Поэтому
# штампуется ОДИН названный файл, а не всё дерево скопом: массовая штамповка превращала бы гейт
# свежести в кнопку «сделать зелёным», и первое же отставание переводов уехало бы к читателю.
set -euo pipefail

# ШТАМПУЕМОЕ ДЕРЕВО и КАТАЛОГ САМОГО ШТАМПОВЩИКА — разные величины, и путать их нельзя: фикстуры
# самопроверке строит ЭТОТ штамповщик, а не её копия правил (иначе «гейт отбил отставший перевод»
# проверялось бы на дереве иного устройства, чем то, которое штампует человек), а библиотеки при
# этом обязаны грузиться отсюда — в фикстурном дереве их нет вовсе.
SELF=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
ROOT=${DOCS_ROOT:-$SELF}
# shellcheck source=scripts/release_lib.sh
. "$SELF/scripts/release_lib.sh"
# shellcheck source=scripts/docs_pairs_lib.sh
. "$SELF/scripts/docs_pairs_lib.sh"

[ $# -eq 1 ] || { echo "употребление: docs_stamp.sh <путь к ru-документу от корня репозитория>" >&2; exit 2; }
RU=${1#./}
[ -f "$ROOT/$RU" ] || { echo "нет файла $RU" >&2; exit 2; }

# Источник ищется в тех же парах, которыми его ищет гейт: своя формула «ru → en» разъехалась бы с
# ним молча, и штамп ложился бы от файла, с которым гейт документ не сверяет.
EN=$(docs_pairs "$ROOT" | awk -v ru="$RU" '$2 == ru { print $1 }')
[ -n "$EN" ] || { echo "$RU не является переводом ни одного документа docs/en" >&2; exit 2; }
[ -f "$ROOT/$EN" ] || { echo "нет источника $EN" >&2; exit 2; }

SUM=$(sha256_of "$ROOT/$EN")
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
# Прежний штамп снимается ТОЛЬКО СО СТРОКИ 1 — там же, где его читает гейт. Снятие «везде, где
# встретится» вырезало бы штамп, ПРОЦИТИРОВАННЫЙ в теле документа (первый же документ, который
# объясняет этот механизм, такую строку и содержит), и делало бы это молча.
sed '1{/^<!-- en-sha256: [0-9a-f]\{64\} -->$/d;}' "$ROOT/$RU" | sed '/./,$!d' > "$TMP"
# Пустой перевод — отказ СЛОВАМИ. Под `set -e` пустой результат конвейера ронял штамповщик молча, а
# фабрика фикстур читала это как «фикстура не собралась», после чего все ожидающие отказа кейсы
# самопроверки проезжали бы, не позвав утверждения ни разу.
[ -s "$TMP" ] || { echo "$RU пуст — штамповать нечего" >&2; exit 2; }
{ printf '<!-- en-sha256: %s -->\n\n' "$SUM"; cat "$TMP"; } > "$ROOT/$RU"
echo "docs-stamp: $RU ← $EN ($(printf '%.8s' "$SUM")…)"
