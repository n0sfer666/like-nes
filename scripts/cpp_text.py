"""Разбор C++-текста: где кончается литерал, где комментарий, на какой строке находка.

Вынесено из `hash_seam_rules.py`, когда потребителей стало двое (шов хешей и шов файлового
ввода-вывода) — по тому же правилу, которое дерево записало в шапке `hash_mix.hpp` и которое
находка 5 аудита #21 сделала механическим: примитив выносится, как только его переписали второй
раз. Своя копия этих сорока строк разъехалась бы молча — гейты просто судили бы РАЗНЫЙ текст,
и увидеть это можно было бы только по находке, которую один нашёл, а другой пропустил.

Обе половины (`код`, `комментарии`) сохраняют нумерацию строк исходника: пустышка ставится той же
ВЫСОТЫ, что и вырезанный кусок.

Литерал при этом гасится НЕ ПУСТОТОЙ, а плейсхолдером `_`: пустой след делает аргумент вызова
невидимым, и `std::remove("tmp.bin")` приходит в разбор скобок как `std::remove()` — ноль
аргументов, то есть «алгоритм из <algorithm>», то есть самая естественная форма удаления файла
проезжает мимо гейта молча. Найдено ревью находки 6 аудита #21 прогоном через сам гейт. `_` выбран
потому, что числом не является (шов хешей ищет константы) и именем из списков тоже.
"""
import re


def _blank(chunk):
    """Пустышка той же ВЫСОТЫ: номера строк во второй половине не должны поехать."""
    return "\n" * chunk.count("\n")


def _placeholder(chunk):
    """След литерала в кодовой половине: один символ плюс та же ВЫСОТА.

    Пустой след равнозначен отсутствию аргумента — см. шапку модуля.
    """
    return "_" + "\n" * chunk.count("\n")


def split_code_comments(text):
    """(код, комментарии) — обе половины сохраняют нумерацию строк исходника.

    Строковые и символьные литералы гасятся в ОБЕИХ: `"http://x"` иначе открывал бы комментарий до
    конца строки, а маркер, написанный внутри литерала, подавлял бы находку. В коде от литерала
    остаётся плейсхолдер `_` — аргумент вызова обязан оставаться ВИДИМЫМ разбору скобок.
    """
    code, com, i, n = [], [], 0, len(text)
    while i < n:
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
        else:
            j = _literal_end(text, i)
            if j < 0:
                code.append(text[i])
                com.append(_blank(text[i]))
                i += 1
                continue
            code.append(_placeholder(text[i:j]))
            com.append(_blank(text[i:j]))
            i = j
            continue
        com.append(text[i:j])
        code.append(_blank(text[i:j]))
        i = j
    return "".join(code), "".join(com)


def _literal_end(text, i):
    """Конец строкового/символьного литерала, начатого в позиции i, или -1, если он там не начат."""
    if text.startswith('R"', i):
        m = re.compile(r'R"([^()\\ \t\n]{0,16})\(').match(text, i)
        if m:
            end = text.find(')%s"' % m.group(1), m.end())
            return len(text) if end < 0 else end + len(m.group(1)) + 2
    if text[i] not in "\"'":
        return -1
    if text[i] == "'" and _digit_sep(text, i):
        return -1
    quote, j = text[i], i + 1
    while j < len(text) and text[j] != quote:
        j += 2 if text[j] == "\\" else 1
    return min(j + 1, len(text))


def _digit_sep(text, i):
    """Апостроф разделителя разрядов (`1'099'511'628'211`), а не начало символьного литерала.

    Принят за литерал — и `1'099'511'628'211` гасится вместе с половиной строки, то есть ровно то
    написание прайма, которым его напишет следующая копия, проходит гейт молча. Отличается по тому,
    ЧЕМ начинается слово слева: цифрой — число, буквой — префикс символьного литерала (`u8'a'`).
    """
    j = i - 1
    while j >= 0 and (text[j].isalnum() or text[j] == "'"):
        j -= 1
    return j + 1 < i and text[j + 1].isdigit()


def line_of(text, pos):
    """Номер строки (1-based), на которой стоит позиция pos."""
    return text.count("\n", 0, pos) + 1


def marker_lines(comments, pattern, min_words=3):
    """Номера строк, накрытых маркером-отпиской: сама строка маркера и следующая за ней.

    Причина короче `min_words` слов не подавляет: односимвольная отписка — то же самое, что её
    отсутствие, только выглядит как решение.
    """
    ok = set()
    for num, line in enumerate(comments.splitlines(), 1):
        m = pattern.search(line)
        if m and len(m.group(1).split()) >= min_words:
            ok.update((num, num + 1))
    return ok
