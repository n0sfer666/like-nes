#!/usr/bin/env bash
# Самопроверка суждений замера — той же дисциплиной, что у ci_lint.py и line_budget.py: правило, у
# которого нет сломанной фикстуры, ничего не сторожит.
#
# Отдельный файл, потому что живьём это доказать нечем: чтобы сработал детектор шума, нужен ЧУЖОЙ
# процесс, занявший машину ровно в окне одной ячейки из четырёх пересборок. Воспроизводить это
# фоновой нагрузкой — гадание, поэтому фикстуры берутся из реальных прогонов владельца 2026-08-13:
# на Windows испорчена была ячейка 8/300, на Linux — ни одной.
set -uo pipefail

DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
. "$DIR/perf_sweep_lib.sh"

fails=0

ok() {
    local want=$1 got=$2 name=$3
    if [ "$got" = "$want" ]; then
        printf 'ok   %s\n' "$name"
    else
        printf 'FAIL %s: ожидалось «%s», получено «%s»\n' "$name" "$want" "$got"
        fails=$((fails + 1))
    fi
}

expect() {
    local want=$1 name=$2 got
    shift 2
    got=$(column_noise "$@" | tr '\n' ' ')
    ok "$want" "${got% }" "$name"
}

# --- контроль по сцене column -------------------------------------------------------------------

# Windows, 2026-08-13. Колонна при 300 телах стоила 0.214 и 0.511 мс — работа одна и та же.
expect "3" "испорченная ячейка названа поимённо" \
    500:0.666 500:0.670 300:0.214 300:0.511
# Linux, тот же прогон, та же матрица: 1.6% и 3.4% расхождения — находок быть не должно.
expect "" "чистый прогон молчит" \
    500:0.388 500:0.382 300:0.149 300:0.154
# Группа из одной ячейки сравнивать не с чем. Молчание тут — не «чисто», и таблица метит такие «?».
expect "" "одиночную ячейку не с чем сравнивать" \
    500:0.666 300:0.214
# Испорченными могут оказаться обе группы разом — детектор обязан назвать обе, а не первую.
expect "1 3" "две находки в разных группах" \
    500:0.666 500:1.500 300:0.214 300:0.511
# Порог ровно 10% — граница закрыта с обеих сторон, иначе он гуляет от округления. Числа крупные
# намеренно: на мелких границу сторожил бы абсолютный пол, и проверялось бы не то правило.
expect "" "ровно 10% ещё не находка" 500:10.000 500:11.000
expect "1" "10% с копейкой уже находка" 500:10.000 500:11.001
# Реальный ложноположительный 2026-08-13 (2), Linux: 19% относительных, но 31 микросекунда кадра.
expect "" "разница ниже абсолютного пола не находка" 300:0.162 300:0.193
# Пол не должен глушить настоящую находку: Windows выше — 297 микросекунд при том же порядке чисел.
expect "3" "пол не глушит находку той же мелкости" \
    500:0.666 500:0.670 300:0.214 300:0.511
# Формат печати цели изменился. Детектор обязан промолчать, а не выдать находку из мусора: за смену
# формата отвечает разбор вывода в самом обходе, и две диагностики об одном ведут в разные стороны.
expect "" "битое число не превращается в находку" 500:abc 500:0.670

# --- арифметика повторов ------------------------------------------------------------------------

ok "2.254" "$(median_ms 2.253 2.254 2.270)" "медиана трёх повторов (macOS, реальные числа)"
ok "2.254" "$(median_ms 2.270 2.253 2.254)" "медиана не зависит от порядка"
ok "2.253" "$(median_ms 2.253 2.254)" "при чётном числе берётся нижний из средних"
# Испорченный повтор обязан НЕ утащить судейское число: ровно ради этого медиана, а не среднее.
ok "2.254" "$(median_ms 2.253 2.254 9.999)" "один испорченный повтор из трёх медиану не двигает"
ok "2.894" "$(max_ms 2.411 2.406 2.894)" "худшее берётся максимумом, а не медианой"
ok "1" "$(
    median_ms 2.253 abc >/dev/null 2>&1
    printf '%d' $?
)" "битое число ломает медиану отказом, а не правдоподобным ответом"

# 0.8% на реальных повторах macOS — то самое дрожание, по которому назначен порог пометки в 5%.
ok "7" "$(spread_tenths 2.253 2.254 2.270)" "разброс чистой ячейки — 0.7%"
ok "191" "$(spread_tenths 0.162 0.193 0.162)" "разброс шумной ячейки — 19.1%"
ok "1" "$(
    spread_tenths 2.253 >/dev/null 2>&1
    printf '%d' $?
)" "один повтор — разброса нет, а не ноль"

# --- таблица и вердикты (perf_sweep_report.sh) ---------------------------------------------------

# Метка строки — последнее поле. Разбор на bash, а не awk: гейт обязан работать там же, где замер, а
# на Windows это git-bash, и наличия awk там никто не обещал (то же правило, что у pct_of_budget).
mark_of() {
    local out=$1 want_i=$2 want_b=$3
    local -a f
    while read -r -a f; do
        [ "${#f[@]}" -ge 9 ] || continue
        [ "${f[0]}" = "$want_i" ] && [ "${f[1]}" = "$want_b" ] || continue
        printf '%s' "${f[$((${#f[@]} - 1))]}"
        return 0
    done <<<"$out"
    printf 'СТРОКИ-НЕТ'
}

report() { printf '%s\n' "$1" | bash "$DIR/perf_sweep_report.sh" 2>&1; }

# Чистый прогон: разбросы в пределах порога, колонна сходится. Все метки ok, код возврата ноль.
CLEAN="16 500 7.317 11.155 0.485 38448 7
8 500 4.932 8.491 0.490 17576 9
16 300 2.520 5.857 0.162 14752 6
8 300 2.719 6.181 0.193 9920 8"
out=$(report "$CLEAN")
rc=$?
ok "ok" "$(mark_of "$out" 16 500)" "чистая ячейка помечена ok"
ok "ok" "$(mark_of "$out" 8 300)" "ложноположительного 2026-08-13 (2) больше нет"
ok "0" "$rc" "чистый прогон возвращает ноль"

# Неустойчивая ячейка: 12% разброса повторов. Метка есть, но прогон НЕ красный — решение принимается
# по отношениям внутри прогона, и они машинную тряску переживают. Флаг, валящий прогон впустую,
# учатся игнорировать, и тогда он молчит и по делу.
out=$(report "16 500 7.317 11.155 0.485 38448 120
8 500 4.932 8.491 0.490 17576 9")
rc=$?
ok "ШУМ" "$(mark_of "$out" 16 500)" "разброс выше порога метит строку"
ok "ok" "$(mark_of "$out" 8 500)" "соседняя ячейка от чужой пометки не страдает"
ok "0" "$rc" "ШУМ не валит прогон"

# Ровно на пороге 5.0% — граница закрыта, иначе она гуляет от округления.
out=$(report "16 500 7.317 11.155 0.485 38448 49
8 500 4.932 8.491 0.490 17576 9")
ok "ok" "$(mark_of "$out" 16 500)" "4.9% ещё не пометка"
out=$(report "16 500 7.317 11.155 0.485 38448 50
8 500 4.932 8.491 0.490 17576 9")
ok "ШУМ" "$(mark_of "$out" 16 500)" "5.0% уже пометка"

# Один повтор: разброса нет. «Не проверено» и «чисто» обязаны различаться на взгляд.
out=$(report "16 500 7.317 11.155 0.485 38448 -1
8 500 4.932 8.491 0.490 17576 -1")
ok "?" "$(mark_of "$out" 16 500)" "без повторов строка помечена вопросом, а не ok"

# Позитивный контроль всего замера: пересборка не доехала, все ячейки сняты с одного бинаря. Таблица
# при этом идеально ровная — красным её делает только совпадение vel при разных итерациях.
out=$(report "16 500 7.317 11.155 0.485 38448 7
8 500 7.301 11.020 0.487 38448 6")
rc=$?
ok "1" "$rc" "одинаковый vel при разных итерациях валит прогон"
case "$out" in *"пересборка не доехала"*) ok "yes" "yes" "и диагноз назван словами" ;;
    *) ok "yes" "no" "и диагноз назван словами" ;; esac

# Пустой вход — это сломанный обход, а не «находок нет»: то же основание, что у правила vacuous-gate.
out=$(printf '' | bash "$DIR/perf_sweep_report.sh" 2>&1)
ok "1" "$?" "пустой вход отчёта — отказ, а не пустая таблица"

if [ "$fails" -ne 0 ]; then
    printf '\nperf-sweep-selftest: FAIL — правил с находками %d\n' "$fails"
    exit 1
fi
printf '\nperf-sweep-selftest: PASS\n'
