#!/usr/bin/env bash
# Итоговая таблица замера и вердикты по ней. Отделено от perf_sweep.sh по границе смысла: обход
# владеет деревом, пересборками и прогоном, а здесь нет ни одного побочного действия — только
# суждение над уже снятыми числами. Ровно поэтому у таблицы и вердиктов появился позитивный
# контроль: до разделения их нельзя было проверить, не пересобрав движок четыре раза, и они
# оставались единственной частью замера, которую никто не сторожил.
#
# Вход — записи ячеек на stdin, по одной на строку, поля через пробел:
#   <итераций> <тел> <медиана,мс> <худшее,мс> <column,мс> <vel> <разброс,десятых процента>
# Разброс -1 означает «повтор был один, судить не о чем».
set -uo pipefail

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/perf_sweep_lib.sh"

# С 5% ставится пометка. Три повтора одной ячейки на macOS дали 0.8%, то есть порог втрое выше
# измеренного дрожания и заметно ниже расхождений, ради которых замер и затевается.
SPREAD_MARK_TENTHS=50

ITERS=()
BODIES=()
MEAN=()
WORST=()
COL=()
VEL=()
SPREAD=()
while read -r it bo mean worst col vel spread; do
    [ -n "${it:-}" ] || continue
    ITERS+=("$it")
    BODIES+=("$bo")
    MEAN+=("$mean")
    WORST+=("$worst")
    COL+=("$col")
    VEL+=("$vel")
    SPREAD+=("$spread")
done
n=${#ITERS[@]}
[ "$n" -gt 0 ] || {
    printf 'perf-sweep: на вход отчёта не пришло ни одной ячейки\n' >&2
    exit 1
}

# Позитивный контроль всего замера: две ячейки с разным числом итераций обязаны дать РАЗНОЕ число
# проекций решателя. Совпадение означает, что пересборка не доехала и все строки таблицы сняты с
# одного бинаря, — а таблица при этом выглядит идеально ровной.
same=0
for ((i = 0; i < n; i++)); do
    for ((j = i + 1; j < n; j++)); do
        [ "${BODIES[$i]}" = "${BODIES[$j]}" ] && [ "${ITERS[$i]}" != "${ITERS[$j]}" ] &&
            [ "${VEL[$i]}" = "${VEL[$j]}" ] && same=1
    done
done

pairs=()
for ((i = 0; i < n; i++)); do pairs+=("${BODIES[$i]}:${COL[$i]}"); done
NOISY=" $(column_noise "${pairs[@]}" | tr '\n' ' ')"

printf '\n=== Итог (бюджет кадра %d.%02d мс)\n' $((BUDGET_US / 1000)) $((BUDGET_US % 1000 / 10))
# Судейское число — МЕДИАНА повторов ячейки, и она стоит первой. Абсолютные числа этой коробки не
# воспроизводятся: тот же прогон той же матрицы 2026-08-13 разошёлся на 21-24% по всем четырём
# ячейкам сразу. Худшее печатается рядом, потому что кадр — единица бюджета, но критерием не служит:
# на трёх повторах одной ячейки медиана сошлась до 0.8%, а худшее разошлось на 20%.
printf 'итераций тел  медиана  %% бюдж  худшее   %% бюдж  разброс  vel       метка\n'
noisy=0
for ((i = 0; i < n; i++)); do
    sp="${SPREAD[$i]}"
    # «не проверено» и «чисто» обязаны различаться на взгляд: при одном повторе разброса нет, и
    # молчаливый «ok» под такой строкой читался бы как доказанная устойчивость.
    mark="ok"
    spshow="?"
    if [ "$sp" -ge 0 ]; then
        spshow=$(printf '%d.%d%%' $((sp / 10)) $((sp % 10)))
        [ "$sp" -ge "$SPREAD_MARK_TENTHS" ] && mark="ШУМ"
    else
        mark="?"
    fi
    case "$NOISY" in *" $i "*) mark="ШУМ" ;; esac
    [ "$mark" = "ШУМ" ] && noisy=1
    printf '%-8s %-4s %-8s %-7s %-8s %-7s %-8s %-9s %s\n' \
        "${ITERS[$i]}" "${BODIES[$i]}" "${MEAN[$i]}" "$(pct_of_budget "${MEAN[$i]}")" \
        "${WORST[$i]}" "$(pct_of_budget "${WORST[$i]}")" "$spshow" "${VEL[$i]}" "$mark"
done

if [ "$same" -eq 1 ]; then
    printf '\nperf-sweep: FAIL — две ячейки с разным числом итераций дали одинаковый vel:\n'
    printf 'пересборка не доехала, и таблица выше снята с одного бинаря. Числам верить нельзя.\n'
    exit 1
fi
# ШУМ помечает строку, но прогон НЕ валит. Красный код за него означал бы «этими числами пользоваться
# нельзя», а это неправда: решение принимается по отношениям между ячейками одного прогона, и они
# переживают машинную тряску — на двух прогонах, разошедшихся по абсолюту на 22%, отношения совпали
# до 1%. Флаг, который валит прогон впустую, учатся игнорировать, и тогда он молчит и по делу.
if [ "$noisy" -eq 1 ]; then
    printf '\nperf-sweep: ШУМ — помеченные строки неустойчивы: повторы ячейки разошлись выше порога\n'
    printf 'или сцена column при равной работе стоила разного. Абсолютные числа этих строк не\n'
    printf 'переносимы; отношения внутри прогона годны. Нужен абсолют — перезапусти строку одну.\n'
fi
printf '\nperf-sweep: PASS — заголовки восстановлены, цель пересобрана из исходников HEAD\n'
