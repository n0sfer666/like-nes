"""Вывод скрипта в UTF-8 независимо от локали.

Python берёт кодировку stdout у локали, и на Windows это cp1251/cp1252, а не UTF-8. Русская строка
там не «портится» — `print` падает `UnicodeEncodeError`, то есть скрипт возвращает НЕНУЛЕВОЙ код на
исправном дереве: вердикт «гейт нашёл нарушение» и вердикт «гейт не смог напечатать вывод»
становятся неразличимы. Ровно это и случилось 2026-09-06 на windows-раннере: четыре опорных `pass`
самопроверки врезок отдали код 1 при исправных фикстурах, а сам набор умер трейсбеком в `print`.

Мера жила ТРЕМЯ копиями по скриптам, и четыре новых файла её просто не взяли — тот же `list-drift`,
что стережёт `ci_lint.py`. Поэтому она здесь одна, а `check_py_utf8.py` требует её у каждого
скрипта с шебангом.

Комментарий у прежних копий вдобавок УТВЕРЖДАЛ, что на раннерах CI локаль UTF-8 и там это не
воспроизводится. Прогон 2026-09-06 это опроверг: на windows-раннере GitHub перенаправленный stdout
идёт в cp1252.
"""
import sys


def enable():
    """Переключить stdout и stderr на UTF-8. Идемпотентно и безопасно на любом потоке."""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
