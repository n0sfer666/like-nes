# shellcheck shell=bash
# Утверждение о ПЕРЕНОСИМОСТИ awk в файлах прогона гейта 5 (спека #19). Своим файлом, а не рядом с
# прочими утверждениями о прогоне (docs_start_rules_lib.sh): предмет здесь не «чем прогон
# пользуется и что подменяет», а диалект awk на машине, которой прогон и адресован. Подключить
# обязан вызывающий; ему же принадлежат start_ok/start_bad и start_code.

# Интервальный квантификатор (`{3}`, `{2,4}`) в тех файлах, которые исполняются НА ЧИСТОЙ МАШИНЕ.
# mawk — awk голой Ubuntu, то есть ровно той системы, ради которой гейт и заведён, — интервалов не
# понимает: подстановка молча не срабатывает и оставляет строку целиком. На macOS то же выражение
# работает, поэтому на хосте дефект неразличим, а живой прогон 2026-09-06 умер на нём «в документе
# нет команды клонирования».
#
# Ищется квантификатор в ЛЮБОЙ позиции, а не только после `)` или `]`: mawk не понимает `.{3}` и
# `\t{2}` ровно так же, и утверждение, ловящее половину форм, обещает больше, чем проверяет.
# Отсюда же нейтральный текст находки: файл читается целиком (границы awk-программы в шелле не
# провести), и легитимный `grep -E '[0-9]{4}'` рядом получил бы обвинение с неверным диагнозом.
# `${1}` из образца выброшен — это подстановка шелла, а не квантификатор.
#
# Подключения обходятся РЕКУРСИВНО и в обеих формах (`.` и `source`): библиотека, подключённая из
# библиотеки, исполняется на чистой машине наравне с прочими, а форма записи предметом утверждения
# не является. Позитивных контроля два, и первый — про сам обход: НАЙДЕННЫЕ библиотеки считаются
# ОТДЕЛЬНЫМ счётчиком, потому что общий (вместе с раннером) не бывает нулевым по построению — то
# есть обход, промахнувшийся мимо всех подключений, объявлял бы дерево чистым. Ровно vacuous-gate.
assert_start_awk_portable() {
  local root="$1" runner="scripts/docs_start_run.sh" code libs=0 awks=0 bad=0
  [ -f "$root/$runner" ] || { start_bad "нет $runner — судить не о чем"; return 1; }
  local queue="$runner" seen="" cur rest more
  while [ -n "$queue" ]; do
    cur=${queue%%$'\n'*}
    rest=${queue#"$cur"}
    queue=${rest#$'\n'}
    [ -n "$cur" ] || continue
    case $'\n'"$seen"$'\n' in *$'\n'"$cur"$'\n'*) continue ;; esac
    seen="$seen$cur"$'\n'
    [ "$cur" = "$runner" ] || libs=$((libs + 1))
    if [ ! -f "$root/$cur" ]; then
      start_bad "прогон грузит несуществующий $cur"
      bad=1
      continue
    fi
    code=$(start_code "$root/$cur")
    grep -q 'awk' <<<"$code" && awks=$((awks + 1))
    if grep -qE '(^|[^$])[{][0-9]+(,[0-9]*)?[}]' <<<"$code"; then
      start_bad "$cur: интервальный квантификатор {N} — mawk его не понимает, и на чистой машине выражение молчит"
      bad=1
    fi
    more=$(awk '/^[.]|^source/ { if (match($0, /scripts\/[A-Za-z0-9_.-]+\.sh/)) print substr($0, RSTART, RLENGTH) }' <<<"$code")
    [ -z "$more" ] || queue="$queue$more"$'\n'
  done
  [ "$libs" -gt 0 ] || { start_bad "прогон не грузит ни одной библиотеки — обход промахнулся, судить не о чем"; return 1; }
  [ "$awks" -gt 0 ] || { start_bad "ни один файл прогона не зовёт awk — утверждение о переносимости беспредметно"; return 1; }
  [ "$bad" = 0 ] || return 1
  start_ok "awk прогона переносим: интервалов нет ни в одном из $((libs + 1)) файлов ($awks с awk)"
}
