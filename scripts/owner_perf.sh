#!/usr/bin/env bash
# Цена кадра на ЭТОЙ машине: шаг физики (гейт 8 спеки #15) и тик персонажа на уровне целевого
# размера (гейт 7 спеки #16).
#
# Обе цели прогоняются и общим циклом `owner_check.sh`, но там от них остаётся одно слово PASS: оно
# говорит, что счётчики совпали с эталоном, и молчит про ВРЕМЯ. Время и есть то, ради чего файл
# заведён: судить его может только живое железо, а не раннер GitHub, где стенные часы гуляют кратно
# (правило 18). Заодно в отчёт попадают сами счётчики — расхождение между ОС валит гейт само, но в
# отчёте обязано быть видно, каким числом именно.
#
# Внешней командой, а не куском `owner_check.sh`, по тому же основанию, что этапы `preflight.sh`:
# числа владельцу нужны и сами по себе, без часового прогона всего дерева. Печатает он в СТДАУТ, а в
# отчёт его заводит вызывающий: своего `tee` здесь нет, и вместе с ним нет ловушки, из-за которой
# этап, напечатавший «FAIL: …», уходил бы в отчёт зелёным по коду возврата `tee`.
#
# Запуск:
#   bash scripts/owner_perf.sh
#   BUILD_DIR=build-full bash scripts/owner_perf.sh
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1

BUILD_DIR=${BUILD_DIR:-build}
rc=0

# Несобранная цель — НЕ провал: набор целей задаётся набором опций, и урезанный каталог законен.
# Но и молчанием это быть не вправе: «числа нет» и «число в норме» обязаны выглядеть по-разному,
# иначе отчёт с половиной неснятых замеров читается как чистый.
stage() { # заголовок цель пояснение...
    local title="$1" target="$2" bin note
    shift 2
    printf '\n--- %s\n' "$title"
    bin="$BUILD_DIR/$target"
    [ -x "$bin" ] || bin="$BUILD_DIR/$target.exe"
    if [ ! -x "$bin" ]; then
        printf '  %s не собран — число на этой машине не снято\n' "$target"
        return 0
    fi
    "$bin" || rc=1
    for note in "$@"; do printf '  %s\n' "$note"; done
}

stage "Цена шага физики (framework_physics_perf_test, гейт 8 спеки #15)" \
    framework_physics_perf_test \
    "бюджет 16.67 мс; гейт закрыт 2026-08-22 на 350 телах: 3.560 (21.4%) MSVC, 2.931 (17.6%) gcc" \
    "счётчики закреплены в бинаре: расхождение печатает FAIL само, вправе гулять worst/mean"

stage "Цена тика персонажа (framework_character_perf_test, гейт 7 спеки #16)" \
    framework_character_perf_test \
    "бюджет тот же 16.67 мс на кадр — тик персонажа одна его строка, рядом с шагом физики выше" \
    "карты 256x32 и 1024x256 обязаны дать ОДИН счётчик: инвариант 4 наблюдаем только сравнением" \
    "уровень порождается гейтом, а не читается из ассетов — замер не зависит от бандла" \
    "worst/mean вправе гулять; счётчики и хеш закреплены в бинаре и печатают FAIL сами"

exit $rc
