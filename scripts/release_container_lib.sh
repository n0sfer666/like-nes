# shellcheck shell=bash
# Механика контейнерного пути релиза (спека #20, вертикаль 2): найти движок, назвать образ и
# каталог кеша. Отдельно от самого прогона, потому что этих функций три потребителя — сам
# release_container.sh, гейт check_release_container.sh и его самопроверка; повтори их у каждого,
# и «гейт проверил выбор движка» означало бы «гейт проверил СВОЮ копию выбора движка».

# Дайджест базового образа читается ИЗ САМОГО Dockerfile, а не пишется здесь второй раз: пин,
# существующий в двух местах, разъезжается на первом же обновлении, и обе половины при этом
# остаются внутренне непротиворечивыми.
container_base_pin() {
  grep -m1 '^FROM ' "$1" | sed 's/^FROM //'
}

# Движок ищется по порядку docker → podman и выбирается ПЕРВЫЙ живой, а не первый установленный:
# docker на машине без запущенного демона — это команда, которая есть в PATH и не работает, и
# молчаливый выбор такой отдал бы отказ демона там, где рядом стоит рабочий podman.
container_engine() {
  local e
  for e in ${LIKE_NES_CONTAINER_ENGINE:-docker podman}; do
    command -v "$e" >/dev/null 2>&1 || continue
    "$e" info >/dev/null 2>&1 || continue
    printf '%s\n' "$e"
    return 0
  done
  return 1
}

# Отказ печатается ОДНОЙ функцией, а не в каждой ветке вызывающего: сообщение с инструкцией — это
# и есть требование спеки («внятное сообщение, а не падение»), и три его копии разъехались бы, а
# самопроверке пришлось бы утверждать про ту, что попалась.
container_engine_hint() {
  local e found=""
  for e in ${LIKE_NES_CONTAINER_ENGINE:-docker podman}; do
    command -v "$e" >/dev/null 2>&1 && found="$found $e"
  done
  if [ -n "$found" ]; then
    printf 'release: контейнерный движок есть (%s), но не отвечает — запусти его демон\n' \
      "${found# }" >&2
    printf '        Docker Desktop: открой приложение; colima: colima start; podman: podman machine start\n' >&2
  else
    printf 'release: пакет Linux собирается в контейнере, а контейнерного движка на машине нет\n' >&2
    printf '        поставь один из двух: brew install --cask docker  |  brew install podman\n' >&2
    printf '        затем запусти его демон и повтори: scripts/release.sh --only linux\n' >&2
  fi
}

# Каталог кеша сборки лежит ВНЕ репозитория и принадлежит текущему пользователю. Оба свойства
# несущие: том, созданный движком, достаётся root'у и не пишется под `--user`, а каталог внутри
# дерева оставил бы след, который гейт 10 обязан считать нарушением гигиены.
container_build_dir() {
  local base=${TMPDIR:-/tmp}
  printf '%s/like-nes-release-container/%s\n' "${base%/}" "$1"
}

# Тег образа несёт КОРОТКИЙ дайджест пина и архитектуру. Дайджест — потому что образ, собранный
# вчерашним пином, иначе оставался бы под тем же именем, и `build` с кешем отдавал бы его молча,
# то есть пакет собирался бы не той базой, которую называет Dockerfile. Архитектура — потому что
# эмулированный образ иначе занял бы имя нативного, и следующий прогон получил бы x86_64-сборку
# там, где просил родную: разошлись бы не имена, а содержимое пакета.
container_image_tag() {
  local pin digest arch="$2"
  pin=$(container_base_pin "$1")
  digest=${pin##*:}
  printf 'like-nes-release:%s-%s\n' "${digest:0:12}" "$arch"
}

# Каталог сборки, в котором CMake начал конфигурацию и не закончил, — мусор, а не «чужая
# конфигурация»: `CMakeCache.txt` он пишет РАНЬШЕ, чем доходит до наших опций, поэтому упавший
# прогон оставляет кеш без LIKE_NES_RELEASE, и следующий получает от release.sh отказ «назови свой
# через --build» на каталоге, который и так свой. Найдено живым прогоном: сборка умерла на
# FetchContent, и вторая команда встала колом с сообщением не про ту причину.
#
# Признак завершённой конфигурации — файл генератора, а не сам кеш: ninja-файла нет ровно до тех
# пор, пока CMake не дошёл до конца.
container_cache_broken() {
  local dir="$1"
  [ -f "$dir/CMakeCache.txt" ] || return 1
  [ -f "$dir/build.ninja" ] && return 1
  return 0
}
