#!/usr/bin/env bash
# Правила, читающие дерево как ТЕКСТ: линтер workflow, статические инварианты, бюджет длины файлов
# и гейт документации. Ни сборки, ни сети им не нужно, и это единственный признак, по которому они
# собраны вместе — ровно та же граница, по какой рядом стоит preflight_release_rules.sh.
#
# Своя группа у них потому, что preflight.sh держит ПОРЯДОК и условия этапов, а не их тела, и сам
# он уже упирался в жёсткий лимит длины: следующий такой гейт дописывает строку СЮДА, а не туда.
# Самопроверка каждого правила идёт ПЕРЕД ним и отдельным этапом: сломанное правило молчит
# неотличимо от чистого дерева, а в логе обязано быть названо, что именно разошлось.
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1
# shellcheck source=scripts/preflight_stage_lib.sh
. "$ROOT/scripts/preflight_stage_lib.sh"

stage "Линтер workflow — самопроверка правил" python3 scripts/ci_lint.py --selftest
stage "Линтер workflow — .github/workflows" python3 scripts/ci_lint.py

# Те же скрипты, что и шаги CI. Гейты статические, знание о нарушении полностью доступно
# локально — узнавать про него из красного раннера значило платить двадцать минут за находку
# на полсекунды.
# Направление зависимостей (инвариант 1 спеки #14) до аудита #21 судило рукописный список из
# восьми подсистем при двенадцати в дереве, и порчи у семейства не было ни одной. Набор покрывает
# ровно это правило; о трёх соседних он говорит вслух в собственной шапке.
stage "Направление зависимостей — самопроверка правил" \
    bash scripts/tree_invariants_deps_selftest.sh
stage "Статические инварианты дерева (швы, зависимости, ASCII-вывод)" \
    bash scripts/tree_invariants.sh
# Признак обхода дерева живёт в четырёх копиях (инварианты швов, ASCII-проверка, шов хешей, шов
# файлов), внешнего эталона у него нет — значит копии сверяются между собой (форма mirrors-group).
# Половин у признака две: КУДА идти (ROOTS) и ЧТО там брать (EXTS). Расхождение любой из них молчит —
# корень или расширение, добавленное в одну копию, проходит соседние гейты и остаётся вне
# четвёртого, и узнать об этом можно только по коду, который туда положат потом.
stage "Признак обхода дерева — самопроверка правил" python3 scripts/check_tree_roots.py --selftest
stage "Признак обхода: все копии совпадают корнями и расширениями" python3 scripts/check_tree_roots.py
# Оба конца шва: locale-дефолт Windows — cp1252, и русская строка там роняет print, а не портится,
# а вывод дочернего процесса тот же дефолт роняет при ЧТЕНИИ. Гейт требует py_utf8.enable() у
# скриптов с не-ASCII выводом и encoding= у текстовых вызовов subprocess: первая мера жила тремя
# копиями и четыре новых файла её не взяли, вторая покраснела прогоном 3381a95 уже после неё.
stage "Кодировка на швах процесса — самопроверка правил" python3 scripts/check_py_utf8.py --selftest
stage "Свой вывод переключён, чужой читается явно" python3 scripts/check_py_utf8.py
stage "Бюджет длины файлов — самопроверка правил" \
    python3 scripts/line_budget.py --selftest
stage "Бюджет длины файлов — дерево" python3 scripts/line_budget.py
# Документация (спека #19) ломается правкой ТЕКСТА, а не сборкой, и потому попадает сюда же.
# Самопроверка зовёт второй набор внешней командой: пара языков и содержимое документа — разные
# предметы, и в логе обязано стоять имя упавшего.
stage "Документация — самопроверка правил (пары языков и содержимое)" \
    bash scripts/check_docs_selftest.sh
stage "Документация: зеркальность, свежесть переводов, ссылки, лицензия (#19)" \
    bash scripts/check_docs.sh
# Выбор bash — тот же шов процесса, что и кодировка выше, и ломается он на той же ОС: на
# windows-раннере первым `bash` в PATH стоит мост в WSL, а не шелл. Самопроверка идёт перед
# набором врезок, который этим выбором и пользуется.
stage "Выбор bash — самопроверка правил" python3 scripts/posix_bash_selftest.py
# Врезки (гейт 3 спеки #19) читают тот же текст: код в документе обязан совпадать с помеченным
# куском компилируемого примера, а отсутствующий маркер — быть ошибкой, а не пустой врезкой.
# Сборки гейту не нужно — он сверяет текст с текстом, поэтому стоит здесь, а не рядом с примерами.
stage "Врезки в документации — самопроверка правил" \
    python3 scripts/check_docs_snippets_selftest.py
stage "Врезки совпадают с помеченными кусками примеров (#19)" \
    bash scripts/check_docs_snippets.sh
# Гейт 5 той же спеки: чистая машина проходит getting-started ДОСЛОВНО. Сюда попадает его
# статическая половина — разметка блоков, совпадение команд двух языков, адрес клона, пин голой
# базы и живая заглушка клона: ни демона, ни сети им не нужно. Сам прогон в контейнере
# (`--live`) стоит вне preflight: он поднимает демон и собирает движок с нуля.
stage "Проход getting-started — самопроверка правил" \
    bash scripts/check_docs_start_selftest.sh
stage "Разметка и подмены прогона на чистой машине (#19)" \
    bash scripts/check_docs_start.sh
# Список ручных гейтов (правило 15): статус каждого живёт МЕТКОЙ под заголовком раздела, а таблица
# шапки, вводный абзац и перечень в owner_check.sh выводятся из него. Три рукописных копии одного
# факта уже разъехались втроём — перечень звал закрытый гейт открытым четыре дня и молчал о шести.
stage "Список ручных гейтов — самопроверка правил" \
    bash scripts/check_owner_gates_selftest.sh
stage "Ручные гейты выведены из docs/owner-verification.md" \
    bash scripts/check_owner_gates.sh
# Шов хешей (находка 5 аудита #21): константы FNV-1a живут в двух примитивах, а не рукописными
# копиями по дереву. Копии сведены, но пятнадцатая пишется по памяти за десять секунд и проходит
# все прочие гейты — значит мера обязана быть механической, а не дисциплиной.
stage "Шов хешей — самопроверка правил" python3 scripts/check_hash_seam.py --selftest
stage "Константы FNV живут только в примитивах" python3 scripts/check_hash_seam.py
# Шов файлового ввода-вывода (находка 6 того же аудита): конвенция называла его прямо, а не
# проверял его никто, и обходили её девять раз. Грепом это не делается — файловая форма `remove`
# отличается от алгоритма `<algorithm>` ЧИСЛОМ аргументов, то есть требует разбора скобок.
stage "Шов файлового ввода-вывода — самопроверка правил" python3 scripts/check_fs_seam.py --selftest
stage "Файловый ввод-вывод идёт через platform::" python3 scripts/check_fs_seam.py
# Цена сетевого кадра (гейт 8 спеки #22): сам гейт требует прогона пары пиров и живёт у владельца,
# а его вердикт — чистая функция от строк замера, и до аудита #21 он не сравнивал сумму с бюджетом
# вовсе. Фикстурам ни сборки, ни сети не нужно, значит место утверждения здесь.
stage "Вердикт о цене сетевого кадра — самопроверка правил" \
    bash scripts/owner_net_budget_selftest.sh

stages_verdict "правила дерева"
