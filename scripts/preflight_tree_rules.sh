#!/usr/bin/env bash
# Правила, читающие дерево как ТЕКСТ: линтер workflow, статические инварианты, бюджет длины файлов
# и гейт документации. Ни сборки, ни сети им не нужно, и это единственный признак, по которому они
# собраны вместе — ровно та же граница, по какой рядом стоит preflight_release_rules.sh.
#
# Своя группа у них потому, что preflight.sh держит ПОРЯДОК и условия этапов, а не их тела, и сам
# он уже упирался в жёсткий лимит длины: следующий такой гейт дописывает строку СЮДА, а не туда.
# Самопроверка каждого правила идёт ПЕРЕД ним и отдельным этапом: сломанное правило молчит
# неотличимо от чистого дерева, а в логе обязано быть названо, что именно разошлось.
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1
# shellcheck source=scripts/preflight_stage_lib.sh
. "$ROOT/scripts/preflight_stage_lib.sh"

stage "Линтер workflow — самопроверка правил" python3 scripts/ci_lint.py --selftest
stage "Линтер workflow — .github/workflows" python3 scripts/ci_lint.py

# Те же скрипты, что и шаги CI. Гейты статические, знание о нарушении полностью доступно
# локально — узнавать про него из красного раннера значило платить двадцать минут за находку
# на полсекунды.
stage "Статические инварианты дерева (швы, зависимости, ASCII-вывод)" \
    bash scripts/tree_invariants.sh
stage "Бюджет длины файлов — самопроверка правил" \
    python3 scripts/line_budget.py --selftest
stage "Бюджет длины файлов — дерево" python3 scripts/line_budget.py
# Документация (спека #19) ломается правкой ТЕКСТА, а не сборкой, и потому попадает сюда же.
# Самопроверка зовёт второй набор внешней командой: пара языков и содержимое документа — разные
# предметы, и в логе обязано стоять имя упавшего.
stage "Документация — самопроверка правил (пары языков и содержимое)" \
    bash scripts/check_docs_selftest.sh
stage "Документация: зеркальность, свежесть переводов, ссылки, лицензия (#19)" \
    bash scripts/check_docs.sh
stages_verdict "правила дерева"
