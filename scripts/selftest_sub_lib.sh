# Хелпер САМОПРОВЕРОК (спека #20): подмена, которая ничего не подменила, читается как «утверждение её
# отбило» — опечатка в имени заводит НОВУЮ функцию, оригинал остаётся в силе, и сценарий полгейта
# проверяет собственный промах. Общий на все impl-наборы: копия правила у каждого — ровно тот
# случай, который оно и ловит. Свой файл, а не строка в release_check_hygiene.sh: к гигиене прогона
# релиза он отношения не имеет, и `assert_*` он не является.
subbed() {
  [ "$(declare -f "$1")" != "$2" ] || { bad "подмена $1 ничего не подменила"; return 1; }
}
