# shellcheck shell=bash
# Суждение о цене сетевого кадра: чистая функция от строк замера, без сборки и без пиров.
#
# Вынесена сюда находкой аудита #21 (проход B, находка 3). Комментарий гейта заявлял «Судится СУММА
# худших», а блок печатал проценты и возвращал ноль: `rc` формировался кодами процессов и позитивным
# контролем грепа, а `FRAME_MS` в условие не входил нигде. Сетевой кадр мог вырасти вдвое, гейт
# печатал «200.4% бюджета» и уходил в отчёт владельца зелёным — гейт 8 спеки #22 был закрыт
# формально. Тот же класс, что правило `vacuous-gate` в `ci_lint.py`.
#
# Отдельным файлом по тому же основанию, что `ci_watch_lib.sh`: вердикт есть функция от текста, и
# проверяется он фикстурами, а не часовым прогоном пары пиров. Без этого у утверждения нет ни одной
# фикстуры, где оно падает, то есть оно неотличимо от отсутствующего.

# Читает строки замера со stdin, печатает сумму по каждой роли и её долю бюджета.
# Возвращает 1 при превышении бюджета хоть одной ролью, 2 — когда разбирать нечего.
net_budget_verdict() {
    local frame="$1" out rc=0
    # Вывод забирается в ПЕРЕМЕННУЮ, а не течёт в `sort` пайпом: код возврата пайпа есть код
    # ПОСЛЕДНЕЙ команды, и вердикт awk терялся бы в сортировке ровно так же, как терялся до фикса.
    out=$(awk -v frame="$frame" '
        BEGIN { over = 0; seen = 0 }
        match($0, /worst=[0-9.]+/) {
            w = substr($0, RSTART + 6, RLENGTH - 6) + 0
            role = $2; sub(":", "", role)
            worst[role] += w
            seen++
        }
        END {
            # Пустой разбор — ОТКАЗ, а не «уложились»: грепу, не нашедшему ничего, нечего сравнивать
            # с бюджетом, и молчание арифметики читалось бы как пройденный гейт.
            if (seen == 0) { print "  FAIL: ни одной строки «worst=» — сравнивать с бюджетом нечего"; exit 2 }
            for (r in worst) {
                printf "  худший кадр пира %s: %.3f мс из %.2f (%.1f%% бюджета)\n", \
                    r, worst[r], frame, 100 * worst[r] / frame
                # Сумма, а не половины порознь: шаг симуляции и обслуживание сокета живут в ОДНОМ
                # кадре, и каждый влезает в бюджет даже тогда, когда вместе они его пробивают.
                if (worst[r] > frame) {
                    printf "  FAIL: кадр пира %s не влезает в бюджет %.2f мс\n", r, frame
                    over = 1
                }
            }
            exit over
        }') || rc=$?
    [ -z "$out" ] || printf '%s\n' "$out" | LC_ALL=C sort
    return "$rc"
}
