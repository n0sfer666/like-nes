#!/usr/bin/env bash
# Разбор чисел замера и контроль посторонней нагрузки. Отделено от perf_sweep.sh не по длине, а по
# границе смысла: обход владеет матрицей пересборок и деревом, а здесь нет ни одного побочного
# действия — только арифметика над строками вывода цели. Именно поэтому это можно проверить
# фикстурами (`perf_sweep_selftest.sh`), не собирая ничего.
#
# Файл подключается через `.`, самостоятельно не запускается.

# Бюджет кадра в МИКРОсекундах: вся арифметика доли ниже целочисленная, и держать рядом вторую
# константу «то же число, но с точкой» значило бы завести две правды об одном числе.
BUDGET_US=16670

# "9.594" -> 9594 микросекунд. `10#` обязателен: "0.966" даёт "0966", а это для шелла ВОСЬМЕРИЧНОЕ
# число — на девятке он ругается, а на "0.027" молча вернул бы 23 микросекунды вместо 27. Цель
# печатает время с тремя знаками (`%.3f`), другой формат означает, что печать изменилась, и тогда
# честнее вернуть отказ, чем правдоподобное число из мусора.
ms_to_us() {
    case "$1" in
        *.[0-9][0-9][0-9]) printf '%d' $((10#${1/./})) ;;
        *) return 1 ;;
    esac
}

# Доля бюджета — на целочисленной арифметике шелла, а не через `awk`. Причина ровно та же, по
# которой `ci_lint.py` держит правило `portability`: замер обязан идти на ТОЙ машине, где цифра
# нужна, а на Windows его шелл — git-bash, и наличия `awk` там никто не обещал.
pct_of_budget() {
    local us tenths
    us=$(ms_to_us "$1") || {
        printf '?'
        return 0
    }
    tenths=$(((us * 1000 + BUDGET_US / 2) / BUDGET_US))
    printf '%d.%d' $((tenths / 10)) $((tenths % 10))
}

# Детектор посторонней нагрузки. Сцена `column` не делает ни одной итерации решателя (`vel=0`) и при
# равном числе тел выполняет РОВНО ту же работу, поэтому её среднее в таких ячейках обязано совпасть.
# На прогоне владельца 2026-08-13 совпадение было 0.6% (Windows) и 1.6-3.4% (Linux), а испорченная
# ячейка ушла в 2.4 раза — вместе с ней вспухли и две другие сцены, то есть цифры ячейки описывали
# соседний процесс, а не шаг физики.
#
# Сравнивается СРЕДНЕЕ, не худшее: худшее на той же одинаковой работе разошлось на 37% (Linux, 0.667
# против 0.486), и контроль по нему обвинял бы чистые ячейки. Виновата всегда МЕДЛЕННАЯ ячейка —
# посторонняя нагрузка время добавляет, а не отнимает, поэтому эталоном группы берётся минимум.
#
# Аргументы: по одному «тела:среднее-column» на ячейку, в порядке ячеек. Печатает индексы негодных.
column_noise() {
    local cells n i j min cur other bi bj
    cells=("$@")
    n=$#
    for ((i = 0; i < n; i++)); do
        bi=${cells[$i]%%:*}
        cur=$(ms_to_us "${cells[$i]##*:}") || continue
        min=$cur
        for ((j = 0; j < n; j++)); do
            bj=${cells[$j]%%:*}
            [ "$bj" = "$bi" ] || continue
            other=$(ms_to_us "${cells[$j]##*:}") || continue
            [ "$other" -lt "$min" ] && min=$other
        done
        [ $((cur * 100)) -gt $((min * 110)) ] && printf '%d\n' "$i"
    done
    return 0
}
