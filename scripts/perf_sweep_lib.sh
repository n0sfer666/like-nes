#!/usr/bin/env bash
# Разбор чисел замера и контроль посторонней нагрузки. Отделено от perf_sweep.sh не по длине, а по
# границе смысла: обход владеет матрицей пересборок и деревом, а здесь нет ни одного побочного
# действия — только арифметика над строками вывода цели. Именно поэтому это можно проверить
# фикстурами (`perf_sweep_selftest.sh`), не собирая ничего.
#
# Файл подключается через `.`, самостоятельно не запускается.

# Бюджет кадра в МИКРОсекундах: вся арифметика доли ниже целочисленная, и держать рядом вторую
# константу «то же число, но с точкой» значило бы завести две правды об одном числе.
BUDGET_US=16670

# "9.594" -> 9594 микросекунд. `10#` обязателен: "0.966" даёт "0966", а это для шелла ВОСЬМЕРИЧНОЕ
# число — на девятке он ругается, а на "0.027" молча вернул бы 23 микросекунды вместо 27. Цель
# печатает время с тремя знаками (`%.3f`), другой формат означает, что печать изменилась, и тогда
# честнее вернуть отказ, чем правдоподобное число из мусора.
ms_to_us() {
    case "$1" in
        *.[0-9][0-9][0-9]) printf '%d' $((10#${1/./})) ;;
        *) return 1 ;;
    esac
}

# Доля бюджета — на целочисленной арифметике шелла, а не через `awk`. Причина ровно та же, по
# которой `ci_lint.py` держит правило `portability`: замер обязан идти на ТОЙ машине, где цифра
# нужна, а на Windows его шелл — git-bash, и наличия `awk` там никто не обещал.
pct_of_budget() {
    local us tenths
    us=$(ms_to_us "$1") || {
        printf '?'
        return 0
    }
    tenths=$(((us * 1000 + BUDGET_US / 2) / BUDGET_US))
    printf '%d.%d' $((tenths / 10)) $((tenths % 10))
}

# Детектор посторонней нагрузки. Сцена `column` не делает ни одной итерации решателя (`vel=0`) и при
# равном числе тел выполняет РОВНО ту же работу, поэтому её среднее в таких ячейках обязано совпасть.
# На прогоне владельца 2026-08-13 совпадение было 0.6% (Windows) и 1.6-3.4% (Linux), а испорченная
# ячейка ушла в 2.4 раза — вместе с ней вспухли и две другие сцены, то есть цифры ячейки описывали
# соседний процесс, а не шаг физики.
#
# Сравнивается СРЕДНЕЕ, не худшее: худшее на той же одинаковой работе разошлось на 37% (Linux, 0.667
# против 0.486), и контроль по нему обвинял бы чистые ячейки. Виновата всегда МЕДЛЕННАЯ ячейка —
# посторонняя нагрузка время добавляет, а не отнимает, поэтому эталоном группы берётся минимум.
#
# Порог ОТНОСИТЕЛЬНЫЙ, и без абсолютного пола он тем чувствительнее, чем меньше измеряемое число, —
# то есть срабатывает громче всего там, где значит меньше всего. Прогон 2026-08-13 (2) это и показал:
# на 300 телах `column` дал 0.162 против 0.193, флаг покраснел на 31 микросекунде кадра, это 0.19%
# бюджета. Пол взят между наблюдавшимся дрожанием (повтор той же ячейки — 18 мкс) и настоящей
# находкой (Windows, 0.214 против 0.511 — 297 мкс), и обе эти цифры измерены, а не назначены.
NOISE_FLOOR_US=100

# Аргументы: по одному «тела:среднее-column» на ячейку, в порядке ячеек. Печатает индексы негодных.
column_noise() {
    local cells n i j min cur other bi bj
    cells=("$@")
    n=$#
    for ((i = 0; i < n; i++)); do
        bi=${cells[$i]%%:*}
        cur=$(ms_to_us "${cells[$i]##*:}") || continue
        min=$cur
        for ((j = 0; j < n; j++)); do
            bj=${cells[$j]%%:*}
            [ "$bj" = "$bi" ] || continue
            other=$(ms_to_us "${cells[$j]##*:}") || continue
            [ "$other" -lt "$min" ] && min=$other
        done
        [ $((cur * 100)) -gt $((min * 110)) ] && [ $((cur - min)) -gt "$NOISE_FLOOR_US" ] &&
            printf '%d\n' "$i"
    done
    return 0
}

# Медиана, а не среднее из повторов: посторонняя нагрузка время только ДОБАВЛЯЕТ, поэтому испорченный
# повтор тянет среднее вверх, а медиану — нет, пока испорчен один из трёх. При чётном числе повторов
# берётся нижний из двух средних: выбор между ними произволен, а вверх округляет в сторону помехи.
# Аргументы — миллисекунды строками; печатает миллисекунды строкой в том же формате.
median_ms() {
    local vals=() i j tmp n
    for i in "$@"; do
        tmp=$(ms_to_us "$i") || return 1
        vals+=("$tmp")
    done
    n=${#vals[@]}
    [ "$n" -gt 0 ] || return 1
    # Вставками, с индексом j строго внутри границ: `vals[j-1]` в условии цикла bash 3.2 вычисляет
    # и на j=0, а отрицательный индекс там — не «с конца», а ошибка разбора.
    for ((i = 1; i < n; i++)); do
        tmp=${vals[$i]}
        j=$i
        while [ "$j" -gt 0 ] && [ "${vals[$((j - 1))]}" -gt "$tmp" ]; do
            vals[$j]=${vals[$((j - 1))]}
            j=$((j - 1))
        done
        vals[$j]=$tmp
    done
    tmp=${vals[$(((n - 1) / 2))]}
    printf '%d.%03d' $((tmp / 1000)) $((tmp % 1000))
}

# Разброс повторов ОДНОЙ ячейки: (макс - мин) к медиане, в десятых долях процента. Это прямая мера
# того, что косвенно выводил `column_noise`, — насколько числу этой ячейки вообще можно верить. Три
# повтора одной ячейки на macOS дали 0.8%, поэтому пометка ставится с 5%: выше измеренного дрожания
# втрое и заметно ниже расхождений, ради которых замер и затевался.
spread_tenths() {
    local vals=() i tmp lo hi mid
    for i in "$@"; do
        tmp=$(ms_to_us "$i") || return 1
        vals+=("$tmp")
    done
    [ ${#vals[@]} -gt 1 ] || return 1
    lo=${vals[0]}
    hi=${vals[0]}
    for i in "${vals[@]}"; do
        [ "$i" -lt "$lo" ] && lo=$i
        [ "$i" -gt "$hi" ] && hi=$i
    done
    mid=$(ms_to_us "$(median_ms "$@")") || return 1
    [ "$mid" -gt 0 ] || return 1
    printf '%d' $(((hi - lo) * 1000 / mid))
}

# Максимум из повторов. Худшее — само по себе максимум по кадрам, и брать от него медиану значило бы
# усреднять то, что заведено как «самый дорогой кадр из всех».
max_ms() {
    local i tmp hi=-1
    for i in "$@"; do
        tmp=$(ms_to_us "$i") || return 1
        [ "$tmp" -gt "$hi" ] && hi=$tmp
    done
    [ "$hi" -ge 0 ] || return 1
    printf '%d.%03d' $((hi / 1000)) $((hi % 1000))
}
