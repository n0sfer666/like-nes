#!/usr/bin/env bash
# Правила релизного пакета, которым НЕ нужна сборка (спека #20): четыре самопроверки и два гейта,
# читающих файлы — контейнерный путь и путь через CI. Своя группа у них потому, что семейство за
# четыре вертикали выросло с трёх скриптов до пяти, а preflight.sh держит порядок и условия этапов,
# а не их тела: следующая вертикаль дописывает строку СЮДА.
#
# Гейты, требующие собранного дерева (сам пакет и образ macOS), остались в preflight.sh: они обязаны
# идти ПОСЛЕ сборок, и переносить их сюда значило бы прятать это условие.
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1
# shellcheck source=scripts/preflight_stage_lib.sh
. "$ROOT/scripts/preflight_stage_lib.sh"

stage "Гейт релизного пакета — самопроверка правил" bash scripts/check_release_selftest.sh
stage "Гейт контейнерного релиза — самопроверка правил" \
    bash scripts/check_release_container_selftest.sh
# Правила контейнерного пути читают ФАЙЛЫ (пин базы, монтирование, коды отказа) и демона не требуют.
# Живая сборка осталась за `--live`: она поднимает docker и качает базу, а preflight — перед push.
stage "Правила контейнерного релиза (#20, вертикаль 2)" bash scripts/check_release_container.sh
stage "Гейт релиза через CI — самопроверка правил" bash scripts/check_release_ci_selftest.sh
# Правила пути через CI читают workflow и ветку диспатча, сети не требуют. Живой прогон (dispatch,
# ожидание, скачивание артефакта) стоит до часа раннерского времени и остался за `--live`.
stage "Правила релиза через CI (#20, вертикаль 3)" bash scripts/check_release_ci.sh
# Самопроверка образа .dmg сборки не требует (том строится из фикстурного стейджа) и потому стоит
# здесь, среди правил, а не рядом с гейтом ниже. Она сама зовёт два соседних набора: подмены
# реализаций и живой цикл hdiutil.
stage "Гейт образа macOS — самопроверка правил (#20, вертикаль 4)" \
    bash scripts/check_release_dmg_selftest.sh
# AppImage — вторая половина той же вертикали, и его самопроверке сборка тоже не нужна: AppDir
# раскладывается из фикстурного стейджа настоящим раскладчиком. Она зовёт три соседних набора —
# подмены реализаций, вызов appimagetool (а тот, в свой черёд, набор про то, что уезжает в СУММУ
# образа) и связь внутри ELF; последний идёт только на Linux и говорит об этом вслух.
stage "Гейт AppImage — самопроверка правил (#20, вертикаль 4)" \
    bash scripts/check_release_appimage_selftest.sh
stages_verdict "правила релиза"
