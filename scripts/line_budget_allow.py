"""Allowlist бюджета длины: строка на файл, осознанно переваливший мягкий лимит.

Причина пишется РЯДОМ С ЧИСЛОМ, а не в голове автора и не в истории обсуждений: разрешение,
которое нельзя прочитать, через месяц неотличимо от недосмотра — ровно так `preflight.sh` дорос до
297 строк при жёстком лимите 250. Та же участь настигла и саму таблицу: она перевалила ЖЁСТКИЙ
лимит, который причиной не выкупается, и разрезана по предмету на две половины — инструменты
(гейты, обёртки, файлы сборки) и авторский код движка.

Пороги и закрытый список обоснований живут в `line_budget_rules.py`: не подошло ни одно — файл идёт
в разбиение, а не в эти таблицы.
"""

from line_budget_allow_code import ALLOW_CODE
from line_budget_allow_tools import ALLOW_TOOLS

# Путь, попавший в ОБЕ половины, слиянием был бы подменён молча — и потолок читался бы не тот,
# который автор писал. Пересечение здесь есть находка, а не разрешение (тот же класс, что висящая
# запись вендоренного файла).
#
# Слияние — ФУНКЦИЯ, а не код на импорте: отказ, который исполняется ровно один раз при загрузке
# модуля, невозможно позвать с фикстурой, а значит неизвестно, умеет ли он падать.
def merge_allow(tools, code):
    both = sorted(set(tools) & set(code))
    if both:
        raise SystemExit(
            "line-budget: БРАК одна и та же запись в обеих половинах allowlist: " + ", ".join(both))
    return {**tools, **code}


ALLOW = merge_allow(ALLOW_TOOLS, ALLOW_CODE)
