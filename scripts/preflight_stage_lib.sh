# shellcheck shell=bash
# Этап и его вердикт — общее для preflight.sh и его групп (сейчас preflight_release_rules.sh).
# Вынесено в тот день, когда групп стало две: копия помощника разъезжается с оригиналом молча, а
# главное свойство здесь ровно одно и оно поведенческое — этапы НЕ останавливают друг друга, чтобы
# один прогон выдавал все находки разом. Копия, потерявшая это свойство, выглядела бы как прогон,
# у которого просто нет остальных находок.

FAILED=()

stage() {
    local title=$1; shift
    printf '\n\033[1m=== %s\033[0m\n' "$title"
    if "$@"; then
        printf '\033[32m--- OK: %s\033[0m\n' "$title"
    else
        printf '\033[31m--- ПРОВАЛ: %s\033[0m\n' "$title"
        FAILED+=("$title")
    fi
}

skip() { printf '\n\033[1m=== %s\033[0m\n\033[33m--- пропущено: %s\033[0m\n' "$1" "$2"; }

# Вердикт группы: имена упавших этапов, а не одно число. Группа, сказавшая «провал» без имён,
# заставляет перезапускать её целиком, чтобы узнать, что именно упало.
stages_verdict() {
    local name=$1
    printf '\n'
    if [ ${#FAILED[@]} -eq 0 ]; then return 0; fi
    printf '%s: FAIL — %d этап(ов):\n' "$name" "${#FAILED[@]}"
    printf '  - %s\n' "${FAILED[@]}"
    return 1
}
