# shellcheck shell=bash
# Утверждения о контейнерном пути релиза (спека #20, вертикаль 2) — отдельно от того, что их
# запускает: один и тот же код проверяет живое дерево (check_release_container.sh) и сломанные копии
# (check_release_container_selftest.sh). Утверждение, живущее только внутри своего прогона,
# невозможно уронить нарочно, а значит — неизвестно, умеет ли оно падать. Предмет здесь — ПРАВИЛА,
# видные без запущенного демона: пин базы, отсутствие второго упаковщика, коды отказов. Живая
# сборка — второй этап того же гейта, и она требует движка.

# Пин базы обязан быть ДАЙДЖЕСТОМ. Тег `ubuntu:24.04` переставляют на новый слепок, поэтому
# «образ тот же» через месяц значит другой компилятор и другую сумму пакета — а гейт
# воспроизводимости обвинил бы в этом наш код.
assert_base_pinned() {
  local dockerfile="$1" pin
  pin=$(container_base_pin "$dockerfile")
  [ -n "$pin" ] || { bad "в $dockerfile нет строки FROM"; return 1; }
  if ! printf '%s' "$pin" | grep -Eq '@sha256:[0-9a-f]{64}$'; then
    bad "база не пиннута дайджестом: '$pin'"; return 1
  fi
  ok "база пиннута дайджестом (${pin##*@})"
}

# Контейнер обязан звать ТОТ ЖЕ release.sh, а не паковать сам: второй упаковщик разошёлся бы с
# первым нормализацией архива или составом, и узналось бы это по расхождению сумм у скачавшего.
# Позитивный контроль внутри утверждения: сначала доказываем, что делегирование в файле видно, и
# только потом ищем самодеятельность — иначе опечатка в пути делает гейт вечно зелёным.
#
# Упаковщиков ищется ЧЕТЫРЕ: с шагом B контейнер отдаёт ещё и `.AppImage`, и «второй упаковщик» для
# него зовут appimagetool или mksquashfs — ищи мы только tar с gzip, половина продукта линукс-хоста
# жила бы без утверждения вовсе. После имени требуется НАЧАЛО АРГУМЕНТА (флаг, кавычка, переменная):
# имя стоит и в объяснении рядом с вызовом release.sh, а в прозе за ним идёт слово, а не `-"$`.
container_packer_hits() {
  grep -nE '(^|[^_[:alnum:]])(tar|gzip|appimagetool|mksquashfs)[[:space:]]+[-"'"'"'$]' "$1"
}

assert_no_second_packer() {
  local script="$1" hits
  if ! grep -q 'release\.sh' "$script"; then
    bad "$script не зовёт release.sh — контейнер стал вторым упаковщиком"; return 1
  fi
  hits=$(container_packer_hits "$script")
  if [ -n "$hits" ]; then
    bad "$script пакует сам:"
    printf '%s\n' "$hits" | sed 's/^/       /' >&2
    return 1
  fi
  ok "контейнер делегирует упаковку release.sh, своей не заводит (tar, gzip, appimagetool, mksquashfs)"
}

# Дерево монтируется только для чтения: гейт 10 требует чистого `git status` после релиза, а
# сборка с правом писать в /src оставляет каталог и файлы с чужим владельцем.
assert_ro_mount() {
  local script="$1"
  if ! grep -q '\-v "\$ROOT:/src' "$script"; then
    bad "$script не монтирует дерево в /src — проверять нечего"; return 1
  fi
  if ! grep -q '\-v "\$ROOT:/src:ro"' "$script"; then
    bad "дерево смонтировано в контейнер БЕЗ :ro"; return 1
  fi
  ok "дерево монтируется только для чтения"
}

# Тег образа обязан различать архитектуры: иначе эмулированная сборка занимает имя нативной, и
# следующий прогон молча получает чужой пакет — расходятся не имена, а содержимое.
assert_tag_per_arch() {
  local dockerfile="$1" a b
  a=$(container_image_tag "$dockerfile" aarch64)
  b=$(container_image_tag "$dockerfile" x86_64)
  if [ "$a" = "$b" ]; then bad "тег образа один на две архитектуры: '$a'"; return 1; fi
  ok "тег образа различает архитектуры ($a / $b)"
}

# Выбор движка обязан проверять ЖИВОСТЬ, а не наличие в PATH: docker без запущенного демона — это
# команда, которая есть и не работает, и выбор по наличию отдал бы её отказ там, где рядом стоит
# рабочий podman.
assert_engine_liveness() {
  local tmp got
  tmp=$(mktemp -d)
  printf '#!/bin/sh\nexit 1\n' > "$tmp/deadengine"
  chmod +x "$tmp/deadengine"
  got=0
  PATH="$tmp:$PATH" LIKE_NES_CONTAINER_ENGINE=deadengine container_engine >/dev/null 2>&1 || got=$?
  rm -rf "$tmp"
  if [ "$got" = 0 ]; then
    bad "движок выбран по наличию в PATH, хотя его демон не отвечает"; return 1
  fi
  ok "движок без живого демона не выбирается"
}

# Отказ проверяется ПРОГОНОМ, а не чтением исходника: предмет спеки — «внятное сообщение с
# инструкцией, а не падение», и сообщение узнаётся только у того, кто его напечатал. Код 4 отделён
# от 2 и 3 потому, что означает единственное: доустанови движок и повтори. Зовётся
# release_container.sh НАПРЯМУЮ: на линукс-хосте `release.sh --only linux` — своя платформа, то есть
# полная сборка вместо отказа, и утверждение проверяло бы разное на разных ОС (делегирование —
# отдельным утверждением ниже).
assert_refusal_without_engine() {
  local script="$1" out rc=0
  out=$(LIKE_NES_CONTAINER_ENGINE=likenes-no-such-engine \
    bash "$script" --version v0.0.0-check 2>&1) || rc=$?
  if [ "$rc" != 4 ]; then
    bad "без движка ждали код 4, получили $rc"
    printf '%s\n' "$out" | sed 's/^/       /' >&2
    return 1
  fi
  if ! printf '%s' "$out" | grep -q 'brew install'; then
    bad "отказ без движка не называет, что поставить"; return 1
  fi
  ok "без движка — код 4 и инструкция, а не падение"
}

# Кеш сборки живёт ВНЕ дерева: каталог внутри репозитория оставил бы след, который гейт 10 обязан
# считать нарушением гигиены, а `.gitignore` на него — молчаливым исключением из проверки.
assert_cache_outside_tree() {
  local root="$1" dir
  dir=$(container_build_dir aarch64)
  case "$dir" in
    "$root"/*) bad "кеш контейнерной сборки лежит внутри дерева: $dir"; return 1 ;;
  esac
  ok "кеш контейнерной сборки вне дерева ($dir)"
}

# Кеш от упавшего прогона распознаётся по ФАЙЛУ ГЕНЕРАТОРА, а не по наличию `CMakeCache.txt`: тот
# пишется раньше наших опций, и «кеш есть» ничего не говорит о том, дошла ли конфигурация до конца.
# Фикстур две: правило, считающее сломанным ЛЮБОЙ каталог, сносило бы готовую сборку каждый прогон.
assert_broken_cache_detected() {
  local tmp rc=0
  tmp=$(mktemp -d)
  mkdir -p "$tmp/half" "$tmp/whole"
  : > "$tmp/half/CMakeCache.txt"
  : > "$tmp/whole/CMakeCache.txt"
  : > "$tmp/whole/build.ninja"
  container_cache_broken "$tmp/half" || rc=1
  if [ "$rc" != 0 ]; then
    bad "кеш без build.ninja не распознан как недоконфигурированный"; rm -rf "$tmp"; return 1
  fi
  if container_cache_broken "$tmp/whole"; then
    bad "готовый каталог сборки принят за мусор — снос стирал бы работу каждый прогон"
    rm -rf "$tmp"; return 1
  fi
  rm -rf "$tmp"
  ok "кеш от упавшего прогона отличается от готового"
}
