# shellcheck shell=bash
# Утверждения о контейнерном пути релиза (спека #20, вертикаль 2) — отдельно от того, что их
# запускает: один и тот же код проверяет живое дерево (check_release_container.sh) и сломанные
# копии (check_release_container_selftest.sh). Утверждение, живущее только внутри своего прогона,
# невозможно уронить нарочно, а значит — неизвестно, умеет ли оно падать.
#
# Предмет здесь — ПРАВИЛА, которые видны без запущенного демона: пин базы, отсутствие второго
# упаковщика, коды отказов. Живая сборка — второй этап того же гейта, и она требует движка.

# Пин базы обязан быть ДАЙДЖЕСТОМ. Тег `ubuntu:24.04` переставляют на новый слепок, поэтому
# «образ тот же» через месяц значит другой компилятор и другую сумму пакета — а гейт
# воспроизводимости обвинил бы в этом наш код.
assert_base_pinned() {
  local dockerfile="$1" pin
  pin=$(container_base_pin "$dockerfile")
  [ -n "$pin" ] || { bad "в $dockerfile нет строки FROM"; return 1; }
  if ! printf '%s' "$pin" | grep -Eq '@sha256:[0-9a-f]{64}$'; then
    bad "база не пиннута дайджестом: '$pin'"; return 1
  fi
  ok "база пиннута дайджестом (${pin##*@})"
}

# Контейнер обязан звать ТОТ ЖЕ release.sh, а не паковать сам. Второй упаковщик разошёлся бы с
# первым нормализацией архива или составом, и узналось бы это по расхождению сумм у скачавшего.
# Позитивный контроль внутри утверждения: сначала доказываем, что делегирование в файле видно, и
# только потом ищем самодеятельность — иначе опечатка в пути делает гейт вечно зелёным.
assert_no_second_packer() {
  local script="$1"
  if ! grep -q 'release\.sh' "$script"; then
    bad "$script не зовёт release.sh — контейнер стал вторым упаковщиком"; return 1
  fi
  if grep -Eq '(^|[^_[:alnum:]])(tar|gzip)[[:space:]]+-' "$script"; then
    bad "$script пакует сам:"
    grep -nE '(^|[^_[:alnum:]])(tar|gzip)[[:space:]]+-' "$script" | sed 's/^/       /' >&2
    return 1
  fi
  ok "контейнер делегирует упаковку release.sh, своей не заводит"
}

# Дерево монтируется только для чтения: гейт 10 требует чистого `git status` после релиза, а
# сборка с правом писать в /src оставляет каталог и файлы с чужим владельцем.
assert_ro_mount() {
  local script="$1"
  if ! grep -q '\-v "\$ROOT:/src' "$script"; then
    bad "$script не монтирует дерево в /src — проверять нечего"; return 1
  fi
  if ! grep -q '\-v "\$ROOT:/src:ro"' "$script"; then
    bad "дерево смонтировано в контейнер БЕЗ :ro"; return 1
  fi
  ok "дерево монтируется только для чтения"
}

# Тег образа обязан различать архитектуры: иначе эмулированная сборка занимает имя нативной, и
# следующий прогон молча получает чужой пакет — расходятся не имена, а содержимое.
assert_tag_per_arch() {
  local dockerfile="$1" a b
  a=$(container_image_tag "$dockerfile" aarch64)
  b=$(container_image_tag "$dockerfile" x86_64)
  if [ "$a" = "$b" ]; then bad "тег образа один на две архитектуры: '$a'"; return 1; fi
  ok "тег образа различает архитектуры ($a / $b)"
}

# Выбор движка обязан проверять ЖИВОСТЬ, а не наличие в PATH: docker без запущенного демона — это
# команда, которая есть и не работает, и выбор по наличию отдал бы её отказ там, где рядом стоит
# рабочий podman.
assert_engine_liveness() {
  local tmp got
  tmp=$(mktemp -d)
  printf '#!/bin/sh\nexit 1\n' > "$tmp/deadengine"
  chmod +x "$tmp/deadengine"
  got=0
  PATH="$tmp:$PATH" LIKE_NES_CONTAINER_ENGINE=deadengine container_engine >/dev/null 2>&1 || got=$?
  rm -rf "$tmp"
  if [ "$got" = 0 ]; then
    bad "движок выбран по наличию в PATH, хотя его демон не отвечает"; return 1
  fi
  ok "движок без живого демона не выбирается"
}

# Отказ проверяется ПРОГОНОМ, а не чтением исходника: предмет спеки — «внятное сообщение с
# инструкцией, а не падение», и сообщение узнаётся только у того, кто его напечатал. Код 4
# отдельный от 2 и 3 ровно потому, что означает единственное: доустанови движок и повтори.
#
# Зовётся release_container.sh НАПРЯМУЮ, а не через `release.sh --only linux`: на линукс-хосте
# вторая форма — это своя платформа, то есть полная сборка вместо отказа, и утверждение проверяло
# бы разные вещи на разных ОС. Делегирование проверяет отдельное утверждение ниже.
assert_refusal_without_engine() {
  local script="$1" out rc=0
  out=$(LIKE_NES_CONTAINER_ENGINE=likenes-no-such-engine \
    bash "$script" --version v0.0.0-check 2>&1) || rc=$?
  if [ "$rc" != 4 ]; then
    bad "без движка ждали код 4, получили $rc"
    printf '%s\n' "$out" | sed 's/^/       /' >&2
    return 1
  fi
  if ! printf '%s' "$out" | grep -q 'brew install'; then
    bad "отказ без движка не называет, что поставить"; return 1
  fi
  ok "без движка — код 4 и инструкция, а не падение"
}

# Граница вертикали: код 3 по-прежнему живой. Без этого утверждения «linux больше не 3» прошло бы
# и на скрипте, который перестал отказывать вообще.
#
# Предмет сменился вместе с деревом: до вертикали 3 третьим отказывал `--only windows`, теперь он
# делегируется в CI, и код 3 остался ровно за веткой `*)` — платформой, которую этот хост не
# собирает и делегировать некому (пакет macOS с линукс-машины). Ветка достижима только с ЧУЖОГО
# хоста, поэтому хост подменяется заглушкой `uname` в PATH, а не ручкой в самом скрипте: ручка,
# заведённая ради проверки, проверяла бы себя.
#
# Форм ДВЕ, и первая из них — БЕЗ `--version`: пока утверждение звало только вторую, оно молчало о
# том, что вертикаль 2 подняла `resolve_version` выше диспатча, и чужая платформа на HEAD без тега
# отказывала кодом 2 («укажи --version») вместо кода 3. Обещание контракта — «код 3 независимо от
# версии», и проверять его версией, которую сам же и подставил, значит не проверять его вовсе.
assert_foreign_platform_refused() {
  local release="$1" fake rc=0
  fake=$(mktemp -d)
  printf '#!/bin/sh\ncase "$1" in -m) echo x86_64 ;; *) echo Linux ;; esac\n' > "$fake/uname"
  chmod +x "$fake/uname"
  # Позитивный контроль на саму заглушку: не подхватись она, хостом остался бы macOS, `--only
  # macos` означал бы `host` и ушёл бы в сборку — то есть утверждение проверяло бы не то.
  if [ "$(PATH="$fake:$PATH" uname -s)" != Linux ]; then
    bad "заглушка uname не подхватилась — чужую платформу проверять не на чем"; rm -rf "$fake"; return 1
  fi
  PATH="$fake:$PATH" bash "$release" --only macos >/dev/null 2>&1 || rc=$?
  if [ "$rc" != 3 ]; then
    bad "для чужой платформы без --version ждали код 3, получили $rc"; rm -rf "$fake"; return 1
  fi
  rc=0
  PATH="$fake:$PATH" bash "$release" --only macos --version v0.0.0-check >/dev/null 2>&1 || rc=$?
  if [ "$rc" != 3 ]; then
    bad "для чужой платформы с --version ждали код 3, получили $rc"; rm -rf "$fake"; return 1
  fi
  rm -rf "$fake"
  ok "платформе, которую некому делегировать, остаётся код 3 (с версией и без)"
}

# Флаг чужого этажа обязан быть отказом, а не тишиной: съеденный --platform читается как
# выполненный, и «собрал под linux/amd64» вышло бы из прогона, собравшего под хост.
assert_platform_rejected_on_host() {
  local release="$1" rc=0
  bash "$release" --only host --platform linux/amd64 --version v0.0.0-check >/dev/null 2>&1 || rc=$?
  if [ "$rc" != 2 ]; then bad "--platform на хостовой сборке: ждали код 2, получили $rc"; return 1; fi
  ok "--platform на хостовой сборке отвергается"
}

# Кеш сборки живёт ВНЕ дерева: каталог внутри репозитория оставил бы след, который гейт 10 обязан
# считать нарушением гигиены, а `.gitignore` на него — молчаливым исключением из проверки.
assert_cache_outside_tree() {
  local root="$1" dir
  dir=$(container_build_dir aarch64)
  case "$dir" in
    "$root"/*) bad "кеш контейнерной сборки лежит внутри дерева: $dir"; return 1 ;;
  esac
  ok "кеш контейнерной сборки вне дерева ($dir)"
}

# Делегирование: на не-линукс хосте `--only linux` обязано дойти ДО контейнера, а не отказать
# кодом 3, как было в вертикали 1. Проверяется тем же фальшивым движком — код 4 доказывает, что
# управление дошло до контейнерного пути, ничего при этом не собрав.
assert_linux_delegated() {
  local release="$1" rc=0
  LIKE_NES_CONTAINER_ENGINE=likenes-no-such-engine \
    bash "$release" --only linux --version v0.0.0-check >/dev/null 2>&1 || rc=$?
  if [ "$rc" = 3 ]; then
    bad "release.sh всё ещё отказывает по linux кодом 3 — вертикаль 2 не подключена"; return 1
  fi
  if [ "$rc" != 4 ]; then
    bad "--only linux без движка: ждали код 4 от контейнерного пути, получили $rc"; return 1
  fi
  ok "--only linux уходит в контейнер, а не в отказ"
}

# Кеш от упавшего прогона обязан распознаваться по ФАЙЛУ ГЕНЕРАТОРА, а не по наличию кеша CMake:
# `CMakeCache.txt` пишется раньше наших опций, поэтому «кеш есть» ничего не говорит о том, дошла
# ли конфигурация до конца. Две фикстуры внутри одного утверждения, потому что предмет — граница
# между ними: правило, считающее сломанным ЛЮБОЙ каталог, сносило бы готовую сборку каждый прогон.
assert_broken_cache_detected() {
  local tmp rc=0
  tmp=$(mktemp -d)
  mkdir -p "$tmp/half" "$tmp/whole"
  : > "$tmp/half/CMakeCache.txt"
  : > "$tmp/whole/CMakeCache.txt"
  : > "$tmp/whole/build.ninja"
  container_cache_broken "$tmp/half" || rc=1
  if [ "$rc" != 0 ]; then
    bad "кеш без build.ninja не распознан как недоконфигурированный"; rm -rf "$tmp"; return 1
  fi
  if container_cache_broken "$tmp/whole"; then
    bad "готовый каталог сборки принят за мусор — снос стирал бы работу каждый прогон"
    rm -rf "$tmp"; return 1
  fi
  rm -rf "$tmp"
  ok "кеш от упавшего прогона отличается от готового"
}
