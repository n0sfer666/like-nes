# shellcheck shell=bash
# Якорь заголовка по правилу хостинга (спека #19, вертикаль 1). Отдельно от утверждений о
# содержимом: slug — правило ХОСТИНГА, а не документа, и его читают напрямую, мимо дерева.

# Заголовки документа как ЯКОРЯ, по правилу хостинга: нижний регистр, пунктуация выброшена,
# каждый пробел — свой дефис. Кириллица не транслитерируется, только опускает регистр, и ссылка
# `#windows-из-какой-оболочки` в ru-паре живёт ровно так. Разметка кода (```) пропускается: `#` в
# начале строки внутри блока — комментарий шелла, а не заголовок, и принятый за заголовок он
# делал бы живым якорь, которого у документа нет.
docs_heading_slugs() {
  awk '
    /^```/ { fence = !fence; next }
    !fence && /^#+[ \t]/ {
      sub(/^#+[ \t]+/, "")
      sub(/[ \t]+$/, "")
      print
    }' "$1" | while read -r h; do docs_slug "$h"; done
}

# Класс пробельных символов — ИМЕНОВАННЫЙ, а не `[ \t]`: в скобочном выражении BSD sed обратный
# слэш буквой не является, то есть класс читается как «пробел, слэш или буква t», и `Prerequisites`
# давал бы якорь `prerequisi-es`. Утверждение при этом оставалось бы зелёным на любой ссылке,
# которая ту же порчу повторяет, — то есть врало бы согласованно.
#
# Хостинг меняет дефисом КАЖДЫЙ пробел, не схлопывая, и выбрасывает любую пунктуацию, а не только
# ASCII: «Стадии — крупная сетка» даёт `стадии--крупная-сетка`. Регистр русского алфавита и
# не-ASCII пунктуация снимаются буквальными заменами по символу, а не `tr`, `y///` или скобочным
# классом: GNU `tr` многобайтовых символов не знает, класс `[«»]` в C-локали режет по байтам и
# задевает кириллицу с тем же байтом в хвосте, а `Ё` (U+0401) в диапазон `А-Я` не входит вовсе.
# Буквальная замена совпадает и как байты, и как символ, поэтому от локали не зависит. Без неё якорь
# `#Объекты`, мёртвый на хостинге, совпадал с заголовком «Объекты», а живой `#объекты` — нет.
docs_slug() {
  printf '%s\n' "$1" | tr 'A-Z' 'a-z' | sed '
    s/А/а/g; s/Б/б/g; s/В/в/g; s/Г/г/g; s/Д/д/g; s/Е/е/g; s/Ё/ё/g; s/Ж/ж/g; s/З/з/g; s/И/и/g; s/Й/й/g
    s/К/к/g; s/Л/л/g; s/М/м/g; s/Н/н/g; s/О/о/g; s/П/п/g; s/Р/р/g; s/С/с/g; s/Т/т/g; s/У/у/g; s/Ф/ф/g
    s/Х/х/g; s/Ц/ц/g; s/Ч/ч/g; s/Ш/ш/g; s/Щ/щ/g; s/Ъ/ъ/g; s/Ы/ы/g; s/Ь/ь/g; s/Э/э/g; s/Ю/ю/g; s/Я/я/g
    s/[]!"#$%&()*+,./:;<=>?@\\^`{|}~[]//g; s/'"'"'//g; s/[[:space:]]/-/g
    s/—//g; s/–//g; s/«//g; s/»//g; s/…//g; s/№//g; s/„//g; s/“//g; s/”//g; s/‘//g; s/’//g'
}
