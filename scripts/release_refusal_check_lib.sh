# shellcheck shell=bash
# Утверждения о ДИСПАТЧЕ release.sh (спека #20, вертикали 2-4): какой платформе он отказывает, какую
# делегирует и какой флаг обязан отбить. Предмет отдельный от правил контейнерного пути (пин базы,
# монтирование, второй упаковщик, кеш) — по той же границе, по которой ещё раньше разошлись наборы
# check_release_container_selftest.sh и check_release_refusal_selftest.sh: там ломают ФАЙЛЫ пути, а
# здесь — ВЕТВЛЕНИЕ, и узнаётся оно только прогоном. Свой файл, потому что имя у предмета уже есть.

# Каталог заглушек, общий для всех утверждений о диспатче. Их две, и вторая — не гигиена.
#
# `cmake`: до сборки прогон доходит только на СЛОМАННОЙ фикстуре, и там она не «медленная», а
# разрушительная — фикстура под заглушкой `uname` собрала бы на машине macOS пакет со штампом
# linux-x86_64 прямо в `release/` дерева, а следующий этап preflight сверил бы его как свой. Так и
# вышло на первом же прогоне: `check_release.sh` поймал чужую тройку и объявил невоспроизводимость.
# Заглушка обрывает такой прогон первой же командой сборки, `--out`/`--build` уводят его из дерева.
#
# `uname` (по требованию): ветки, живущие на другой ОС, иначе проверялись бы ручкой, заведённой ради
# проверки, то есть сами собой. Подхват заглушки утверждается на месте — не подхватилась, значит
# проверять нечего, и это находка, а не пропуск.
dispatch_stub_dir() {
  local d
  # Каталог заглушек проверяется на месте: пустой `$d` из отказавшего mktemp превращал бы `PATH=":$PATH"`
  # в текущий каталог, заглушки не подхватывались бы, и утверждение проверяло бы настоящую сборку.
  d=$(mktemp -d) || return 1
  [ -d "$d" ] || return 1
  printf '#!/bin/sh\necho "release-check: сборке в утверждении о диспатче взяться неоткуда" >&2\nexit 90\n' > "$d/cmake"
  chmod +x "$d/cmake"
  if [ "${1:-}" = linux ]; then
    printf '#!/bin/sh\ncase "$1" in -m) echo x86_64 ;; *) echo Linux ;; esac\n' > "$d/uname"
    chmod +x "$d/uname"
    [ "$(PATH="$d:$PATH" uname -s)" = Linux ] || { rm -rf "$d"; return 1; }
  fi
  printf '%s\n' "$d"
}

# Прогон release.sh под заглушками: тройка, каталоги и PATH — из каталога заглушек, чтобы ни одно
# утверждение о диспатче не могло оставить в дереве пакет.
dispatch_run() {
  local d="$1"; shift
  PATH="$d:$PATH" bash "$@" --out "$d/out" --build "$d/build"
}

# Код 2 у release.sh отдают ПЯТЬ разных веток (нет значения у флага, незнакомое --only, нерезолвимая
# версия, …), поэтому сам по себе он утверждением быть не может: фикстура, вырезавшая проверку
# --platform, отдаёт «непонятый аргумент» тем же кодом 2 и проезжает зелёной. Отказ опознаётся по
# коду И по своим словам. Находка ревью шага B вертикали 4.
dispatch_refused() {
  local want_rc="$1" want_text="$2" d="$3"; shift 3
  local out rc=0
  out=$(dispatch_run "$d" "$@" 2>&1) || rc=$?
  [ "$rc" = "$want_rc" ] || { printf '%s\n' "код $rc вместо $want_rc" ; return 1; }
  case "$out" in
    *"$want_text"*) return 0 ;;
    # Имя переменной берётся в скобки НЕ для красоты: `«$want_text»` bash читает как имя, в котором
    # закрывающая кавычка — часть слова, и под `set -u` функция умирает раньше, чем скажет причину;
    # вызывающий видит пустую строку и объявляет отказ доказанным. Найдено фикстурой ниже.
    *) printf '%s\n' "код $want_rc, но без слов «${want_text}»"; return 1 ;;
  esac
}

# Граница вертикали: код 3 по-прежнему живой. Без этого утверждения «linux больше не 3» прошло бы
# и на скрипте, который перестал отказывать вообще.
#
# Предмет сменился вместе с деревом: до вертикали 3 третьим отказывал `--only windows`, теперь он
# делегируется в CI, и код 3 остался за веткой `*)` — платформой, которую этот хост не собирает и
# делегировать некому (пакет macOS с линукс-машины). Она достижима только с ЧУЖОГО хоста, поэтому
# хост и подменяется заглушкой.
#
# Форм ДВЕ, и первая — БЕЗ `--version`: пока утверждение звало только вторую, оно молчало о том, что
# вертикаль 2 подняла `resolve_version` выше диспатча, и чужая платформа на HEAD без тега отказывала
# кодом 2 вместо 3. Контракт — «код 3 независимо от версии»; проверять его версией, которую сам же и
# подставил, значит не проверять вовсе.
assert_foreign_platform_refused() {
  local release="$1" fake rc=0
  fake=$(dispatch_stub_dir linux) || {
    bad "заглушка uname не подхватилась — чужую платформу проверять не на чем"; return 1
  }
  dispatch_run "$fake" "$release" --only macos >/dev/null 2>&1 || rc=$?
  if [ "$rc" != 3 ]; then
    bad "для чужой платформы без --version ждали код 3, получили $rc"; rm -rf "$fake"; return 1
  fi
  rc=0
  dispatch_run "$fake" "$release" --only macos --version v0.0.0-check >/dev/null 2>&1 || rc=$?
  rm -rf "$fake"
  if [ "$rc" != 3 ]; then
    bad "для чужой платформы с --version ждали код 3, получили $rc"; return 1
  fi
  ok "платформе, которую некому делегировать, остаётся код 3 (с версией и без)"
}

# Флаг чужого этажа обязан быть отказом, а не тишиной: съеденный --platform читается как
# выполненный, и «собрал под linux/amd64» вышло бы из прогона, собравшего под хост.
#
# Хостов проверяется ДВА, и второй — линуксовый заглушкой. `host` разворачивается в имя хоста ДО
# сравнения, поэтому на линукс-машине `--only host` становился неотличим от `--only linux`, условие
# `$ONLY != linux` его пропускало, и флаг съедался молча ровно на одной ОС — той, на которой гейт не
# гонялся. Утверждение, ветвящееся по хосту, такой дефект и пропустило: теперь оно проверяет одно и
# то же на всех трёх.
PLATFORM_REFUSAL="--platform относится к сборке linux в контейнере"

assert_platform_rejected_on_host() {
  local release="$1" own fake why
  own=$(dispatch_stub_dir) || { bad "каталог заглушек не создан"; return 1; }
  why=$(dispatch_refused 2 "$PLATFORM_REFUSAL" "$own" "$release" \
    --only host --platform linux/amd64 --version v0.0.0-check)
  rm -rf "$own"
  [ -z "$why" ] || { bad "--platform на хостовой сборке: $why"; return 1; }
  fake=$(dispatch_stub_dir linux) || {
    bad "заглушка uname не подхватилась — линукс-хост проверять не на чем"; return 1
  }
  why=$(dispatch_refused 2 "$PLATFORM_REFUSAL" "$fake" "$release" \
    --only host --platform linux/amd64 --version v0.0.0-check)
  rm -rf "$fake"
  [ -z "$why" ] || { bad "--platform на ЛИНУКС-хосте: $why"; return 1; }
  ok "--platform на хостовой сборке отвергается своими словами (и на своём хосте, и на линуксовом)"
}

# Делегирование: на не-линукс хосте `--only linux` обязано дойти ДО контейнера, а не отказать кодом 3,
# как в вертикали 1. Фальшивый движок: код 4 доказывает, что управление дошло до контейнера.
assert_linux_delegated() {
  local release="$1" own rc=0
  own=$(dispatch_stub_dir) || { bad "каталог заглушек не создан"; return 1; }
  LIKE_NES_CONTAINER_ENGINE=likenes-no-such-engine \
    dispatch_run "$own" "$release" --only linux --version v0.0.0-check >/dev/null 2>&1 || rc=$?
  rm -rf "$own"
  if [ "$rc" = 3 ]; then
    bad "release.sh всё ещё отказывает по linux кодом 3 — вертикаль 2 не подключена"; return 1
  fi
  if [ "$rc" != 4 ]; then
    bad "--only linux без движка: ждали код 4 от контейнерного пути, получили $rc"; return 1
  fi
  ok "--only linux уходит в контейнер, а не в отказ"
}
