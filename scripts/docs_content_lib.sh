# shellcheck shell=bash
# Утверждения о СОДЕРЖИМОМ публичного документа (спека #19, вертикаль 1) — отдельно от утверждений
# о паре языков (docs_pairs_lib.sh). Предмет здесь не соответствие en и ru, а то, что документ не
# врёт читателю: ссылки в нём открываются, а лицензионная часть называет ту лицензию, под которой
# движок действительно отдан (гейты 4 и 7 спеки).
#
# Печать берётся у соседа (docs_ok/docs_bad); подключить обоих обязан вызывающий: своя копия
# разошлась бы в формате вывода, по которому владелец сверяет прогон построчно.

# Файлы, о которых говорят оба утверждения. Список ВЫВОДИТСЯ обходом, а не пишется руками: раздел,
# добавленный в docs/, иначе молча остался бы непроверенным — ровно list-drift.
docs_all_files() {
  local root="$1" found rc
  # Обход идёт по ВСЕМУ docs/, а не по паре языковых каталогов: в корне раздела лежат страницы,
  # которых зеркало не описывает (docs/first-run.md — указатель на обе языковые ветки,
  # docs/owner-verification.md — процедура ручных гейтов), и ломает их ровно переезд en-страницы,
  # то есть то самое, ради чего гейт заведён. Найдено ревью раунда: обход, названный «списком,
  # выведенным из дерева», читал две трети дерева.
  #
  # Список забирается в ПЕРЕМЕННУЮ, а не течёт в `sort` пайпом: код пайпа есть код ПОСЛЕДНЕЙ
  # команды, поэтому обход, оборвавшийся на середине дерева, отдавал бы НЕПОЛНЫЙ список нулём —
  # тот же класс, что «импорты до фильтра» в assert_redist_expected_named. Его stderr по той же
  # причине больше не глушится: `2>/dev/null` гасил ровно ту строку, по которой обрыв и
  # опознаётся, и на windows-раннере 2026-09-06 список из 9 файлов вместо 15 приехал с кодом 1 и
  # без единого слова о причине.
  found=$( cd "$root" && find docs -type f -name '*.md' )
  rc=$?
  [ "$rc" = 0 ] || {
    printf 'docs_all_files: обход docs отказал кодом %s — список неполон\n' "$rc" >&2
    return 1
  }
  ( cd "$root" && {
      [ -f README.md ] && printf 'README.md\n'
      [ -f README.ru.md ] && printf 'README.ru.md\n'
      if [ -n "$found" ]; then printf '%s\n' "$found" | LC_ALL=C sort; fi
    } )
}

# Относительные ссылки документа: внешние (http, mailto) и внутренние якоря отброшены — про первые
# гейт без сети ничего не скажет, вторые к файловой системе отношения не имеют. Якорь у пути
# срезается: `guide/input.md#rebinding` есть ссылка на файл `guide/input.md`.
docs_links_of() {
  grep -o '](\([^)]*\))' "$1" \
    | sed 's/^](//; s/)$//' \
    | grep -v '^[a-z][a-z0-9+.-]*:' \
    | grep -v '^#' \
    | sed 's/#.*$//' \
    | grep -v '^$'
}

# Заголовки документа как ЯКОРЯ, по правилу хостинга: нижний регистр, пунктуация выброшена,
# пробелы стали дефисами. Кириллица остаётся как есть — GitHub её не транслитерирует, и ссылка
# `#windows-из-какой-оболочки` в ru-паре живёт ровно так. Разметка кода (```) пропускается: `#` в
# начале строки внутри блока — комментарий шелла, а не заголовок, и принятый за заголовок он
# делал бы живым якорь, которого у документа нет.
docs_heading_slugs() {
  awk '
    /^```/ { fence = !fence; next }
    !fence && /^#+[ \t]/ {
      sub(/^#+[ \t]+/, "")
      sub(/[ \t]+$/, "")
      print
    }' "$1" | while read -r h; do docs_slug "$h"; done
}

# Класс пробельных символов — ИМЕНОВАННЫЙ, а не `[ \t]`: в скобочном выражении BSD sed обратный
# слэш буквой не является, то есть класс читается как «пробел, слэш или буква t», и `Prerequisites`
# давал бы якорь `prerequisi-es`. Утверждение при этом оставалось бы зелёным на любой ссылке,
# которая ту же порчу повторяет, — то есть врало бы согласованно.
docs_slug() {
  printf '%s\n' "$1" | tr 'A-Z' 'a-z' \
    | sed 's/[]!"#$%&()*+,./:;<=>?@\\^`{|}~[]//g; s/'"'"'//g; s/[[:space:]][[:space:]]*/-/g'
}

# Ссылки с ЯКОРЕМ, обеими формами: `page.md#anchor` и `#anchor` в том же документе. Печатается пара
# «файл-цель<TAB>якорь», где пустой файл значит «этот же документ».
docs_anchor_links_of() {
  grep -o '](\([^)]*#[^)]*\))' "$1" \
    | sed 's/^](//; s/)$//' \
    | grep -v '^[a-z][a-z0-9+.-]*:' \
    | sed 's/#/\t/'
}

# Якорь ведёт в существующий заголовок. Без этого утверждения гейт 4 спеки закрыт наполовину:
# ссылка `prerequisites.md#windows-which-shell` остаётся зелёной после переименования заголовка,
# то есть ровно тогда, когда она у читателя и ломается. Счётчик здесь по той же причине, что у
# ссылок: ноль осмотренных якорей — отказ, а не «битых нет».
assert_docs_anchors_live() {
  local root="$1" f dir file anchor target slugs bad=0 n=0
  while read -r f; do
    [ -n "$f" ] || continue
    dir=$(dirname "$f")
    while IFS=$(printf '\t') read -r file anchor; do
      [ -n "$anchor" ] || continue
      if [ -z "$file" ]; then
        target=$f
      else
        target=$(docs_normalize "$dir/$file")
      fi
      case "$target" in *.md) ;; *) continue ;; esac
      # Цель, которой нет, — предмет соседнего утверждения о ссылках, и обвинять в ней якорь значило
      # бы печатать одну поломку дважды разными словами.
      [ -f "$root/$target" ] || continue
      n=$((n + 1))
      # Заголовки забираются в ПЕРЕМЕННУЮ, а не текут в `grep -q` пайпом: под `pipefail` ранний
      # выход grep'а по первому совпадению рвёт пайп, писатель слева получает SIGPIPE, и код
      # пайплайна становится ненулевым РОВНО НА СОВПАДЕНИИ. Гейт печатал FAIL на живом якоре, а
      # тот же вызов из шелла без pipefail — OK. Тот же класс, что «импорты до фильтра» в
      # assert_redist_expected_named.
      slugs=$(docs_heading_slugs "$root/$target")
      printf '%s\n' "$slugs" | grep -qxF "$anchor" && continue
      docs_bad "$f: якорь «${anchor}» не найден среди заголовков $target"
      bad=1
    done <<EOF2
$(docs_anchor_links_of "$root/$f")
EOF2
  done <<EOF2
$(docs_all_files "$root")
EOF2
  [ "$n" != 0 ] || { docs_bad "ссылок с якорем не найдено — проверять было нечего"; return 1; }
  [ "$bad" = 0 ] || return 1
  docs_ok "якоря ссылок ведут в существующие заголовки ($n якорей)"
}

# Каждая относительная ссылка ведёт в существующий файл или каталог. Счётчик проверенных здесь не
# украшение: обход, промахнувшийся мимо документов, не находит ни одной ссылки, нарушений тоже нет,
# и гейт печатал бы «битых нет» про дерево, которого он не читал.
assert_docs_links_live() {
  local root="$1" f dir link target bad=0 n=0
  while read -r f; do
    [ -n "$f" ] || continue
    dir=$(dirname "$f")
    while read -r link; do
      [ -n "$link" ] || continue
      n=$((n + 1))
      target=$(docs_normalize "$dir/$link")
      # Ссылка, ушедшая выше корня, проверкой существования НЕ ловится: пустой путь делает
      # `[ -e "$root/" ]` истинным всегда, а сохранённые нормализатором `..` уводят проверку в
      # каталог над репозиторием, где файл с таким именем может и найтись. И то и другое — «ссылка
      # жива» про то, чего в дереве нет. Тот же класс, что vacuous-gate.
      case "$target" in
        ''|..|../*)
          docs_bad "$f: ссылка «${link}» уходит выше корня дерева ($target)"
          bad=1
          continue
          ;;
      esac
      [ -e "$root/$target" ] && continue
      # Имя в фигурных скобках не для красоты: следом стоит кавычка-ёлочка, и bash в UTF-8 локали
      # берёт её первый байт частью имени переменной — вся ветка падала «unbound variable» вместо
      # того, чтобы НАЗВАТЬ битую ссылку. Гоняется она только на сломанном дереве, поэтому нашлась
      # первым же прогоном самопроверки, а не гейтом.
      docs_bad "$f: ссылка «${link}» ведёт в никуда ($target)"
      bad=1
    done <<EOF2
$(docs_links_of "$root/$f")
EOF2
  done <<EOF2
$(docs_all_files "$root")
EOF2
  [ "$n" != 0 ] || { docs_bad "относительных ссылок не найдено — проверять было нечего"; return 1; }
  [ "$bad" = 0 ] || return 1
  docs_ok "внутренние ссылки документации открываются ($n ссылок)"
}

# Лицензионная часть (гейт 7): свободный движок, чьё README не называет лицензию, юридически
# читается как «все права защищены» — то есть заявление #9 существует только в файлах, которых
# читатель не открывает. Проверяются ОБА README: перевод, потерявший эту часть, врёт ровно так же.
assert_docs_license() {
  local root="$1" f bad=0 n=0 need
  for f in README.md README.ru.md; do
    [ -f "$root/$f" ] || { docs_bad "нет $f — лицензионную часть проверять не в чем"; return 1; }
    n=$((n + 1))
    grep -q 'MIT OR Apache-2.0' "$root/$f" || {
      docs_bad "$f не называет двойную лицензию MIT OR Apache-2.0"
      bad=1
    }
    # Ссылки на сами тексты, а не только их имена в прозе: читатель, которому назвали лицензию и не
    # дали текста, обязан искать его сам, а Apache-2.0 требует сохранять уведомления дословно.
    for need in LICENSE-MIT LICENSE-APACHE THIRD-PARTY.md; do
      grep -q "($need)" "$root/$f" || {
        docs_bad "$f не ссылается на $need"
        bad=1
      }
    done
  done
  # Сами тексты — свойство ДЕРЕВА, а не README, поэтому проверяются один раз: внутри цикла по двум
  # README одна пустая лицензия печаталась бы двумя строками, и читатель прогона считал бы две
  # поломки там, где она одна.
  for need in LICENSE-MIT LICENSE-APACHE THIRD-PARTY.md; do
    [ -s "$root/$need" ] || {
      docs_bad "$need отсутствует или пуст — ссылка из README ведёт в пустоту"
      bad=1
    }
  done
  [ "$n" = 2 ] || { docs_bad "лицензионная часть проверена не в обоих README ($n из 2)"; return 1; }
  [ "$bad" = 0 ] || return 1
  docs_ok "оба README называют MIT OR Apache-2.0 и ссылаются на тексты лицензий"
}
