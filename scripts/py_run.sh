# shellcheck shell=bash
# Тело для python3 едет ФАЙЛОМ, а не stdin: форма `python3 - <путь>` на Windows не выполняется.
#
# `python3` в PATH Windows — это лончер (PyManager, Store-заглушка), и рантайм он выбирает, ОСМАТРИВАЯ
# аргументы на шебанг. Аргументом у наших подмен идёт путь к `.sh`-фикстуре, её `#!/usr/bin/env bash`
# лончер и находит: вместо heredoc запускается bash, причём кодом НОЛЬ. Подмена молча не происходит,
# вызывающий читает успех — ровно тот вакуумный гейт, что ловит правило `vacuous-gate` в
# `ci_lint.py`. Найдено прогоном preflight на машине владельца 2026-10-03: пять «БРАК подмена …
# ничего не изменила» сразу в трёх наборах, и спасла их только сверка `cksum` до и после.
#
# Формы `-c` и «тело файлом» лончер не перехватывает: у первого аргумента расширение .py и шебанга
# нет, осмотр на нём и заканчивается. Поэтому мера одна и живёт здесь, а не N копиями по наборам —
# то же основание, по которому заведены `py_utf8.py` и `posix_bash.py`.
#
# Позиционные аргументы доезжают как есть: `sys.argv[1]` у тела не меняется, диффу call-site'а
# хватает одного слова.
py_run() {
  local room src rc=0
  room=$(mktemp -d) || return 1
  src="$room/body.py"
  cat > "$src"
  # Пустое тело — ровно тот вакуумный исход, против которого шов и заведён: call-site, потерявший
  # heredoc или закрывший его не тем словом (в одном файле у нас соседствуют `PY` и `PY2`), отдал бы
  # питону нечего выполнять, а вызывающий прочитал бы ноль как «подмена прошла».
  if [ ! -s "$src" ]; then
    printf 'py_run: тело пустое — heredoc не доехал\n' >&2
    rm -rf "$room"
    return 2
  fi
  python3 "$src" "$@" || rc=$?
  # Уборка обеими ветками вручную, а НЕ `trap ... RETURN`: trap у RETURN не снимается после
  # срабатывания и живёт в шелле вызывающего, то есть сработал бы на возврате ЧУЖОЙ функции и
  # затёр бы её собственный trap. Цена отказа — каталог, остающийся в TMPDIR при Ctrl-C.
  rm -rf "$room"
  return "$rc"
}
