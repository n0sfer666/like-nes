# shellcheck shell=bash
# Разбор ИСПОЛНИМЫХ блоков getting-started и утверждения о них, которым не нужен ни контейнер, ни
# сеть (гейт 5 спеки #19). Отдельно от того, что их запускает, по той же причине, что у
# docs_pairs_lib.sh: утверждение, живущее только внутри своего прогона, невозможно уронить нарочно,
# а значит неизвестно, умеет ли оно падать.
#
# Предмет гейта — «на чистой машине пройти getting-started дословно», поэтому команды берутся ИЗ
# документа, а не пишутся рядом с ним: рукописная копия разъехалась бы с текстом молча и проверяла
# бы вчерашнюю инструкцию — ровно list-drift из ci_lint.py.

start_ok() { printf 'docs-start: OK   %s\n' "$1"; }
start_bad() { printf 'docs-start: FAIL %s\n' "$1" >&2; }

# Роли ЗАКРЫТЫ, и каждая — фаза прогона: поставить систему, собрать, запустить. Незнакомая роль
# есть отказ, а не пропуск: опечатка в ней тихо выкинула бы блок из прогона, оставив гейт зелёным
# без предмета проверки.
START_ROLES="install build run check"

# Тело размеченных блоков одного документа. Печатается построчно: роль, файл, номер блока, текст —
# потребитель собирает тело по номеру. Маркер, за которым не идёт фенс, печатается ролью `!`:
# «размечено, но показывать нечего» и «не размечено» иначе неразличимы.
#
# Ожидание блока сюда НЕ попадает и живёт отдельной функцией: оно свойство блока, а не строки, и
# повторённое на каждой строке давало бы пустое поле посреди записи у блоков без него. Таб в IFS
# считается пробелом, пустое поле схлопывается — и команда приезжала бы в поле ожидания.
start_blocks() {
  local root="$1" rel="$2"
  awk -v rel="$rel" '
    /^<!-- container: [a-z]+( .*)? -->$/ { pend = 1; role = $3; blk++; next }
    # Строка, ПОХОЖАЯ на маркер, но не совпавшая с формой (лишний пробел, заглавная буква), — находка,
    # а не пропуск: незнакомая роль отбивалась и раньше, а опечатка в самой разметке молча выкидывала
    # блок из прогона, и покрытие сжималось при зелёном гейте. Ровно vacuous-gate из ci_lint.py.
    /^[ \t]*<!--.*container:/ { printf "?\t%s\t%d\t%s\n", rel, blk, $0; next }
    pend && /^```/ { pend = 0; inb = 1; next }
    pend { printf "!\t%s\t%d\t%s\n", rel, blk, $0; pend = 0 }
    inb && /^```/ { inb = 0; next }
    inb { printf "%s\t%s\t%d\t%s\n", role, rel, blk, $0 }
  ' "$root/$rel"
}

# Ожидания размеченных блоков документа: файл, номер блока, строка, которую бинарь обязан
# напечатать. Живёт в разметке, а не в коде гейта, потому что обещает её сам документ; что обещает
# он именно её, держит отдельное утверждение (assert_start_expect_in_text).
start_expect() {
  local root="$1" rel="$2"
  awk -v rel="$rel" '
    /^<!-- container: [a-z]+( .*)? -->$/ {
      blk++
      want = $0
      sub("^<!-- container: " $3, "", want)
      sub("-->$", "", want)
      gsub(/^ +| +$/, "", want)
      if (want != "") printf "%s\t%d\t%s\n", rel, blk, want
    }
  ' "$root/$rel"
}

# Адрес клона выкусывается ОДНОЙ функцией, потому что читают его трое: гейт (сверяет с origin),
# раннер (отдаёт заглушке) и сама заглушка (сверяет с аргументом команды). У списка нет внешнего
# эталона, и разъехавшиеся копии дали бы WANT, которого заглушка не узнает, — то есть тихий
# настоящий клон вместо подмены. Правило одно: первый операнд после `clone`, флаги пропускаются;
# что sh-копия внутри заглушки понимает его так же, держит кейс с флагом в assert_start_stub_runs.
start_clone_url() {
  local line="$1" w
  for w in $line; do
    case "$w" in git|clone|-*) continue ;; esac
    printf '%s\n' "$w"
    return 0
  done
}

# Команды плана без служебных полей: разделитель записи — таб, и `$4` обрубал бы команду документа
# по первому же табу внутри неё. Режется тремя подстановками подряд, а НЕ интервальным
# квантификатором `([^\t]*\t){3}`: mawk — awk голой Ubuntu, то есть ровно той машины, ради которой
# гейт и заведён, — интервалов не понимает и оставляет строку целиком. На macOS то же выражение
# работает, поэтому дефект жил бы ровно в контейнере: раннер не находил бы команды клонирования, а
# фаза A исполняла бы строки вместе с номером блока и путём документа. Найдено первым живым прогоном
# после разреза; что интервалов у нас не появится снова, держит assert_start_awk_portable.
start_cmds() {
  awk -F'\t' '{ line = $0; for (i = 0; i < 3; i++) sub(/^[^\t]*\t/, "", line); print line }'
}

# Запуск продукта дерева: команда без хвостового комментария, если строка запускает файл ОТСЮДА
# (`./…`), и пусто иначе. Функция ОДНА на обе фазы прогона — фаза A выбрасывает ровно то, что фаза B
# запускает: две копии признака разъехались бы молча, и блок, не попавший ни туда, ни сюда, сжимал
# бы покрытие при зелёном гейте. Что каждый блок ролей run/check содержит хоть один распознанный
# запуск, требует сам прогон: `cd build && ./editor_shell` не запуск ОТСЮДА, и тихо пропустить его
# значило бы не проверить продукт, который документ обещает.
#
# Хвостовой комментарий снимается, а АРГУМЕНТЫ остаются: `./build/editor_shell --gate6` без флага —
# другой прогон с другим выводом, и сверка его с обещанием документа была бы сверкой не того.
start_run_cmd() {
  local line="$1" cmd
  case "$line" in ./*) ;; *) return 0 ;; esac
  cmd=$(printf '%s\n' "$line" | sed -e 's/[[:space:]]*#.*$//' -e 's/[[:space:]]*$//')
  [ -n "$cmd" ] || return 0
  printf '%s\n' "$cmd"
}

# Документы, где разметка вообще ищется, — ОБХОДОМ каталога, а не списком: раздел, добавленный в
# getting-started, иначе молча остался бы вне прогона.
start_docs() {
  local root="$1"
  [ -d "$root/docs/en/getting-started" ] || return 0
  (cd "$root" && find docs/en/getting-started -type f -name '*.md' | LC_ALL=C sort)
}

# Все размеченные блоки дерева в ПОРЯДКЕ ИСПОЛНЕНИЯ. Порядок задают РОЛИ, а не имена файлов:
# алфавит поставил бы build.md впереди prerequisites.md, то есть сборку впереди установки, и
# «дословный проход» врал бы порядком. Внутри роли — обход документов и порядок блоков в них.
start_plan() {
  local root="$1" role rel
  for role in $START_ROLES; do
    while read -r rel; do
      [ -n "$rel" ] || continue
      start_blocks "$root" "$rel" | awk -F'\t' -v r="$role" '$1 == r'
    done <<EOF2
$(start_docs "$root")
EOF2
  done
}
