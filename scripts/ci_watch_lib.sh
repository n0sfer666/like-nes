#!/usr/bin/env bash
# Чистое суждение о прогонах CI: из списка прогонов ОДНОГО коммита — одно слово вердикта. Отделено
# от ci_watch.sh по той же границе, что perf_sweep_lib.sh от perf_sweep.sh: там сеть, сон и цикл,
# здесь ни одного побочного действия. Только поэтому это проверяется фикстурами, не трогая GitHub, —
# а проверять тут есть что, потому что предыдущий наблюдатель врал тремя способами сразу.
#
# Файл подключается через `.`, самостоятельно не запускается.

# Сколько прогонов ждать — СЧИТАЕТСЯ ПО ТРИГГЕРАМ, а не пишется числом. Константа `2` («на push
# идут `ci` и `dco`») продержалась один раунд и оказалась неверной ровно на том пути, ради которого
# наблюдатель заведён: `dco.yml` подписан ТОЛЬКО на `pull_request`, поэтому push в ветку порождает
# ОДИН прогон, ожидание двух не сбывается никогда, и наблюдатель честно молчал сорок минут, отдавая
# код «узнать не удалось» на каждом зелёном пуше. Число, выведенное из дерева, едет вместе с ним:
# добавленный workflow не делает наблюдателя вечно-неуверенным, а удалённый — слепым.
#
# `CI_WATCH_EXPECT_RUNS` остаётся ручкой на случай, когда триггеры разобрать нельзя, но дефолта у
# неё нет: пустое значение означает «считай сам», а не «жди двух».
CI_WATCH_EXPECT_RUNS=${CI_WATCH_EXPECT_RUNS:-}

# Список событий, на которые подписан ОДИН workflow. Вход — его текст на stdin, выход — по событию
# в строке. Три ответа, и третий несущий:
#   push / pull_request / …  — событие, на которое файл подписан как есть;
#   push_tags                — `push:` с фильтром `tags:`: на push ветки такой workflow НЕ идёт,
#                              и считать его подписчиком push значило бы ждать прогон, которого нет;
#   unparsed                 — форму `on:` разобрать не удалось (инлайн-список, отсутствие блока).
#                              Она идёт наружу словом, а не молчанием: «не разобрал» и «подписок
#                              нет» дают одно и то же число прогонов и расходятся только в том,
#                              врёт оно или нет. То же правило, что `unparsed` в ci_lint.py.
workflow_events() {
    awk '
        /^on:[[:space:]]*$/ { inon = 1; seen = 1; next }
        /^on:/ { bad = 1; seen = 1; next }
        inon && /^[^[:space:]#]/ { inon = 0 }
        inon && /^  [a-z_]+:/ {
            key = $0; sub(/^  /, "", key); sub(/:.*/, "", key)
            cur = key; order[++n] = key; next
        }
        inon && cur != "" && /^[[:space:]]+tags:/ { tagged[cur] = 1 }
        END {
            if (bad || !seen) { print "unparsed"; exit }
            for (i = 1; i <= n; i++) {
                k = order[i]
                if (k == "push" && tagged[k]) print "push_tags"; else print k
            }
        }
    '
}

# Сколько прогонов породит событие `$1` в каталоге workflow'ов `$2`. Печатает число и возвращает 0;
# при неразобранном файле не печатает ничего и возвращает 1 — вызывающий обязан различить это с
# честным нулём, а не подставить дефолт.
expected_runs() {
    local event=$1 dir=${2:-.github/workflows} total=0 f events
    for f in "$dir"/*.yml "$dir"/*.yaml; do
        [ -f "$f" ] || continue
        events=$(workflow_events <"$f")
        case "$events" in unparsed) return 1 ;; esac
        printf '%s\n' "$events" | grep -qx -- "$event" && total=$((total + 1))
    done
    printf '%s' "$total"
}

# Вход на stdin: по строке на прогон, «<status> <conclusion>». Печатает ОДНО слово:
#   none    — прогонов у коммита нет вовсе (это находка, а не «зелено»: push мог не доехать)
#   running — хоть один не досчитал ЛИБО их меньше ожидаемого
#   failure — хоть один завершился не успехом
#   success — все досчитали успехом и их не меньше ожидаемого
#
# Порядок проверок несущий: красный назван РАНЬШЕ незавершённого. Прогон `ci` уже упал, `dco` ещё
# идёт — ждать нечего, ответ известен, и молчать до конца второго значит отдать находку позже даром.
runs_verdict() {
    local expect=$1 n=0 pending=0 bad=0 status conclusion
    while read -r status conclusion; do
        [ -n "${status:-}" ] || continue
        n=$((n + 1))
        if [ "$status" != "completed" ]; then
            pending=1
            continue
        fi
        # Пустой `conclusion` у завершённого прогона — состояние, которого быть не должно. Оно идёт
        # в красное, а не в зелёное: неизвестное обязано вести себя как плохое, иначе вердикт по
        # непонятому ответу API окажется «всё хорошо».
        case "$conclusion" in
            success | skipped) ;;
            *) bad=1 ;;
        esac
    done
    if [ "$n" -eq 0 ]; then
        printf 'none'
    elif [ "$bad" -eq 1 ]; then
        printf 'failure'
    elif [ "$pending" -eq 1 ] || [ "$n" -lt "$expect" ]; then
        printf 'running'
    else
        printf 'success'
    fi
}

# Сколько опросов ОБЯЗАНО уместиться в бюджет `$1` секунд при интервале `$2`. Отдельным суждением,
# потому что бюджет наблюдателя и его способность видеть — разные величины, и до 2026-08-24 они
# считались одной: цикл мерил себя `SECONDS`, то есть СТЕННЫМИ часами, а узнать что-либо мог только
# опросом. Между ними нет связи. Наблюдатель, чей процесс не исполнялся, честно досидит до
# сорока минут и скажет «прогоны не досчитали» про коммит, позеленевший двадцать одну минуту назад,
# — ровно это и случилось на `ed34c6d` (прогон завершён 10:11:03Z, вывод дописан 10:32:11Z, при
# этом ни одного сбоя запроса в логе). Причина, по которой опросы не состоялись, отсюда не видна;
# видно ЧИСЛО, и оно обязано ехать в вывод, а не подразумеваться.
polls_due() {
    local budget=$1 interval=$2
    [ "$interval" -gt 0 ] 2>/dev/null || return 1
    printf '%s' $((budget / interval))
}

# Смотрел ли наблюдатель на самом деле. `observed` — опросов сделано столько, сколько позволял
# интервал; `asleep` — сделано меньше ПОЛОВИНЫ, то есть о CI этот прогон не знает почти ничего и
# говорить о нём не вправе.
#
# Половина — величина ПРОИЗВОЛЬНАЯ, и потому названа здесь числом, а не спрятана в условие: точной
# границы между «сеть отвечала медленно» и «процесс не исполнялся» не существует, а запас нужен —
# каждый опрос стоит ещё и времени самого запроса, поэтому даже здоровый прогон делает опросов
# чуть меньше, чем позволяет деление. Ноль ожидаемых опросов — это `observed`: бюджет короче
# интервала не является сном.
watch_health() {
    local made=$1 due=$2
    if [ "$due" -le 0 ]; then printf 'observed'; return; fi
    if [ $((made * 2)) -lt "$due" ]; then printf 'asleep'; else printf 'observed'; fi
}

# Кодов возврата ТРИ, и третий — весь смысл этого файла. Прошлый наблюдатель кончился словом
# `timeout` при двух зелёных прогонах: «не смог узнать» он печатал теми же средствами, что вердикт,
# и читалось это как «CI не досчитал». «Не знаю» обязано иметь СВОЙ код, не совпадающий ни с
# зелёным, ни с красным, — иначе вызывающий не сможет отличить отсутствие ответа от ответа.
verdict_exit() {
    case "$1" in
        success) printf '0' ;;
        failure) printf '1' ;;
        *) printf '2' ;;
    esac
}
