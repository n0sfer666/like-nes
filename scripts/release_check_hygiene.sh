# shellcheck shell=bash
# Утверждения о ГИГИЕНЕ релиза (спека #20, гейты 9 и 10) — отдельно от утверждений о содержимом
# пакета (release_check_lib.sh): там предмет «что внутри», здесь — «в какой форме сложено и что
# осталось снаружи». Оба набора сходятся в check_release.sh и в его самопроверке, и `ok`/`bad`
# приходят из release_check_lib.sh: два печатающих слова на две библиотеки дали бы гейт, у которого
# половина строк лога выглядит иначе, чем другая.

# Нормализация архива — предмет всей вертикали, а до этого утверждения она не проверялась ничем:
# два прогона гейта идут на одной машине из одного стейджа, поэтому uid совпадает по построению, а
# порядок обхода стабилен. То есть выкинь кто-нибудь `--numeric-owner` или `LC_ALL=C sort`, сумма
# всё равно воспроизвелась бы, и «детерминированный архив» осталось бы утверждать нечем. Здесь
# читается САМ архив: владелец, порядок имён и заголовок gzip.
assert_pack_normalized() {
  local pkg="$1" listing names sorted gz
  [ -s "$pkg" ] || { bad "пакет пуст или отсутствует: $pkg"; return 1; }
  listing=$(tar -tvf "$pkg" 2>/dev/null) || { bad "архив не читается: $pkg"; return 1; }
  # GNU tar печатает владельца как `0/0`, BSD — двумя колонками `0  0`; общее у них ровно то, что
  # утверждается: числовой ноль вместо имени пользователя машины сборки.
  if printf '%s\n' "$listing" | grep -qvE '^[-dlrwxsSt.@+]+ +(0/0|0 +0) '; then
    bad "в архиве есть файл с чужим владельцем (ожидался числовой 0/0)"
    printf '%s\n' "$listing" | grep -vE '^[-dlrwxsSt.@+]+ +(0/0|0 +0) ' | sed 's/^/       /' >&2
    return 1
  fi
  names=$(tar -tf "$pkg")
  sorted=$(printf '%s\n' "$names" | LC_ALL=C sort)
  if [ "$names" != "$sorted" ]; then
    bad "имена в архиве лежат не в порядке LC_ALL=C — порядок обхода каталога проехал в байты"
    return 1
  fi
  # Байты 4..7 gzip-заголовка — это MTIME. `gzip -n` зануляет его; без `-n` там время упаковки, то
  # есть сумма архива менялась бы каждую секунду при неизменном содержимом.
  gz=$(od -An -tx1 -j4 -N4 "$pkg" | tr -d ' \n')
  if [ "$gz" != "00000000" ]; then
    bad "в заголовке gzip записано время ($gz) — упаковано без -n"
    return 1
  fi
  ok "архив нормализован: владелец 0, порядок LC_ALL=C, gzip без времени"
}

# Путь спрашивается СО СЛЕШЕМ: правило `release/` в .gitignore — про каталог, а `check-ignore` без
# слеша считает аргумент файлом и на несуществующем пути отвечает «не игнорируется». Пока гейт не
# убирал за собой, ответ совпадал с верным случайно — каталог лежал на диске; уборка сделала
# утверждение красным, хотя .gitignore не менялся. Вопрос здесь про ФАЙЛ ПРАВИЛ, а не про дерево.
assert_ignored() {
  local root="$1" path="$2"
  if ! git -C "$root" check-ignore -q -- "$path/"; then
    bad "$path/ не в .gitignore — артефакт релиза попадёт в коммит (инвариант 5 спеки #20)"
    return 1
  fi
  ok "$path/ игнорируется git"
}

# Утверждение здесь — «релиз не пачкает дерево», а не «дерево чисто»: гейт гоняется и на
# незакоммиченной работе, и требование чистоты сделало бы его вечно красным, то есть выключенным.
# Сравниваются два снимка, поэтому новый отслеживаемый артефакт виден разницей.
assert_tree_unchanged() {
  local before="$1" after="$2"
  if [ "$before" != "$after" ]; then
    bad "прогон релиза изменил состояние дерева:"
    diff <(printf '%s\n' "$before") <(printf '%s\n' "$after") | sed 's/^/       /' >&2 || true
    return 1
  fi
  ok "прогон релиза не оставил следов в отслеживаемом дереве"
}
