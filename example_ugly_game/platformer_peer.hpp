#pragma once

#include <cstdint>
#include <string>

// Один пир вертикали 1 (спека #22, шаг C): своя сессия отката над той же сценой платформера и один
// канал к соседу поверх шва UDP.
//
// Пир — ОТДЕЛЬНЫЙ ПРОЦЕСС, а не поток: гейт 1 утверждает, что из одного ввода два процесса получают
// одно состояние, и поток в общем адресном пространстве этого не проверяет вовсе — он делит с
// соседом и кучу, и статику, то есть ровно те места, где прячется скрытое состояние симуляции.
// Запускается пир перезапуском СОБСТВЕННОГО exe со служебным флагом: fork'а на Windows нет
// (`platform_process.hpp`).
namespace platformer {

// Насколько вперёд пир играет по предсказанию, обогнав подтверждённый ввод. Меньше глубины отката,
// потому что откат ровно этой величиной и меряется: подтверждение, приехавшее на тик `t`, застаёт
// голову не дальше `t + PEER_PREDICT`.
constexpr uint32_t PEER_PREDICT = 4;
constexpr uint32_t PEER_DEPTH = 8;

// Потолок неподтверждённых у отправителя. Не тот же, что окно надёжного слоя (32): сессия
// принимает ввод не дальше `LEAD` тиков вперёд, и отправитель, разогнавшийся на всё окно, слал бы
// подтверждения, которые сосед обязан отвергнуть как «слишком далеко» — а второй раз слой их не
// доставит, потому что дедупликация считает их принятыми.
constexpr size_t PEER_INFLIGHT = 8;

// Оба бюджета пира обязаны уместиться ПОД потолком шва ВМЕСТЕ: родитель ждёт ребёнка через
// `platform::Child::wait`, а тот на Windows ждёт конечно — 30 с, дальше `TerminateProcess` и
// `ExitKind::Unknown`. Не уместившись, живой, но медленный прогон убивал бы САМ РОДИТЕЛЬ: гейт
// краснел бы от загрузки раннера, а не от дефекта, и ровно на той ОС, которой нет локально. И
// наоборот — заявленные пиром коды отказа (3 «не дождался порта соседа», 4 «дедлайн») не
// наблюдались бы никогда, их всегда опережал бы `Unknown`. Локально три гейта укладываются в 6.3 с,
// то есть около двух секунд на пару: запас у 28 с четырнадцатикратный.
constexpr int64_t PEER_RENDEZVOUS_MS = 8000;
constexpr int64_t PEER_DEADLINE_MS = 20000;

struct PeerConfig {
    // Отправитель владеет вводом: у образца ОДИН персонаж, и второй источник нажатий на него
    // означал бы не сеть, а двух игроков за одного героя.
    bool sender = false;
    std::string bundle;
    // Не каталог, а ПРЕФИКС пути: файлы рандеву и результата зовутся `<prefix>-send.port` и
    // так далее. Каталог пришлось бы создавать и удалять, а удаления каталога в шве ФС нет — то
    // есть каждый прогон гейта оставлял бы после себя пустую директорию.
    std::string prefix;
    // Сломанная реализация гейта 1: этот `InputFrame` не уходит в сеть вовсе. Отправитель играет
    // его у себя, получатель — не узнаёт никогда, и хеши обязаны разойтись.
    int64_t drop_tick = -1;
    // Гейт 7: на этом тике пир перестаёт читать сокет и не читает его `deaf_ms` миллисекунд.
    uint32_t deaf_at = 0;
    uint32_t deaf_ms = 0;
    // Гейт 9: адресация соседа без общей файловой системы. Пир на ДРУГОЙ машине файла рандеву не
    // увидит никогда, и до этого раунда назвать соседа было нечем — знакомство умело только петлю.
    // Оба поля или ни одного: адресация половиной себя не бывает, и пир, получивший половину,
    // отказывается (код 3) вместо тихого отката на файлы. Молчаливый откат был бы худшим из
    // исходов — гейт двух машин зеленел бы на одной, ничего про сеть не проверив.
    uint16_t listen_port = 0;
    std::string peer_at;
};

// Код возврата процесса-пира: 0 — прогон дошёл до конца и результат записан; 2 — уровень не
// загрузился, 3 — сосед не назван (не дождался его порта в файле, либо адресация задана
// наполовину, либо `--at` не разобрался), 4 — дедлайн, 5 — не записан результат, 6 — сокет
// непригоден, 9 — замер кадра не сошёлся с прогоном. Коды именованы, потому что stdout ребёнка
// уходит в никуда: расшифровывает их РОДИТЕЛЬ (`platformer_net_runs.hpp`), и без них в логе стояло
// бы «peers exited send=6».
int run_peer(const PeerConfig& cfg);

} // namespace platformer
