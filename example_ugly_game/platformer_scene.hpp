#pragma once
#include <optional>
#include <string>

#include "collision.hpp"
#include "controller.hpp"
#include "map_read.hpp"
#include "profile_read.hpp"

// Уровень образца-платформера: сетка из бандла, профиль из бандла и ОДНО тело — движущаяся
// платформа (шаг C вертикали 3 спеки #16).
//
// Отдельным файлом от прогона по той же границе, что у гейтов персонажа: здесь ОБСТАНОВКА, там
// утверждения. Живая цель и headless-голден делят её буквально — иначе «управление ощущается
// отзывчивым» и «хеш сошёлся на трёх ОС» говорили бы про разные уровни, и первое перестало бы
// что-либо значить для второго.
//
// Ни одна константа раскладки здесь не дублирует карту: сетка приезжает из `tilemap.txt` через
// бандл. Записаны только те числа, которых в карте нет и быть не может, — маршрут платформы (она
// тело, а не тайл) и точка появления персонажа.
namespace platformer {

namespace ch = framework::character;
namespace tm = framework::tilemap;
namespace ph = framework::physics;

using framework::Vec2;

inline fix32 tick_dt() { return fix32::from_int(1) / fix32::from_int(60); }

// Персонаж ростом в два тайла и шириной в один: карта рисовалась под эти полуразмеры, и проходы в
// ней считаны от них. Совпадение с фикстурой гейтов (`framework_character_scene.hpp`) не случайно,
// но и не связано — там своя геометрия, здесь своя.
constexpr fix32 HULL_HALF_W = fix32::from_int(8);
constexpr fix32 HULL_HALF_H = fix32::from_int(16);

// Верх пола карты: строка 14 из пятнадцати при тайле в 16. Число выписано, потому что от него
// считается точка появления, а не наоборот — карту оно не задаёт.
constexpr fix32 FLOOR_TOP = fix32::from_int(224);
constexpr fix32 SPAWN_X = fix32::from_int(40);

// Платформа ходит между ступенью и козырьком, на высоте верха ступени (176): с неё на платформу
// переходят шагом, а не прыжком. Полувысота в 8 — половина тайла, чтобы платформа читалась на глаз
// как плита, а не как ещё один тайл пола.
//
// Концы маршрута — не «примерно там», и оба конца выписаны из ШИРИНЫ ПЛИТЫ, а не из вида карты.
// Слева край плиты (520−24=496) встаёт вплотную к правому краю ступени: дальше влево плита въезжает
// В ТАЙЛЫ ступени, и персонаж на её крыше давится о них — проверено, это и был первый прогон с
// центром 504. Справа край плиты (568+24=592) упирается в левый край козырька, а везомый (568+8=576)
// остаётся левее него с запасом: козырёк низом на 176, крыша плиты тоже на 176, значит места под
// ним для пассажира нет вовсе — он упирается в его ГРАНЬ. Это скольжение, а не раздавливание:
// плита едет дальше под подошвами, а персонаж стоит (`support.hpp`). До 2026-09-01 тот же упор
// объявлялся раздавливанием и выбрасывал игрока в точку появления — третья находка гейта 8.
constexpr fix32 LIFT_HALF_W = fix32::from_int(24);
constexpr fix32 LIFT_HALF_H = fix32::from_int(8);
constexpr fix32 LIFT_TOP = fix32::from_int(176);
constexpr fix32 LIFT_LEFT = fix32::from_int(520);
constexpr fix32 LIFT_RIGHT = fix32::from_int(568);
constexpr fix32 LIFT_SPEED = fix32::from_int(60);

struct Stage {
    // Ёмкость мира — ровно под платформу: тайлы телами не становятся (`grid.hpp`), и запас здесь
    // означал бы, что в уровне ожидается что-то ещё.
    ph::World world{2};
    // `optional`, потому что у `TileGrid` нет умолчания намеренно: пустая сетка отвечала бы «пути
    // ничто не мешает» на любой запрос, то есть непрочитанный уровень выглядел бы как уровень без
    // стен (`map_read.hpp`).
    std::optional<tm::TileGrid> grid;
    ph::BodyId lift{ph::BodyId::INVALID};
    ch::MoveProfile profile;
    ch::MoveDerived derived;
    ch::Character hero;

    // Сцена отдаётся методом, а не полем: `Stage` живёт на стеке вызывающего и переезжает, а
    // указатель, взятый до переезда, смотрел бы в прежнее место.
    ch::CollisionScene view() const {
        ch::CollisionScene s;
        s.world = &world;
        s.grid = grid ? &*grid : nullptr;
        return s;
    }

    ch::CharacterHull hull() const {
        ch::CharacterHull h;
        h.shape = ph::sanitize(ph::box(HULL_HALF_W, HULL_HALF_H));
        return h;
    }
};

// Уровень целиком из бандла: секция `tilemap` разворачивается в сетку, секция `movement` — в
// профиль. Отказ ЗДЕСЬ, а не позже: игра, стартовавшая без карты, показала бы персонажа, падающего
// сквозь пустоту, и это читалось бы как дефект контроллера.
bool load_stage(const std::string& bundle_path, Stage& out);

// Персонаж в точке появления уровня. Наружу, потому что мест два — загрузка и возврат
// раздавленного в кадре, — а задаёт её УРОВЕНЬ, и вторая копия этих чисел стала бы второй правдой
// о карте.
void place_at_spawn(Stage& st);

// Один кадр в порядке КОНТРАКТА (решение владельца B3): сначала мир, потом персонаж. Порядок здесь
// не «как удобно», а условие переноса: персонаж переносится на путь опоры, пройденный ЭТИМ шагом
// мира, и обратный порядок отдавал бы ему путь прошлого кадра.
void step_stage(Stage& st, const ch::MoveInput& in);

// Прямоугольник уровня — прямоугольник СЕТКИ и ничей больше. Одно место на двоих: им ограничена и
// камера (`platformer_view.cpp`), и ход персонажа (`clamp_to_level`), а две копии этих чисел,
// разъехавшись, дали бы невидимый упор или проход за нарисованное — то есть ровно ту находку,
// которую кламп и закрывает. Без сетки границ не существует: `false`, а не выдуманный прямоугольник.
struct LevelBounds {
    Vec2 min;
    Vec2 max;
};
bool level_bounds(const Stage& st, LevelBounds& out);

// Флаги тайла в произвольной точке уровня. Наружу это нужно прогону: «прошёл сквозь одностороннюю
// снизу вверх» доказывается тем, что подошва оказалась ВНУТРИ такого тайла на подъёме, а опоры в
// этот момент нет вовсе, поэтому `ground_tile` про такой тик молчит.
tm::TileFlags tile_at_point(const Stage& st, Vec2 p);

// Флаги тайла под ногами — способ спросить у уровня, на чём персонаж стоит, не заводя поля в
// `Character`: контроллеру нормаль опоры наружу не нужна, а прогону нужно доказать, что склон и
// односторонняя площадка в маршруте были. Вне опоры возвращает `TILE_EMPTY`.
tm::TileFlags ground_tile(const Stage& st);

} // namespace platformer
