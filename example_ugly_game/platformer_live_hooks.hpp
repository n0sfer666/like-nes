#pragma once

#include <chrono>
#include <cstdint>

#include "platformer_live_input.hpp"
#include "platformer_peer_hooks.hpp"
#include "platformer_window.hpp"

// Живая половина сетевого образца: ввод с клавиатуры и пада, кадр на экране, отказ по Esc.
//
// Длина сессии ФИКСИРОВАНА и известна обеим сторонам заранее, ровно как `script_ticks()` у гейтов:
// пир ждёт подтверждений до `total`, и сторона, решившая играть дольше, упёрлась бы в дедлайн
// соседа — то есть «конец сессии» выглядел бы как обрыв сети. Договориться о конце по сети было бы
// вторым протоколом поверх ввода, и проверять его на двух машинах пришлось бы отдельно.
namespace platformer {

// 3600 тиков — минута при 60 Гц. Минута выбрана так, чтобы человеку хватило успеть разойтись с
// соседом в стороны, прыгнуть и вернуться: субъективную половину гейта 9 («играется ли по сети»)
// на десяти секундах не увидеть, а стоять пять минут перед второй машиной незачем.
constexpr uint32_t LIVE_TICKS = 3600;

// Такт сессии — СТЕННЫЕ часы (`tick_period_ns()`), а не кадр экрана. Кадром его брать нельзя:
// `Fifo` ждёт вертикальной синхронизации, и на мониторе 120 Гц сессия из 3600 тиков кончилась бы за
// тридцать секунд, а на 30 Гц тянулась бы две минуты — то есть длина «одной минуты» зависела бы от
// того, у кого какой монитор. Одиночный прогон держит тот же период и из того же места.
//
// Потолок прогона вдвое длиннее самой сессии, и он ВЫВОДИТСЯ из неё, а не пишется числом. Числом
// он был и совпал с длиной сессии на мониторе 30 Гц ровно: 3600 тиков в темпе кадра — это те же
// 120 000 мс, то есть исправная пара получала бы код 4, а §14 велит читать его как «сосед ушёл».
// Дедлайн здесь — не таймер игры, а последняя защита от зависания: сосед, чей процесс умер, иначе
// держал бы вторую сторону вечно. Ровно длина сессии не годится — окно, утащенное мышью, и сон
// машины съедают стенное время, не двигая тиков.
inline int64_t live_deadline_ms() {
    return 2 * static_cast<int64_t>(LIVE_TICKS) * tick_period_ns() / 1000000;
}

// Сколько тиков долга живая половина отдаёт залпом. Долг копится законно — проход цикла с показом
// кадра длиннее тика, — но машина, уснувшая на минуту, вернулась бы с долгом в три тысячи тиков и
// проиграла бы их без единого опроса клавиатуры. Списанный долг НЕ съедает тиков сессии: их всё
// равно ровно `LIVE_TICKS`, просто минута игры займёт больше минуты стенных часов.
constexpr int64_t LIVE_DEBT_TICKS = 12;

class LiveHooks final : public PeerHooks {
public:
    LiveHooks(Window& win, LiveInput& in) : win_(win), in_(in) {}

    uint32_t horizon() const override { return LIVE_TICKS; }
    int64_t deadline_ms() const override { return live_deadline_ms(); }

    bool input(uint32_t tick, ch::MoveInput& out) override;
    bool show(const Stage& stage) override;

private:
    using Clock = std::chrono::steady_clock;

    Window& win_;
    LiveInput& in_;
    // Момент, когда созреет СЛЕДУЮЩИЙ тик. Копится сложением периода, а не отсчётом от «сейчас»:
    // отсчёт от момента выдачи накапливал бы задержку каждого кадра, и минута сессии оказалась бы
    // длиннее минуты у соседа — то есть стороны разъехались бы по темпу, играя одну и ту же запись.
    Clock::time_point next_{};
    bool armed_ = false;
    // Сколько тиков долга списано за прогон ВСЕГО: см. печать в `input`.
    int64_t dropped_ = 0;
};

} // namespace platformer
