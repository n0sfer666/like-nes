#pragma once
#include <cstdint>
#include <vector>

#include "camera.hpp"
#include "platformer_scene.hpp"
#include "sprite.hpp"
#include "tile_draw.hpp"
#include "viewport.hpp"

// Что видно на экране — отдельно от того, чем это рисуется. Камера, окно и порядок отрисовки взяты
// у фреймворка (вертикаль 3 спеки #17): раньше этот файл считал их сам, и «камера упирается в край
// уровня» жило здесь ВТОРОЙ реализацией того же контракта. Ни окно, ни GLFW, ни WebGPU про эту
// половину по-прежнему не знают — гейт гоняется headless на трёх ОС.
namespace platformer {

namespace gx = framework::graphics;

// Вид — 320x240 юнитов УРОВНЯ: ровно половина карты по ширине и вся её высота. Больше вида быть не
// может — при виде во весь уровень камере некуда ехать, кламп не срабатывает никогда, и камеры
// фактически нет. Скейл целый: дробный растянул бы пиксель тайла неравномерно, а весь рендер здесь
// как раз из пиксельных квадов.
constexpr int VIEW_W = 320;
constexpr int VIEW_H = 240;
constexpr int VIEW_SCALE = 3;

// Цвет несёт СМЫСЛ тайла, а не украшение. Плоские квады через tint — это весь рендер образца
// (решение владельца), поэтому односторонняя площадка, покрашенная как стена, врала бы игроку ровно
// про то, чем она от стены и отличается: сквозь неё проходят снизу.
//
// Тон упакован в RGBA8, а не в четыре float'а: столько его и несёт спрайт фреймворка, и обратный
// перевод в доли единицы точен не был бы — 0.30 в восьми разрядах не представим.
constexpr uint32_t C_SOLID = 0x4d5770ffu;
constexpr uint32_t C_SLOPE = 0x478552ffu;
constexpr uint32_t C_ONEWAY = 0xc79e3dffu;
constexpr uint32_t C_LIFT = 0x38a3c2ffu;
constexpr uint32_t C_HERO = 0xe0524dffu;

// Регион здесь один на всё — сплошной блок атласа: рисунка у образца нет, всё различие несёт тон.
constexpr framework::graphics::RegionId R_SOLID = 1;

// Слой задаёт порядок ЯВНО, а не порядком подачи: платформа рисуется до персонажа, потому что
// везомый стоит на её крыше, и обратный порядок прятал бы его подошвы под плитой ровно в тот
// момент, ради которого она в уровне есть.
constexpr int16_t L_TILES = -1;
constexpr int16_t L_LIFT = 0;
constexpr int16_t L_HERO = 1;

// Квад в координатах ВИДА: левый верхний угол и размер, +Y ВНИЗ — те же оси, что у уровня. Перевод
// в оси спрайт-батча (центр квада, +Y вверх) живёт в окне: у чистой половины нет причин знать про
// NDC, а у гейта — сверять числа, дважды перевёрнутые по дороге.
struct Quad {
    float x, y, w, h;
    uint32_t color;
};

using Camera = gx::Camera;

// Развёртка вида: один экранный пиксель на юнит уровня, зум единичный. Целый масштаб здесь не
// украшение — при нецелом пиксельная сетка перестаёт быть сеткой, а весь рендер образца пиксельный.
gx::Viewport stage_viewport();

// Левый верхний угол вида в мировых координатах. Отдельной функцией, потому что камера фреймворка
// держит ЦЕНТР: половина вида прибавляется в одном месте, а не в каждом потребителе.
Vec2 view_origin(const Camera& cam);

// Камера следит за персонажем и упирается в края уровня. Политики — `CAMERA_BOUNDS` и ничего
// больше: сглаживания у образца не было и раньше, а заводить его здесь значило бы менять поведение
// под видом перевода.
Camera camera_at(const Stage& st);

// Буферы кадра принадлежат ВЫЗЫВАЮЩЕМУ (гейт 8 спеки #17): список спрайтов памятью не владеет, и
// резерв берётся ОДИН раз на прогон, а не на кадр.
class FrameSprites {
public:
    FrameSprites();
    gx::SpriteList list();

private:
    std::vector<gx::Sprite> sprites_;
    std::vector<uint64_t> keys_;
};

// Склон рисуется СТУПЕНЬКОЙ подквадов, а не одним прямоугольником, и подступенька берётся из той же
// `physics::Shape`, которую решатель подставляет под ноги. Один квад на тайл-склон соврал бы про
// геометрию дважды: холм выглядел бы стеной, а персонаж — идущим сквозь неё. Шагов ровно столько,
// сколько юнитов в тайле карты (16), то есть подступенька шириной в пиксель: мельче квантования
// самого экрана рисовать нечего.
constexpr int SLOPE_STEPS = 16;

// Кадр целиком, в порядке отрисовки. Порядок даёт `SpriteList::build` по слою, а не порядок вызовов
// ниже. Всё, что не пересекает вид, отбрасывается ДО подачи: квад за краем экрана это не
// «невидимый квад», а занятый слот батча.
void build_quads(const Stage& st, const Camera& cam, FrameSprites& buf, std::vector<Quad>& out);

} // namespace platformer
