#pragma once
#include <vector>

#include "platformer_scene.hpp"

// Что видно на экране — отдельно от того, чем это рисуется. Камера и сборка квадов ЧИСТЫЕ: ни окно,
// ни GLFW, ни WebGPU про них не знают. Граница проведена здесь ровно затем, чтобы оба утверждения
// живой цели — «камера упирается в край уровня» и «склон нарисован тем, по чему герой ходит» —
// проверялись headless-гейтом на трёх ОС, а не глазами владельца на одной.
namespace platformer {

// Вид — 320x240 юнитов УРОВНЯ: ровно половина карты по ширине и вся её высота. Больше вида быть не
// может — при виде во весь уровень камере некуда ехать, кламп не срабатывает никогда, и камеры
// фактически нет. Скейл целый: дробный растянул бы пиксель тайла неравномерно, а весь рендер здесь
// как раз из пиксельных квадов.
constexpr int VIEW_W = 320;
constexpr int VIEW_H = 240;
constexpr int VIEW_SCALE = 3;

struct Rgba {
    float r, g, b, a;
    bool operator==(const Rgba&) const = default;
};

// Цвет несёт СМЫСЛ тайла, а не украшение. Плоские квады через tint — это весь рендер образца
// (решение владельца), поэтому односторонняя площадка, покрашенная как стена, врала бы игроку ровно
// про то, чем она от стены и отличается: сквозь неё проходят снизу.
constexpr Rgba C_SOLID{0.30f, 0.34f, 0.44f, 1.0f};
constexpr Rgba C_SLOPE{0.28f, 0.52f, 0.32f, 1.0f};
constexpr Rgba C_ONEWAY{0.78f, 0.62f, 0.24f, 1.0f};
constexpr Rgba C_LIFT{0.22f, 0.64f, 0.76f, 1.0f};
constexpr Rgba C_HERO{0.88f, 0.32f, 0.30f, 1.0f};

// Квад в координатах ВИДА: левый верхний угол и размер, +Y ВНИЗ — те же оси, что у уровня. Перевод
// в оси спрайт-батча (центр квада, +Y вверх) живёт в окне: у чистой половины нет причин знать про
// NDC, а у гейта — сверять числа, дважды перевёрнутые по дороге.
struct Quad {
    float x, y, w, h;
    Rgba color;
};

// Левый верхний угол вида в мировых координатах. Камера следит за персонажем и упирается в края
// уровня; уровень уже вида по какой-то оси — прижимается к его началу по ней.
struct Camera {
    fix32 left, top;
};
Camera camera_at(const Stage& st);

// Склон рисуется СТУПЕНЬКОЙ подквадов, а не одним прямоугольником, и подступенька берётся из той же
// `physics::Shape`, которую решатель подставляет под ноги. Один квад на тайл-склон соврал бы про
// геометрию дважды: холм выглядел бы стеной, а персонаж — идущим сквозь неё. Шагов ровно столько,
// сколько юнитов в тайле карты (16), то есть подступенька шириной в пиксель: мельче квантования
// самого экрана рисовать нечего.
constexpr int SLOPE_STEPS = 16;

// Кадр целиком, в порядке рисования: тайлы, платформа, персонаж. Всё, что не пересекает вид,
// отбрасывается — квад за краем экрана это не «невидимый квад», а занятый слот батча.
void build_quads(const Stage& st, const Camera& cam, std::vector<Quad>& out);

} // namespace platformer
