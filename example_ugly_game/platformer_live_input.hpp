struct GLFWwindow;

// Живой ввод образца: раскладка из бандла, клавиатура через окно, пад через нативный бэкенд.
//
// Отдельным файлом от окна, потому что предмет другой: там показ, здесь намерение персонажа. Общим
// у двух целей (одиночной и сетевой) он стал по той же причине, что и окно, — вторая копия
// разошлась бы молча, и «в сети управление другое» нашёл бы только человек за клавиатурой.
namespace platformer {

class LiveInput {
public:
    // `false` — раскладки нет: играть нечем, и молчаливый пустой `ActionMap` выглядел бы как «игра
    // не реагирует». Причина печатается здесь же.
    //
    // Бандл называется ЯВНО и тот же, из которого загружен уровень: два пути к одному файлу
    // разъехались бы молча, а выглядело бы это как «кнопки в сети другие».
    bool open(GLFWwindow* win, const std::string& bundle);

    // Намерение персонажа на тике `t`. Пад опрашивается ровно здесь: между кадрами его состояние не
    // меняется для симуляции, а лишний опрос стоил бы кадру системного вызова.
    ch::MoveInput read(uint32_t t);

    // Имя бэкенда пада или "none" — для строки приветствия. Не диагностика ради диагностики:
    // владелец проверяет пад живым прогоном (правило 18), и «пад не подхватился» обязано быть
    // видно ДО того, как он решит, что игра его не слушает.
    const char* pad_name() const;

private:
    game::Controls controls_;
    Binding bind_;
    std::unique_ptr<::input::InputEngine> engine_;
    ::input::GamepadSource* pad_ = nullptr;
    bool have_pad_ = false;
};

} // namespace platformer
