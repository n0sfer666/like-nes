#pragma once

#include "hash.hpp"
#include "platformer_mark_io.hpp"
#include "platformer_rollback.hpp"

// Состояние сцены ОДНИМ числом — то, чем реплей заявляет каждый свой тик (спека #22, вертикаль 2).
//
// Считается оно по БАЙТАМ наблюдаемого, а не по полям сцены заново: словарь `Mark` уже решил, что
// именно составляет состояние, и второй ответ на тот же вопрос разъехался бы с первым молча. Хеш и
// `difference()` тогда судили бы о разном — заявка сходилась бы там, где сцены различны, и это
// худший исход для гейта, который иначе называет расхождение поимённо.
//
// Отсюда же и запись байтами: `mark_io` пишет поле за полем, обходя набивку структуры, а хеш по
// структуре целиком зависел бы от байтов, в которые никто не писал.
namespace platformer {

// Возвращает записанную длину, а не void: заявка обязана покрывать наблюдаемое ЦЕЛИКОМ, и формат,
// уехавший на поле вперёд читателя, урезал бы её молча — хеш от половины `Mark` остаётся
// правдоподобным числом.
inline size_t mark_bytes(const Mark& m, uint8_t* out) {
    net::Writer w(out, mark_io::BYTES);
    if (!mark_io::put_mark(w, m)) return 0;
    return w.size();
}

// Отказ записи — худший из возможных исходов, и потому спрашивается ОТДЕЛЬНО, а не читается по
// хешу: `mark_bytes` вернул бы тогда ноль, `fnv1a(buf, 0)` — базис свёртки, то есть ОДНО И ТО ЖЕ
// число для любой сцены. Верификатор, у которого все заявки равны, принимает любой поток ввода:
// гейт 6 стал бы тождеством, оставаясь зелёным.
//
// Спрашивают этот вопрос ВСЕ пути, считающие заявки (запись образца, переигрывание, пир), а не один
// гейт: разъехаться `mark_io::BYTES` с `put_mark` может только разом для всех, и путь, не задавший
// вопроса, молчал бы ровно там, где остальные краснеют. Марка нулевая намеренно — вопрос про ДЛИНУ
// формата, а не про содержимое сцены.
inline bool claim_format_holds() {
    const Mark m{};
    uint8_t buf[mark_io::BYTES];
    return mark_bytes(m, buf) == mark_io::BYTES;
}

inline uint64_t mark_hash(const Mark& m) {
    uint8_t buf[mark_io::BYTES];
    const size_t n = mark_bytes(m, buf);
    return asset::fnv1a(buf, n);
}

inline uint64_t stage_claim(const Stage& st) { return mark_hash(observe(st)); }

// Симуляция в том виде, какого требует верификатор: тот же `StageSim`, что гоняет откат, плюс
// заявка о состоянии. Наследованием, а не полем в `StageSim`: переигрывание обязано звать ТОТ ЖЕ
// `step`, что и живой прогон, — своя копия шага здесь означала бы, что реплей проверяет вторую
// реализацию правил, а не первую.
struct StageReplaySim : StageSim {
    uint64_t hash() const { return stage_claim(*stage); }
};

} // namespace platformer
