#pragma once
#include <cstdint>

#include "atlas_regions.hpp"
#include "instance.hpp"
// Путь с подсистемой, а не голое имя: `engine/render/sprite.hpp` зовётся ТАК ЖЕ и стоит в списке
// каталогов раньше, поэтому `#include "sprite.hpp"` отсюда приводит спрайт СТАРОГО рендера — тот
// компилируется и молча даёт «нет типа SpriteList в framework::graphics». Внутри самого фреймворка
// коллизии нет: там имя разрешается относительно файла.
#include "graphics/sprite.hpp"

// Перевод спрайта фреймворка в инстанс шутера (спека #17, вертикаль 3, шаг B3). Шов узкий
// намеренно: он один знает и про порядок байт в `Sprite::rgba`, и про то, что фреймворк меряет
// ПОЛУразмерами, а вершинный буфер игры — полными, и про то, что регион там номер, а здесь UV.
namespace game {

// Материал у фреймворка — число без смысла (`Sprite::material`), и смысл ему даёт потребитель.
// Здесь смысл один: ЭКСПОЗИЦИЯ, с которой цвет уходит в HDR-цель. Иначе яркости больше единицы
// (`br = 1.9` старого `fx.cpp`, тонировки `draw.cpp`) не во что положить — восемь бит канала
// кончаются на 1.0, а bloom берётся именно за то, что выше неё.
//
// Таблица здесь, а не в спрайте, по решению вертикали 3: свечение есть свойство ВЫВОДА, а не
// частицы. Спрайт остаётся LDR, и тот же спрайт, выведенный в SDR-цель, просто не светится.
enum MaterialSlot : uint16_t { MAT_Flat = 0, MAT_Glow, MAT_Count };

float material_exposure(uint16_t material);

// Возвращает число записанных инстансов. Не поместившееся ОТБРАСЫВАЕТСЯ, а не пишется мимо буфера:
// вызывающий владеет памятью (гейт 8), и молчаливая запись за границу — единственный отказ, который
// не виден вообще ниоткуда.
uint32_t sprites_to_instances(const framework::graphics::SpriteList& list, const Atlas& atlas,
                              Instance* out, uint32_t max);

} // namespace game
