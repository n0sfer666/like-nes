#pragma once
#include <webgpu/webgpu.h>

namespace game {

// Базовый пайплайн спрайта: тот же вершинный этап, что у библиотеки эффектов (спека #18), и
// фрагмент «текстура × тинт» без эффекта. Вынесен из `SpriteBatch` отдельным файлом, потому что у
// накопителя кадра вопрос «что и в каком порядке рисуем», а здесь — «как устроен конвейер»:
// раскладка атрибутов, смешивание и текст модуля больше нигде не нужны.
//
// Раскладка привязки приходит СНАРУЖИ: когда игра рисует материалами, она обязана совпасть с той,
// на которой построены пайплайны кэша, — иначе группа привязки одного пайплайна не подходит
// другому, и совпадение это нечем проверить, кроме падения валидатора в рантайме.
WGPURenderPipeline make_sprite_pipeline(WGPUDevice device, WGPUTextureFormat target,
                                        WGPUBindGroupLayout bgl);

} // namespace game
