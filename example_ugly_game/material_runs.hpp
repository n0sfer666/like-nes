#pragma once
#include <cstdint>

namespace game {

// Спрайт без материала: рисуется базовым пайплайном образца. Значение — не индекс, потому что
// таблица материалов заведомо короче 65535, а «нет» обязано быть отличимо от нулевого материала.
constexpr uint16_t NO_MATERIAL = 0xffff;

// Отрезок инстансов, идущих подряд и делящих материал: один такой отрезок — один вызов отрисовки.
struct MaterialRun {
    uint32_t first;
    uint32_t count;
    uint16_t material;
};

// Нарезка кадра на прогоны. Отдельной функцией от `SpriteBatch::flush`, а не веткой внутри него,
// ровно по той причине, по которой `InstanceStage` живёт отдельно от батча: утверждение «десять
// врагов с разными параметрами остались ОДНИМ вызовом» (гейт 5 спеки #18) не должно требовать
// открытого устройства и окна — иначе оно проверяется только там, где есть видеокарта.
//
// Порядок НЕ меняется: в 2D порядок отрисовки и есть перекрытие, и группировка, собравшая
// одинаковые материалы со всего кадра в один вызов, нарисовала бы другую картинку.
uint32_t material_runs(const uint16_t* ids, uint32_t n, MaterialRun* out, uint32_t cap);

} // namespace game
