// Гейт 2 спеки #17: эталонный кадр сцены. Побайтового сравнения тут быть не может — кадр считает
// ВИДЕОКАРТА, а Metal, lavapipe и DX12-WARP расходятся на растеризации, фильтрации и порядке
// сложения в блуме. Поэтому сравнение с допуском, и допусков ДВА, потому что вопросов два:
//
//   `same_backend` — «повторяем ли кадр вообще»: два прогона одной и той же машины на одном
//                    адаптере обязаны совпасть ТОЧНО. Ноль здесь не смелость, а измерение: на
//                    Metal два прогона демо дают побитово равные кадры, и любое послабление
//                    закрывало бы дрейф собственного тракта — то есть ровно то, ради чего гейт.
//   `cross_backend` — «узнаваем ли кадр на чужом бэкенде»: сверка с эталоном, испечённым на другой
//                    машине.
//
// Второй допуск меряет не пиковую ошибку, а РАЗМЕР СВЯЗНОГО ПЯТНА, и это следствие улики, а не
// вкус. Первый прогон гейта в CI: lavapipe разошёлся с Metal на 15 пикселях из 518 400 (0.0029%),
// разбитых на 10 пятен, крупнейшее — 4 пикселя, и все они лежат на кромках спрайтов, где пиксель
// целиком либо небо, либо корпус: ошибка канала там 0.73, то есть любой кап пиковой ошибки, под
// который она пролезает, пропускает заодно и настоящий артефакт. Windows (DX12-WARP) в том же
// прогоне разошёлся на 0.004 — один уровень, шум сложения.
//
// Дефект же двигает ОБЛАСТЬ: спрайт, съехавший на пиксель, даёт пятна высотой в спрайт; потерянный
// слой — пятно во весь кадр; сдвиг тинта — долю. Поэтому порог стоит на пятне (12 пикселей, три
// раза с запасом от измеренных четырёх) и на доле (0.1% при измеренных 0.0029%). Чего этот критерий
// НЕ ловит и что не надо читать шире: одиночный яркий артефакт мельче 12 связных пикселей от
// расхождения растеризаторов неотличим ничем.
namespace game {

struct FrameTolerance {
    double pixel_eps;      // порог отличия канала [0..1]
    double frac_tol;       // допустимая доля разошедшихся пикселей
    uint32_t max_cluster;  // допустимый размер связного пятна из них
};

inline constexpr FrameTolerance TOL_SAME_BACKEND{0.0, 0.0, 0};
inline constexpr FrameTolerance TOL_CROSS_BACKEND{0.02, 0.001, 12};

struct FrameDiff {
    double mean_abs = 0.0;
    double max_abs = 0.0;
    double frac_over = 0.0;
    uint32_t max_cluster = 0;
    bool pass = false;
};

FrameDiff compare_frames(const std::vector<uint8_t>& px, const std::vector<uint8_t>& ref,
                         uint32_t w, uint32_t h, FrameTolerance tol);
bool read_png_rgba(const char* path, std::vector<uint8_t>& out, uint32_t& w, uint32_t& h);

// Позитивный контроль сравнения. Гейт, у которого сравнение всегда отвечает «сошлось», выглядит
// ровно как честный, поэтому кадр портится ТРЕМЯ способами: пятно 5×5 (доля мизерная — отбивает
// только порог пятна), россыпь одиночных пикселей по всему кадру (пятна по одному — отбивает
// только доля) и сдвиг всей картинки на пиксель — тот самый дефект, ради которого гейт и стоит.
// Каждый обязан быть отбит.
bool comparator_refuses_spoiled(const std::vector<uint8_t>& px, uint32_t w, uint32_t h);

} // namespace game
