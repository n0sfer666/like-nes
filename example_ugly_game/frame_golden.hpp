#pragma once
#include <cstdint>
#include <vector>

// Гейт 2 спеки #17: эталонный кадр сцены. Побайтового сравнения тут быть не может — кадр считает
// ВИДЕОКАРТА, а Metal, lavapipe и DX12-WARP расходятся на растеризации, фильтрации и порядке
// сложения в блуме. Поэтому сравнение с допуском, и допусков ДВА, потому что вопросов два:
//
//   `same_backend` — «повторяем ли кадр вообще»: два прогона одной и той же машины на одном
//                    адаптере обязаны совпасть ТОЧНО. Ноль здесь не смелость, а измерение: на
//                    Metal два прогона демо дают побитово равные кадры, и любое послабление
//                    закрывало бы дрейф собственного тракта — то есть ровно то, ради чего гейт.
//   `cross_backend` — «узнаваем ли кадр на чужом бэкенде»: сравнение с эталоном, испечённым на
//                    другой машине. Числа взяты у render-вертикали (#2, `render_golden`), где они
//                    уже пережили Metal и lavapipe: канал считается разошедшимся с 0.02, доля
//                    таких пикселей допускается до 2%, и пиковая ошибка каппируется 0.35 — кап
//                    ловит малый грубый артефакт, который в средней доле утонул бы.
namespace game {

struct FrameTolerance {
    double pixel_eps;   // порог отличия канала [0..1]
    double frac_tol;    // допустимая доля пикселей за порогом
    double max_cap;     // жёсткий кап пиковой ошибки
};

inline constexpr FrameTolerance TOL_SAME_BACKEND{0.0, 0.0, 0.0};
inline constexpr FrameTolerance TOL_CROSS_BACKEND{0.02, 0.02, 0.35};

struct FrameDiff {
    double mean_abs = 0.0;
    double max_abs = 0.0;
    double frac_over = 0.0;
    bool pass = false;
};

FrameDiff compare_frames(const std::vector<uint8_t>& px, const std::vector<uint8_t>& ref,
                         FrameTolerance tol);
bool read_png_rgba(const char* path, std::vector<uint8_t>& out, uint32_t& w, uint32_t& h);

// Позитивный контроль сравнения. Гейт, у которого сравнение всегда отвечает «сошлось», выглядит
// ровно как честный, поэтому кадр портится ДВУМЯ способами, по одному на каждую половину допуска:
// малое яркое пятно (доля пикселей мизерная — ловит только кап пиковой ошибки) и слабый сдвиг всего
// кадра чуть выше порога канала (пик под капом — ловит только доля). Оба обязаны быть отбиты.
bool comparator_refuses_spoiled(const std::vector<uint8_t>& px);

} // namespace game
