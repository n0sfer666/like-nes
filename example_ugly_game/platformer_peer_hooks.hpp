#pragma once

#include <cstdint>

#include "platformer_scene.hpp"

// Шов между сетевым пиром и ЖИВОЙ половиной образца (гейт 9 спеки #22).
//
// До этого шва пир умел только скриптовый ввод и не показывал ничего: гейты 1-7 сверяют хеши двух
// процессов, и окна им не нужно. Вторая половина гейта 9 — субъективная, «играется ли по сети», —
// проверяется только человеком за клавиатурой, и проверять её было нечем.
//
// Второй копии цикла отката ради окна не появляется. Копия разошлась бы с оригиналом молча: гейты
// продолжали бы сходиться на своей, а владелец играл бы в другую — то есть ровно то, чего вертикаль
// и добивается («живой прогон и гейт делят код»), перестало бы быть правдой в первый же месяц.
//
// `nullptr` в `PeerConfig::hooks` означает сегодняшний headless-пир БУКВАЛЬНО: ввод берётся у
// скрипта, кадр не показывается, дедлайн прежний. Позитивный контроль на это и стоит — прогон через
// хуки со скриптовым вводом обязан дать тот же `state_hash` и ту же запись побайтно.
namespace platformer {

struct PeerHooks {
    virtual ~PeerHooks() = default;

    // Сколько тиков длится сессия. Обе стороны обязаны знать это ЧИСЛО заранее и одинаково: пир
    // ждёт подтверждений до `total`, и сторона, решившая играть дольше, упёрлась бы в дедлайн
    // соседа. Живая сессия поэтому фиксированной длины, а не «пока не надоест».
    virtual uint32_t horizon() const = 0;

    // Потолок прогона в миллисекундах. Своим он нужен потому, что headless-дедлайн (20 с) короче
    // самой живой сессии (60 с): оставь его прежним — и каждый живой прогон отказывал бы кодом 4 на
    // третьей секунде игры.
    virtual int64_t deadline_ms() const = 0;

    // Ввод тика `t`. `false` — «ещё не готов»: живой ввод рождается КАДРОМ, а не проходом цикла, и
    // отправитель, берущий его по первому требованию, разогнался бы на весь `PEER_INFLIGHT` и
    // сыграл бы восемь тиков за один кадр экрана.
    virtual bool input(uint32_t tick, ch::MoveInput& out) = 0;

    // Показ состояния. `false` — «прогон прерван человеком» (Esc, закрытое окно): пир выходит своим
    // кодом 10, и сосед упирается в собственный дедлайн, а не гадает, куда делся ввод.
    virtual bool show(const Stage& stage) = 0;
};

} // namespace platformer
