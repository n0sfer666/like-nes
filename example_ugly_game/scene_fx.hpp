#pragma once
#include <cstdint>

#include "material_fx.hpp"

namespace game {

// Какие материалы библиотеки образец надевает на кого (гейт 9 спеки #18) и по какому состоянию
// мира. Отдельный файл, а не ветки внутри `draw.cpp`: подача кадра отвечает за ЧТО и в каком
// порядке рисуется, а этот — за то, каким материалом; слитые вместе, они дали бы файл, который
// правят по двум разным причинам.
//
// Состояние мира сюда приходит уже числом (доля, не HP): выбор материала не смеет ни читать
// компоненты, ни тем более их менять — эффекты на симуляцию не влияют (гейт 8 спеки #18).
class SceneFx {
public:
    // Библиотеки нет или она не поднялась — `false`, и образец рисует как рисовал.
    bool bind(MaterialFx* fx);
    bool ready() const { return fx_ != nullptr; }

    // Враг: красная вспышка, набирающая силу по мере подхода к игроку. Значение едет ДАННЫМИ
    // инстанса, поэтому десяток врагов с разной силой остаётся одним вызовом отрисовки
    // (инвариант 2 спеки #18) — ровно это и видно счётчиком `SpriteBatch::draws()`.
    uint32_t enemy(float approach, float p[mat::PARAM_BLOCK_FLOATS]) const;

    // Босс: красный контур, пока цел, и выгорание в пепел на последней четверти HP.
    uint32_t boss(float hp_frac, float p[mat::PARAM_BLOCK_FLOATS]) const;

private:
    MaterialFx* fx_ = nullptr;
    uint32_t flash_ = 0, outline_ = 0, dissolve_ = 0;
    int32_t strength_slot_ = -1, threshold_slot_ = -1;
};

} // namespace game
