#pragma once
#include <cstdint>

#include "platformer_scene.hpp"

// Скриптованный прогон образца-платформера: тот же уровень и тот же контроллер, что в живой игре,
// но без окна, рендера и часов. Отсюда берётся sim-голден шага C (гейт 8 спеки #16 в машинной
// части) — и отсюда же будет видно, если контроллер поедет.
namespace platformer {

// Что маршрут ЗАДЕЛ. Не отладка и не статистика: голден отвечает «три ОС сошлись», а не «сошлись на
// содержательном», и без этих флагов маршрут, промахнувшийся мимо склона, давал бы такой же
// стабильный хеш на всех трёх машинах. Ровно этим B1b и кончился: голден траектории не сдвинулся,
// потому что в его сцене не было ни одного склона, — то есть про склоны он не утверждал ничего.
struct Visited {
    bool walked_slope = false;    // подошва стояла на тайле-склоне
    bool stood_oneway = false;    // подошва стояла на односторонней площадке
    bool rose_through = false;    // прошёл сквозь одностороннюю СНИЗУ ВВЕРХ
    bool dropped_through = false; // «вниз + прыжок» уронил его сквозь неё
    bool rode_lift = false;       // опорой было тело платформы
    bool carried = false;         // и платформа при этом его ВЕЗЛА (сдвиг за тик без ввода)
    bool hit_ceiling = false;
    bool hit_wall = false;
    bool crushed = false;         // обязан остаться ЛОЖЬЮ: маршрут не давит персонажа
};

struct RunResult {
    uint64_t hash = 0;
    Visited seen;
    Vec2 last_position;
    uint32_t ticks = 0;
};

// Прогон целиком. `trace` печатает потиковую строку — им маршрут и настраивался, и он же
// единственный способ понять, ЧЕМ разошёлся хеш, когда он разойдётся.
RunResult run_script(Stage& st, bool trace);

// Тот же маршрут, но ПОТИКОВО: сколько тиков в скрипте и что нажато на тике `t`.
//
// Наружу это нужно откату (спека #22): он гоняет по этому уровню тот же маршрут, но подаёт ввод с
// задержкой, и второй список нажатий рядом стал бы вторым маршрутом — про который известно ровно
// то, что он не тот, чей хеш прибит голденом. Источник у обеих ручек один — таблица `SCRIPT`.
uint32_t script_ticks();
ch::MoveInput script_input(uint32_t tick);

} // namespace platformer
