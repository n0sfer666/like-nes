// Нарезка БЕЙКНУТОГО пути (спека #17, вертикаль 3, шаг B): регионы берутся из секции
// `atlas_regions` бандла ПО ИМЕНАМ, а не из зашитой в код копии `game::set_regions()`.
//
// Копия и текст расходились молча: пиксели приезжают из `atlas.png` через бейк, а UV к ним
// приписывались руками, и разъезд был виден только глазами и только на том спрайте, по которому
// попали. `set_regions()` остаётся ПРОЦЕДУРНОМУ пути — тот рисует пиксели сам, по тем же
// координатам, что и называет, поэтому его нарезка есть свойство его собственной картинки.
//
// Размер страницы тоже берётся у таблицы: зашитые 512x256 были вторым утверждением о ней, и
// перепаковка атласа в другую страницу сдвинула бы все UV разом.
namespace game {

// Номер региона (шаг B2): спрайт фреймворка адресует картинку ЧИСЛОМ (`Sprite::region`), а не
// полем структуры, поэтому у нарезки появляется ПОРЯДОК. Список имён при этом остаётся ОДИН — тот
// же, по которому секция бандла раскладывается в поля: номер и имя, объявленные по отдельности,
// были бы двумя копиями одной нарезки, то есть ровно тем, что убирал шаг B1.
//
// Ноль означает «не рисовать» — соглашение фреймворка (`ParticleStore::draw`, `tile_draw`), —
// поэтому нумерация начинается с единицы, а не с нуля.
enum RegionSlot : uint16_t {
    RID_None = 0,
    RID_Ship,
    RID_Star,
    RID_Enemy,
    RID_Bullet,
    RID_Boss,
    RID_Hostile,
    RID_Solid,
    RID_Digit0,
    RID_LetterA = RID_Digit0 + 10,
    RID_Count = RID_LetterA + 26
};

// Имя региона по номеру и поле нарезки по номеру. Оба — `nullptr` вне диапазона: номер вне таблицы
// это ошибка вызывающего, а не «регион, который не нарисуется», и молчаливый нулевой прямоугольник
// прятал бы её до самой картинки.
const char* region_name(uint16_t id);
const Region* region_at(const Atlas& atlas, uint16_t id);

// Отказ, а не молчание: имя, которого нет в таблице, оставил бы регион нулевым, то есть точкой в
// левом верхнем углу страницы — на экране это пустое место, неотличимое от «спрайт не рисовали».
// Вызывающий по `false` откатывается на процедурный атлас целиком.
bool regions_from_table(const framework::graphics::AtlasTable& table, Atlas& atlas);

} // namespace game
